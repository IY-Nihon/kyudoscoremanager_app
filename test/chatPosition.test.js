/**
 * 射位ごとの成績の「見込みの的中率」の検査。
 *
 *   npm test
 *
 * 2026-10-17 の本番で「大前に向いているのは誰？」に、大前 8 射 8 中・全体 50% の人を、
 * 全体 94% の人と同じ 100% として並べた。少ない射数の率は本人の全体の率へ寄せて比べる。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 射位ごとの成績 } = require('../src/chatStats');

// 一人で立つ記録：その人は大前。印の並びをそのまま入れる
const 記録 = (名, 印, date) => ({ date, archers: [{ id: 'a-' + 名, name: 名, memberId: 名, marks: 印 }] });
const 二人 = (前, 後, date) => ({
  date,
  archers: [
    { id: 'a-' + 前[0], name: 前[0], memberId: 前[0], marks: 前[1] },
    { id: 'a-' + 後[0], name: 後[0], memberId: 後[0], marks: 後[1] },
  ],
});
const 並べる = (n, 中) => Array.from({ length: n }, (無, i) => (i < 中 ? '○' : '×'));

test('射数の少ない射位は、本人の全体の率へ寄せて見込む', () => {
  const 人 = ['甲', '乙'].map((名) => ({ id: 名, name: 名 }));
  const 記録たち = [
    // 甲：大前で 8 射 8 中、落で 8 射 0 中 → 全体 50%
    二人(['甲', 並べる(8, 8)], ['乙', 並べる(8, 7)], 1),
    二人(['乙', 並べる(8, 8)], ['甲', 並べる(8, 0)], 2),
  ];
  const 結果 = 射位ごとの成績(人, 記録たち, {});
  const 大前 = (名) => 結果.一覧.find((x) => x.名前 === 名).射位ごと.find((p) => p.射位 === '大前');
  assert.equal(大前('甲').的中率, 100);
  assert.equal(大前('乙').的中率, 100);
  assert.ok(大前('乙').見込みの的中率 > 大前('甲').見込みの的中率, '全体の高い乙の方が見込みは高い');
  assert.equal(大前('甲').見込みの的中率, 75, '(8 + 8×0.5) / 16');
});

test('記録が無い射位は見込みを出さない（出てこない）', () => {
  const 結果 = 射位ごとの成績([{ id: '丙', name: '丙' }], [記録('丙', 並べる(4, 2), 1)], {});
  assert.equal(結果.一覧[0].射位ごと.length, 1);
  assert.equal(結果.一覧[0].射位ごと[0].見込みの的中率, 50);
});

test('人で絞る：渡した部員の射だけを数える（10/25 まで性別・学年を渡しても絞れていなかった）', () => {
  const 記録たち = [二人(['甲', 並べる(8, 8)], ['乙', 並べる(8, 4)], 1), 記録('ゲスト', 並べる(4, 4), 2)];
  const 甲だけ = 射位ごとの成績([{ id: '甲', name: '甲' }], 記録たち, { 人で絞る: true });
  assert.deepEqual(
    甲だけ.一覧.map((x) => x.名前),
    ['甲']
  );
  // 絞らなければ、記録に書かれた名前で束ねる（ゲストも並ぶ）。これまでどおり
  const 全部 = 射位ごとの成績([{ id: '甲', name: '甲' }], 記録たち, {});
  assert.equal(全部.一覧.length, 3);
});

test('射位を渡すと、その射位に向いている順（見込みの高い順）の順位を返す', () => {
  const 人 = ['甲', '乙'].map((名) => ({ id: 名, name: 名 }));
  const 記録たち = [
    二人(['甲', 並べる(8, 8)], ['乙', 並べる(8, 7)], 1),
    二人(['乙', 並べる(8, 8)], ['甲', 並べる(8, 0)], 2),
  ];
  const 結果 = 射位ごとの成績(人, 記録たち, { 射位: '大前' });
  assert.deepEqual(
    結果.その射位の順位.map((x) => [x.順位, x.名前, x.射位]),
    [
      [1, '乙', '大前'],
      [2, '甲', '大前'],
    ]
  );
  assert.equal(射位ごとの成績(人, 記録たち, {}).その射位の順位, undefined, '渡さなければ付けない');
});
