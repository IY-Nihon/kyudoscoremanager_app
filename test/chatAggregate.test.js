test('名簿：人数・学年ごと・性別ごと。絞り込みと卒業生', () => {
  const r = 名簿を数える(部員, {});
  assert.equal(r.人数, 3);
  assert.deepEqual(r.性別ごと, { 男子: 2, 女子: 1 });
  assert.deepEqual(
    r.一覧.map((x) => x.名前),
    ['山田', '佐藤', '鈴木'].sort((甲, 乙) => 0)
  );
  assert.equal(名簿を数える(部員, { 学年: 2 }).人数, 2);
  assert.deepEqual(
    名簿を数える(部員, { 性別: '女子' }).一覧.map((x) => x.名前),
    ['佐藤']
  );
  assert.equal(名簿を数える(部員, { 名前に: '鈴' }).人数, 1);
  const 期 = 名簿を数える([Object.assign({}, 山田, { termKi: 53 })], { 期を出す: true });
  assert.deepEqual(期.期ごと, { '53期': 1 });
  const 卒 = 名簿を数える(部員, { 卒業生も: true, 卒業生: [{ name: '先輩' }] });
  assert.equal(卒.卒業生の人数, 1);
  assert.equal(名簿を数える(部員, {}).卒業生の人数, undefined, '頼まれなければ卒業生は返さない');
});

test('計算：四則と括弧・全角・桁。数と記号のほかは断る（eval を使わない）', () => {
  assert.deepEqual(計算する('(15+12)/40*100'), { 式: '(15+12)/40*100', 答え: 67.5 });
  assert.equal(計算する('３２０×０．６１６').答え, 197.12);
  assert.equal(計算する('2/3', 4).答え, 0.6667);
  assert.equal(計算する('-(-3)+1,234').答え, 1237);
  assert.match(計算する('1/0').error, /0 で割って/);
  assert.match(計算する('2*(3+4').error, /括弧/);
  assert.match(計算する('process.exit()').error, /数と/);
  assert.match(計算する('').error, /空/);
  assert.match(計算する('1'.repeat(400)).error, /長すぎ/);
});
