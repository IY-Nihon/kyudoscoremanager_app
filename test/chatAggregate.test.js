'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 集計する, 名簿を数える } = require('../src/chatAggregate');
const { 計算する } = require('../src/chatCalc');
const { 全員の成績 } = require('../src/chatStats');

const 人 = (name, o) => Object.assign({ id: name, name, grade: 1, gender: '男子' }, o);
const 列 = (memberId, marks, o) => Object.assign({ id: 'a-' + memberId, name: memberId, memberId, marks }, o);
const 記録 = (日, archers, o) =>
  Object.assign({ id: 'r-' + 日, date: new Date(日 + 'T18:00:00').getTime(), title: '通常練習', archers }, o);

const 山田 = 人('山田');
const 佐藤 = 人('佐藤', { gender: '女子', grade: 2 });
const 鈴木 = 人('鈴木', { grade: 2 });
const 部員 = [山田, 佐藤, 鈴木];
// 9/5 は土曜、9/7 は月曜、10/3 は土曜
const 記録たち = [
  記録(
    '2026-09-05',
    [列('山田', ['○', '○', '○', '○', '×', '×', '×', '×']), 列('佐藤', ['○', '×', '○', '×'])],
    {
      tags: ['#正規練習'],
    }
  ),
  記録(
    '2026-09-07',
    [
      列('山田', ['○', '×', '×', '×']),
      列('鈴木', ['○', '○', '○', '○']),
      列('ゲスト', ['○', '○'], { memberId: null }),
    ],
    {
      tags: ['#自主稽古'],
    }
  ),
  記録(
    '2026-10-03',
    [列('山田', ['×', '×', '×', '×']), 列('佐藤', ['○', '○', '○', '○']), 列('鈴木', ['○', '×', '○', '×'])],
    {
      tags: ['#正規練習', '#大会'],
    }
  ),
];

test('集計：切り口が無い・知らない切り口だけのときは、使える切り口を返す', () => {
  assert.match(集計する(部員, 記録たち, {}).error, /切り口/);
  const r = 集計する(部員, 記録たち, { 切り口: ['天気'] });
  assert.match(r.error, /人・月/);
  assert.deepEqual(r.使えない切り口, ['天気']);
});

test('集計：月ごと（古い順）。全体は全員の成績の合計と同じ・ゲストは数えない', () => {
  const r = 集計する(部員, 記録たち, { 切り口: ['月'] });
  assert.deepEqual(
    r.一覧.map((x) => [x.月, x.的中, x.射数, x.的中率, x.記録の数, x.人数]),
    [
      ['2026-09', 11, 20, 55, 2, 3],
      ['2026-10', 6, 12, 50, 1, 3],
    ]
  );
  const 合計 = 全員の成績(部員, 記録たち, {}).全体;
  assert.equal(r.全体.的中, 合計.的中);
  assert.equal(r.全体.射数, 合計.射数, 'ゲストの 2 射は入らない');
  assert.equal(r.並び, '月の順');
});

test('集計：皆中は同じ人が 1 立（4 射）を全部当てた数。何射目の切り口では出さない', () => {
  // 山田 9/5 の 1 立目・鈴木 9/7・佐藤 10/3 が皆中。皆中が同じなら射数の多い順（山田 16 射）
  const r = 集計する(部員, 記録たち, { 切り口: ['人'], 並び: '皆中' });
  assert.deepEqual(
    r.一覧.map((x) => [x.人, x.皆中]),
    [
      ['山田', 1],
      ['佐藤', 1],
      ['鈴木', 1],
    ]
  );
  assert.deepEqual(
    r.一覧.map((x) => x.順位),
    [1, 2, 3]
  );
  assert.equal(r.全体.皆中, 3);
  // 4 射の途中で交代した立は、4 つとも ○ でも皆中にしない
  const 交代 = 集計する(
    部員,
    [
      記録('2026-09-12', [
        列('山田', ['○', '○', '○', '○'], {
          substitutions: { 2: '鈴木', 3: '鈴木' },
          substitutionIds: { 2: '鈴木', 3: '鈴木' },
        }),
      ]),
    ],
    { 切り口: ['人'] }
  );
  assert.equal(交代.全体.皆中, 0);
  assert.deepEqual(
    交代.一覧.map((x) => [x.人, x.射数]).sort(),
    [
      ['山田', 2],
      ['鈴木', 2],
    ].sort()
  );
  const 射目 = 集計する(部員, 記録たち, { 切り口: ['射目'] });
  assert.equal(射目.一覧[0].皆中, undefined);
  assert.deepEqual(
    射目.一覧.map((x) => x.射目),
    ['1射目', '2射目', '3射目', '4射目', '5射目', '6射目', '7射目', '8射目']
  );
  // 1 射目：9/5 山田○ 佐藤○、9/7 山田○ 鈴木○、10/3 山田× 佐藤○ 鈴木○
  assert.deepEqual([射目.一覧[0].的中, 射目.一覧[0].射数], [6, 7]);
});

