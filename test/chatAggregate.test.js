test('集計：何射目・曜日・人・射位で絞る', () => {
  const 後半 = 集計する(部員, 記録たち, { 切り口: ['人'], 射目: { から: 5, まで: 8 } });
  assert.deepEqual(
    後半.一覧.map((x) => [x.人, x.射数]),
    [['山田', 4]]
  );
  assert.equal(後半.条件.射目, '5〜8射目');
  const 土曜 = 集計する(部員, 記録たち, { 切り口: ['月'], 曜日たち: ['土曜日'] });
  assert.equal(土曜.全体.射数, 24);
  const 山田だけ = 集計する(部員, 記録たち, { 切り口: ['月'], 名前たち: ['山田', '誰か'] });
  assert.equal(山田だけ.全体.射数, 16);
  assert.deepEqual(山田だけ.見つからない名前, ['誰か']);
  const 大前 = 集計する(部員, 記録たち, { 切り口: ['人'], 射位たち: ['大前'] });
  assert.deepEqual(
    大前.一覧.map((x) => x.人),
    ['山田'],
    '3 つの記録とも先頭は山田'
  );
});

test('集計：切り口 2 つ（人 × 月）。内訳と振れ幅、振れ幅の順。射数の足りない内訳は振れ幅に使わない', () => {
  // 並びを言わなければ人の的中率の順。内訳は月の順
  const r = 集計する(部員, 記録たち, { 切り口: ['人', '月'] });
  const 山田の行 = r.一覧.find((x) => x.人 === '山田');
  assert.deepEqual(
    山田の行.内訳.map((x) => [x.月, x.的中, x.射数]),
    [
      ['2026-09', 5, 12],
      ['2026-10', 0, 4],
    ]
  );
  // 10 月は 4 射しかない（8 射に満たない）ので、振れ幅は出さない
  assert.equal(山田の行.振れ幅, null);
  const 振れ幅で = 集計する(部員, 記録たち, { 切り口: ['人', '月'], 並び: '振れ幅' });
  assert.equal(振れ幅で.一覧.length, 0);
  assert.equal(振れ幅で.振れ幅を出せず外した数, 3);

  // 2 か月とも 8 射ずつある人どうしなら、振れ幅の大きい順
  const 八 = (n) => Array.from({ length: 8 }, (_, i) => (i < n ? '○' : '×'));
  const 二か月 = [
    記録('2026-09-05', [列('山田', 八(8)), 列('鈴木', 八(4))]),
    記録('2026-10-03', [列('山田', 八(2)), 列('鈴木', 八(5))]),
  ];
  const 落差 = 集計する(部員, 二か月, { 切り口: ['人', '月'], 並び: '振れ幅' });
  assert.deepEqual(
    落差.一覧.map((x) => [x.人, x.振れ幅, x.いちばん高い.月, x.いちばん低い.月]),
    [
      ['山田', 75, '2026-09', '2026-10'],
      ['鈴木', 12.5, '2026-10', '2026-09'],
    ]
  );
});

