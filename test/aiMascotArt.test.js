/**
 * AIアシスタントのキャラクターの絵（src/aiMascotArt.js）の検査。
 *
 *   npm test
 *
 * ドット絵は文字の並びなので、段の幅が 1 つずれても、弓を握る手が離れても、コンパイルも lint も通ってしまう。
 * 絵を直すたびに、崩れていないことをここで確かめる。
 *
 * 「道着と袴に見える」ための決まりも、ここに書く。形を決めた理由は aiMascotArt.js の頭にある
 * （顔は元のまま・裾を頭よりずっと広く・顔と襟の間に首の段・袖を広げない・13 段まで）。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const {
  体の絵,
  弓の絵,
  目の段,
  開いた絵,
  閉じた絵,
  連なりにする,
  開いた連なり,
  閉じた連なり,
  色,
  幅のマス,
  高さのマス,
} = require('../src/aiMascotArt');

const 体の幅 = 体の絵[0].length;
const 弓の幅 = 弓の絵[0].length;
const 握り = 弓の絵.findIndex((行) => 行.startsWith('W'));
const 中心 = (体の幅 - 1) / 2;
/** その段の、何かを塗ったマスの数（記号は問わない） */
const 塗った数 = (行) => [...行].filter((字) => 字 !== '.').length;
/** その記号が入っている列（0 から数える） */
const 列たち = (行, 記号) => [...行].flatMap((字, i) => (字 === 記号 ? [i] : []));
/** 袴の幅（N と n の数） */
const 袴の幅 = (行) => {
  const 列 = [...行].flatMap((字, i) => (字 === 'N' || 字 === 'n' ? [i] : []));
  return 列[列.length - 1] - 列[0] + 1;
};
/** 色（#RRGGBB）の明るさ（0〜255） */
const 明るさ = (c) => [1, 3, 5].reduce((和, i) => 和 + parseInt(c.slice(i, i + 2), 16), 0) / 3;
/** 頭の幅（腕は含めない。目のある段までで数える） */
const 頭の幅 = Math.max(...体の絵.slice(0, 目の段 + 1).map(塗った数));

test('どの段も同じ幅で、使っている記号は色が決まっている', () => {
  for (const 絵 of [開いた絵, 閉じた絵]) {
    assert.strictEqual(絵.length, 高さのマス);
    for (const 行 of 絵) {
      assert.strictEqual(行.length, 幅のマス, `幅がずれた段: ${行}`);
      for (const 字 of 行) assert.ok(字 === '.' || 字 in 色, `色の無い記号「${字}」（${行}）`);
    }
  }
  assert.ok(
    体の絵.every((行) => 行.length === 体の幅),
    '体の段の幅がそろっていない'
  );
  assert.ok(
    弓の絵.every((行) => 行.length === 弓の幅),
    '弓の段の幅がそろっていない'
  );
  assert.strictEqual(幅のマス, 体の幅 + 弓の幅);
});

test('大きさは 14 段・16 列まで（丸いボタンには、整数のマスのまま 1.5px 右へ寄せて置く（倍率で縮めると継ぎ目の線が出る））', () => {
  assert.ok(高さのマス <= 14);
  assert.ok(幅のマス <= 16);
});

test('弓を握る手は、腕を伸ばした段にある（手が弓から離れない）', () => {
  assert.ok(握り >= 0, '弓に握りの手が無い');
  // 体の右端（腕の先）が、同じ段で弓の手とつながる。腕は頭の右から、顔の段（目のある段）につながる
  assert.strictEqual(握り, 目の段 + 3, '握りが右肩の段にない（腕は肩から出る）');
  assert.ok(体の絵[握り].endsWith('D'), '腕が肩（道着）につながっていない');
  assert.ok(体の絵[目の段 + 1].endsWith('..'), '顔の高さから腕が出ている');
});

test('顔は元のまま：鉢巻と目の間に 1 段あり、目は 2 段', () => {
  const 鉢巻 = 体の絵.findIndex((行) => /R/.test(行));
  assert.strictEqual(目の段 - 鉢巻, 2, '鉢巻と目の間の 1 段が無い（顔つきが変わる）');
  assert.ok(体の絵[目の段].includes('K') && 体の絵[目の段 + 1].includes('K'), '目が 2 段でない');
});

test('目を閉じた絵は、目の段の K が体の色になるだけで、ほかは開いた絵と同じ', () => {
  assert.ok(開いた絵[目の段].includes('K'), '開いた絵に目が無い');
  assert.ok(!閉じた絵[目の段].includes('K'), '閉じた絵に目が残っている');
  assert.ok(開いた絵[目の段 + 1].includes('K'), '目は 2 段ある（閉じても下の段が細い目として残る）');
  開いた絵.forEach((行, i) => {
    if (i === 目の段) assert.strictEqual(閉じた絵[i], 行.replace(/K/g, 'W'));
    else assert.strictEqual(閉じた絵[i], 行, `${i} 段目が変わっている`);
  });
});

test('袴：腰から裾へ向かって広がり、左右対称で、一番下にある（足は袴に隠れる）', () => {
  const 袴の段 = 体の絵.map((行, i) => ({ 行, i })).filter(({ 行 }) => /N/.test(行));
  assert.ok(袴の段.length >= 3, `袴が短い（${袴の段.length} 段）`);
  // 続いた段で、途中で切れない
  袴の段.forEach(({ i }, 番) => {
    if (番 > 0) assert.strictEqual(i, 袴の段[番 - 1].i + 1, '袴が途中で切れている');
  });
  // 下へ行くほど広がる（狭まらない）
  袴の段.forEach(({ 行 }, 番) => {
    if (番 > 0) assert.ok(袴の幅(行) > 袴の幅(袴の段[番 - 1].行), `袴が広がっていない: ${行}`);
  });
  for (const { 行 } of 袴の段) assert.strictEqual(行, [...行].reverse().join(''), `左右がずれている: ${行}`);
  // 袴の下に、足袋の段が 1 段だけ続く（体の色だけで、左右対称）
  assert.strictEqual(袴の段[袴の段.length - 1].i, 体の絵.length - 2, '袴の下に足の段が 1 段だけ続かない');
  const 足 = 体の絵[体の絵.length - 1];
  assert.ok(/^[.W]+$/.test(足) && 足.includes('W'), '足の段は体の色だけ');
  assert.strictEqual(足, [...足].reverse().join(''), '足が左右対称でない');
  // 腕の段の下の、首と道着の 4 段を過ぎてから始まる
  assert.strictEqual(袴の段[0].i, 握り + 3, '袴が道着の段に食い込んでいるか、離れている');
});

test('裾は頭よりずっと広く、腰よりずっと広い（袴だと分かる決め手）。袴は濃い色', () => {
  // 細い台形だと、ただの短いスカートに見える。裾が頭（幅 9）より 4 マス以上広く、腰より 6 マス以上広いこと
  const 袴の段 = 体の絵.filter((行) => /N/.test(行));
  const 腰 = 袴の幅(袴の段[0]);
  const 裾 = 袴の幅(袴の段[袴の段.length - 1]);
  assert.ok(裾 >= 頭の幅 + 2, `裾が狭い（裾 ${裾}、頭 ${頭の幅}）`);
  assert.ok(裾 - 腰 >= 4, `腰から裾への広がりが小さい（腰 ${腰}、裾 ${裾}）`);
  // 袴は濃い色（ほぼ黒）。青いボタンの上でも、青い体の上でも浮く
  assert.ok(明るさ(色.N) < 50, `袴の色が明るい（${色.N}）`);
});

test('道着：顔の下に首の段、肩から V の襟を 3 段。襟は目の列より 1 マス外から始まる', () => {
  const 首 = 目の段 + 2;
  // 首は頭と同じ幅（細いと、両脇に背景の切り欠きができて変に見える）。襟が無い段で、顔と襟を切り離す
  assert.strictEqual(塗った数(体の絵[首]), 頭の幅, '首の幅が頭と違う');
  const 肩 = 首 + 1;
  assert.ok(塗った数(体の絵[肩]) >= 頭の幅 + 2);
  // 襟：3 段。1 段下るごとに両側から 1 マスずつ中心へ寄り、最後の段は目の列より内側
  // 左前（右側の襟が上）：左の襟は短く、右の襟が斜めに長く降りて、中心より左で合わさる
  assert.deepStrictEqual(列たち(体の絵[肩], 'C'), [中心 - 3, 中心 + 3]);
  assert.deepStrictEqual(列たち(体の絵[肩 + 1], 'C'), [中心 - 2, 中心 + 2]);
  assert.deepStrictEqual(列たち(体の絵[肩 + 2], 'C'), [中心 + 1]);
  // 襟の先は、袴の腰の結び目（n）のすぐ左上
  assert.strictEqual(体の絵[肩 + 3][中心], 'n', '襟の先に結び目が無い');
  // 襟は、この 3 段のほかには出ない
  体の絵.forEach((行, i) => {
    if (i < 肩 || i > 肩 + 2) assert.ok(!行.includes('C'));
  });
});

test('上衣は肩幅が頭よりずっと広い台形（13 → 11 → 9）で、布の色 D は顔（体）と違う', () => {
  const 布の段 = 体の絵.filter((行) => /D/.test(行));
  assert.strictEqual(布の段.length, 3, '上衣が 3 段でない');
  const 幅たち = 布の段.map(塗った数);
  assert.deepStrictEqual(幅たち, [13, 11, 9], `上衣の幅の並び: ${幅たち}`);
  assert.ok(幅たち[0] >= 頭の幅 + 4, '肩が頭より 4 マス以上広くない');
  // 襟（C）だけは左前で左右が違う。布（D）の輪郭は左右対称
  布の段.forEach((行) => {
    const 布だけ = 行.replace(/C/g, 'D');
    assert.strictEqual(布だけ, [...布だけ].reverse().join(''), `左右がずれている: ${行}`);
  });
  // 布の色は、顔（体の白）と違う。ただし襟の紺よりは明るく、白に近い薄い色
  assert.notStrictEqual(色.D, 色.W);
  assert.ok(明るさ(色.D) > 200 && 明るさ(色.D) < 255, `布の色の明るさ（${色.D}）`);
});

test('襟は目の真下に来ない。顔と襟の間に首の段がある（無いと、目の下の濃い線が泣き顔に見える）', () => {
  const 目の列 = 列たち(体の絵[目の段], 'K');
  assert.strictEqual(目の列.length, 2);
  const 首 = 目の段 + 2;
  const 肩 = 首 + 1;
  assert.ok(!体の絵[首].includes('C'), '首の段に襟がある');
  for (const 列 of 列たち(体の絵[肩], 'C')) assert.ok(!目の列.includes(列));
  // 襟は、白い体の上で読める濃さ（紺）。青い体の上では白にする（AIChatBot）
  assert.ok(明るさ(色.C) < 80);
});

test('袖を垂らさない：上衣の段に隙間が無く、体の両脇に袖の垂れが出ない（羽のように見える）', () => {
  for (const 行 of 体の絵.filter((r) => /D/.test(r))) {
    assert.ok(!行.replace(/^\.+|\.+$/g, '').includes('.'), '上衣の中に隙間がある: ' + 行);
  }
});

test('鉢巻は目より上にある', () => {
  const 鉢巻 = 体の絵.findIndex((行) => /R/.test(行));
  assert.ok(鉢巻 >= 0 && 鉢巻 < 目の段, '鉢巻が目より上に無い');
});

test('弓は先が上下にあり、上端は 1 段空け（バッジに隠れない）、体より長くならない', () => {
  assert.ok(弓の絵.length <= 体の絵.length);
  assert.ok(
    !/[BS]/.test(弓の絵[0] + 弓の絵[1] + 弓の絵[2] + 弓の絵[3]),
    '弓が上の 4 段から始まっている（「AI」のバッジに隠れる）'
  );
  const 先 = 弓の絵.map((行, i) => (/B/.test(行) ? i : -1)).filter((i) => i >= 0);
  assert.strictEqual(先[0], 4, '弓の上の先が 5 段目に無い');
  assert.match(弓の絵[弓の絵.length - 1], /B/, '弓の先が下端に無い');
  assert.ok(握り > 1 && 握り < 弓の絵.length - 1);
});

test('連なりにする：同じ記号が横に続くところをまとめ、何も無いマスは含めない', () => {
  assert.deepStrictEqual(連なりにする('NNnNN'), [
    { 字: 'N', 始め: 0, 長さ: 2 },
    { 字: 'n', 始め: 2, 長さ: 1 },
    { 字: 'N', 始め: 3, 長さ: 2 },
  ]);
  assert.deepStrictEqual(連なりにする('.W.W'), [
    { 字: 'W', 始め: 1, 長さ: 1 },
    { 字: 'W', 始め: 3, 長さ: 1 },
  ]);
  assert.deepStrictEqual(連なりにする('...'), []);
  assert.deepStrictEqual(連なりにする(''), []);
});

test('横の連なりにまとめても、1 マスずつ描くのと同じ絵になる。まとめ残しも無い', () => {
  for (const [絵, 連なり] of [
    [開いた絵, 開いた連なり],
    [閉じた絵, 閉じた連なり],
  ]) {
    assert.strictEqual(連なり.length, 絵.length);
    絵.forEach((行, y) => {
      const 戻す = [...'.'.repeat(行.length)];
      for (const { 字, 始め, 長さ } of 連なり[y]) for (let i = 0; i < 長さ; i++) 戻す[始め + i] = 字;
      assert.strictEqual(戻す.join(''), 行, `${y} 段目が元の絵と違う`);
      連なり[y].forEach((c, i) => {
        assert.ok(c.字 !== '.' && c.長さ >= 1, '何も無いマスが含まれている');
        if (i === 0) return;
        const 前 = 連なり[y][i - 1];
        assert.ok(前.字 !== c.字 || 前.始め + 前.長さ < c.始め, `${y} 段目にまとめ残しがある`);
      });
    });
  }
});

test('描く図形の数は、1 マスずつより少なく、増やしすぎない（答えのたびに 1 体並ぶ）', () => {
  const セル = 開いた絵.join('').replace(/\./g, '').length;
  const 図形 = 開いた連なり.reduce((n, 行) => n + 行.length, 0);
  assert.ok(図形 < セル, `まとめても減っていない（${図形} / ${セル}）`);
  // 袴も道着も無かった最初の 1 体は 89 マス（まとめる前）。いまは 56 個。65 を超えるなら、まとめ方か絵を見直す
  assert.ok(図形 <= 65, `図形が多すぎる（${図形}）`);
});
