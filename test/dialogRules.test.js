/**
 * 確認・お知らせを帯で流すか、窓で止めるかの検査。
 *
 *   npm test
 *
 * ここに並べているのは、アプリが実際に出す文そのもの。43か所すべてを
 * e2e で踏むのは現実的でないので、分かれ目だけをここで押さえる。
 * 文を書き換えて長くしたときに、黙って帯のまま流れてしまうのを防ぐ。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 窓で止めるか, 帯の長さ, 帯の時計をつくる, 帯の下限, 帯の上限 } = require('../src/dialogRules');

// 帯のまま（短い一言。押させる必要がない）
const 帯でよい文 = [
  'すべての項目を入力してください',
  '名前を入力してください',
  '団体IDを入力してください',
  '団体IDとパスワードを入力してください',
  '団体IDと個人IDを入力してください',
  '練習日が検出されませんでした。',
  '対象のデータがありません',
  'パスワードが正しくありません。',
  '認証に失敗しました。',
  '書き出しはWeb版のみ対応しています。',
  'メンバーモードでは自分以外の情報は編集できません。',
  'メンバーの追加は団体ログイン、かつ管理者のみ可能です。',
  'メンバーの編集は団体ログイン時のみ可能です。',
  'メンバーの削除は団体ログイン時のみ可能です。',
  '道具管理は団体ログイン時のみ可能です。',
  '団体ID、パスワード、新しいメールアドレスを入力してください',
  '登録メールアドレスにパスワード再設定用のリンクを送信しました。',
  'クラウドとの同期に失敗しました。時間をおいて再度お試しください。',
];

// 窓で止める（読んで控える文。流れると取り返しがつかない）
const 窓で止める文 = [
  '団体IDは、アカウント登録時のメールに記載されています。見当たらない場合は管理者にお問い合わせください。',
  '団体アカウントを作成しました。\n\n■ 登録情報\n団体ID: 100001',
  'メールアドレスを変更しました。今後は新しいメールアドレスでログインできます。\n\n◆セキュリティ',
];

test('短い一言は帯で流す', () => {
  for (const 文 of 帯でよい文) {
    assert.strictEqual(窓で止めるか({ 文, ボタン: [] }), false, `帯のはず: ${文}`);
  }
});

test('読んで控える文は窓で止める', () => {
  for (const 文 of 窓で止める文) {
    assert.strictEqual(窓で止めるか({ 文, ボタン: [] }), true, `窓のはず: ${文}`);
  }
});

test('選ばせる確認は、短くても必ず窓で止める', () => {
  const 確認 = { 文: '削除しますか？', ボタン: [{ text: 'キャンセル' }, { text: '削除' }] };
  assert.strictEqual(窓で止めるか(確認), true);
});

test('ボタンが1つだけの知らせは、短ければ帯のまま', () => {
  assert.strictEqual(窓で止めるか({ 文: '保存しました', ボタン: [{ text: 'OK' }] }), false);
});

test('改行を含む文は、短くても窓で止める', () => {
  assert.strictEqual(窓で止めるか({ 文: 'あ\nい', ボタン: [] }), true);
});

test('文が無くても落ちない', () => {
  assert.strictEqual(窓で止めるか({}), false);
  assert.strictEqual(窓で止めるか({ 文: null, ボタン: null }), false);
});

test('帯は文が長いほど長く出るが、上限を超えない', () => {
  assert.strictEqual(帯の長さ(''), 帯の下限);
  assert.ok(帯の長さ('あ'.repeat(30)) > 帯の長さ('あ'.repeat(10)));
  assert.strictEqual(帯の長さ('あ'.repeat(500)), 帯の上限);
});

test('帯で流す文はすべて、消えるまでに読み切れる長さ', () => {
  // 1秒に10字として、出ている間に読み切れること
  for (const 文 of 帯でよい文) {
    const 読むのに要る = (文.length / 10) * 1000;
    assert.ok(
      帯の長さ(文) >= 読むのに要る,
      `${文.length}字なのに ${帯の長さ(文)}ミリ秒しか出ない: ${文}`
    );
  }
});

// ── 帯を消す時計 ──────────────────────────────────────────────
// 続けて知らせが来たとき、前の時計が後の帯を早く消してしまう不具合があった。
// 実際の時計だと待ち時間が要るので、ここでは手で進められる時計を渡して確かめる。

/** 手で進められる時計。掛けた順ではなく、時刻の早い順に鳴る */
function にせの時計() {
  let いま = 0;
  let 次の札 = 1;
  const 予定 = new Map();
  return {
    掛ける: (f, ms) => {
      const 札 = 次の札++;
      予定.set(札, { f, 鳴る: いま + ms });
      return 札;
    },
    止める: (札) => 予定.delete(札),
    進める(ミリ秒) {
      const 終わり = いま + ミリ秒;
      for (;;) {
        const 次 = [...予定.entries()].filter(([, x]) => x.鳴る <= 終わり).sort((a, b) => a[1].鳴る - b[1].鳴る)[0];
        if (!次) break;
        予定.delete(次[0]);
        いま = 次[1].鳴る;
        次[1].f();
      }
      いま = 終わり;
    },
    残り: () => 予定.size,
  };
}

test('続けて出しても、後の帯が前の時計に消されない', () => {
  const 時 = にせの時計();
  const 時計 = 帯の時計をつくる(時.掛ける, 時.止める);
  let 帯;

  // 1つめ：短い知らせ
  const 短い = '団体IDを入力してください';
  帯 = 短い;
  時計.掛ける(帯の長さ(短い), () => { 帯 = null; });

  // まだ出ている間に、2つめ：長い知らせ
  時.進める(2000);
  assert.strictEqual(帯, 短い, '2.0秒では、まだ1つめが出ているはず');
  const 長い = '団体ID、パスワード、新しいメールアドレスを入力してください';
  帯 = 長い;
  時計.掛ける(帯の長さ(長い), () => { 帯 = null; });

  // 1つめの時計が切れる時刻を越えても、2つめは自分の持ち時間ぶん出ていること
  時.進める(2500); // ここまで 4.5秒。1つめは 3.64秒で切れる予定だった
  assert.strictEqual(帯, 長い, '前の時計が後の帯を消してしまっている');

  // 2つめは自分の持ち時間（2.0秒＋5.0秒＝7.0秒）で消える
  時.進める(2600); // ここまで 7.1秒
  assert.strictEqual(帯, null, '2つめが自分の持ち時間を過ぎても消えない');
});

test('片付けると、あとから鳴る時計は残らない', () => {
  const 時 = にせの時計();
  const 時計 = 帯の時計をつくる(時.掛ける, 時.止める);
  let 帯 = 'なにか';
  時計.掛ける(3000, () => { 帯 = null; });
  assert.strictEqual(時計.掛かっているか(), true);
  時計.片付ける();
  assert.strictEqual(時計.掛かっているか(), false);
  assert.strictEqual(時.残り(), 0, '止めたはずの時計が残っている');
  時.進める(5000);
  assert.strictEqual(帯, 'なにか', '片付けたのに消しに来た');
});

test('掛け直しても、時計は1つしか持たない', () => {
  const 時 = にせの時計();
  const 時計 = 帯の時計をつくる(時.掛ける, 時.止める);
  for (let i = 0; i < 5; i++) 時計.掛ける(3000, () => {});
  assert.strictEqual(時.残り(), 1, '掛け直したぶんが溜まっている');
});

test('帯は Modal に入れない：焦点も指も取らない箱に描き、窓より手前に置く', () => {
  // 2026-08-29 に踏んだ「帯が出ている間、下の入力欄が押せない」は、Modal の容器に
  // pointer-events: none を付けて直した。2026-10-03 に残りが分かった：react-native-web の Modal は
  // 窓の外へ焦点が移ると中へ戻す囲い（ModalFocusTrap）を持つので、押せても焦点が取れず、帯が出ている
  // 2.6〜6 秒のあいだ字が打てなかった（ログイン失敗の帯の間はIDを打ち直せない）。
  // 帯は読ませるだけなので、Modal を使わず、焦点にも指にも関わらない箱（帯の層）に描く。
  // 窓（ボタン付き）は押させるので、Modal のまま。
  const 本体 = require('fs').readFileSync(
    require('path').join(__dirname, '..', 'src', 'AppDialog.js'),
    'utf8'
  );
  const 帯の所 = 本体.slice(本体.indexOf('{帯 ?'), 本体.indexOf('{いま ?'));
  assert.ok(帯の所.includes('<帯の層>'), '帯が専用の箱（帯の層）に描かれていない');
  assert.ok(
    !/<Modal/.test(帯の所),
    '帯が Modal に入っている：Modal は窓の外へ焦点が移ると中へ戻すので、帯の間は入力欄に打てなくなる'
  );
  // 箱は指を通し、窓（react-native-web の Modal は 9999）より手前
  const 層の所 = 本体.slice(本体.indexOf('const 帯の層'), 本体.indexOf('const 帯の見た目'));
  assert.ok(/pointerEvents: *'none'/.test(層の所), '帯の箱が指を通さない（帯の下が押せなくなる）');
  const z = Number((層の所.match(/zIndex: *'?([0-9]+)'?/) || [])[1]);
  assert.ok(z > 9999, `帯の箱の重なり(${z})が窓の 9999 より手前にない`);
  // 帯そのものも指を通す
  const 見た目の所 = 本体.slice(本体.indexOf('const 帯の見た目'), 本体.indexOf('// 画面側（アプリの窓）'));
  assert.ok(/pointerEvents="none"/.test(見た目の所), '帯が指を通さない');
  assert.ok(/testID="アプリの帯"/.test(見た目の所), '検査が見る印（アプリの帯）が無い');
  // 窓は Modal のまま
  const 窓の所 = 本体.slice(本体.indexOf('{いま ?'));
  assert.ok(/<Modal/.test(窓の所), '窓が Modal でなくなっている');
  assert.ok(!窓の所.includes('帯の層'), '窓まで帯の箱に入れると、焦点が囲われず背面が操作できてしまう');
});
