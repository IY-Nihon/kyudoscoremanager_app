/**
 * マスの見た目を、1射ずつの○×に開く検査。
 *
 *   npm test
 *
 * ■ なぜこれを入れたか
 *
 * ホワイトボードでは1つのマスに2射ぶんが重ねて書かれる。この展開まで
 * 模型に任せたところ、実物の写真で 45.8% しか合わなかった（2026-09-09）。
 * ほとんどのマスを○と答え、射数も24（正しくは20）になった。
 *
 * 決まりきった変換なので、模型には「マスがどう見えるか」だけを答えさせ、
 * 開くのはこちらでやる。書き方は次のとおり（利用者に教わったまま）:
 *
 *   1本目を外す → 右上から左下へ線
 *   そのあと2本目を中てる → その上に丸（線の入った丸）
 *   1本目を中てる → 丸
 *   そのあと2本目を外す → その上に左上から右下へ線（線の入った丸）
 *   2本とも中てる → 丸の内側にもう1つ丸（◎）
 *   2本とも外す → 線が交わって ×
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { マスを開く, 記号を整える, 射数にそろえる } = require('../src/ocrCells');

const 逆 = String.fromCharCode(92); // ＼（左上から右下）

test('2射のマスを、教わったとおりに開く', () => {
  assert.deepStrictEqual(マスを開く(['◎'], '2射'), ['○', '○'], '2本とも中り');
  assert.deepStrictEqual(マスを開く(['○' + 逆], '2射'), ['○', '×'], '中り→外れ');
  assert.deepStrictEqual(マスを開く(['○/'], '2射'), ['×', '○'], '外れ→中り');
  assert.deepStrictEqual(マスを開く(['×'], '2射'), ['×', '×'], '2本とも外れ');
  assert.deepStrictEqual(マスを開く(['○'], '2射'), ['○', ''], '1本目だけ中り');
  assert.deepStrictEqual(マスを開く(['/'], '2射'), ['×', ''], '1本目だけ外れ');
  assert.deepStrictEqual(マスを開く([''], '2射'), ['', ''], 'まだ引いていない');
});

test('1射のマス（紙の横書き）は、そのまま', () => {
  assert.deepStrictEqual(マスを開く(['○', '×', ''], '1射'), ['○', '×', '']);
});

test('並びは、書いてある順のまま開く', () => {
  // 上から ◎ / 外れ→中り / × なら、6射ぶんがこの順に並ぶ
  assert.deepStrictEqual(
    マスを開く(['◎', '○/', '×'], '2射'),
    ['○', '○', '×', '○', '×', '×']
  );
});

test('書き方の揺れを、決めた記号に寄せる', () => {
  assert.strictEqual(記号を整える('◯'), '○', '別の丸');
  assert.strictEqual(記号を整える('〇'), '○', '別の丸');
  assert.strictEqual(記号を整える('✕'), '×', '別のばつ');
  assert.strictEqual(記号を整える('◯／'), '○/', '全角の線');
  assert.strictEqual(記号を整える('○＼'), '○' + 逆, '全角の線');
  assert.strictEqual(記号を整える('○○'), '◎', '丸を2つ書いたとき');
  assert.strictEqual(記号を整える('  '), '', '空白だけ');
  assert.strictEqual(記号を整える('あ'), '', '知らない字は読めなかった扱い');
  assert.strictEqual(記号を整える(null), '', '無いとき');
});

test('知らない記号は、当てずっぽうにせず空にする', () => {
  // 当てずっぽうで○を入れると、的中率が実態より高く出る。空のほうがまし
  assert.deepStrictEqual(マスを開く(['？', 'あ'], '2射'), ['', '', '', '']);
});

test('射数に合わせて、位置を保ったままそろえる', () => {
  assert.deepStrictEqual(射数にそろえる(['○', '×'], 4), ['○', '×', '', '']);
  assert.deepStrictEqual(射数にそろえる(['○', '×', '○', '×', '○'], 4), ['○', '×', '○', '×']);
  assert.deepStrictEqual(射数にそろえる(null, 2), ['', '']);
});
