test('二つの期間で比べる：下がった順・上がった順・差の大きさ。どちらかの期間で射数が足りない人は比べない', () => {
  const 部員 = [人('山田'), 人('佐藤'), 人('鈴木'), 人('田中')];
  const 八 = (n) => Array.from({ length: 8 }, (_, i) => (i < n ? '○' : '×'));
  const 記録たち = [
    // 前の期間（9 月）
    記録(日('2026-09-10'), [列('山田', 八(6)), 列('佐藤', 八(2)), 列('鈴木', 八(4)), 列('田中', ['○'])]),
    // 今の期間（10 月）
    記録(日('2026-10-10'), [列('山田', 八(2)), 列('佐藤', 八(6)), 列('鈴木', 八(4)), 列('田中', 八(8))]),
  ];
  const 注文 = { 今の期間: 期間('2026-10-01', '2026-10-31'), 前の期間: 期間('2026-09-01', '2026-09-30') };
  const 下 = 二つの期間で比べる(部員, 記録たち, 注文);
  assert.equal(下.並び, '下がった');
  assert.deepEqual(
    下.一覧.map((x) => [x.名前, x.差, x.順位]),
    [
      ['山田', -50, 1],
      ['鈴木', 0, 2],
      ['佐藤', 50, 3],
    ]
  );
  assert.equal(下.射数が足りず比べなかった人数, 1, '田中は前の期間に 1 射だけ');
  assert.deepEqual(下.今の期間, { 始め: '2026-10-01', 終わり: '2026-10-31' });
  // 全体は比べなかった人（田中）の射も入れた団体の合計：前 13/25＝52%、今 20/32＝62.5%
  assert.equal(下.全体.差, 10.5);
  assert.equal(二つの期間で比べる(部員, 記録たち, { ...注文, 並び: '上がった' }).一覧[0].名前, '佐藤');
  assert.deepEqual(
    二つの期間で比べる(部員, 記録たち, { ...注文, 並び: '差の大きさ', 件数: 2 })
      .一覧.map((x) => x.名前)
      .sort(),
    ['佐藤', '山田']
  );
  assert.equal(
    二つの期間で比べる(部員, 記録たち, { ...注文, 最小射数: 1 }).比べた人数,
    4,
    '最小射数を下げれば田中も比べる'
  );
});

test('比べる期間を決める：省くと今日までの 30 日とその前の 30 日。今の期間だけ渡すと、すぐ前の同じ日数', () => {
  const 今日 = new Date(2026, 9, 25, 15, 0);
  const 文 = (ms) => {
    const d = new Date(ms);
    return `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()} ${d.getHours()}:${d.getMinutes()}`;
  };
  const 既定 = 比べる期間を決める({}, 今日);
  assert.equal(文(既定.今の期間.始め), '2026-9-26 0:0');
  assert.equal(文(既定.今の期間.終わり), '2026-10-25 23:59');
  assert.equal(文(既定.前の期間.始め), '2026-8-27 0:0');
  assert.equal(文(既定.前の期間.終わり), '2026-9-25 23:59');
  const 月 = 比べる期間を決める({ dateFrom: '2026-10-01', dateTo: '2026-10-31' }, 今日);
  assert.equal(文(月.前の期間.始め), '2026-8-31 0:0', '31 日ぶん前へ');
  assert.equal(文(月.前の期間.終わり), '2026-9-30 23:59');
  const 指定 = 比べる期間を決める(
    { dateFrom: '2026-10-01', compareFrom: '2026-04-01', compareTo: '2026-06-30' },
    今日
  );
  assert.equal(文(指定.前の期間.始め), '2026-4-1 0:0');
  assert.equal(文(指定.前の期間.終わり), '2026-6-30 23:59');
});

test('射の前後で比べる：列の 1〜4 射目と 5〜8 射目。差が小さい（安定している）順、範囲は変えられる', () => {
  const 部員 = [人('山田'), 人('佐藤')];
  const 記録たち = [
    記録(日('2026-09-01'), [
      列('山田', ['○', '○', '×', '×', '○', '○', '×', '×']),
      列('佐藤', ['○', '○', '○', '○', '×', '×', '×', '×']),
    ]),
    記録(日('2026-09-02'), [
      列('山田', ['○', '×', '○', '×', '×', '○', '×', '○']),
      列('佐藤', ['○', '○', '○', '×', '×', '×', '×', '○']),
    ]),
  ];
  const r = 射の前後で比べる(部員, 記録たち, {});
  assert.equal(r.前の射の範囲, '1〜4射目');
  assert.deepEqual(
    r.一覧.map((x) => [x.名前, x.前の射.的中率, x.後の射.的中率, x.差]),
    [
      ['山田', 50, 50, 0],
      ['佐藤', 87.5, 12.5, -75],
    ]
  );
  assert.equal(射の前後で比べる(部員, 記録たち, { 並び: '後が下がった' }).一覧[0].名前, '佐藤');
  const 二本ずつ = 射の前後で比べる(部員, 記録たち, {
    前: { から: 1, まで: 2 },
    後: { から: 3, まで: 4 },
    最小射数: 4,
  });
  assert.equal(二本ずつ.後の射の範囲, '3〜4射目');
  assert.deepEqual(二本ずつ.一覧.find((x) => x.名前 === '佐藤').前の射, { 的中: 4, 射数: 4, 的中率: 100 });
  assert.equal(射の前後で比べる(部員, 記録たち, { 最小射数: 9 }).比べた人数, 0, '8 射ずつしか無い');
});

