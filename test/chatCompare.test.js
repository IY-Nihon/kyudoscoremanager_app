/**
 * AI の比べる道具（2026-10-25 に足した）の検査。
 *
 *   npm test
 *
 * 2026-10-24 の AI のログで「最近的中率が落ちている人」「最初の 4 射と後半の 4 射で安定している人」に
 * 「その機能はありません」と断っていた。引き算と並べ替えは模型にさせない決まりなので、ここで済ませる。
 * 名簿の性別は '男子'・'女子' で持つ（前の検査は 'male' で書いていて、本物の名簿で絞れないことに気づかなかった）
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const {
  全員の成績,
  出欠の集計,
  二つの期間で比べる,
  比べる期間を決める,
  射の前後で比べる,
  弓具の前後,
  記録の的中,
} = require('../src/chatStats');

const 人 = (name, o) => Object.assign({ id: name, name, grade: 1, gender: '男子' }, o);
const 記録 = (date, archers, o) => Object.assign({ date, archers }, o);
const 列 = (memberId, marks, o) => Object.assign({ id: 'a-' + memberId, name: memberId, memberId, marks }, o);
const 日 = (文) => new Date(文 + 'T18:00:00').getTime();
const 期間 = (始め, 終わり) => ({
  始め: new Date(始め + 'T00:00:00').getTime(),
  終わり: new Date(終わり + 'T23:59:59').getTime(),
});

test('性別で絞る：名簿の「男子」「女子」で絞れる（引数は 男子・male のどちらでも）', () => {
  const 部員 = [人('山田'), 人('佐藤', { gender: '女子' }), 人('鈴木', { gender: 'male' })];
  const 記録たち = [
    記録(日('2026-09-06'), [列('山田', ['○', '○']), 列('佐藤', ['○', '×']), 列('鈴木', ['×', '×'])]),
  ];
  const 男子 = 全員の成績(部員, 記録たち, { 性別: '男子' });
  assert.deepEqual(
    男子.一覧.map((x) => x.名前),
    ['山田', '鈴木']
  );
  assert.deepEqual(男子.絞り込み, { 性別: '男子', 学年: null });
  assert.equal(全員の成績(部員, 記録たち, { 性別: 'female' }).一覧[0].名前, '佐藤');
  assert.equal(全員の成績(部員, 記録たち, {}).絞り込み, null, '絞らないときは null');
  // 出欠も同じ比べ方
  const 出欠 = 出欠の集計(部員, 記録たち, {
    期間: 期間('2026-09-01', '2026-09-30'),
    練習日: { '2026-09-06': {} },
    今日: '2026-09-20',
    性別: '男子',
  });
  assert.deepEqual(出欠.一覧.map((x) => x.名前).sort(), ['山田', '鈴木']);
});

