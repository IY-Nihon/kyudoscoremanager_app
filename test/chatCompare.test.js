test('弓具の前後：変えた日ごとに、その弓具のあいだと前の弓具のあいだ。弓具の記録が無ければその旨', () => {
  const 基準 = 日('2026-09-15');
  const 一日 = 86400000;
  const 山田 = 人('山田', {
    equipments: [
      { id: 'e1', date: 基準 - 30 * 一日, weight: 12 },
      { id: 'e2', date: 基準, weight: 14, note: '弓を替えた' },
    ],
  });
  const 二十 = (n) => Array.from({ length: 20 }, (_, i) => (i < n ? '○' : '×'));
  const 記録たち = [
    記録(基準 - 2 * 一日, [列('山田', 二十(10))]),
    記録(基準 + 2 * 一日, [列('山田', 二十(15))]),
  ];
  const r = 弓具の前後([山田], 記録たち, '山田');
  assert.equal(r.一覧.length, 2);
  assert.equal(r.一覧[0].変えた日, '2026-09-15');
  assert.equal(r.一覧[0].弓力, '14kg');
  assert.equal(r.一覧[0].覚え書き, '弓を替えた');
  assert.deepEqual(r.一覧[0].その弓具のあいだ, { 的中: 15, 射数: 20, 的中率: 75 });
  assert.equal(r.一覧[0].差, 25);
  assert.match(r.一覧[0].見立て, /弓具だけが理由とは限りません/);
  assert.equal(弓具の前後([人('佐藤')], 記録たち, '佐藤').弓具の記録, 0);
  assert.ok(弓具の前後([山田], 記録たち, '誰か').error);
});

