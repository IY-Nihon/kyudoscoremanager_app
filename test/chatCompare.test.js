const { 出欠を月ごとに } = require('../src/chatStats');

test('出欠を月ごとに：人ごとに各月の来た回数・練習日数・出席率。上限を渡すと、その率以下の月を数えて多い順', () => {
  const 部員 = [人('山田'), 人('佐藤', { gender: '女子' })];
  const 練習日 = { '2026-09-05': {}, '2026-09-12': {}, '2026-10-03': {}, '2026-10-10': {} };
  const 記録たち = [
    記録(日('2026-09-05'), [列('山田', ['○']), 列('佐藤', ['○'])]),
    記録(日('2026-09-12'), [列('山田', ['○'])]),
    記録(日('2026-10-03'), [列('佐藤', ['○'])]),
    記録(日('2026-10-10'), [列('佐藤', ['×'])]),
  ];
  const 注文 = { 期間: 期間('2026-09-01', '2026-10-31'), 練習日, 今日: '2026-10-25' };
  const r = 出欠を月ごとに(部員, 記録たち, 注文);
  assert.deepEqual(r.月たち, ['2026-09', '2026-10']);
  const 山田 = r.一覧.find((x) => x.名前 === '山田');
  assert.deepEqual(
    山田.月ごと.map((x) => [x.月, x.来た回数, x.練習日数, x.出席率]),
    [
      ['2026-09', 2, 2, 100],
      ['2026-10', 0, 2, 0],
    ]
  );
  const 上限 = 出欠を月ごとに(部員, 記録たち, { ...注文, 出席率の上限: 50 });
  assert.deepEqual(
    上限.一覧.map((x) => [x.名前, x.当てはまった月の数, x.当てはまった月]),
    [
      ['佐藤', 1, ['2026-09']],
      ['山田', 1, ['2026-10']],
    ]
  );
  const 男子 = 出欠を月ごとに(部員, 記録たち, { ...注文, 性別: '男子' });
  assert.deepEqual(
    男子.一覧.map((x) => x.名前),
    ['山田']
  );
});

