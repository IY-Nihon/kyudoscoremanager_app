/**
 * 上のバーの並べ方（src/tabBarLayout.js）。
 * 最近の携帯（360px 以上）では「絵＋名前」、それより狭くて収まらないときだけ
 * 「絵だけ（今いるタブだけ名前）」。
 */
const test = require('node:test');
const assert = require('node:assert');
const { 並べ方を決める, 字の幅, 絵の大きさ, 絵と字の間, 外の余白, ゆとり } = require('../src/tabBarLayout');

const 団体 = ['記録', '履歴', '分析', 'メンバー', '出欠', '設定'];
const 個人 = ['記録', '履歴', '分析', 'メンバー', '設定'];

test('字の幅：全角の字は 1 字ぶん（メンバーの ー も）', () => {
  assert.strictEqual(字の幅('記録'), 24);
  assert.strictEqual(字の幅('メンバー'), 48);
  assert.strictEqual(字の幅('記録', 1.5), 36, '端末の文字の拡大も見る');
});

test('最近の携帯の幅（360〜430）は、団体の 6 タブでも絵＋名前', () => {
  for (const 幅 of [360, 375, 390, 412, 430]) {
    assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅 }).型, 'ぜんぶ', `${幅}px`);
  }
});

test('それより狭い携帯（320・340）は絵だけ。団体の 6 タブ', () => {
  for (const 幅 of [280, 320, 340]) {
    assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅 }).型, '絵だけ', `${幅}px`);
  }
});

test('広い幅（横向きの携帯・タブレット・パソコン）では絵＋名前', () => {
  for (const 幅 of [640, 844, 1000, 1280]) {
    assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅 }).型, 'ぜんぶ', `${幅}px`);
  }
});

test('切り替えの境：一番詰めた余白で収まるぎりぎりの幅でぜんぶ、1px 足りなければ絵だけ', () => {
  let 境 = 0;
  for (let 幅 = 200; 幅 < 800; 幅++) {
    if (並べ方を決める({ 名前たち: 団体, 幅 }).型 === 'ぜんぶ') {
      境 = 幅;
      break;
    }
  }
  assert.ok(境 > 0);
  const ぎりぎり = 並べ方を決める({ 名前たち: 団体, 幅: 境 });
  assert.strictEqual(ぎりぎり.余白, 4, '境では一番詰めた余白');
  assert.ok(ぎりぎり.必要な幅 <= 境 - 外の余白 - ゆとり);
  assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅: 境 - 1 }).型, '絵だけ');
  assert.ok(境 <= 360, '最近の携帯の幅（360px）では収まる');
});

test('個人ログイン（出欠が無い 5 タブ）は、団体より狭い幅（320px）まで絵＋名前で収まる', () => {
  const 団体の境 = 並べ方を決める({ 名前たち: 団体, 幅: 2000 }).必要な幅 + 外の余白 + ゆとり;
  const 個人の境 = 並べ方を決める({ 名前たち: 個人, 幅: 2000 }).必要な幅 + 外の余白 + ゆとり;
  assert.ok(個人の境 < 団体の境);
  assert.strictEqual(並べ方を決める({ 名前たち: 個人, 幅: 個人の境 }).型, 'ぜんぶ');
  assert.strictEqual(並べ方を決める({ 名前たち: 個人, 幅: 320 }).型, 'ぜんぶ');
});

test('絵＋名前の余白は、幅が広いほど広い（狭い携帯では詰める）', () => {
  const 余白 = (幅) => 並べ方を決める({ 名前たち: 団体, 幅 }).余白;
  assert.ok(余白(390) > 余白(360), '390px は 360px より余白が広い');
  assert.ok(余白(360) >= 4);
});

test('絵だけは、どの幅でも帯が収まる（今いるタブがいちばん長い名前でも）。余白を狭めて合わせる', () => {
  for (let 幅 = 260; 幅 <= 640; 幅 += 10) {
    const 並べ方 = 並べ方を決める({ 名前たち: 団体, 幅 });
    if (並べ方.型 !== '絵だけ') continue;
    assert.ok(並べ方.必要な幅 <= 幅 - 外の余白 - ゆとり || 並べ方.余白 === 4, `${幅}px で溢れる（必要 ${並べ方.必要な幅}）`);
  }
  // 320px でも広いほうの余白が使える（タップしやすい）
  const 並べ方 = 並べ方を決める({ 名前たち: 団体, 幅: 320 });
  assert.ok(並べ方.余白 >= 8, '320px は余白 8 以上で収まる');
});

test('分からない幅（0・数でない）は、溢れない絵だけ', () => {
  assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅: 0 }).型, '絵だけ');
  assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅: NaN }).型, '絵だけ');
});

test('文字の拡大が大きい端末は、同じ幅でも収まりにくい', () => {
  const 幅 = 400;
  assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅, 拡大: 1 }).型, 'ぜんぶ');
  assert.strictEqual(並べ方を決める({ 名前たち: 団体, 幅, 拡大: 1.3 }).型, '絵だけ');
});

test('名前が無いときは何もしない（ぜんぶ）', () => {
  assert.strictEqual(並べ方を決める({ 名前たち: [], 幅: 390 }).型, 'ぜんぶ');
  assert.strictEqual(並べ方を決める(undefined).型, 'ぜんぶ');
});

test('絵の大きさと間は、見積もりに入っている（1 タブぶんの幅の足し算）', () => {
  const 一つ = 並べ方を決める({ 名前たち: ['記録'], 幅: 2000 });
  // 枠の内側 6 + 余白 6×2 + 絵 + 間 + 名前 24
  assert.strictEqual(一つ.必要な幅, 6 + 12 + 絵の大きさ + 絵と字の間 + 24);
});
