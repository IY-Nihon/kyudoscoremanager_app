/**
 * AI の相談役の道具「組を均等に分ける」の検査。
 *
 *   npm test
 *
 * 10/17 の本番で、AI が自分で組を考えて、人を勝手に外し・人数を数え違え・均等にならなかった。
 * 全員が入ること、外すと言われた人だけ外れること、組の見込みがそろうこと、余りの扱いを押さえる。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 組を均等に分ける, 組の大きさ } = require('../src/chatTeams');

const 人 = (name) => ({ id: name, name, grade: 1 });
const 射手 = (name, 印) => ({ id: 'a-' + name, name, memberId: name, marks: 印 });
// 一人ずつ、中り数 n を 20 射で持たせる
const 記録を作る = (成績, date = 1000) => [
  {
    date,
    archers: Object.entries(成績).map(([名, 中]) =>
      射手(
        名,
        Array.from({ length: 20 }, (無, 番) => (番 < 中 ? '○' : '×'))
      )
    ),
  },
];

test('組の大きさ：割り切れないときは 余り の指定どおり', () => {
  assert.deepEqual(組の大きさ(9, 3, '足す').大きさ, [3, 3, 3]);
  assert.deepEqual(組の大きさ(10, 3, '足す').大きさ, [4, 3, 3]);
  assert.deepEqual(組の大きさ(10, 3, '別に'), { 大きさ: [3, 3, 3], 余りの人数: 1 });
  assert.deepEqual(組の大きさ(10, 3, '少ない組').大きさ, [2, 2, 3, 3]);
  assert.deepEqual(組の大きさ(2, 3, '足す').大きさ, [2], '一組に満たないときは 1 組にまとめる');
});

test('全員を入れ、外すと言われた人だけ外す。人数を数え違えない', () => {
  const 名 = Array.from({ length: 29 }, (無, 番) => '部員' + (番 + 1));
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, (番 * 7) % 20]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3, 外す: ['部員1', '部員2'] });
  assert.equal(r.分けた人数, 27);
  assert.equal(r.組の数, 9);
  assert.deepEqual(r.外した人.sort(), ['部員1', '部員2']);
  const 入った = r.組.flatMap((組) => 組.部員.map((p) => p.名前));
  assert.equal(new Set(入った).size, 27, '同じ人が 2 回入らない');
  assert.ok(!入った.includes('部員1'));
});

test('組の見込みがそろう（蛇行と入れ替えで開きが小さい）', () => {
  const 名 = Array.from({ length: 12 }, (無, 番) => 'p' + 番);
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, [19, 18, 16, 15, 12, 11, 10, 8, 6, 5, 3, 1][番]]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3 });
  assert.equal(r.組の数, 4);
  assert.equal(r.組の人数の内訳, '3人の組 4');
  assert.ok(r.組の見込みの開き <= 3, `開きが大きい: ${r.組の見込みの開き}`);
});

test('組の人数の内訳：余りを 1 人少ない組にしたら、人数ごとに数を書く（模型が「3人ずつ5組」と言い違えないように）', () => {
  const 名 = Array.from({ length: 14 }, (無, 番) => 'p' + 番);
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, 5 + 番]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3, 余り: '少ない組' });
  assert.equal(r.組の人数の内訳, '3人の組 4・2人の組 1');
});

test('期間に記録が無い人は、期間の外の記録から見込み、そう書く', () => {
  const 記録たち = [...記録を作る({ 古株: 18 }, 100), ...記録を作る({ 甲: 10, 乙: 10, 丙: 10 }, 5000)];
  const r = 組を均等に分ける(['古株', '甲', '乙', '丙'].map(人), 記録たち, {
    一組の人数: 2,
    期間: { 始め: 1000, 終わり: 9999 },
  });
  const 古株 = r.組.flatMap((組) => 組.部員).find((p) => p.名前 === '古株');
  assert.equal(古株.期間の射数, 0);
  assert.ok(古株.見込みの的中率 > 50, '期間の外の 18/20 から高めに見込む');
  assert.ok(r.見積もった人.some((p) => p.名前 === '古株'));
});

test('見つからない名前・同じ名前が複数は、外さずにそのまま伝える', () => {
  const r = 組を均等に分ける([人('山田 太郎'), 人('山田 花子'), 人('佐藤')], 記録を作る({}), {
    一組の人数: 1,
    外す: ['山田', '鈴木'],
  });
  assert.deepEqual(r.見つからない名前, ['鈴木']);
  assert.equal(r.同じ名前が複数[0].名前, '山田');
  assert.equal(r.分けた人数, 3);
});

test('余り＝別に のときは、記録のいちばん少ない人を余りにする', () => {
  const r = 組を均等に分ける(['甲', '乙', '丙', '丁'].map(人), [...記録を作る({ 甲: 10, 乙: 10, 丙: 10 })], {
    一組の人数: 3,
    余り: '別に',
  });
  assert.deepEqual(r.余った人, ['丁']);
  assert.equal(r.分けた人数, 3);
});
