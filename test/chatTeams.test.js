/**
 * AI の相談役の道具「組を均等に分ける」の検査。
 *
 *   npm test
 *
 * 10/17 の本番で、AI が自分で組を考えて、人を勝手に外し・人数を数え違え・均等にならなかった。
 * 全員が入ること、外すと言われた人だけ外れること、組の見込みがそろうこと、余りの扱いを押さえる。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 組を均等に分ける, 組の大きさ } = require('../src/chatTeams');

const 人 = (name) => ({ id: name, name, grade: 1 });
const 射手 = (name, 印) => ({ id: 'a-' + name, name, memberId: name, marks: 印 });
// 一人ずつ、中り数 n を 20 射で持たせる
const 記録を作る = (成績, date = 1000) => [
  {
    date,
    archers: Object.entries(成績).map(([名, 中]) =>
      射手(
        名,
        Array.from({ length: 20 }, (無, 番) => (番 < 中 ? '○' : '×'))
      )
    ),
  },
];

test('組の大きさ：割り切れないときは 余り の指定どおり', () => {
  assert.deepEqual(組の大きさ(9, 3, '足す').大きさ, [3, 3, 3]);
  assert.deepEqual(組の大きさ(10, 3, '足す').大きさ, [4, 3, 3]);
  assert.deepEqual(組の大きさ(10, 3, '別に'), { 大きさ: [3, 3, 3], 余りの人数: 1 });
  assert.deepEqual(組の大きさ(10, 3, '少ない組').大きさ, [2, 2, 3, 3]);
  assert.deepEqual(組の大きさ(2, 3, '足す').大きさ, [2], '一組に満たないときは 1 組にまとめる');
});

test('全員を入れ、外すと言われた人だけ外す。人数を数え違えない', () => {
  const 名 = Array.from({ length: 29 }, (無, 番) => '部員' + (番 + 1));
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, (番 * 7) % 20]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3, 外す: ['部員1', '部員2'] });
  assert.equal(r.分けた人数, 27);
  assert.equal(r.組の数, 9);
  assert.deepEqual(r.外した人.sort(), ['部員1', '部員2']);
  const 入った = r.組.flatMap((組) => 組.部員.map((p) => p.名前));
  assert.equal(new Set(入った).size, 27, '同じ人が 2 回入らない');
  assert.ok(!入った.includes('部員1'));
});

test('組の見込みがそろう（蛇行と入れ替えで開きが小さい）', () => {
  const 名 = Array.from({ length: 12 }, (無, 番) => 'p' + 番);
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, [19, 18, 16, 15, 12, 11, 10, 8, 6, 5, 3, 1][番]]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3 });
  assert.equal(r.組の数, 4);
  assert.equal(r.組の人数の内訳, '3人の組 4');
  assert.ok(r.組の見込みの開き <= 3, `開きが大きい: ${r.組の見込みの開き}`);
});

test('組の人数の内訳：余りを 1 人少ない組にしたら、人数ごとに数を書く（模型が「3人ずつ5組」と言い違えないように）', () => {
  const 名 = Array.from({ length: 14 }, (無, 番) => 'p' + 番);
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, 5 + 番]));
  const r = 組を均等に分ける(名.map(人), 記録を作る(成績), { 一組の人数: 3, 余り: '少ない組' });
  assert.equal(r.組の人数の内訳, '3人の組 4・2人の組 1');
});

test('期間に記録が無い人は、期間の外の記録から見込み、そう書く', () => {
  const 記録たち = [...記録を作る({ 古株: 18 }, 100), ...記録を作る({ 甲: 10, 乙: 10, 丙: 10 }, 5000)];
  const r = 組を均等に分ける(['古株', '甲', '乙', '丙'].map(人), 記録たち, {
    一組の人数: 2,
    期間: { 始め: 1000, 終わり: 9999 },
  });
  const 古株 = r.組.flatMap((組) => 組.部員).find((p) => p.名前 === '古株');
  assert.equal(古株.期間の射数, 0);
  assert.ok(古株.見込みの的中率 > 50, '期間の外の 18/20 から高めに見込む');
  assert.ok(r.見積もった人.some((p) => p.名前 === '古株'));
});

test('見つからない名前・同じ名前が複数は、外さずにそのまま伝える', () => {
  const r = 組を均等に分ける([人('山田 太郎'), 人('山田 花子'), 人('佐藤')], 記録を作る({}), {
    一組の人数: 1,
    外す: ['山田', '鈴木'],
  });
  assert.deepEqual(r.見つからない名前, ['鈴木']);
  assert.equal(r.同じ名前が複数[0].名前, '山田');
  assert.equal(r.分けた人数, 3);
});

test('余り＝別に のときは、記録のいちばん少ない人を余りにする', () => {
  const r = 組を均等に分ける(['甲', '乙', '丙', '丁'].map(人), [...記録を作る({ 甲: 10, 乙: 10, 丙: 10 })], {
    一組の人数: 3,
    余り: '別に',
  });
  assert.deepEqual(r.余った人, ['丁']);
  assert.equal(r.分けた人数, 3);
});

// ── 2026-10-25：均等だけでなく（本人「一番的中の出るチームを組むとかもっと色々」）
const { 組を作る } = require('../src/chatTeams');
const 十二人 = Array.from({ length: 12 }, (無, 番) => 'p' + 番);
// p0 が いちばん当たり、p11 が いちばん当たらない
const 十二人の成績 = Object.fromEntries(十二人.map((n, 番) => [n, 19 - 番]));
const 顔ぶれ = (組) => 組.部員.map((人) => 人.名前).sort();

test('強い順：見込みの高い人から 1 組目・2 組目…と組む', () => {
  const r = 組を作る(十二人.map(人), 記録を作る(十二人の成績), { 一組の人数: 3, 目的: '強い順' });
  assert.equal(r.目的, '強い順');
  assert.deepEqual(顔ぶれ(r.組[0]), ['p0', 'p1', 'p2']);
  assert.deepEqual(顔ぶれ(r.組[3]), ['p10', 'p11', 'p9']);
  assert.ok(r.組[0].見込みの的中率 > r.組[1].見込みの的中率);
});

test('組の数：最強の 1 組だけ。必ず入れる人は先に入れ、残りは見込みの高い人から。選ばなかった人を返す', () => {
  const r = 組を作る(十二人.map(人), 記録を作る(十二人の成績), {
    一組の人数: 3,
    目的: '強い順',
    組の数: 1,
    必ず入れる: ['p11'],
  });
  assert.equal(r.組の数, 1);
  assert.deepEqual(顔ぶれ(r.組[0]), ['p0', 'p1', 'p11']);
  assert.equal(r.選ばなかった人.length, 9);
  assert.equal(r.選ばなかった人[0].名前, 'p2', '見込みの高い順');
  // 均等でも組の数を指定できる（見込みの高い 6 人を 2 組にそろえる）
  const 均 = 組を作る(十二人.map(人), 記録を作る(十二人の成績), { 一組の人数: 3, 組の数: 2 });
  assert.deepEqual(均.組.flatMap(顔ぶれ).sort(), ['p0', 'p1', 'p2', 'p3', 'p4', 'p5']);
});

test('だけ・同じ組・別の組：決まりを守って均等に組む。守れないときは 守れなかった決まり', () => {
  const r = 組を作る(十二人.map(人), 記録を作る(十二人の成績), {
    一組の人数: 3,
    同じ組: [['p0', 'p1']],
    別の組: [['p10', 'p11']],
  });
  const 組の番 = (名) => r.組.findIndex((組) => 組.部員.some((人) => 人.名前 === 名));
  assert.equal(組の番('p0'), 組の番('p1'), 'p0 と p1 は同じ組');
  assert.notEqual(組の番('p10'), 組の番('p11'), 'p10 と p11 は別の組');
  assert.deepEqual(r.守れなかった決まり, []);
  // 4 人を同じ 3 人の組には入れられない
  const 無理 = 組を作る(十二人.map(人), 記録を作る(十二人の成績), {
    一組の人数: 3,
    同じ組: [['p0', 'p1', 'p2', 'p3']],
  });
  assert.equal(無理.守れなかった決まり.length, 1);
  const だけ = 組を作る(十二人.map(人), 記録を作る(十二人の成績), {
    一組の人数: 2,
    だけ: ['p0', 'p1', 'p2', 'p3'],
  });
  assert.equal(だけ.分けた人数, 4);
  assert.deepEqual(だけ.この人たちだけで組んだ.sort(), ['p0', 'p1', 'p2', 'p3']);
});

test('散らす：各組に男女と学年を散らす。組ごとの内訳を返す', () => {
  // 男子 6 人は強く、女子 6 人は弱い。散らさないと見込みだけでそろえる
  const 部員 = 十二人.map((n, 番) => ({
    id: n,
    name: n,
    grade: (番 % 3) + 1,
    gender: 番 < 6 ? '男子' : '女子',
  }));
  const r = 組を作る(部員, 記録を作る(十二人の成績), { 一組の人数: 4, 散らす: ['性別', '学年'] });
  for (const 組 of r.組) {
    assert.deepEqual(組.男女の内訳, { 男子: 2, 女子: 2 }, `組${組.組}の男女`);
    assert.ok(
      Object.values(組.学年の内訳).every((数) => 数 <= 2),
      `組${組.組}の学年が偏る`
    );
  }
  assert.deepEqual(r.散らした, ['性別', '学年']);
});

test('強い順では、同じ組・別の組・散らすは見ないと返す', () => {
  const r = 組を作る(十二人.map(人), 記録を作る(十二人の成績), {
    一組の人数: 3,
    目的: '強い順',
    同じ組: [['p0', 'p11']],
  });
  assert.ok(r.守れなかった決まり.some((x) => /強い順では/.test(x)));
});

test('168 人でも 2 秒以内に組める（入れ替えは差分で比べる）', () => {
  const 名 = Array.from({ length: 168 }, (無, 番) => 'm' + 番);
  const 成績 = Object.fromEntries(名.map((n, 番) => [n, (番 * 7) % 20]));
  const 部員 = 名.map((n, 番) => ({ id: n, name: n, grade: (番 % 4) + 1, gender: 番 % 2 ? '男子' : '女子' }));
  const 始め = Date.now();
  const r = 組を作る(部員, 記録を作る(成績), { 一組の人数: 6, 散らす: ['性別'] });
  assert.equal(r.組の数, 28);
  assert.ok(Date.now() - 始め < 2000, `${Date.now() - 始め}ms かかった`);
});
