/**
 * 射手の列の選び方（scripts/ocr-cells/kiridasu.mjs の 連なりで選ぶ）。
 * 板の端の字の列が、隣の薄い射手の列に点でわずかに勝っても、穴のない連なりを選ぶ。
 */
const test = require('node:test');
const assert = require('node:assert');

const 列 = (中心, 点) => ({ 列: { 中心 }, 点 });

test('学校名の字の列（丸さ 1.0）が薄い射手の列に 0.01 勝っても、穴のない 4 列を選ぶ', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  // 9/13 の板の右半分の形：松元・川合（薄い）・小中・荒井・字の列。川合 0.74、字の列 0.75
  const 点数つき = [列(164, 0.52), 列(409, 0.85), 列(642, 0.74), 列(869, 1.0), 列(1078, 0.98), 列(1314, 0.75)];
  const 選び = 連なりで選ぶ(点数つき, 4, [点数つき[1], 点数つき[3], 点数つき[4]]);
  assert.deepStrictEqual(選び.map((c) => c.中心), [409, 642, 869, 1078]);
});

test('点が大きく離れた列は、穴があっても点の高い順（これまでの選び方のまま）', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  // 川合の列が空に近い（0.35）。字の列 0.9 が穴の先でも、点の和が大きく勝つ側を取る
  const 点数つき = [列(409, 1.0), 列(642, 0.35), 列(869, 1.0), 列(1078, 1.0), 列(1314, 0.9)];
  const 選び = 連なりで選ぶ(点数つき, 4);
  assert.deepStrictEqual(選び.map((c) => c.中心), [409, 869, 1078, 1314]);
});

test('連なりで選ぶ：4 人以下の板は穴を空けない。端の射手の列（点が低い）を落として、穴の先の合計の列を取らない', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  // 10/4 の日大工科の途中の板（左の 4 人）。41 が左端の射手（印が小さく 0.71）、430 は合計の列（2 桁の数字が丸く見えて 0.94）
  const 点たち = [[41, 0.71], [119, 1.5], [200, 1.5], [282, 1.13], [324, 0.45], [362, 0.52], [395, 0.45], [430, 0.94], [459, 0.87]].map(
    ([x, p]) => ({ 列: { 中心: x }, 点: p })
  );
  const 強い = [点たち[1], 点たち[2], 点たち[3], 点たち[7]]; // 合計の列も「強い列」に入る
  const 穴なし = 連なりで選ぶ(点たち, 4, 強い, false).map((c) => c.中心);
  assert.deepStrictEqual(穴なし, [41, 119, 200, 282]);
});

test('連なりで選ぶ：穴を許すときも、穴 1 つごとに点を 0.25 引いて比べる', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  const 点たち = [[41, 0.71], [119, 1.5], [200, 1.5], [282, 1.13], [362, 0.52], [430, 0.94]].map(([x, p]) => ({ 列: { 中心: x }, 点: p }));
  // 穴なし 41・119・200・282（4.84）と、穴 1 つの 119・200・282・430（5.07 − 0.25 = 4.82）。同点の範囲なので穴の少ないほう
  assert.deepStrictEqual(連なりで選ぶ(点たち, 4).map((c) => c.中心), [41, 119, 200, 282]);
});
