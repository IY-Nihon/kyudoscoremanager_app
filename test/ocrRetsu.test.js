/**
 * 射手の列の選び方（scripts/ocr-cells/kiridasu.mjs の 連なりで選ぶ）。
 * 板の端の字の列が、隣の薄い射手の列に点でわずかに勝っても、穴のない連なりを選ぶ。
 */
const test = require('node:test');
const assert = require('node:assert');

const 列 = (中心, 点) => ({ 列: { 中心 }, 点 });

test('学校名の字の列（丸さ 1.0）が薄い射手の列に 0.01 勝っても、穴のない 4 列を選ぶ', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  // 9/13 の板の右半分の形：松元・川合（薄い）・小中・荒井・字の列。川合 0.74、字の列 0.75
  const 点数つき = [列(164, 0.52), 列(409, 0.85), 列(642, 0.74), 列(869, 1.0), 列(1078, 0.98), 列(1314, 0.75)];
  const 選び = 連なりで選ぶ(点数つき, 4, [点数つき[1], 点数つき[3], 点数つき[4]]);
  assert.deepStrictEqual(選び.map((c) => c.中心), [409, 642, 869, 1078]);
});

test('点が大きく離れた列は、穴があっても点の高い順（これまでの選び方のまま）', async () => {
  const { 連なりで選ぶ } = await import('../scripts/ocr-cells/kiridasu.mjs');
  // 川合の列が空に近い（0.35）。字の列 0.9 が穴の先でも、点の和が大きく勝つ側を取る
  const 点数つき = [列(409, 1.0), 列(642, 0.35), 列(869, 1.0), 列(1078, 1.0), 列(1314, 0.9)];
  const 選び = 連なりで選ぶ(点数つき, 4);
  assert.deepStrictEqual(選び.map((c) => c.中心), [409, 869, 1078, 1314]);
});
