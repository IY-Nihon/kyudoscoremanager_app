/**
 * 立の番号の札で、空きごとの組を立にまとめる（src/ocrTachiFuda.js）。名前は架空。
 */
const test = require('node:test');
const assert = require('node:assert');
const { 札で立にまとめる, 札の番号 } = require('../src/ocrTachiFuda');

const 組 = (fuda, row, n, 頭) => ({ fuda, row, seats: Array.from({ length: n }, (_, i) => `${頭}${i + 1}`) });
const 人数 = (立たち) => 立たち.map((x) => x.seats.length).join('+');

test('札の字から番号を取る', () => {
  assert.strictEqual(札の番号('壱'), 1);
  assert.strictEqual(札の番号('弐之立'), 2);
  assert.strictEqual(札の番号('参'), 3);
  assert.strictEqual(札の番号('四'), 4);
  assert.strictEqual(札の番号('3立'), 3);
  assert.strictEqual(札の番号(''), null);
  assert.strictEqual(札の番号('A立'), null);
});

test('札の番号：十一〜九十九の漢数字・丸数字・全角の数字も読む', () => {
  // 前は最初の 1 字だけを見ていて、「二十」を 2、「十二」を 10 と読んでいた
  assert.strictEqual(札の番号('十'), 10);
  assert.strictEqual(札の番号('十一'), 11);
  assert.strictEqual(札の番号('第十一立'), 11);
  assert.strictEqual(札の番号('十二'), 12);
  assert.strictEqual(札の番号('二十'), 20);
  assert.strictEqual(札の番号('二十三'), 23);
  assert.strictEqual(札の番号('九十九'), 99);
  assert.strictEqual(札の番号('壱拾弐'), 12);
  assert.strictEqual(札の番号('①'), 1);
  assert.strictEqual(札の番号('⑳'), 20);
  assert.strictEqual(札の番号('㉑'), 21);
  assert.strictEqual(札の番号('㊿'), 50);
  assert.strictEqual(札の番号('❸'), 3);
  assert.strictEqual(札の番号('１２'), 12);
  assert.strictEqual(札の番号('３立'), 3);
  // 数でない字は数にしない（「質」を 7 と読む案があったが、札に書く字ではない）
  assert.strictEqual(札の番号('質'), null);
});

test('札が無ければ組をそのまま立にする', () => {
  assert.strictEqual(人数(札で立にまとめる([{ seats: ['a', 'b'] }, { seats: ['c'] }])), '2+1');
});

test('札1枚に組2つ・上下2段で、札の番号の順に並べる（10/19 の板の形）', () => {
  // 上の段：参（6）＋札なし（5）、四（5）。下の段：壱（6）＋札なし（6）、弐（6）＋札なし（6）
  const 立たち = 札で立にまとめる([
    組('参', 1, 6, 'あ'),
    組('', 1, 5, 'い'),
    組('四', 1, 5, 'う'),
    組('壱', 2, 6, 'え'),
    組('', 2, 6, 'お'),
    組('弐', 2, 6, 'か'),
    組('', 2, 6, 'き'),
  ]);
  assert.strictEqual(人数(立たち), '12+12+11+5');
  assert.strictEqual(立たち[0].seats[0], 'え1');
  assert.strictEqual(立たち[0].seats[6], 'お1');
});

test('段の頭の札の無い組は、写っていない札の立として先に置く（10/17 の板の形）', () => {
  const 立たち = 札で立にまとめる([
    組('', 1, 6, 'あ'),
    組('', 1, 6, 'い'),
    組('弐', 1, 6, 'う'),
    組('', 1, 5, 'え'),
  ]);
  assert.strictEqual(人数(立たち), '12+11');
});

test('札の無い組は、別の段の立には入れない', () => {
  assert.strictEqual(人数(札で立にまとめる([組('壱', 1, 3, 'あ'), 組('', 2, 4, 'い')])), '4+3');
});

// 11/20 から：札は組に付けず、札だけの項目（seats が []）として並びの中の札の位置に出させる
const 札 = (fuda, row) => ({ fuda, row, seats: [] });

test('札だけの項目：札のあとに続く組をその札の立にまとめる（11/6 の板：札が両隣の組に接していた）', () => {
  // 壱・組 8・組 4・弐・組 7・組 4。札を組に付けさせていたころは、弐を落の側の組（4 人）に付けて 8+15 になった
  const 立たち = 札で立にまとめる([
    札('壱', 1),
    組('', 1, 8, 'あ'),
    組('', 1, 4, 'い'),
    札('弐', 1),
    組('', 1, 7, 'う'),
    組('', 1, 4, 'え'),
  ]);
  assert.strictEqual(人数(立たち), '12+11');
  assert.strictEqual(立たち[0].seats[8], 'い1');
  assert.strictEqual(立たち[1].seats[0], 'う1');
});

test('札だけの項目：上下 2 段・札の前の手書きの 1 人は前の立の終わりに入る（11/16 の板）', () => {
  // 上の段：参・組 4・組 2。下の段：壱・組 3・3・2・2・手書きの 1 人・弐・組 3・3・3
  const 立たち = 札で立にまとめる([
    札('参', 1),
    組('', 1, 4, 'あ'),
    組('', 1, 2, 'い'),
    札('壱', 2),
    組('', 2, 3, 'う'),
    組('', 2, 3, 'え'),
    組('', 2, 2, 'お'),
    組('', 2, 2, 'か'),
    組('', 2, 1, 'き'),
    札('弐', 2),
    組('', 2, 3, 'く'),
    組('', 2, 3, 'け'),
    組('', 2, 3, 'こ'),
  ]);
  assert.strictEqual(人数(立たち), '11+9+6');
  assert.strictEqual(立たち[0].seats[10], 'き1');
  assert.strictEqual(立たち[1].seats[0], 'く1');
});

test('札だけの項目：格子の板（行ごとに 壱之立…）。人のいない立は返さない', () => {
  const 立たち = 札で立にまとめる([
    札('壱之立', 1),
    { fuda: '', row: 1, seats: ['あ', 'い', 'う', 'え', '', ''] },
    札('弐之立', 2),
    { fuda: '', row: 2, seats: ['お', 'か', 'き', '', '', ''] },
    札('参之立', 3),
    { fuda: '', row: 3, seats: ['く', 'け', 'こ', '', '', ''] },
    札('四之立', 4),
    // 名札の無い行を空欄だけの組として出してくることがある（11/20 に別の団体の板で）
    { fuda: '', row: 4, seats: ['', '', '', '', '', ''] },
  ]);
  assert.strictEqual(人数(立たち), '6+6+6');
  assert.deepStrictEqual(
    立たち.map((x) => x.seats[0]),
    ['あ', 'お', 'く']
  );
});

test('札の付いた組（前の形）と札だけの項目が混ざっても同じにまとまる', () => {
  const 立たち = 札で立にまとめる([
    組('壱', 1, 3, 'あ'),
    組('', 1, 2, 'い'),
    札('弐', 1),
    組('', 1, 3, 'う'),
  ]);
  assert.strictEqual(人数(立たち), '5+3');
});

test('札だけで人のいない答え・空の組は立にしない（読めなかったと出す）', () => {
  assert.deepStrictEqual(札で立にまとめる([札('壱', 1), 札('弐', 1)]), []);
  assert.deepStrictEqual(札で立にまとめる([{ fuda: '', seats: [] }]), []);
  assert.deepStrictEqual(札で立にまとめる([{ seats: ['', ' '] }]), []);
  // 名前が 1 つでもあれば、空欄は位置として残す
  assert.deepStrictEqual(札で立にまとめる([{ seats: ['', 'a', ''] }]), [{ seats: ['', 'a', ''] }]);
  assert.strictEqual(人数(札で立にまとめる([{ seats: [] }, { seats: ['a'] }])), '1');
});

test('札を組の後ろに並べて答えた段は、札をすぐ前の組に付ける（10/26 のノートの写真。組で始まり札で終わる段だけ）', () => {
  const 立たち = 札で立にまとめる([組('', 1, 4, 'あ'), 札('壱之立', 1), 組('', 1, 4, 'い'), 札('弐之立', 1)]);
  assert.strictEqual(人数(立たち), '4+4');
  assert.strictEqual(立たち[0].seats[0], 'あ1');
  assert.strictEqual(立たち[1].seats[0], 'い1');
  // 札で始まる段は前のとおり（最後の札は人がいないので立にしない）
  assert.strictEqual(人数(札で立にまとめる([札('壱', 1), 組('', 1, 3, 'あ'), 札('弐', 1)])), '3');
  // 札の見えない組で始まり組で終わる段（11/7 の板）も前のとおり
  const 前の形 = 札で立にまとめる([
    組('', 1, 6, 'あ'),
    組('', 1, 5, 'い'),
    札('弐', 1),
    組('', 1, 7, 'う'),
    組('', 1, 4, 'え'),
  ]);
  assert.strictEqual(人数(前の形), '11+11');
});
