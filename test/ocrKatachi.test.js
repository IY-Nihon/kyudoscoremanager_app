  const 画 = 白いマス(幅, 高);
  丸をかく(画, 幅, 高, 75, 80, 67, 6, 120);
  線をひく(画, 幅, 高, 30, 130, 120, 30, 3, 30);
  const 形 = await 形にする(画, 幅, 高);
