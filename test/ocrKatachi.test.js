/**
 * マスの切り抜きを網に渡す形にそろえる（scripts/ocr-cells/manabu.mjs の 形にする）。
 * 描いたマスで、囲み直しの決まりを確かめる。
 */
const test = require('node:test');
const assert = require('node:assert');

/** 白いマス（幅×高、明るさ 230）に、丸と線を描く道具 */
function 白いマス(幅, 高) {
  return new Uint8Array(幅 * 高).fill(230);
}
function 丸をかく(画, 幅, 高, cx, cy, 半径, 太さ, 明るさ, 抜く) {
  for (let y = 0; y < 高; y++) {
    for (let x = 0; x < 幅; x++) {
      const r = Math.hypot(x - cx, y - cy);
      if (Math.abs(r - 半径) > 太さ / 2) continue;
      // 抜く … 輪のこの角度の範囲（ラジアン）を描かない（照り返しで切れた輪）
      const 角 = Math.atan2(y - cy, x - cx);
      if (抜く && 抜く.some(([a, b]) => 角 >= a && 角 <= b)) continue;
      画[y * 幅 + x] = 明るさ;
    }
  }
}
function 線をひく(画, 幅, 高, x1, y1, x2, y2, 太さ, 明るさ) {
  const 長さ = Math.hypot(x2 - x1, y2 - y1);
  for (let t = 0; t <= 長さ; t += 0.5) {
    const px = x1 + ((x2 - x1) * t) / 長さ;
    const py = y1 + ((y2 - y1) * t) / 長さ;
    for (let dy = -太さ; dy <= 太さ; dy++) {
      for (let dx = -太さ; dx <= 太さ; dx++) {
        const x = Math.round(px + dx), y = Math.round(py + dy);
        if (x >= 0 && x < 幅 && y >= 0 && y < 高 && Math.hypot(dx, dy) <= 太さ / 2) 画[y * 幅 + x] = Math.min(画[y * 幅 + x], 明るさ);
      }
    }
  }
}

/** 20×20 の形の、右端の列と下端の行の真ん中あたり（8〜11）の墨の最大 */
function 端の墨(形, 辺) {
  let 右端 = 0, 下端 = 0;
  for (let i = 8; i <= 11; i++) {
    右端 = Math.max(右端, 形[i * 辺 + 辺 - 1]);
    下端 = Math.max(下端, 形[(辺 - 1) * 辺 + i]);
  }
  return { 右端, 下端 };
}

test('照り返しで 2 つに割れた輪は、隙間が小さければ 1 つの印として囲む', async () => {
  const { 形にする, 辺 } = await import('../scripts/ocr-cells/manabu.mjs');
  // 200×220 のマスに、半径 60 の輪。右上と左下で 2px ほど切れている（9/13 の板 B、大前の 8 段目）
  const 幅 = 200, 高 = 220;
  const 画 = 白いマス(幅, 高);
  const 切れ = 0.05; // 半径 60 × 0.05 rad × 2 ≒ 6px の切れ目（隙間の縛り 3% ＝ 6px の内）
  丸をかく(画, 幅, 高, 100, 110, 60, 7, 60, [[-Math.PI / 4 - 切れ, -Math.PI / 4 + 切れ], [(3 * Math.PI) / 4 - 切れ, (3 * Math.PI) / 4 + 切れ]]);
  // 細く薄い ＼ の線（別のペン。墨の境より薄いので、かたまりの橋にはならない）
  線をひく(画, 幅, 高, 45, 55, 160, 170, 2, 180);
  const 形 = await 形にする(画, 幅, 高);
  // 輪ぜんぶを囲めば、20×20 の右端の列と下端の行の真ん中に輪が触れる。
  // 上左の半分だけを囲むと、右端の真ん中と下端の真ん中は輪の内側（白）になる
  const { 右端, 下端 } = 端の墨(形, 辺);
  assert.ok(右端 >= 0.5, `右端の真ん中に輪が無い（${右端.toFixed(2)}）：輪の右半分を落としている`);
  assert.ok(下端 >= 0.5, `下端の真ん中に輪が無い（${下端.toFixed(2)}）：輪の下半分を落としている`);
});

test('隣のマスの印のかけら（切り抜きの縁に触れている）は、近くても囲みに入れない', async () => {
  const { 形にする, 辺 } = await import('../scripts/ocr-cells/manabu.mjs');
  const 幅 = 200, 高 = 220;
  const 画 = 白いマス(幅, 高);
  // 真ん中の丸（半径 50、閉じている）
  丸をかく(画, 幅, 高, 100, 120, 50, 7, 60);
  // 上の縁に、隣のマスの丸の底（中心はマスの外）。丸の上端（y=66.5）から 4px しか離れていない
  丸をかく(画, 幅, 高, 100, 9, 50, 7, 60);
  const 形 = await 形にする(画, 幅, 高);
  // 囲みが丸だけなら、20×20 の上端の行は輪の上の弧（真ん中だけ墨）。隣の弧まで入れると
  // 縦に伸びて上端が墨の帯になる。上端の行の両端が白いことで見分ける
  const 上の行の端 = 形[0] + 形[1] + 形[辺 - 2] + 形[辺 - 1];
  assert.ok(上の行の端 < 1, `上端の両端に墨がある（${上の行の端.toFixed(2)}）：隣のマスの印まで囲んでいる`);
});

