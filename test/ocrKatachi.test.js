test('輪が罫線と下の段の印に薄くつながって箱いっぱいになるとき：境を締めて拾い直し、輪だけを囲む', async () => {
  const { 形にする, 辺 } = await import('../scripts/ocr-cells/manabu.mjs');
  // 160×200 のマス。真ん中に ○＼（輪は黒 30）。左の縦の罫線（高さの 85%。9 割未満なので罫線消しに掛からない）と
  // 下の段の印の上の弧が、薄い橋（150）で輪につながっている。暗いほうから 1% の境（≒170）だと
  // 橋も墨に入って 1 つの箱いっぱいのかたまりになり、いちばん暗い点から測った境（≒160）なら切れる
  const 幅 = 160, 高 = 200;
  const 画 = 白いマス(幅, 高);
  丸をかく(画, 幅, 高, 85, 90, 45, 6, 30);
  線をひく(画, 幅, 高, 55, 55, 118, 128, 2, 30); // ＼
  線をひく(画, 幅, 高, 2, 12, 2, 182, 2, 30); // 左の罫線
  丸をかく(画, 幅, 高, 97, 240, 75, 6, 30); // 下の段の印の上の弧（中心はマスの外。右へ寄せて、囲みの右辺の真ん中に輪が来ないように）
  線をひく(画, 幅, 高, 40, 90, 3, 90, 1, 150); // 輪 → 罫線 の薄い橋
  線をひく(画, 幅, 高, 85, 135, 85, 181, 1, 150); // 輪 → 下の弧 の薄い橋
  for (let i = 0; i < 12; i++) 画[(20 + i) * 幅 + 150] = 0; // いちばん暗い点（1% の点より暗い）
  const 形 = await 形にする(画, 幅, 高);
  // 輪だけを囲めば、上端の行の真ん中に弧があり、両端は白い。下の段の弧まで囲むと縦に伸びて
  // 真ん中の輪が上に寄る（上端の真ん中は輪、下端は弧）。罫線まで囲むと左端が上から下まで縦の帯になる
  //（輪だけなら左端の墨は輪の左の弧のぶん、8 行ほど）
  let 上の真ん中 = 0, 左の帯 = 0;
  for (let i = 8; i <= 11; i++) 上の真ん中 = Math.max(上の真ん中, 形[i]);
  for (let y = 0; y < 辺; y++) 左の帯 += 形[y * 辺] > 0.5 ? 1 : 0;
  assert.ok(上の真ん中 >= 0.5, `上端の真ん中に輪が無い（${上の真ん中.toFixed(2)}）：輪を外して下の弧を主にしている`);
  assert.ok(左の帯 <= 12, `左端が縦の帯（${左の帯} 行）：罫線まで囲んでいる`);
  assert.ok(端の墨(形, 辺).右端 >= 0.5, `右端の真ん中に輪が無い（${端の墨(形, 辺).右端.toFixed(2)}）：囲みが横に伸びている`);
});

test('印が箱いっぱいの板でも、縁に沿って走る L 字（罫線）は触れかけでも囲みに入れない', async () => {
  const { 形にする, 辺 } = await import('../scripts/ocr-cells/manabu.mjs');
  // 158×202 のマス（WebKit の切り抜き）。小さな ×（幅 90）と、右端の縦線と下端の横線の L 字
  const 幅 = 158, 高 = 202;
  const 画 = 白いマス(幅, 高);
  線をひく(画, 幅, 高, 30, 55, 120, 145, 3, 40);
  線をひく(画, 幅, 高, 120, 55, 30, 145, 3, 40);
  線をひく(画, 幅, 高, 157, 70, 157, 201, 2, 60); // 右の罫線（高さの 6 割。罫線消しには掛からない）
  線をひく(画, 幅, 高, 95, 201, 157, 201, 2, 60); // 下の罫線のかけら
  線をひく(画, 幅, 高, 120, 145, 153, 160, 2, 150); // × の端 → 縦線 の薄いつながり（触れかけ）
  // 印の幅が箱の 85% 以上（印が箱いっぱいの板）として渡す
  const 形 = await 形にする(画, 幅, 高, undefined, { 印の幅: 135 });
  // × だけを囲めば、右端の列と下端の行に墨の帯は無い
  let 右の帯 = 0, 下の帯 = 0;
  for (let i = 0; i < 辺; i++) {
    右の帯 += 形[i * 辺 + 辺 - 1] > 0.4 ? 1 : 0;
    下の帯 += 形[(辺 - 1) * 辺 + i] > 0.4 ? 1 : 0;
  }
  assert.ok(右の帯 <= 4 && 下の帯 <= 4, `罫線の L 字まで囲んでいる（右 ${右の帯} 下 ${下の帯}）`);
});

