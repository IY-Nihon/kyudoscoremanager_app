/**
 * チャットボットの質問例の検査。
 *
 *   npm test
 *
 * 例に出したことは、道具で答えられなければならない。答えられない例を
 * 出すと、一度外れただけで使われなくなる。ここでは「その団体の中身に
 * 合った例だけを出すこと」を押さえる。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 質問例, 打ちかけの候補, 分類ごと } = require('../src/chatSuggestions');

const 記録 = (o) => Object.assign({ date: Date.now(), archers: [] }, o);
const 文たち = (例) => 例.map((x) => x.文);

test('記録がまだ無い団体には、成績の例を出さない', () => {
  // 出しても必ず空振りする。使い方の案内に寄せる
  const 例 = 質問例({ 人たち: [{ name: '山田' }], 記録たち: [] });
  assert.ok(!文たち(例).some((x) => x.includes('的中率')), '記録が無いのに的中率を勧めている');
  assert.ok(文たち(例).some((x) => x.includes('記録の付け方')), '使い方の案内が無い');
});

test('出欠を付けた記録が無ければ、出欠の例を出さない', () => {
  const 例 = 質問例({ 人たち: [{ name: '山田' }], 記録たち: [記録({ archers: [{ name: '山田', marks: ['○'] }] })] });
  assert.ok(!文たち(例).some((x) => x.includes('練習に来ている')), '出欠が無いのに勧めている');
});

test('出欠を付けた記録があれば、出欠の例を出す', () => {
  const 例 = 質問例({
    人たち: [{ name: '山田' }],
    記録たち: [記録({ archers: [{ name: '山田', marks: ['○'] }], attendance: { m1: 'present' } })],
  });
  assert.ok(文たち(例).some((x) => x.includes('練習に来ている')));
});

test('名前の例は、いちばん新しい記録に出ている人から採る', () => {
  // 部員一覧の先頭だと、辞めた人や名簿の並び順が出てしまう
  const 例 = 質問例({
    人たち: [{ name: '名簿の先頭' }],
    記録たち: [
      記録({ date: 1000, archers: [{ name: '古い人', marks: ['○'] }] }),
      記録({ date: 9000, archers: [{ name: '最近の人', marks: ['○'] }] }),
    ],
  });
  assert.ok(文たち(例).some((x) => x.includes('最近の人')), '最近の人が使われていない');
  assert.ok(!文たち(例).some((x) => x.includes('名簿の先頭')), '名簿の先頭が出ている');
});

test('区切りや合計の列は、名前の例に使わない', () => {
  const 例 = 質問例({
    人たち: [],
    記録たち: [記録({ archers: [{ isSeparator: true, name: '区切り' }, { name: '本物', marks: ['○'] }] })],
  });
  assert.ok(!文たち(例).some((x) => x.includes('区切り')));
  assert.ok(文たち(例).some((x) => x.includes('本物')));
});

test('今月の表記は、渡した日付に従う', () => {
  const 例 = 質問例({
    人たち: [{ name: '山田' }],
    記録たち: [記録({ archers: [{ name: '山田', marks: ['○'] }] })],
    いま: new Date('2026-05-15'),
  });
  assert.ok(文たち(例).some((x) => x.includes('2026年5月')), '今月が反映されていない');
});

test('人も記録も無くても落ちない', () => {
  const 例 = 質問例({});
  assert.ok(例.length > 0, '何も出せないと入口が空になる');
});

test('打ちかけの言葉で候補を絞る', () => {
  const 例 = [
    { 分類: '成績', 文: '大前に向いているのは誰？' },
    { 分類: '出欠', 文: '欠席が多いのは誰？' },
    { 分類: '成績', 文: '団体全体の的中率は？' },
  ];
  const r = 打ちかけの候補('大前', 例);
  assert.equal(r.length, 1);
  assert.equal(r[0].文, '大前に向いているのは誰？');
});

test('打ちかけ：前の方で当たるものを先に出す', () => {
  const 例 = [
    { 分類: 'a', 文: '今月の誰かの話' },
    { 分類: 'b', 文: '誰かの話' },
  ];
  const r = 打ちかけの候補('誰', 例);
  assert.equal(r[0].文, '誰かの話', '前から当たる方が先');
});

test('打ちかけ：空のときは頭から出す。上限も効く', () => {
  const 例 = [1, 2, 3, 4, 5, 6].map((n) => ({ 分類: 'x', 文: '例' + n }));
  assert.equal(打ちかけの候補('', 例).length, 4, '既定は4件');
  assert.equal(打ちかけの候補('', 例, 2).length, 2);
});

test('打ちかけ：空白の有無は無視する', () => {
  const 例 = [{ 分類: 'a', 文: '大前 に 向いて いる のは 誰？' }];
  assert.equal(打ちかけの候補('大前に向いて', 例).length, 1);
});

test('分類ごとにまとめられる', () => {
  const r = 分類ごと([
    { 分類: '成績', 文: 'A' },
    { 分類: '出欠', 文: 'B' },
    { 分類: '成績', 文: 'C' },
  ]);
  assert.equal(r.length, 2);
  assert.deepEqual(r[0], { 分類: '成績', 文たち: ['A', 'C'] });
});

test('頼める操作（部員の追加・画面を開く）が質問例に出る', () => {
  const 例 = 質問例({ 人たち: [{ name: '山田' }], 記録たち: [記録({ archers: [{ name: '山田', marks: ['○'] }] })] });
  assert.ok(文たち(例).some((x) => x.includes('部員を追加')), '部員の追加が無い');
  const 全部 = 質問例({ 件数: Infinity });
  assert.ok(文たち(全部).some((x) => x.includes('画面を開いて')), '画面を開く例が無い');
});

// 個人ログイン（部員）には、本人の分だけで答えられる例を出す。
// 全員の成績・団体全体・出欠・部員の追加は、個人の道具では答えられない（src/chatPersonal.js）
test('個人ログイン：全員の成績・団体全体・出欠・部員の追加を勧める例は出さない', () => {
  const 記録たち = [
    記録({ archers: [{ name: '山田', marks: ['○'] }], attendance: { m1: 'present' } }),
  ];
  const 例 = 文たち(質問例({ 人たち: [{ name: '山田' }, { name: '佐藤' }], 記録たち, 個人: true }));
  const 団体の言い回したち = [
    'さんの最近の調子',
    '高い順',
    '団体全体',
    '部員を追加',
    '写真から記録を読み取る',
    '練習に来ている',
    '欠席が多い',
    '誰',
  ];
  for (const 団体の言い回し of 団体の言い回したち) {
    assert.ok(!例.some((x) => x.includes(団体の言い回し)), `個人に「${団体の言い回し}」を含む例が出ている`);
  }
  assert.ok(例.some((x) => x.includes('自分の')), '自分の成績を聞く例が無い');
  assert.ok(例.includes('分析の画面を開いて'), '画面を開く例が無い');
});

test('個人ログイン：人の名前を入れた例は出さない', () => {
  const 記録たち = [
    記録({
      archers: [
        { name: '山田', marks: ['○'] },
        { name: '佐藤', marks: ['×'] },
      ],
    }),
  ];
  const 例 = 文たち(質問例({ 人たち: [{ name: '山田' }, { name: '佐藤' }], 記録たち, 個人: true }));
  assert.ok(!例.some((x) => x.includes('山田') || x.includes('佐藤')), '名前が例に入っている');
});

test('個人ログイン：記録がまだ無いときは、成績・射位の例を出さず、使い方の例を出す', () => {
  const 例 = 質問例({ 人たち: [], 記録たち: [], 個人: true });
  assert.ok(!例.some((x) => x.分類 === '成績' || x.分類 === '射位' || x.分類 === '記録'), '記録が無いのに成績を勧めている');
  assert.ok(文たち(例).some((x) => x.includes('記録の付け方')));
  assert.ok(文たち(例).some((x) => x.includes('ライブに参加')));
});

test('個人ログイン：今月の表記は、渡した日付に従う', () => {
  const 例 = 質問例({
    人たち: [{ name: '山田' }],
    記録たち: [記録({ archers: [{ name: '山田', marks: ['○'] }] })],
    いま: new Date('2026-05-15'),
    個人: true,
  });
  assert.ok(文たち(例).some((x) => x.includes('2026年5月')), '今月が反映されていない');
});

test('個人ログインの分岐は、団体の例を変えない（個人でなければ、これまでどおり出る）', () => {
  const 記録たち = [記録({ archers: [{ name: '山田', marks: ['○'] }] })];
  const 団体 = 文たち(質問例({ 人たち: [{ name: '山田' }], 記録たち, 件数: Infinity }));
  assert.ok(団体.some((x) => x.includes('団体全体')), '団体に、団体全体の例が出ていない');
  assert.ok(団体.some((x) => x.includes('部員を追加')), '団体に、部員の追加の例が出ていない');
  const 個人でない = 文たち(質問例({ 人たち: [{ name: '山田' }], 記録たち, 件数: Infinity, 個人: false }));
  assert.deepStrictEqual(個人でない, 団体);
});

test('質問例：全員の矢所やダークモードの候補が含まれる', () => {
  const 候補 = 文たち(質問例({ 人たち: [{ name: '山田' }], 記録たち: [], 件数: Infinity }));
  assert.ok(候補.some((x) => x.includes('メンバー全員の矢所')), '全員の矢所が候補にない');
  assert.ok(候補.some((x) => x.includes('ダークモード')), 'ダークモードが候補にない');
});

test('質問例：矢所の傾向を教えての候補が個人・団体の両方に含まれる', () => {
  const 記録たち = [記録({ archers: [{ name: '山田', marks: ['○'] }] })];
  // 団体
  const 団体候補 = 文たち(質問例({ 人たち: [{ name: '山田' }], 記録たち, 件数: Infinity, 個人: false }));
  assert.ok(団体候補.some((x) => x.includes('山田さんの矢所の傾向を教えて')), '団体の候補に矢所の傾向がない');

  // 個人
  const 個人候補 = 文たち(質問例({ 人たち: [{ name: '山田' }], 記録たち, 件数: Infinity, 個人: true }));
  assert.ok(個人候補.some((x) => x.includes('自分の矢所の傾向を教えて')), '個人の候補に矢所の傾向がない');
});
