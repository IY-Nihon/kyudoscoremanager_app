/**
 * 言葉の近さ測りの検査。
 *
 *   npm test
 *
 * 外のAPIを使わず、コードだけで測る。日本語は語の切れ目が無いので
 * 文字の二つ組で見る。言い換えられても当たること、
 * ありふれた言い回しだけで当たらないことを押さえる。
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { 二つ組, 引きをつくる, 近い順 } = require('../src/textMatch');

test('文字の二つ組に割る', () => {
  assert.deepEqual(二つ組('弓道'), ['弓道']);
  assert.deepEqual(二つ組('大前は'), ['大前', '前は']);
});

test('空白と記号は落とす', () => {
  assert.deepEqual(二つ組('大前 は？'), ['大前', '前は']);
});

test('1文字だけでも組にする（空にしない）', () => {
  assert.deepEqual(二つ組('矢'), ['矢']);
});

test('空や数字以外でも落ちない', () => {
  assert.deepEqual(二つ組(''), []);
  assert.deepEqual(二つ組(null), []);
});

test('同じ言葉がいちばん近い', () => {
  const 引き = 引きをつくる([
    { id: 'a', 文: '記録表を横向きにする' },
    { id: 'b', 文: '部員を追加する' },
  ]);
  const r = 近い順(引き, '記録表を横向きにする');
  assert.equal(r[0].id, 'a');
  assert.ok(r[0].近さ > 0.9, '同じ文なのに近さが低い: ' + r[0].近さ);
});

test('言い換えても当たる', () => {
  const 引き = 引きをつくる([
    { id: '写真', 文: '紙の記録表を写真から取り込む 画像 読み取り' },
    { id: '出欠', 文: '出席率を確認する 出欠 カレンダー' },
  ]);
  const r = 近い順(引き, '写真から取り込みたい');
  assert.equal(r[0].id, '写真');
});

test('どこにでも出る言い回しでは、上位が決まらない', () => {
  // 「してください」だけで当たると、関係ないものが並ぶ
  const 引き = 引きをつくる([
    { id: 'a', 文: '横向きにしてください' },
    { id: 'b', 文: '追加してください' },
    { id: 'c', 文: '削除してください' },
  ]);
  const r = 近い順(引き, 'してください');
  const 差 = r.length > 1 ? r[0].近さ - r[1].近さ : 1;
  assert.ok(差 < 0.05, 'ありふれた言い回しで順位が付いてしまっている');
});

test('珍しい言葉は強く効く', () => {
  const 引き = 引きをつくる([
    { id: '交代', 文: '途中交代を入れてください' },
    { id: '追加', 文: '部員を追加してください' },
    { id: '削除', 文: '記録を削除してください' },
  ]);
  const r = 近い順(引き, '途中交代');
  assert.equal(r[0].id, '交代');
  assert.ok(r[0].近さ > (r[1] ? r[1].近さ : 0) * 2, '珍しい言葉が効いていない');
});

test('長い文が、ただ長いだけで有利にならない', () => {
  const 引き = 引きをつくる([
    { id: '短い', 文: '横向き' },
    { id: '長い', 文: '出欠と履歴と分析と設定とメンバーと記録の話がとても長く続く文章です' },
  ]);
  const r = 近い順(引き, '横向き');
  assert.equal(r[0].id, '短い');
});

test('件数と下限で絞れる', () => {
  const 引き = 引きをつくる([
    { id: 'a', 文: '横向きにする' },
    { id: 'b', 文: '縦向きにする' },
    { id: 'c', 文: '部員を追加' },
  ]);
  assert.equal(近い順(引き, '向きにする', { 件数: 1 }).length, 1);
  assert.equal(近い順(引き, '向きにする', { 下限: 0.99 }).length, 0);
});

test('聞かれた文が空なら、何も返さない', () => {
  const 引き = 引きをつくる([{ id: 'a', 文: '横向き' }]);
  assert.deepEqual(近い順(引き, ''), []);
});

test('品が無くても落ちない', () => {
  assert.deepEqual(近い順(引きをつくる([]), '横向き'), []);
  assert.deepEqual(近い順(引きをつくる(null), '横向き'), []);
});
