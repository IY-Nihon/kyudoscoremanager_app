// 1. SwiftUIHostingView.swift
applyPatch(findFile(iosPath, ['Views', 'SwiftUI', 'SwiftUIHostingView.swift']), 'SwiftUIHostingView', (content) => {
  // Fix double @MainActor
  content = content.replace(/@MainActor\s+@MainActor/g, '@MainActor');

  // Fix inheritance: Remove @MainActor from protocol list (Swift 6 unknown attribute error)
  content = content.replace(/:\s+ExpoView,\s+@MainActor\s+AnyExpoSwiftUIHostingView/g, ': ExpoView, AnyExpoSwiftUIHostingView');
  
  // Ensure class HostingView is @MainActor
  if (content.includes('public final class HostingView') && !content.includes('@MainActor public final class HostingView')) {
    content = content.replace('public final class HostingView', '@MainActor public final class HostingView');
  }
  
  // Ensure AnyExpoSwiftUIHostingView protocol is NOT @MainActor itself to avoid call-site errors
  content = content.replace('@MainActor internal protocol AnyExpoSwiftUIHostingView', 'internal protocol AnyExpoSwiftUIHostingView');
  
  // Ensure methods are nonisolated in protocol and implementation
  ['updateProps', 'getContentView', 'getProps'].forEach(m => {
    if (content.includes(`func ${m}`) && !content.includes(`nonisolated func ${m}`)) {
      content = content.replace(new RegExp(`func ${m}`, 'g'), `nonisolated func ${m}`);
    }
  });

  // Fix safe area configuration access in Swift 6 concurrency
  content = content.replace('private var hasSafeAreaBeenConfigured = false', 'private nonisolated(unsafe) var hasSafeAreaBeenConfigured = false');
  content = content.replace('private var hasSizingBeenConfigured = false', 'private nonisolated(unsafe) var hasSizingBeenConfigured = false');

  return content;
});

// 1.1 SwiftUIVirtualView.swift & ViewDefinition.swift (Extension @MainActor fix)
const extensionFiles = [
  { file: ['Views', 'SwiftUI', 'SwiftUIVirtualView.swift'], name: 'SwiftUIVirtualView' },
  { file: ['Core', 'Views', 'ViewDefinition.swift'], name: 'ViewDefinition' }
];

