import fs from 'fs';
import path from 'path';

const nodeModulesPath = path.resolve('node_modules');
const iosPath = path.join(nodeModulesPath, 'expo-modules-core', 'ios');

/**
 * Robust file finding utility
 */
function findFile(base, relativePathParts) {
  const pathsToTry = [
    path.join(base, 'Swift', ...relativePathParts),
    path.join(base, 'Core', ...relativePathParts),
    path.join(base, 'Legacy', ...relativePathParts),
    path.join(base, ...relativePathParts)
  ];

  for (const p of pathsToTry) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

/**
 * Patch helper
 */
function applyPatch(filePath, label, transformer) {
  if (!filePath) {
    console.log(`⚠️  ${label} not found. Skipping.`);
    return;
  }
  console.log(`Patching ${label} at ${filePath}...`);
  try {
    let content = fs.readFileSync(filePath, 'utf8');
    const patchedContent = transformer(content);
    if (content !== patchedContent) {
      fs.writeFileSync(filePath, patchedContent);
      console.log(`✅ ${label} patched.`);
    } else {
      console.log(`ℹ️  ${label} already patched or no changes needed.`);
    }
  } catch (err) {
    console.error(`❌ Error patching ${label}:`, err);
  }
}

