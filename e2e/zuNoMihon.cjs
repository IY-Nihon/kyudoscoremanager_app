/**
 * AI の図の見本（e2e/zuNoGarou.spec.mjs が画面に並べて撮る）。
 *
 * 作りものの団体（名前も記録も作りもの。種を決めた乱数なので毎回同じ）から、道具の結果を作り、
 * src/chatFigures.js で図にする。図の見た目を直すときは、直す前と後でこの見本を撮って比べる（2026-11-13）。
 */
'use strict';

const { 図を作る } = require('../src/chatFigures');
const { 集計する } = require('../src/chatAggregate');

/** 種を決めた乱数（mulberry32） */
function 乱数を作る(種) {
  let a = 種 >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// 作りものの名前（長い名前・短い名前を混ぜる）
const 名前たち = [
  ['見本 一郎', 3, '男子', 0.62],
  ['見本 花', 3, '女子', 0.55],
  ['試作 健太', 2, '男子', 0.48],
  ['試作 さくら', 2, '女子', 0.7],
  ['仮野 翔', 2, '男子', 0.35],
  ['仮野 美咲', 1, '女子', 0.42],
  ['長谷川見本 慎太郎', 1, '男子', 0.28],
  ['林 葵', 1, '女子', 0.5],
];
const 人たち = 名前たち.map(([name, grade, gender], 番) => ({ id: `m${番 + 1}`, name, grade, gender }));

/** 2026 年 4 月〜11 月の記録。週に 2〜3 回。試合の日は 20 射、ふだんは 12 射（少ない日は 4 射） */
function 記録を作る() {
  const 乱 = 乱数を作る(20261113);
  const 記録たち = [];
  let 番 = 0;
  for (let 日 = new Date(2026, 3, 6); 日 < new Date(2026, 10, 13); 日.setDate(日.getDate() + 1)) {
    const 曜 = 日.getDay();
    if (![2, 4, 6].includes(曜)) continue;
    if (乱() < 0.18) continue;
    const 試合 = 曜 === 6 && 乱() < 0.25;
    const 月の伸び = (日.getMonth() - 3) * 0.02;
    const archers = [];
    人たち.forEach((人, 人番) => {
      if (乱() < 0.25) return;
      const 射数 = 試合 ? 20 : 乱() < 0.15 ? 4 : 12;
      const 腕 = 名前たち[人番][3] + 月の伸び + (乱() - 0.5) * 0.25;
      const marks = Array.from({ length: 射数 }, (_, 射) =>
        乱() < 腕 - (射 % 4 === 3 ? 0.08 : 0) ? '○' : '×'
      );
      archers.push({ id: `a${番}-${人.id}`, name: 人.name, memberId: 人.id, marks });
    });
    if (!archers.length) continue;
    番 += 1;
    記録たち.push({
      id: `r${番}`,
      date: new Date(日.getFullYear(), 日.getMonth(), 日.getDate(), 18).getTime(),
      title: 試合 ? '練習試合（対 見本大学）' : 曜 === 6 ? '土曜練習' : '通常練習',
      tags: 試合 ? ['#試合'] : 曜 === 6 ? ['#強化練習', '#正規練'] : ['#正規練'],
      archers,
    });
  }
  return 記録たち;
}

const 率 = (中, 射) => (射 ? Math.round((中 / 射) * 1000) / 10 : null);

/** 見本の図の一覧。{ 名, 問い, 図 } */
function 見本を作る() {
  const 記録たち = 記録を作る();
  const 集 = (注文) => 集計する(人たち, 記録たち, 注文);
  const 一覧 = [];
  const 足す = (名, 問い, 道具, 結果, 形, 題) => {
    const 図 = 図を作る(道具, 結果, 形, 題);
    if (!図 || 図.error) throw new Error(`見本「${名}」を作れない：${図 && 図.error}`);
    一覧.push({ 名, 問い, 図 });
  };
  const 一人 = ['見本 一郎'];
  const 最近 = new Date(2026, 9, 1).getTime();

  // ── 推移（折れ線） ──
  足す('月の推移', '部の月ごとの的中率の推移をグラフにして', 'aggregateStats', 集({ 切り口: ['月'] }), '折れ線', '月ごとの的中率');
  足す(
    '一人の記録ごと',
    '見本 一郎の最近の的中率の推移',
    'aggregateStats',
    集({ 切り口: ['記録'], 名前たち: 一人, 期間: { 始め: 最近 } }),
    '折れ線',
    '見本 一郎さんの記録ごとの的中率の推移（10月〜11月）'
  );
  足す('一人の記録ごと・長い', '見本 一郎の今年度の推移', 'aggregateStats', 集({ 切り口: ['記録'], 名前たち: 一人 }), '折れ線', '見本 一郎さんの記録ごとの的中率');
  足す('日ごと', '日ごとの的中率', 'aggregateStats', 集({ 切り口: ['日'] }), '折れ線');
  足す('週ごと', '週ごとの的中率の推移', 'aggregateStats', 集({ 切り口: ['週'] }), '折れ線');
  足す('一人の週ごと', '見本 一郎の週ごと', 'aggregateStats', 集({ 切り口: ['週'], 名前たち: 一人, 期間: { 始め: new Date(2026, 7, 1).getTime() } }), '折れ線', '見本 一郎さんの週ごとの的中率');
  足す('人×月', '全員の月ごとの推移を比べて', 'aggregateStats', 集({ 切り口: ['人', '月'], 件数: 6 }), '折れ線', 'メンバーごとの月別的中率');
  足す('二人×月', '見本 一郎と試作 さくらの月ごとを比べて', 'aggregateStats', 集({ 切り口: ['人', '月'], 名前たち: ['見本 一郎', '試作 さくら'] }), '折れ線', '2 人の月ごとの的中率');
  足す('性別×月', '男女の月ごとの推移', 'aggregateStats', 集({ 切り口: ['性別', '月'] }), '折れ線');
  足す('学年×月', '学年ごとの月の推移', 'aggregateStats', 集({ 切り口: ['学年', '月'] }), '折れ線');
  足す('2 か月だけ', '10 月と 11 月の的中率', 'aggregateStats', 集({ 切り口: ['月'], 期間: { 始め: 最近 } }), '折れ線');
  足す('1 か月だけ', '11 月の的中率をグラフで', 'aggregateStats', 集({ 切り口: ['月'], 期間: { 始め: new Date(2026, 10, 1).getTime() } }), '折れ線');
  足す('射目・多い', '何射目が中るか', 'aggregateStats', 集({ 切り口: ['射目'] }), '棒', '射目ごとの的中率');
  足す('立目', '何立目が中るか', 'aggregateStats', 集({ 切り口: ['立目'] }), '折れ線');
  {
    // 年をまたぐ月・低い所と高い所の差が大きい
    const 行 = (月, 射数, 的中) => ({ 月, 射数, 的中, 皆中: 0, 的中率: 率(的中, 射数), 記録数: 3, 人数: 5 });
    足す(
      '年またぎ・差が大きい',
      '去年の秋からの推移',
      'aggregateStats',
      {
        切り口: ['月'],
        全体: { 全体: '全体', 射数: 1500, 的中: 720, 的中率: 48 },
        一覧: [
          行('2025-10', 240, 60),
          行('2025-11', 200, 70),
          行('2025-12', 12, 11),
          行('2026-01', 180, 90),
          行('2026-02', 220, 120),
          行('2026-03', 8, 0),
          行('2026-04', 260, 170),
          行('2026-05', 380, 199),
        ],
      },
      '折れ線',
      '月ごとの的中率'
    );
  }
  足す('記録の一覧の折れ線', '最近の記録の的中率', 'getSessionsByDate', {
    sessions: 記録たち.slice(-10).reverse().map((記録) => {
      const 印 = 記録.archers.flatMap((a) => a.marks);
      const d = new Date(記録.date);
      return {
        date: `${d.getFullYear()}/${d.getMonth() + 1}/${d.getDate()}`,
        title: 記録.title,
        totalArrows: 印.length,
        hitRate: `${率(印.filter((x) => x === '○').length, 印.length)}%`,
      };
    }),
  }, '折れ線');

  // ── 比べ（棒） ──
  足す('月の棒', '月ごとの的中率を棒で', 'aggregateStats', 集({ 切り口: ['月'] }), '棒');
  足す('人の順位の棒', '的中率ランキング', 'aggregateStats', 集({ 切り口: ['人'], 並び: '的中率' }), '棒', '的中率ランキング');
  足す('射目・4 射', '1 立の中の何射目が中るか', 'aggregateStats', 集({ 切り口: ['射目'], 射目: { から: 1, まで: 4 } }), '棒');
  足す('曜日', '曜日ごとの的中率', 'aggregateStats', 集({ 切り口: ['曜日'] }), '棒');
  足す('射位', '射位ごとの的中率', 'aggregateStats', 集({ 切り口: ['射位'] }), '棒');
  足す('学年', '学年ごとの的中率', 'aggregateStats', 集({ 切り口: ['学年'] }), '棒');
  足す('性別', '男女の的中率', 'aggregateStats', 集({ 切り口: ['性別'] }), '棒');
  足す('タグ', 'タグごとの的中率', 'aggregateStats', 集({ 切り口: ['タグ'] }), '棒');
  const 順位 = 集({ 切り口: ['人'], 並び: '的中率' }).一覧.map((行) => ({
    順位: 行.順位,
    名前: 行.人,
    学年: 人たち.find((人) => 人.name === 行.人).grade,
    射数: 行.射数,
    的中: 行.的中,
    的中率: 行.的中率,
  }));
  // 18 人の団体（名前の長さはいろいろ）
  const 大勢 = Array.from({ length: 18 }, (_, 番) => ({
    順位: 番 + 1,
    名前: `${['見本', '試作', '仮野', '長谷川見本'][番 % 4]} ${['一', '二', '三', '四', '五', '六'][番 % 6]}${番 % 3 === 0 ? '太郎' : ''}`,
    学年: (番 % 3) + 1,
    射数: 番 === 16 ? 8 : 420 - 番 * 17,
    的中: 番 === 16 ? 3 : Math.round((420 - 番 * 17) * (0.74 - 番 * 0.03)),
    的中率: 番 === 16 ? 37.5 : Math.round((0.74 - 番 * 0.03) * 1000) / 10,
  }));
  足す('全員の順位の棒', '全員の的中率を比べて', 'getAllMembersStats', { 順位: 大勢 }, '棒');
  足す('出席率の棒', '出席率のランキング', 'getAttendanceStats', {
    一覧: 順位.map((行, 番) => ({ 順位: 番 + 1, 名前: 行.名前, 来た回数: 60 - 番 * 6, 練習日数: 64, 出席率: 率(60 - 番 * 6, 64) })),
  }, '棒');
  足す('射位の見込みの棒', '落に向いている人', 'getPositionStats', {
    その射位の順位: 順位.slice(0, 6).map((行, 番) => ({ 順位: 番 + 1, 射位: '落', 名前: 行.名前, 射数: 120 - 番 * 15, 的中率: 行.的中率, 見込みの的中率: Math.round((行.的中率 - 番) * 10) / 10 })),
  }, '棒');
  const 弓具 = {
    一覧: [
      { 変えた日: '2026-09-20', 種類: '弓', 弓力: '15kg', その弓具のあいだ: { 射数: 180, 的中率: 61.1 }, 差: 6.7 },
      { 変えた日: '2026-06-01', 種類: '弓', 弓力: '14kg', その弓具のあいだ: { 射数: 420, 的中率: 54.4 }, 差: 9.2 },
      { 変えた日: '2026-04-10', 種類: '弓', 弓力: '13kg', その弓具のあいだ: { 射数: 210, 的中率: 45.2 }, 差: null },
    ],
  };
  足す('弓具の棒', '弓を変えてからの的中率', 'getEquipmentTrend', 弓具, '棒');
  足す('学年ごとの人数', '学年ごとの人数', 'listMembers', {
    一覧: 人たち.map((人) => ({ 名前: 人.name, 学年: `${人.grade}年`, 性別: 人.gender })),
    学年ごと: { '1年': 3, '2年': 3, '3年': 2 },
  }, '棒');

  // ── 表 ──
  足す('月の表', '月ごとの的中率を表にして', 'aggregateStats', 集({ 切り口: ['月'] }), '表');
  足す('人×月の表', '全員の月ごとの的中率を表にして', 'aggregateStats', 集({ 切り口: ['人', '月'] }), '表');
  足す('全員の順位の表', '的中率ランキングを表で', 'getAllMembersStats', { 順位: 大勢 }, '表');
  足す('2 つの期間の表', '先月と今月を比べて', 'compareMemberStats', {
    一覧: 順位.map((行, 番) => ({ 順位: 番 + 1, 名前: 行.名前, 前の期間: { 的中率: 行.的中率 - 4 + 番 }, 今の期間: { 的中率: 行.的中率 }, 差: Math.round((4 - 番) * 10) / 10 })),
  }, '表');
  足す('前後の射の表', '前半と後半を比べて', 'compareShotRanges', {
    前の射の範囲: '1〜8射目',
    後の射の範囲: '9〜20射目',
    一覧: 順位.map((行, 番) => ({ 順位: 番 + 1, 名前: 行.名前, 前の射: { 的中率: 行.的中率 + 3 }, 後の射: { 的中率: 行.的中率 - 2 + 番 }, 差: Math.round((番 - 5) * 10) / 10 })),
  }, '表');
  足す('月ごとの出席率の表', '月ごとの出席率', 'getAttendanceStats', {
    月たち: ['2026-06', '2026-07', '2026-08', '2026-09', '2026-10', '2026-11'],
    一覧: 順位.map((行, 番) => ({
      名前: 行.名前,
      月ごと: ['2026-06', '2026-07', '2026-08', '2026-09', '2026-10', '2026-11'].map((月, 月番) => ({ 月, 出席率: Math.max(0, 100 - 番 * 9 - 月番 * 3) })),
    })),
  }, '表');
  足す('組分けの表', '5 人立ちで 2 チームに分けて', 'makeBalancedTeams', {
    組: [
      { 組: 'A', 部員: 人たち.slice(0, 4).map((人) => ({ 名前: 人.name })), 見込みの的中率: 52.4 },
      { 組: 'B', 部員: 人たち.slice(4).map((人) => ({ 名前: 人.name })), 見込みの的中率: 51.9 },
    ],
  }, '表');
  足す('記録の表', '最近の記録を表で', 'getSessionsByDate', {
    sessions: 記録たち.slice(-8).reverse().map((記録) => {
      const 印 = 記録.archers.flatMap((a) => a.marks);
      const d = new Date(記録.date);
      return { date: `${d.getFullYear()}/${d.getMonth() + 1}/${d.getDate()}`, title: 記録.title, totalArrows: 印.length, hitRate: `${率(印.filter((x) => x === '○').length, 印.length)}%` };
    }),
  }, '表');
  足す('弓具の表', '弓具ごとの的中率を表で', 'getEquipmentTrend', 弓具, '表');

  // ── 矢所 ──
  {
    const 乱 = 乱数を作る(7);
    const 点たち = Array.from({ length: 60 }, () => {
      const 角 = 乱() * Math.PI * 2;
      const 半径 = Math.sqrt(乱()) * 1.5;
      const x = Math.cos(角) * 半径 + 0.25;
      const y = Math.sin(角) * 半径 - 0.15;
      return { x, y, 印: Math.hypot(x, y) <= 1 ? '○' : '×', targetType: 'kasumi36' };
    });
    足す('矢所', '見本 一郎の矢所の傾向', 'getArrowLocationStats', { _点たち: 点たち }, '矢所', '見本 一郎さんの矢所');
  }
  return 一覧;
}

module.exports = { 見本を作る };
