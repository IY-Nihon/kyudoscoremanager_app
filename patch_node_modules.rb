def patch_file(path, search, replace)
  if File.exist?(path)
    content = File.read(path)
    if content.include?(search)
      puts "Patching #{path}..."
      File.write(path, content.gsub(search, replace))
    else
      puts "Search string not found in #{path}"
    end
  else
    puts "File not found: #{path}"
  end
end

