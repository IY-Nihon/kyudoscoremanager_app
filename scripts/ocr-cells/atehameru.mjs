/**
 * 印の位置に、決まった本数の格子を当てはめる。
 *
 * ■ なぜ束ねるだけでは足りないか
 * 印は割れたり（薄い◎の内と外が別のかたまりになる）、くっついたりする。
 * 束ねただけだと、列によって行が10本になったり14本になったりした（実測）。
 *
 * 行の本数は分かっている（射数と、1マスが何射かで決まる）。
 * 分かっている本数の等間隔の並びを、印にいちばんよく合うように置く。
 * 名前の札や数字が混ざっていても、多数決で決まるので引きずられない。
 */
import { 息継ぎ } from './ikitsugi.mjs';

/**
 * 等間隔の並びを当てはめる。
 *
 * @param {number[]} 値たち 印の中心（yでもxでもよい）
 * @param {number} 本数 置きたい本数
 * @param {number} 許す幅 これより近ければ「合った」とみなす
 * @param {number} [間隔の見当] 間隔のあたり。渡すとその ±25% だけを試す
 * @returns {Promise<{始め:number, 間隔:number, 合った数:number, 位置:number[]}>}
 *   総当たりが重い（板の行で 125 通りの間隔 × 印の数 × 本数）ので、間隔ごとに 息継ぎ を
 *   呼ぶ（30ms 経っていたときだけ休む）。列ごとの短い当てはめでは休まない
 */
export async function 等間隔を当てはめる(値たち, 本数, 許す幅, 間隔の見当, 点をつける) {
  // 点をつける … (位置たち) => 数。渡すと「合った数」にこれを足して選ぶ。
  // 板の行では「射手の列の多くに印がある行の数」を渡す（上の数字や下の名前の
  // 行に引かれて、広い間隔で当てはまるのを防ぐ）
  const 並び = 値たち.slice().sort((a, z) => a - z);
  if (並び.length < 2 || 本数 < 2) {
    return { 始め: 並び[0] || 0, 間隔: 0, 合った数: 並び.length, 位置: 並び.slice(0, 本数) };
  }
  const 下 = 並び[0];
  const 上 = 並び[並び.length - 1];

  // 間隔の見当。渡されなければ、端から端を (本数-1) で割ったものを中心に前後を試す。
  // 罫線のように外れの候補が混じるときは、端から端では見当が狂うので渡してもらう
  const 見当 = 間隔の見当 || (上 - 下) / (本数 - 1);
  let 最良 = { 始め: 下, 間隔: 見当, 合った数: -1, 位置: [] };

  // 見当を渡されたときは、その近く（±20%）だけを試す。
  // 点をつける があるときは狭いほうへ広く探す。見当は端の印から取るので、
  // 下の名前や上の数字が混じると大きく出る（実物で本当は105のところ153になり、
  // 探す範囲 115〜207 の外だった）。埋まった行で選ぶなら広くても迷わない
  const 間隔たち = [];
  // 点をつける があるときの下限 0.35 は、板の下に写った物（木の格子）や上の題字が
  // 射手の列に混じると見当が2倍にもなるため（9/13 の縦の写真で 393、本当は 186）。
  // 上限 1.6 は、上の段がまだ空の板で、印の端から端で取った見当が本当の間隔より
  // 小さく出るため（8段のうち上2段が空で、見当 233 に対して本当は 327）
  const [狭, 広] = 間隔の見当 ? [0.8, 1.2] : 点をつける ? [0.35, 1.6] : [0.75, 1.35];
  for (let r = 狭; r <= 広; r += 0.01) 間隔たち.push(見当 * r);

  for (const 間隔 of 間隔たち) {
    await 息継ぎ();
    // 間隔が許す幅の2倍より狭いと、どの印も必ずどこかの線の許す幅に入り、
    // 当てはめが意味をなさない（実測で本当は102の間隔が61に取られた）
    if (間隔 <= 許す幅 * 2.2) continue;
    // 始めの位置も、印のどれかに合わせて試す（外れ値に引かれにくい）
    for (const 起点 of 並び) {
      for (let ずれ = 0; ずれ < 本数; ずれ++) {
        const 始め = 起点 - 間隔 * ずれ;
        // 印の端の外に置いてよい行は、点をつける があれば3行まで（上の段が2段空の板）、
        // 無ければ1行まで
        const はみ出し = 点をつける ? 3 : 1;
        if (始め < 下 - 間隔 * はみ出し || 始め + 間隔 * (本数 - 1) > 上 + 間隔 * はみ出し) continue;
        let 合 = 0;
        let 残差 = 0;
        for (const v of 並び) {
          let 近さ = Infinity;
          for (let i = 0; i < 本数; i++) {
            const d = Math.abs(v - (始め + 間隔 * i));
            if (d < 近さ) 近さ = d;
          }
          if (近さ <= 許す幅) {
            合++;
            残差 += 近さ;
          }
        }
        // 同点のときは、印が線の近くに乗っている置き方を取る（半個ぶんの重み）。
        // 上の段が空の板では、狭い間隔で印の行を1つ飛ばしに拾う置き方と、正しい置き方の
        // 点が同じになり、先に試した狭いほうが勝っていた
        if (合 > 0) 合 += 0.5 * (1 - 残差 / (合 * 許す幅));
        if (点をつける) {
          const 位置 = [];
          for (let i = 0; i < 本数; i++) 位置.push(始め + 間隔 * i);
          合 += 点をつける(位置);
        }
        if (合 > 最良.合った数) {
          最良 = { 始め, 間隔, 合った数: 合, 位置: [] };
        }
      }
    }
  }
  // ここまでは 0.01 刻みの総当たりなので、いちばん良いものでも少しずれる。
  // 割り当てを決めてから、そのずれがいちばん小さくなる始めと間隔を計算し直し、
  // それを何度か繰り返す。格子は等間隔のままなので、行ごとにばらけることはない
  for (let 巡 = 0; 巡 < 4; 巡++) {
    let n = 0;
    let 和i = 0;
    let 和y = 0;
    let 和ii = 0;
    let 和iy = 0;
    for (const v of 並び) {
      let 近さ = Infinity;
      let どれ = -1;
      for (let i = 0; i < 本数; i++) {
        const d = Math.abs(v - (最良.始め + 最良.間隔 * i));
        if (d < 近さ) {
          近さ = d;
          どれ = i;
        }
      }
      if (近さ > 許す幅) continue;
      n++;
      和i += どれ;
      和y += v;
      和ii += どれ * どれ;
      和iy += どれ * v;
    }
    if (n < 3) break;
    const 分母 = n * 和ii - 和i * 和i;
    if (Math.abs(分母) < 1e-9) break;
    const 間隔 = (n * 和iy - 和i * 和y) / 分母;
    const 始め = (和y - 間隔 * 和i) / n;
    if (!(間隔 > 0)) break;
    const 止まった = Math.abs(間隔 - 最良.間隔) < 1e-4 && Math.abs(始め - 最良.始め) < 1e-4;
    最良.間隔 = 間隔;
    最良.始め = 始め;
    if (止まった) break;
  }

  最良.位置 = [];
  for (let i = 0; i < 本数; i++) 最良.位置.push(最良.始め + 最良.間隔 * i);
  return 最良;
}
