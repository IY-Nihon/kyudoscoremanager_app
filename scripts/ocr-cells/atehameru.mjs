/**
 * 印の位置に、決まった本数の格子を当てはめる。
 *
 * ■ なぜ束ねるだけでは足りないか
 * 印は割れたり（薄い◎の内と外が別のかたまりになる）、くっついたりする。
 * 束ねただけだと、列によって行が10本になったり14本になったりした（実測）。
 *
 * 行の本数は分かっている（射数と、1マスが何射かで決まる）。
 * 分かっている本数の等間隔の並びを、印にいちばんよく合うように置く。
 * 名前の札や数字が混ざっていても、多数決で決まるので引きずられない。
 */

/**
 * 等間隔の並びを当てはめる。
 *
 * @param {number[]} 値たち 印の中心（yでもxでもよい）
 * @param {number} 本数 置きたい本数
 * @param {number} 許す幅 これより近ければ「合った」とみなす
 * @param {number} [間隔の見当] 間隔のあたり。渡すとその ±25% だけを試す
 * @returns {{始め:number, 間隔:number, 合った数:number, 位置:number[]}}
 */
export function 等間隔を当てはめる(値たち, 本数, 許す幅, 間隔の見当) {
  const 並び = 値たち.slice().sort((a, z) => a - z);
  if (並び.length < 2 || 本数 < 2) {
    return { 始め: 並び[0] || 0, 間隔: 0, 合った数: 並び.length, 位置: 並び.slice(0, 本数) };
  }
  const 下 = 並び[0];
  const 上 = 並び[並び.length - 1];

  // 間隔の見当。渡されなければ、端から端を (本数-1) で割ったものを中心に前後を試す。
  // 罫線のように外れの候補が混じるときは、端から端では見当が狂うので渡してもらう
  const 見当 = 間隔の見当 || (上 - 下) / (本数 - 1);
  let 最良 = { 始め: 下, 間隔: 見当, 合った数: -1, 位置: [] };

  // 見当を渡されたときは、その近く（±20%）だけを試す
  const 間隔たち = [];
  const [狭, 広] = 間隔の見当 ? [0.8, 1.2] : [0.75, 1.35];
  for (let r = 狭; r <= 広; r += 0.01) 間隔たち.push(見当 * r);

  for (const 間隔 of 間隔たち) {
    if (間隔 <= 0) continue;
    // 始めの位置も、印のどれかに合わせて試す（外れ値に引かれにくい）
    for (const 起点 of 並び) {
      for (let ずれ = 0; ずれ < 本数; ずれ++) {
        const 始め = 起点 - 間隔 * ずれ;
        if (始め < 下 - 間隔 || 始め + 間隔 * (本数 - 1) > 上 + 間隔) continue;
        let 合 = 0;
        for (const v of 並び) {
          let 近さ = Infinity;
          for (let i = 0; i < 本数; i++) {
            const d = Math.abs(v - (始め + 間隔 * i));
            if (d < 近さ) 近さ = d;
          }
          if (近さ <= 許す幅) 合++;
        }
        if (合 > 最良.合った数) {
          最良 = { 始め, 間隔, 合った数: 合, 位置: [] };
        }
      }
    }
  }
  // ここまでは 0.01 刻みの総当たりなので、いちばん良いものでも少しずれる。
  // 割り当てを決めてから、そのずれがいちばん小さくなる始めと間隔を計算し直し、
  // それを何度か繰り返す。格子は等間隔のままなので、行ごとにばらけることはない
  for (let 巡 = 0; 巡 < 4; 巡++) {
    let n = 0;
    let 和i = 0;
    let 和y = 0;
    let 和ii = 0;
    let 和iy = 0;
    for (const v of 並び) {
      let 近さ = Infinity;
      let どれ = -1;
      for (let i = 0; i < 本数; i++) {
        const d = Math.abs(v - (最良.始め + 最良.間隔 * i));
        if (d < 近さ) {
          近さ = d;
          どれ = i;
        }
      }
      if (近さ > 許す幅) continue;
      n++;
      和i += どれ;
      和y += v;
      和ii += どれ * どれ;
      和iy += どれ * v;
    }
    if (n < 3) break;
    const 分母 = n * 和ii - 和i * 和i;
    if (Math.abs(分母) < 1e-9) break;
    const 間隔 = (n * 和iy - 和i * 和y) / 分母;
    const 始め = (和y - 間隔 * 和i) / n;
    if (!(間隔 > 0)) break;
    const 止まった = Math.abs(間隔 - 最良.間隔) < 1e-4 && Math.abs(始め - 最良.始め) < 1e-4;
    最良.間隔 = 間隔;
    最良.始め = 始め;
    if (止まった) break;
  }

  最良.位置 = [];
  for (let i = 0; i < 本数; i++) 最良.位置.push(最良.始め + 最良.間隔 * i);
  return 最良;
}
