/**
 * 板の写真から、マスを1つずつ切り出す。学習用の札も一緒に貼る。
 *
 *   node scripts/ocr-cells/kiridasu.mjs <画像> <射手の人数> <1人あたりのマス数> [出し先]
 *   node scripts/ocr-cells/kiridasu.mjs 板.jpg 8 10 out --正解 910280:男子リーグ --起点 下から --列 0-7
 *
 * ■ どうやって格子を見つけるか
 * 罫線は薄くて写真では拾えない（実測）。○×そのものが規則正しく並んでいるので、
 * 濃いかたまりを拾い、その並びから格子を復元する。行の本数は分かっている
 *（射数と1マスの射数で決まる）ので、その本数の等間隔をいちばんよく合う位置に置く。
 *
 * ■ 名札の帯を外す
 * 名札は色の枠に入っている。彩度の高い帯を見つけて、そこから下は見ない。
 * 板の上端の数字（各人の的中数）も印ではないので、いちばん上の帯も外す。
 */
import { 暗さの境, かたまりを拾う, 束ねる, 山で束ねる, 明暗を伸ばす, 傾きを測る, 罫線を消す, 平らにする, 平らの境 } from './koushi.mjs';
import { 等間隔を当てはめる } from './atehameru.mjs';

/**
 * 色の濃い（彩度の高い）帯を探す。名札はここに在る。
 *
 * 範囲 を渡すと、その横幅（板の中だけ）と、その y より下だけを見る。
 * 板の外まで見ると、木の格子や床の色が「帯」になり、板の下半分を丸ごと
 * 見ないことになった（9/13 の縦の写真で、印 80 個のうち 23 個しか拾えず）。
 * 帯は「印の帯より下で、彩度の高い行が続くところ」。続かない色（ごみ）は帯にしない
 */
export function 色の帯を探す(色, 幅, 高, 範囲) {
  const data = 色.data;
  const ch = 色.ch;
  const 左 = 範囲 ? Math.max(0, Math.floor(範囲.左)) : 0;
  const 右 = 範囲 ? Math.min(幅, Math.ceil(範囲.右)) : 幅;
  const 上 = 範囲 ? Math.max(0, Math.floor(範囲.上)) : 0;
  if (右 - 左 < 4 || 上 >= 高) return { 札の上: 高, 彩度の平均: 0 };
  const 彩度 = new Array(高).fill(0);
  for (let y = 上; y < 高; y++) {
    let 合 = 0;
    for (let x = 左; x < 右; x++) {
      const i = (y * 幅 + x) * ch;
      const r = data[i];
      const g = data[i + 1];
      const b = data[i + 2];
      const 最大 = Math.max(r, g, b);
      const 最小 = Math.min(r, g, b);
      合 += 0 === 最大 ? 0 : (最大 - 最小) / 最大;
    }
    彩度[y] = 合 / (右 - 左);
  }
  let 平均 = 0;
  for (let y = 上; y < 高; y++) 平均 += 彩度[y];
  平均 /= 高 - 上;
  const 境 = Math.max(平均 * 1.6, 0.08);
  const 続き = 範囲 && 範囲.続き ? 範囲.続き : Math.max(4, Math.round(高 * 0.01));
  if (!範囲) {
    // 昔ながら（板が写真いっぱいのとき）：下半分で色の濃い行のいちばん上
    let 札の上 = 高;
    for (let y = 高 - 1; y > 高 * 0.5; y--) if (彩度[y] > 境) 札の上 = y;
    return { 札の上, 彩度の平均: 平均 };
  }
  // 上から下へ見て、色の濃い行が 続き 行つづく最初のところが帯の上
  let 数 = 0;
  for (let y = 上; y < 高; y++) {
    数 = 彩度[y] > 境 ? 数 + 1 : 0;
    if (数 >= 続き) return { 札の上: y - 続き + 1, 彩度の平均: 平均 };
  }
  return { 札の上: 高, 彩度の平均: 平均 };
}

/**
 * 格子を組み立てる。
 *
 * @param {{画素: Uint8Array, 幅: number, 高: number, 色?: {data:Uint8Array, ch:number}}} 元
 *   明るさの並び。色があれば名札の帯を外すのに使う（Node は gazou-node の 画を読む）
 * @param {{人数:number, 行数:number, 上を除く?:number, 角度?:number, 回す?:Function}} 注文
 *   角度 … 度。渡せばその角度で起こす。渡さなければ印の並びから測る
 *   回す … (生, 度) => 生。傾きを起こすときに使う。無ければ起こさない
 * @returns 列・行のほかに、起こしたあとの明るさ（生）と角度を返す。
 *   角度が付いたときは 列・行 の座標は起こしたあとの画に対するものなので、
 *   マスを切るときは 生 から切ること（元の写真から切るとずれる）
 */
export async function 格子(元, 注文) {
  let 生 = { 画素: 元.画素, 幅: 元.幅, 高: 元.高 };
  // 名札の帯は、印を拾ってから（板の横幅の中、印より下で）探す。先に写真ぜんぶで
  // 探すと、板の外の木や床の色で帯が決まり、板の下半分を見なくなった
  let 札の上 = 生.高;

  // 明暗を伸ばしてから見る。暗い写真・薄い印・照り返しのむらは、
  // 暗さの境を1つ決めるやり方だと印を取りこぼす（実測で、暗くした写真は
  // 印が半分しか拾えなかった）。端の何割かを切ったところで伸ばすと揃う
  // 印を拾うのは「平らにした画」（まわりとの明るさの差）から。板の外の木や壁の
  // 模様は暗い画素にならず、罫線を消したあとの印だけが残る。
  // マスの切り出し（g.生）は、罫線を消した明るさの画から
  let 平ら;
  if (注文.下ごしらえ済み) {
    平ら = 注文.平ら;
  } else {
    生 = { 画素: 明暗を伸ばす(生.画素), 幅: 生.幅, 高: 生.高 };
    ({ 生, 平ら } = 下ごしらえ(生, 罫線の長さ(生.幅, 注文.人数)));
  }

  // 印の大きさの見当は、画像の幅ではなく「1マスがどれくらいか」から取る。
  // 人数が少ない板ほどマスは大きい。幅だけで決めると、4人の板で印が
  // 大きすぎて網に掛からず、数字の列を射手の列と取り違えた（実測）。
  // 列は 射手＋立ごとの小計＋合計＋余白 でおよそ 人数×1.35+2 本
  const 印を拾う = (画) => {
    // 板ごとに切り抜いた画では、幅から見当を付けると小さく出る（切り抜きは射手の列に
    // ぴったりで、小計の列や余白が無い。寄りの写真で印 230px に対して上限 207px になり、
    // 印がほとんど拾えなかった）。写真ぜんぶで測った列の間隔があればそれを使う
    const 幅からの見当 = 画.幅 / (注文.人数 * 1.35 + 2);
    const 期待するマス = 注文.マスの見当 ? Math.max(幅からの見当, 注文.マスの見当 * 0.8) : 幅からの見当;
    const 最小 = Math.max(6, Math.round(Math.min(幅からの見当, 期待するマス) * 0.22));
    const 最大 = Math.round(期待するマス * 1.15);
    // ※ マスいっぱいに大きく書かれた ×（見当の 1.2 倍。9/13 の相手校の板）は 1.15 倍を
    // 超えて印から外れる。上限を 1.35 倍に広げると、合計の列でつながった数字が印になって
    // 自校の板の列を取り違えたので、広げていない（相手校の板はまだ読めない）
    // 板の上端の数字（各人の的中数）は印ではない。上の何割かは見ない
    const 上限 = 注文.上を除く == null ? 画.高 * 0.13 : 注文.上を除く;
    const 全部 = かたまりを拾う(画, 平らの境);
    // 小計・合計の欄に引かれた斜線（数字を区切る／）は、箱で見ると印と同じ正方形になり、
    // 合計の列を「丸い列」に見せた（9/13 の板で、合計の列が射手の列より強くなり
    // 端末の読み取りを使えなかった）。墨が対角の帯に集まっているものは印ではない
    const 印 = 全部.filter(
      (b) =>
        b.幅 >= 最小 && b.幅 <= 最大 && b.高 >= 最小 && b.高 <= 最大 &&
        b.幅 / b.高 > 0.45 && b.幅 / b.高 < 2.2 &&
        b.数 > 最小 * 最小 * 0.12 &&
        b.y < 札の上 - 最小 && b.y > 上限 &&
        !斜線か(画, b)
    );
    // 断片 … 大きさで絞る前のかたまり（ごく小さな点は除く）。字は画数が多く、
    // 1文字が幾つもの断片に割れる。印は1〜2個。行が字か印かを見分けるのに使う
    // 名札の帯（色の枠）と上端の数字は、印と同じく見ない。色の枠は細かい断片になり、
    // 枠に接した最下段の印まで字と間違えて外していた
    const 断片 = 全部.filter(
      (b) => b.数 >= 12 && b.幅 <= 最大 * 1.5 && b.高 <= 最大 * 1.5 && b.y < 札の上 - 最小 && b.y > 上限
    );
    return { 印, 最小, 断片 };
  };
  let { 印, 最小, 断片 } = 印を拾う(平ら);
  if (印.length < 注文.人数 * 3) {
    // 印が大きくて隣どうしや罫線とつながっていると、かたまりとしては拾えない
    //（4人立ちの板の実物で、40マスのうち8個しか拾えなかった）。
    // そのときは罫線を探し、罫線も無ければ墨の量の並びの周期から格子を立てる
    return 罫線で格子(生, 注文, 注文.角度 || 0) || 墨の並びで格子(生, 注文, 注文.角度 || 0);
  }

  // 傾きを測って起こす。斜めに撮った写真では、列のxが上下で1マス以上ずれ、
  // xで束ねるやり方が丸ごと崩れる（10度で1000pxの高さなら176pxずれる）。
  // 印の並びがいちばん縦横に揃う角度を探し、その角度で画ごと回してから
  // 拾い直す。1.5度未満なら回さない。回すと少しぼけて網の読みが鈍るし、
  // それくらいの傾きは行の当てはめと列ごとのずれで吸収できる
  //（実測で、1.45度を回したら写真の読みが 320 → 316 に落ちた）
  const 角度 = 注文.角度 != null ? 注文.角度 : 傾きを測る(印, 最小);
  let 回した = false;
  if (Math.abs(角度) > 1.5 && 注文.回す) {
    // 回してから、罫線を消し直して拾い直す（回す前に消した罫線は傾きで途切れて残っている）
    生 = await 注文.回す(生, 角度);
    ({ 生, 平ら } = 下ごしらえ(生, 罫線の長さ(生.幅, 注文.人数)));
    回した = true;
    ({ 印, 断片 } = 印を拾う(平ら));
    if (印.length < 注文.人数 * 3) {
      throw new Error('起こしたあと、印が少なすぎます（' + 印.length + '個）');
    }
  }
  // 名札の帯。回していなければ色を見られる（回すと色の位置がずれる）。
  // 印の横幅の中で、印のいちばん下より下だけを見る
  if (元.色 && !回した && !注文.下ごしらえ済み) {
    const xs = 印.map((b) => b.x);
    const 印の下 = Math.max(...印.map((b) => b.y));
    const 幅の見当 = 印.map((b) => b.幅).sort((a, z) => a - z)[Math.floor(印.length / 2)];
    札の上 = 色の帯を探す(元.色, 生.幅, 生.高, { 左: Math.min(...xs) - 幅の見当, 右: Math.max(...xs) + 幅の見当, 上: 印の下 - 幅の見当 * 0.5, 続き: Math.max(4, Math.round(幅の見当 * 0.25)) }).札の上;
    if (札の上 < 生.高) ({ 印, 断片 } = 印を拾う(平ら));
  }

  const 印の幅 = 印.map((b) => b.幅).sort((a, z) => a - z)[Math.floor(印.length / 2)];
  // 列は密度の山で取る（隣との近さで鎖にすると、列の間の字で2列がつながる）
  const 全列 = 山で束ねる(印.map((b) => b.x), 印の幅);

  // 射手の列を選ぶ。数だけで選ぶと、小計や合計の数字の列を拾ってしまう
  //（数字も、大きさだけ見れば印と変わらない）。
  // 射手の列は「行が上から下まで埋まっている」ことで見分ける。
  // 数字はところどころにしか書かれない。
  //
  // 「間隔の揃った連続する列を取る」やり方も試されたが、4人ごとに小計の列が
  // 挟まる板で崩れる（描いた板30枚で 30/30 → 17/30 に落ちた）。
  // 4人ずつの切り抜きなら両方とも通るので、そちらだけ見ていると気づけない
  const 埋まり具合 = (列) => {
    const この列 = 印.filter((b) => Math.abs(b.x - 列.中心) <= 印の幅 * 0.8);
    if (この列.length < 2) return 0;
    const 行 = 等間隔を当てはめる(この列.map((b) => b.y), 注文.行数, 印の幅 * 0.45);
    let 埋 = 0;
    for (const y of 行.位置) {
      if (この列.some((b) => Math.abs(b.y - y) <= Math.max(印の幅 * 0.5, 行.間隔 * 0.45))) 埋++;
    }
    return 埋 / 注文.行数;
  };
  // 合計の列は毎行に数字があり、埋まり具合では射手の列と見分けられない
  //（ブラウザによる復号の僅かな差で入れ替わり、右の板で合計の列を取った）。
  // 数字は細長く、印（○・◎・×）は丸い。列のかたまりの「丸さ」を点に掛ける
  // 丸さは「かたまりのうち丸いものの割合」ではなく「印のある段のうち、丸いかたまりを
  // 持つ段の割合」。罫線を消すと ○ に線 の線が別のかたまりになり、線の多い列（× と
  // 丸に線ばかりの列）が 0.47 まで下がって射手の列と見なされなかった（9/13 の板）
  const 丸さ = (列) => {
    const この列 = 印.filter((b) => Math.abs(b.x - 列.中心) <= 印の幅 * 0.8);
    if (!この列.length) return 0;
    const 段 = 束ねる(この列.map((b) => b.y), 印の幅 * 0.7);
    let 丸い段 = 0;
    for (const d of 段) {
      if (この列.some((b) => Math.abs(b.y - d.中心) <= 印の幅 * 0.7 && b.幅 / b.高 >= 0.7 && b.幅 / b.高 <= 1.6 && b.幅 >= 印の幅 * 0.6)) 丸い段++;
    }
    return 丸い段 / 段.length;
  };
  // 大きさ … 列のかたまりの幅の中央値を、写真ぜんぶの印の幅で割ったもの。数字は印より小さい
  const 大きさ = (列) => {
    const 幅たち = 印.filter((b) => Math.abs(b.x - 列.中心) <= 印の幅 * 0.8).map((b) => b.幅).sort((a, z) => a - z);
    return 幅たち.length ? 幅たち[Math.floor(幅たち.length / 2)] / 印の幅 : 0;
  };
  // 大きさが印と同じくらい（0.85〜1.8 倍）の列だけ射手らしい。数字の列は 0.5〜0.83、
  // 板の外の物は 0.56 や 1.86 だった（9/6 の板、9/13 の板 6 枚で実測）。上限 1.4 では、字の大きい人の
  // 列（1.61 倍。中央値が数字のかけらで小さく出る）が外れた
  const 大きさが合う = (x) => x.大 >= 0.85 && x.大 <= 1.8;
  const 点数つき = 全列.map((c) => ({ 列: c, 埋: 埋まり具合(c), 丸: 丸さ(c), 大: 大きさ(c), 点: 0 }));
  for (const x of 点数つき) x.点 = x.埋 * (0.5 + x.丸) * (大きさが合う(x) ? 1 : 0.6);
  if (process.env.OCR_RETSU) console.error('列の点', 点数つき.map((x) => `${x.列.中心.toFixed(0)}:${x.点.toFixed(2)}(埋${x.埋.toFixed(2)}丸${x.丸.toFixed(2)}大${x.大.toFixed(2)}数${x.列.数})`).join(' '));
  // 射手の列らしい列の数（人数を当てにしない見当）。Gemini の行の数が板の列の数と
  // 違うとき（相手校の板で 8列を 10行にした）、人数ぶんの列を取ると小計の列まで
  // 射手にしてしまい、印が黙ってずれる。
  // 見分けは埋まりと丸さで。合計の列は毎行数字があるが細長い（丸さ 0.14〜0.38）、
  // 空に近い列は埋まりが薄い。ただし小計の列（数字が4行に1つ）は埋まり 0.5〜0.6 で、
  // 薄い印の射手の列（0.63〜0.7、見つからない印がある）と重なるので、ここでは
  // 見分けない（緩く数える。厳しくすると本物の列を落として、端末の読み取りを
  // 使えない写真が増えた）。
  //   列の見当 … 射手の列らしい列の数。人数より少なければ、人数ぶん取った列に
  //              明らかな外れ（合計・空）が混じっている
  //   外した強い列 … 選ばなかったのに射手の列らしい列の数。0でなければ人数が少なすぎる
  const 最高の埋 = Math.max(0, ...点数つき.map((x) => x.埋));
  // 字の小さい人の列（印が板の中央値の 0.68 倍）は大きさで外れるので、埋まりと丸さが
  // はっきり高ければ通す（数字の列は丸さが 0.55〜0.67 止まりだった）
  const 列らしい = (x) =>
    x.埋 >= Math.max(0.3, 最高の埋 * 0.5) && x.丸 >= 0.45 && (大きさが合う(x) || (x.丸 >= 0.75 && x.埋 >= 0.75 && x.大 >= 0.6));
  const 強い = (x) => x.埋 >= Math.max(0.3, 最高の埋 * 0.75) && x.丸 >= 0.6 && 大きさが合う(x);
  const 列の見当 = 点数つき.filter(列らしい).length;
  // 射手の列は等間隔に並ぶ。点の高い順に人数ぶん取るだけだと、上の段が空で埋まりの
  // 薄い射手の列より、数字の列（2桁がつながって丸く見える）が勝ち、並びが飛んだ
  //（9/13 の途中の写真をブラウザで読んだとき、右の板が 小計・郷田・櫻木・伊達 になった）。
  // 点が 0.3 以上の列から「間隔のそろった（±25%）連なり」を人数ぶん組み、点の和が
  // いちばん大きい連なりを取る。組めなければ点の高い順
  const 射手の列 = 連なりで選ぶ(点数つき, 注文.人数, 点数つき.filter(強い)) || 点数つき
    .slice()
    .sort((a, z) => z.点 - a.点 || z.列.数 - a.列.数)
    .slice(0, 注文.人数)
    .map((x) => x.列)
    .sort((a, z) => a.中心 - z.中心);
  // 選んだ列の並びから離れた強い列は数えない。射手の列は等間隔に並ぶので、
  // その並びから 1.5 マス以上離れた列は、小計・合計の欄（9/13 の板の合計の列は
  // 数字が丸くて毎行あり、射手の列と同じ強さだった）
  const 選んだ中心 = 射手の列.map((c) => c.中心).sort((a, z) => a - z);
  const 間たち = 選んだ中心.slice(1).map((v, i) => v - 選んだ中心[i]).sort((a, z) => a - z);
  const 列の間 = 間たち.length ? 間たち[Math.floor(間たち.length / 2)] : 印の幅 * 1.5;
  const 並びの近く = (c) => 選んだ中心.some((v) => Math.abs(v - c.中心) <= 列の間 * 1.5);
  const 外した強い列 = 点数つき.filter((x) => 強い(x) && !射手の列.includes(x.列) && 並びの近く(x.列)).length;
  // 並びの人数 … 選んだ列の等間隔の並びに乗っている、射手らしい列の数（人数を当てにしない、
  // 板の本当の人数の見当）。Gemini の人数が違ったとき、これを添えて読み直してもらう。
  // 並びに乗る＝どれかの選んだ列から 列の間 の整数倍（±25%）のところにある
  const 並びに乗る = (c) =>
    選んだ中心.some((v) => {
      const k = Math.round(Math.abs(v - c.中心) / 列の間);
      return k >= 1 && Math.abs(Math.abs(v - c.中心) - k * 列の間) <= 列の間 * 0.25;
    });
  const 並びの人数 = 点数つき.filter((x) => 列らしい(x) && (射手の列.includes(x.列) || 並びに乗る(x.列))).length;

  // 板の下に書かれた氏名（縦書き）は、印と同じ大きさのかたまりになって行と数えられ、
  // 格子が2行ぶん下へずれた（名前を塗りつぶした写真では起きず、元の写真で 320 → 246 に
  // 落ちた）。字は画数が多いので、その高さの帯には断片が多い。射手の列の幅で数えて、
  // 1列あたり 2.5 個以上の帯にある印は字とみなして外す（本物で印の行は 1.1〜1.6、
  // 氏名の行は 3.0〜3.5、立ち位置の札の行は 6.1）
  // 数えるのは「印らしくない」断片だけ。罫線を消すと ◎ の中の丸や外れた斜線が別の
  // かたまりになり、印の行でも 2〜3 個になった（9/13 の板で、印の行を字とみなして
  // 落とした）。印らしい形（印の幅の 6 割以上あって丸い）は数えない。◎ の中の丸や
  // 外れた斜線は 1 個ずつで済み、字の画は 3 個以上になる
  const 印らしい形 = (b) => b.幅 >= 印の幅 * 0.6 && b.幅 / b.高 >= 0.7 && b.幅 / b.高 <= 1.6;
  const 列に近い断片 = 断片.filter(
    (b) => !印らしい形(b) && 射手の列.some((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8)
  );
  const 字の帯か = (y) => {
    let n = 0;
    for (const b of 列に近い断片) if (Math.abs(b.y - y) <= 印の幅 * 0.5) n++;
    return n / 射手の列.length >= 2.5;
  };
  const 射手の印 = 印.filter(
    (b) => 射手の列.some((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8) && !字の帯か(b.y)
  );
  if (process.env.OCR_GYO) {
    const 列の印 = 印.filter((b) => 射手の列.some((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8));
    console.error('行の印', `印の幅${印の幅}`, '列の印', 列の印.length, '字の帯で外した', 列の印.length - 射手の印.length,
      'y:', 列の印.map((b) => `${b.y.toFixed(0)}${字の帯か(b.y) ? '字' : ''}`).sort((a, z) => parseFloat(a) - parseFloat(z)).join(' '));
  }
  // 行は「射手の列の6割以上に印がある行」がいちばん多い置き方を選ぶ。
  // 印の数だけで選ぶと、上端の的中数の数字と下の名前に引かれて、10行を
  // 広い間隔で当てはめてしまう（板1枚まるごと渡した実物で、右の板の行間隔が
  // 105 のところ 121 になり、読みが 316 → 284 に落ちた）。
  // 1行を強く数える（印の総数より重く）ので、埋まった行が多い置き方が勝つ
  // 行に「合った」とみなす近さ。1マス2射の板では、帯（実線で囲まれた2行）の中で
  // 上の行の印は下寄り、下の行の印は上寄りに書かれ、等間隔から ±50px（印の幅の 0.4 倍）
  // ずれていた（9/13 の板の右半分。0.45 では10行のうち4行が外れ、間隔 240 の当てはめが勝った）
  const 行の許し = 印の幅 * 0.55;
  // 行の支えにするのは、印らしい大きさと丸さのかたまりだけ。上端の数字や名前の字は
  // 細い（幅が印の幅の半分ほど）ので、行として数えない。◎ の外の丸、×、丸に線は通る
  const 行の印 = 射手の印.filter(印らしい形);
  // 行を支える列は、印らしいかたまりがそれなりにある列だけ（薄い列に引きずられない）
  const 支える列 = 射手の列.filter((c) => 行の印.filter((b) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8).length >= Math.max(3, 注文.行数 * 0.3));
  const 行を数える列 = 支える列.length >= 2 ? 支える列 : 射手の列;
  // 板は下から書くので、いちばん下の行は埋まっているはず。埋まった行の数が同じ置き方が
  // 2つあるとき（上の段がまだ空の板で、空を上に置くか下に置くか）は、下の行が埋まって
  // いるほうを取る（半行ぶんの重み。かたまりの数の差より重く、行1つより軽い）
  const 埋まった行の数 = (位置たち) => {
    let n = 0;
    let 下が埋まった = false;
    for (let i = 0; i < 位置たち.length; i++) {
      const y = 位置たち[i];
      let 列の数 = 0;
      for (const c of 行を数える列) {
        if (行の印.some((b) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8 && Math.abs(b.y - y) <= 行の許し)) 列の数++;
      }
      if (列の数 >= 行を数える列.length * 0.6) {
        n++;
        if (i === 位置たち.length - 1) 下が埋まった = true;
      }
    }
    return (n + (下が埋まった ? 0.5 : 0)) * 行の印.length;
  };
  if (process.env.OCR_GYO) {
    console.error('行の支え', `支える列 ${支える列.length}/${射手の列.length}`, '行の印', 行の印.length,
      行の印.map((b) => `${b.y.toFixed(0)}@${射手の列.findIndex((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8)}:${(b.数 / (b.幅 * b.高)).toFixed(2)}`).sort((a, z) => parseFloat(a) - parseFloat(z)).join(' '));
  }
  // 同じ写真の別の板で決まった行を渡されたら、それを使う（同じ板の左右で、右半分は
  // 上の段がまだ空のとき、右だけでは行の置き方が決まらない。9/13 の途中の写真）
  const 行 = 注文.行の位置
    ? { 位置: 注文.行の位置.slice(), 間隔: 注文.行の位置.length > 1 ? (注文.行の位置[注文.行の位置.length - 1] - 注文.行の位置[0]) / (注文.行の位置.length - 1) : 印の幅, 始め: 注文.行の位置[0], 合った数: 0 }
    : 等間隔を当てはめる(行の印.map((b) => b.y), 注文.行数, 行の許し, undefined, 埋まった行の数);
  if (process.env.OCR_GYO) console.error('当てはめ', 行.始め.toFixed(0), 行.間隔.toFixed(1), '点', 行.合った数, '埋', 埋まった行の数(行.位置) / 行の印.length);
  // 等間隔に置いたあと、印の支えが列の半分以上ある行だけ、その行の印の真ん中へ寄せる
  //（間隔の 0.3 倍まで）。行ごとに寄せると印の少ない行で引きずられて悪化した経緯が
  // あるので、支えの無い行は等間隔のまま
  for (let i = 0; !注文.行の位置 && i < 行.位置.length; i++) {
    const 近く = 行の印
      .filter((b) => 射手の列.some((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8) && Math.abs(b.y - 行.位置[i]) <= 行.間隔 * 0.42)
      .map((b) => b.y)
      .sort((a, z) => a - z);
    if (近く.length < Math.max(2, Math.ceil(射手の列.length * 0.5))) continue;
    const 真ん中 = 近く[Math.floor(近く.length / 2)];
    行.位置[i] += Math.max(-行.間隔 * 0.3, Math.min(行.間隔 * 0.3, 真ん中 - 行.位置[i]));
  }
  // 行の欠け … 頼まれた行数が板と違うことの手がかり。
  // 設定の射数に引かれた Gemini が 10段の板を 14 と答えた実例では、片方の板は
  // 行の間隔が縮んで印のある行と無い行が交互になり、もう片方は正しい間隔のまま
  // 板の下に4行はみ出した（どちらも印は行に乗るので「乗った割合」では分からない）。
  // 板は下から書くので、まだ書いていない行は上に固まる。埋まった行より下に
  // 空の行があれば、その行は板の外か、間隔が合っていない
  // 行が埋まっているかは、行の間隔に対して厳しめに見る（間隔の 0.35 倍まで）。
  // 当てはめの許しは印の幅の 0.55 倍だが、行数を多く頼まれて行が詰まった置き方
  //（10段の板に14段）では隣の行の印まで届いてしまい、行の欠けが見えなくなった
  const 埋まりの許し = Math.min(行の許し, 行.間隔 * 0.35);
  const 行ごとの列数 = 行.位置.map((y) => {
    let 列の数 = 0;
    for (const c of 射手の列) {
      if (射手の印.some((b) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8 && Math.abs(b.y - y) <= 埋まりの許し)) 列の数++;
    }
    return 列の数;
  });
  // 「空の行」は印がほぼ無い行（列の2割以下、8列なら1つ以下）。薄い印の行は
  // ブラウザで縮めた写真だと 8列中3つしか拾えないことがあるので、6割では厳しすぎた。
  // 行数を間違えた当てはめでは 0〜1 の行が2つ以上できる
  const 空の行 = 行ごとの列数.map((n) => n <= Math.max(1, Math.floor(射手の列.length * 0.2)));
  let 行の欠け = 0;
  let 埋まりが始まった = false;
  for (const 空 of 空の行) {
    if (!空) 埋まりが始まった = true;
    else if (埋まりが始まった) 行の欠け++;
  }
  // 上の字の行 … 埋まった行より上の行のうち、印ではなく字や数字（小さな断片）が
  // 並んでいる行の数。行数を多く頼まれると（10段の板に14段）、余った行が板の上に
  // 置かれ、各人の的中数の数字や題字の行がマスとして読まれてしまう。
  // まだ書いていない上の段（途中の板）は白いままなので断片が無く、ここには数えない
  // 上から順に、空の行か字の行が続く間だけ見る（字の行は数字が印として拾われて
  //「埋まった行」に見えることがあるので、空でなくても断片が多く印らしいものが少なければ字）
  let 上の字の行 = 0;
  for (let i = 0; i < 行.位置.length; i++) {
    let 断片の数 = 0;
    for (const b of 列に近い断片) if (Math.abs(b.y - 行.位置[i]) <= 埋まりの許し) 断片の数++;
    let 印の数 = 0;
    for (const b of 射手の印) if (印らしい形(b) && Math.abs(b.y - 行.位置[i]) <= 埋まりの許し) 印の数++;
    // 1列あたり 1.5 個以上（数字「13」は2個、字は3個以上。消し跡のかけらは列に1つも無い）
    if (断片の数 >= 射手の列.length * 1.5 && 印の数 < 射手の列.length * 0.5) {
      上の字の行++;
      continue;
    }
    if (!空の行[i]) break;
  }

  // 起こしても、板ぜんぶに1つの格子を当てると端の列ほど上下にずれる
  //（手書きの罫線は真っ直ぐではない。実測で、右端の列の印が下で切れていた）。
  // 列ごとに「どれだけ下にずれているか」を測って持たせる。
  // 10行ぶんの印から決めるので、1行ずつ寄せるのと違ってぶれない
  for (const 列 of 射手の列) {
    const 残り = [];
    for (const b of 射手の印) {
      if (Math.abs(b.x - 列.中心) > 印の幅 * 0.8) continue;
      let 近さ = Infinity;
      for (const y of 行.位置) {
        const d = b.y - y;
        if (Math.abs(d) < Math.abs(近さ)) 近さ = d;
      }
      if (Math.abs(近さ) <= 行.間隔 * 0.42) 残り.push(近さ);
    }
    if (残り.length < 4) {
      列.ずれ = 0;
      continue;
    }
    残り.sort((a, z) => a - z);
    const 真ん中 = 残り[Math.floor(残り.length / 2)];
    列.ずれ = Math.max(-行.間隔 * 0.3, Math.min(行.間隔 * 0.3, 真ん中));
  }

  // 列の点 は確かめ用（ブラウザでの見当のずれを追うため）
  const 列の点 = 点数つき.map((x) => ({ 中心: Math.round(x.列.中心), 点: Number(x.点.toFixed(2)), 埋: Number(x.埋.toFixed(2)), 丸: Number(x.丸.toFixed(2)), 数: x.列.数 }));
  return { 幅: 生.幅, 高: 生.高, 札の上, 印の幅, 列: 射手の列, 列の見当, 並びの人数, 外した強い列, 列の点, 行, 行の欠け, 上の字の行, 行ごとの列数, 印: 射手の印, 角度, 生 };
}

/**
 * 罫線から格子を立てる（印がマスいっぱいで、かたまりが拾えないときの代わり）。
 *
 * 罫線は細くて長い。縦横それぞれの墨の量を並べると、罫線のところだけ
 * 細い針のような山が立つ。印の丸や×は幅の広いなだらかな山になるので、
 * 「まわりの中央値からの飛び出し」を取れば罫線だけが残る。
 * 罫線は マスの本数+1 本、等間隔に並ぶので、その本数で当てはめる。
 *
 * 印がマスいっぱいの板では、墨の量の周期からは立てられない（丸は中が空で、
 * 隣と触れているので山谷が無い。実測で半マスずれた）。罫線ならそれでも立つ。
 */
/**
 * かたまりが1本の線（斜線）か。墨の広がりを主軸で見て、細い方向の広がりが
 * 太い方向の 8% 未満なら線。丸・◎・× は縦横に広がる（比は 0.5〜1）、
 * 丸に線でも輪があるので 0.3 以上。1本の斜線は (太さ÷長さ)² で 0.001 ほど
 */
function 斜線か(画, b) {
  let 数 = 0;
  let 和x = 0;
  let 和y = 0;
  let 和xx = 0;
  let 和yy = 0;
  let 和xy = 0;
  for (let y = b.上; y <= b.下; y++) {
    for (let x = b.左; x <= b.右; x++) {
      if (画.画素[y * 画.幅 + x] >= 平らの境) continue;
      数++;
      和x += x;
      和y += y;
      和xx += x * x;
      和yy += y * y;
      和xy += x * y;
    }
  }
  if (数 < 10) return false;
  const mx = 和x / 数;
  const my = 和y / 数;
  const sxx = 和xx / 数 - mx * mx;
  const syy = 和yy / 数 - my * my;
  const sxy = 和xy / 数 - mx * my;
  const 半 = (sxx + syy) / 2;
  const 差 = Math.sqrt(((sxx - syy) / 2) ** 2 + sxy * sxy);
  const 大 = 半 + 差;
  const 小 = Math.max(0, 半 - 差);
  return 大 > 0 && 小 / 大 < 0.08;
}

/**
 * 点の付いた列から、等間隔の目盛りに乗る列を 人数 ぶん選ぶ。
 *
 * 始めの2本の組み合わせを総当たりし、その間隔の整数倍（±25%）の位置にある列を集め、
 * 点の高い順に人数ぶん取る。目盛りの途中が抜けていてもよい（4人ごとに小計の列が
 * 挟まる板では、射手の列は「連続した」並びではなく、小計を飛ばした並びになる。
 * 連続を求めると小計を取って端の射手を落とした：9/6 の板の実測）。
 * 人数ぶん集まった目盛りのうち、点の和が最大のものを返す。強い列（必須）を
 * 含まない目盛りは取らない。組めなければ null
 */
function 連なりで選ぶ(点数つき, 人数, 必須 = []) {
  const 候補 = 点数つき.filter((x) => x.点 >= 0.3).sort((a, z) => a.列.中心 - z.列.中心);
  if (候補.length < 人数 || 人数 < 2) return null;
  if (必須.length > 人数) return null;
  let 最良 = null;
  for (let i = 0; i < 候補.length; i++) {
    for (let j = i + 1; j < 候補.length; j++) {
      const 間 = 候補[j].列.中心 - 候補[i].列.中心;
      if (間 <= 0) continue;
      // 目盛りに乗る列（同じ目盛りに2つ乗ったら点の高いほう）
      const 乗った = new Map();
      for (const x of 候補) {
        const k = Math.round((x.列.中心 - 候補[i].列.中心) / 間);
        if (Math.abs(x.列.中心 - (候補[i].列.中心 + k * 間)) > 間 * 0.25) continue;
        const 今 = 乗った.get(k);
        if (!今 || x.点 > 今.点) 乗った.set(k, x);
      }
      const 列たち = [...乗った.values()];
      if (列たち.length < 人数) continue;
      if (!必須.every((m) => 列たち.includes(m))) continue;
      const 選び = 列たち.sort((a, z) => z.点 - a.点).slice(0, 人数);
      if (!必須.every((m) => 選び.includes(m))) continue;
      const 和 = 選び.reduce((a, x) => a + x.点, 0);
      if (!最良 || 和 > 最良.和) 最良 = { 選び, 和 };
    }
  }
  return 最良 ? 最良.選び.map((x) => x.列).sort((a, z) => a.中心 - z.中心) : null;
}

/** 消す罫線の長さ（画素）。印の線は長くても印の幅（期待するマスの 1.15 倍）ほど */
function 罫線の長さ(幅, 人数) {
  return Math.round((幅 / (人数 * 1.35 + 2)) * 1.3);
}

/**
 * 下ごしらえ：明るさを平らにし、罫線を消す。
 * 返す 生 は罫線を消した明るさの画（マスの切り出しに使う）、平ら は罫線を消した
 * 平らな画（印を拾うのに使う）。平らにする半径は写真の幅の 1/12（マス2つぶんほど）
 */
export function 下ごしらえ(生, 長さ) {
  const 平ら = 平らにする(生, Math.round(生.幅 / 12));
  const 消し = 罫線を消す(生, 長さ, 平らの境, 平ら);
  return { 生: { 画素: 消し.画素, 幅: 生.幅, 高: 生.高 }, 平ら: { 画素: 消し.消した, 幅: 生.幅, 高: 生.高 } };
}

/**
 * 縦横の墨の量を並べる（罫線探しの元）。
 */
export function 墨の量(生) {
  const 境 = 暗さの境(生.画素);
  const 横 = new Float64Array(生.幅);
  const 縦 = new Float64Array(生.高);
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] < 境) {
        横[x]++;
        縦[y]++;
      }
    }
  }
  return { 横, 縦 };
}

/**
 * 墨の量の並びから、等間隔の罫線を 本数+1 本見つける。
 *
 * 罫線は細くて長い。墨の量を並べると、罫線のところだけ細い針のような山が立つ。
 * 印の丸や×は幅の広いなだらかな山になるので、「まわりの中央値からの飛び出し」を
 * 取れば罫線だけが残る。
 *
 * 間隔と起点を総当たりし、各線の位置での針の高さ（±3px の最大）を足した点で選ぶ。
 * 「合った針の本数」で選ぶと、印の縁が作る弱い針を細かい間隔が拾って勝つ
 *（実測で本当は55.6の間隔が48.6に取られ、下の行ほどずれた）。
 *
 * @param {Float64Array} 並び 墨の量
 * @param {number} 本数 マスの数（罫線は本数+1）
 * @param {number} 長さの向こう 直交する向きの画の長さ（針の高さの目安）
 * @param {number} [見当の指定] 間隔のあたり。無ければ 画の長さ÷本数
 * @returns {{位置:number[], 間隔:number, 始め:number}|null}
 */
export function 罫線を拾う(並び, 本数, 長さの向こう, 見当の指定, 探す範囲, 寄せる, 起点の範囲) {
  // 起点の範囲 … [下, 上]。最初の線の位置が分かっているとき（外枠で正した紙は
  // 左端・上端が枠の線）に渡す。置き方の取り違えが無くなる
  // 探す範囲は見当に掛ける倍率。紙の記録用紙は表の右に小計の列が写るので、
  // 画の幅÷人数では見当が大きすぎる（実測で本当は33pxのところ49〜81pxを探していた）
  const [狭, 広] = 探す範囲 || [0.75, 1.25];
  const 見当 = 見当の指定 || 並び.length / 本数;
  const 幅 = Math.max(2, Math.round(見当 * 0.15));
  const 飛び出し = new Float64Array(並び.length);
  for (let i = 0; i < 並び.length; i++) {
    const まわり = [];
    for (let j = Math.max(0, i - 幅); j <= Math.min(並び.length - 1, i + 幅); j++) まわり.push(並び[j]);
    まわり.sort((a, z) => a - z);
    飛び出し[i] = 並び[i] - まわり[Math.floor(まわり.length / 2)];
  }
  // 罫線は画の端から端まで 本数+1 本、ほぼ等間隔。間隔と起点を総当たりし、
  // 各線の位置での針の高さ（±3px の最大）を足した点で選ぶ。
  // 「合った針の本数」で選ぶと、印の縁が作る弱い針を細かい間隔が拾って勝つ
  //（実測で本当は55.6の間隔が48.6に取られ、下の行ほどずれた）。
  // 高さの合計なら、濃い罫線に乗った置き方しか高い点にならない
  const 高さ = (i) => {
    let 最 = 0;
    for (let j = Math.max(0, i - 3); j <= Math.min(並び.length - 1, i + 3); j++) if (飛び出し[j] > 最) 最 = 飛び出し[j];
    return 最;
  };
  let 最良 = null;
  for (let 間隔 = 見当 * 狭; 間隔 <= 見当 * 広; 間隔 += 0.25) {
    // 最初の罫線は画の端とは限らない（左に番号の列が28px在る実物があり、
    // 回した紙の切り抜きには余白が2マスぶん付く）。起点は画の全体から探す。
    // 点は針の高さの合計なので、表の中の線に乗った置き方しか高くならない
    const 始 = 起点の範囲 ? 起点の範囲[0] : -間隔;
    const 終 = 起点の範囲 ? 起点の範囲[1] : 並び.length - 間隔 * (本数 - 0.5);
    for (let 起点 = 始; 起点 <= 終; 起点 += 1) {
      // マスの中心（線と線の真ん中）は、ぜんぶ画の中に在ること。
      // 端の罫線が画の外にあると点が同じ置き方が2つでき、先に見つかった
      // ほうが勝って1行ずれた（実測）
      if (起点 + 間隔 * 0.5 < 0 || 起点 + 間隔 * (本数 - 0.5) > 並び.length) continue;
      let 点 = 0;
      let 乗った = 0;
      for (let k = 0; k <= 本数; k++) {
        const p = Math.round(起点 + 間隔 * k);
        if (p < 0 || p >= 並び.length) continue;
        const h = 高さ(p);
        点 += h;
        if (h > 長さの向こう * 0.06) 乗った++;
      }
      // 置き方の外側、1本ぶん離れたところにも線があるなら、その線を捨てて
      // 別の線を取っている置き方なので減点する。紙では小計の右端の線が
      // 射手の列の線と同じ強さで、左端を捨てて小計の線を取る置き方が勝った
      //（実測で4度傾けた紙の列が1本ずれた）
      // 相手が画の端から3px外に出ていても、端の線は拾う（正した紙の外枠は
      // 端から3pxのところにあり、-2px に落ちて減点が効かなかった）
      for (const p of [Math.round(起点 - 間隔), Math.round(起点 + 間隔 * (本数 + 1))]) {
        if (p >= -3 && p < 並び.length + 3) 点 -= 高さ(Math.max(0, Math.min(並び.length - 1, p))) * 0.8;
      }
      if (!最良 || 点 > 最良.点) 最良 = { 点, 間隔, 起点, 乗った };
    }
  }
  if (!最良 || 最良.乗った < (本数 + 1) * 0.5) return null;
  // 等間隔に置いたあと、頼まれたら線ごとに近くの針へ寄せる。斜めから撮ると
  // 遠い側ほど間隔が縮み、等間隔のままでは端の線が数px外れる（紙の実物で
  // 117→126 と広がり、マス30pxに対して端が5pxずれていた）。
  // 印がマスいっぱいの板では丸の縁も針になり、寄せると逆に崩れる（4人立ちの
  // 実物で2列が外れた）ので、罫線が濃く印が細い紙だけが頼む
  const 位置 = [];
  const 寄せ幅 = 寄せる ? Math.max(2, Math.round(最良.間隔 * 0.12)) : 0;
  for (let k = 0; k <= 本数; k++) {
    const p = Math.round(最良.起点 + 最良.間隔 * k);
    let 最 = p;
    let 高 = -1;
    for (let j = Math.max(0, p - 寄せ幅); j <= Math.min(並び.length - 1, p + 寄せ幅); j++) {
      if (飛び出し[j] > 高) {
        高 = 飛び出し[j];
        最 = j;
      }
    }
    位置.push(寄せる && 高 > 長さの向こう * 0.06 ? 最 : p);
  }
  return { 位置, 間隔: 最良.間隔, 始め: 位置[0] };
}

/**
 * 罫線から格子を立てる（印がマスいっぱいで、かたまりが拾えないときの代わり）。
 * 縦横とも、マスごとに罫線が引かれている板が前提。
 *
 * 印がマスいっぱいの板では、墨の量の周期からは立てられない（丸は中が空で、
 * 隣と触れているので山谷が無い。実測で半マスずれた）。罫線ならそれでも立つ。
 */
function 罫線で格子(生, 注文, 角度) {
  const { 横, 縦 } = 墨の量(生);
  // 見当は画の長さ÷本数（画に写っているのが印の部分だけ、という前提）。
  // 候補の端から端で取ると、印の縁の針に引かれて狂う（実測で 51 が 37 になった）。
  // マスは正方形とは限らない（実測の板で 47×55）ので、列の間隔を行に流用しない
  const 列 = 罫線を拾う(横, 注文.人数, 生.高);
  const 行 = 罫線を拾う(縦, 注文.行数, 生.幅);
  if (!列 || !行) return null;
  const 列の中心 = [];
  for (let i = 0; i < 注文.人数; i++) 列の中心.push(列.位置[i] + 列.間隔 / 2);
  const 行の中心 = [];
  for (let i = 0; i < 注文.行数; i++) 行の中心.push(行.位置[i] + 行.間隔 / 2);
  const 印の幅 = Math.round(Math.min(列.間隔, 行.間隔) * 0.8);
  return {
    幅: 生.幅,
    高: 生.高,
    札の上: 生.高,
    印の幅,
    列: 列の中心.map((x) => ({ 中心: x, 数: 注文.行数, ずれ: 0 })),
    行: { 位置: 行の中心, 間隔: 行.間隔, 始め: 行の中心[0] },
    印: [],
    角度,
    生,
    立て方: '罫線',
  };
}

/**
 * 墨の量の並びから格子を立てる（かたまりが拾えないときの代わり）。
 *
 * マスの真ん中は墨が多く、マスの境は白いか細い罫線しかない。縦横それぞれの
 * 墨の量を並べると、マスの本数ぶんの山と谷が等間隔に並ぶ。
 * 本数は分かっているので、間隔と起点を総当たりして、山が真ん中に来て谷が境に
 * 来る置き方を選ぶ。
 *
 * 前提: 画に写っているのが印の部分だけであること（見出しや名前が入ると
 * 周期が崩れる）。かたまりで立てる方式と違い、数字の列を見分ける力はない。
 */
function 墨の並びで格子(生, 注文, 角度) {
  const 境 = 暗さの境(生.画素);
  const 横 = new Float64Array(生.幅);
  const 縦 = new Float64Array(生.高);
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] < 境) {
        横[x]++;
        縦[y]++;
      }
    }
  }
  const 当てる = (並び, 本数) => {
    const 長さ = 並び.length;
    let 最良 = null;
    for (let 間隔 = (長さ / 本数) * 0.7; 間隔 <= (長さ / 本数) * 1.05; 間隔 += 0.5) {
      for (let 起点 = 0; 起点 < 間隔; 起点 += 1) {
        // 本数ぶん並べたとき、端が画からはみ出しすぎるものは捨てる
        const 終わり = 起点 + 間隔 * 本数;
        if (終わり > 長さ + 間隔 * 0.3) break;
        let 点 = 0;
        for (let i = 0; i < 本数; i++) {
          const 左 = 起点 + 間隔 * i;
          const 右 = 左 + 間隔;
          // 真ん中6割の墨を足し、境の1割の墨を引く
          for (let t = Math.max(0, Math.floor(左 + 間隔 * 0.2)); t < Math.min(長さ, 右 - 間隔 * 0.2); t++) 点 += 並び[t];
          for (let t = Math.max(0, Math.floor(左 - 間隔 * 0.05)); t < Math.min(長さ, 左 + 間隔 * 0.05); t++) 点 -= 並び[t] * 2;
        }
        if (!最良 || 点 > 最良.点) 最良 = { 点, 間隔, 起点 };
      }
    }
    const 位置 = [];
    for (let i = 0; i < 本数; i++) 位置.push(最良.起点 + 最良.間隔 * (i + 0.5));
    return { 位置, 間隔: 最良.間隔 };
  };
  const 列 = 当てる(横, 注文.人数);
  const 行 = 当てる(縦, 注文.行数);
  // 印の幅は、マスの大きさから見当を付ける（印はマスの8割ほど）
  const 印の幅 = Math.round(Math.min(列.間隔, 行.間隔) * 0.8);
  return {
    幅: 生.幅,
    高: 生.高,
    札の上: 生.高,
    印の幅,
    列: 列.位置.map((x) => ({ 中心: x, 数: 注文.行数, ずれ: 0 })),
    行: { 位置: 行.位置, 間隔: 行.間隔, 始め: 行.位置[0] },
    印: [],
    角度,
    生,
    立て方: '墨の並び',
  };
}

/**
 * 1マスを切り出す箱の大きさ。
 *
 * 学習側と本物側で別々に書いていたら、片方が 行の間隔×0.37、もう片方が
 * ×0.48 になっていた。同じ写真から違う大きさで切っていたので、網が見ている
 * ものが食い違っていた。ここ一箇所で決める。
 */
export function 箱の大きさ(格子の中身) {
  // 箱はマスの間隔を超えない。印がマスいっぱいに書かれた板では、印の幅から
  // 決めた箱が隣のマスにかぶり、×の箱に上下の丸が入って「丸に線」と読み違えた
  //（4人立ちの板の実物）。これまでの板では印がマスの半分ほどなので、
  // 間隔の縛りは掛からず、数字は変わらない
  const 列 = 格子の中身.列;
  const 列の間隔 =
    列.length >= 2
      ? 列.slice(1).map((c, i) => c.中心 - 列[i].中心).sort((a, z) => a - z)[Math.floor((列.length - 1) / 2)]
      : Infinity;
  const 半幅 = Math.round(Math.min(格子の中身.印の幅 * (Number(process.env.OCR_HABA) || 0.85), 列の間隔 * 0.48));
  // 縦は行の間隔の 0.55。0.48 だと、マスの下寄りに書かれた印の下が切れて
  // ○／ の下半分が箱の外に出た（本物で ◎ と読み違えた）。上下の隣の印が少し入るが、
  // 囲み直しで真ん中の印だけを取るので困らない（本物2枚で 317・318 → 318・318）。
  // ただし印がマスいっぱいの板（かたまりが拾えず罫線や墨の並びで格子を立てた板。
  // 4人立ちの実物）では隣の印がつながって入るので 0.48 のまま
  //（0.55 にすると 3列 → 2列に落ちた。印の幅と行の間隔の比では見分けられない：
  // ぎっしりの板は 0.66、ふつうの板は 0.72 だった）
  const ぎっしり = !!格子の中身.立て方;
  const 半高 = Math.round(
    Math.min(格子の中身.行.間隔 * (Number(process.env.OCR_TAKA) || (ぎっしり ? 0.48 : 0.55)), 格子の中身.印の幅 * 0.9)
  );
  return { 半幅, 半高 };
}


/**
 * 写真に板が何枚か写っているとき、板ごとに分けて格子を立てる。
 *
 * 印を拾って x で束ね、束と束の間がいちばん広いところで切る（板と板の間は
 * マス何個ぶんも空く）。板の枚数は 板の人数たち の長さ。板ごとに、その人数で
 * 格子を立てる。板は左から順に並んでいるものとする。
 *
 * @param {{画素:Uint8Array, 幅:number, 高:number, 色?:object}} 元
 * @param {{板の人数たち:number[], 行数:number, 回す?:Function}} 注文
 * @returns {Promise<{格子:object, 左:number}[]>} 板ごとの格子と、切り出した左端
 */
export async function 板ごとの格子(元, 注文) {
  const 板の人数たち = 注文.板の人数たち;
  // 箱（○×のマスの範囲）を渡されたときは、その中を等分して格子にする（下の 箱で格子）。
  // 印がマスいっぱいで隣と触れ合う板（相手校の板）は、かたまりからは列も行も立たない
  if (Array.isArray(注文.箱たち) && 注文.箱たち.length === 板の人数たち.length) {
    const 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
    return 注文.箱たち.map((箱, i) => {
      const g = 箱で格子(生, 箱, { 人数: 板の人数たち[i], 行数: 注文.行数 });
      return { 格子: g, 左: g.箱の左 };
    });
  }
  if (板の人数たち.length === 1) {
    return [{ 格子: await 格子(元, { 人数: 板の人数たち[0], 行数: 注文.行数, 回す: 注文.回す }), 左: 0 }];
  }
  let 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
  const 全人数 = 板の人数たち.reduce((a, b) => a + b, 0);
  // 印の大きさの見当。列は 人数×1.35+2 本が板ごと（板の数だけ余白も増える）
  const 期待するマス = 生.幅 / (全人数 * 1.35 + 2 * 板の人数たち.length + 1);
  const 最小 = Math.max(6, Math.round(期待するマス * 0.22));
  const 最大 = Math.round(期待するマス * 1.15);
  // 写真ぜんぶを平らにして罫線を消してから、印を拾って板に分ける。
  // 板ごとの格子には下ごしらえ済みで渡す（切り抜きの 生 と 平ら を両方）
  const 色 = 元.色;
  let 平ら;
  ({ 生, 平ら } = 下ごしらえ(生, Math.round(期待するマス * 1.3)));
  let 印 = かたまりを拾う(平ら, 平らの境).filter(
    (b) =>
      b.幅 >= 最小 && b.幅 <= 最大 && b.高 >= 最小 && b.高 <= 最大 &&
      b.幅 / b.高 > 0.45 && b.幅 / b.高 < 2.2 &&
      b.数 > 最小 * 最小 * 0.12
  );
  if (印.length < 全人数 * 3) throw new Error('印が少なすぎます（' + 印.length + '個）');
  // 傾きは写真ぜんぶで一度だけ測って起こす。板ごとに別の角度で回すと、同じ板の左右で
  // 行の y が食い違い、行を共有できない
  const 角度 = 傾きを測る(印, 最小);
  if (Math.abs(角度) > 1.5 && 注文.回す) {
    生 = await 注文.回す(生, 角度);
    ({ 生, 平ら } = 下ごしらえ(生, Math.round(期待するマス * 1.3)));
    const 拾い直し = かたまりを拾う(平ら, 平らの境).filter(
      (b) =>
        b.幅 >= 最小 && b.幅 <= 最大 && b.高 >= 最小 && b.高 <= 最大 &&
        b.幅 / b.高 > 0.45 && b.幅 / b.高 < 2.2 &&
        b.数 > 最小 * 最小 * 0.12
    );
    if (拾い直し.length < 全人数 * 3) throw new Error('起こしたあと、印が少なすぎます（' + 拾い直し.length + '個）');
    印.length = 0;
    印.push(...拾い直し);
  }
  const 印の幅 = 印.map((b) => b.幅).sort((a, z) => a - z)[Math.floor(印.length / 2)];
  const 束 = 山で束ねる(印.map((b) => b.x), 印の幅).filter((c) => c.数 >= 3);
  // 束の強さ … 印らしい（印の幅の 6 割以上あって丸い）かたまりの数。数字の列や斜線の破片の
  // 列は弱い。板の切れ目は、強い束がどの板にも人数ぶん残る切り方から選ぶ
  for (const c of 束) {
    c.強さ = 印.filter((b) => Math.abs(b.x - c.中心) <= 印の幅 * 0.65 && b.幅 >= 印の幅 * 0.6 && b.幅 / b.高 >= 0.7 && b.幅 / b.高 <= 1.6).length;
  }
  // 束と束の隙間。板と板の間は隙間が広い。ただし写真の端に別の板や物が写ると、
  // いちばん広い隙間がそこになる（9/13 の縦の写真で、左端の隣の板との隙間で切り、
  // 8人の板を丸ごと2枚目にした）。隙間の広い順に見て、左右の束の数がどちらも
  // その板の人数以上になる切り方を取る（列の数の辻褄が合う最初の広い隙間）
  const 隙間 = [];
  for (let i = 1; i < 束.length; i++) 隙間.push({ 幅: 束[i].端[0] - 束[i - 1].端[1], 位置: (束[i].中心 + 束[i - 1].中心) / 2, 番: i });
  // 強い束は、印らしいかたまりが行数の6割以上あるもの（写真の端に写った物は少ない）
  const 切れ目 = 切れ目を選ぶ(束, 隙間, 板の人数たち, Math.max(2, Math.ceil(注文.行数 * 0.6)));
  if (process.env.OCR_WAKE) console.error('板の切れ目', '印の幅', 印の幅, '束', 束.map((c) => `${c.中心.toFixed(0)}(${c.数}/${c.強さ})`).join(' '), '隙間', 隙間.map((g) => `${g.位置.toFixed(0)}:${g.幅.toFixed(0)}`).join(' '), '切れ目', 切れ目.map((v) => v.toFixed(0)).join(','));
  const 出 = [];
  let 左端 = 0;
  for (let i = 0; i < 板の人数たち.length; i++) {
    const 右端 = i < 切れ目.length ? 切れ目[i] : 生.幅;
    // 板の範囲は、その区間の印の端に余白を足したもの
    const その板 = 印.filter((b) => b.x >= 左端 && b.x < 右端);
    if (その板.length < 板の人数たち[i] * 3) throw new Error(`${i + 1}枚目の板の印が少なすぎます（${その板.length}個）`);
    // 余白は印の幅の 0.75 倍（印1つが入る）。1.5 倍だと隣の板の端の列まで入り、
    // 板ごとの格子がその列を射手に取った（9/13 の板で、右の板に左の板の4人目が入った）
    const 左 = Math.max(0, Math.floor(Math.min(...その板.map((b) => b.x)) - 印の幅 * 0.75));
    const 右 = Math.min(生.幅, Math.ceil(Math.max(...その板.map((b) => b.x)) + 印の幅 * 0.75));
    const 切 = { 画素: new Uint8Array((右 - 左) * 生.高), 幅: 右 - 左, 高: 生.高 };
    const 切の平ら = { 画素: new Uint8Array((右 - 左) * 生.高), 幅: 右 - 左, 高: 生.高 };
    for (let y = 0; y < 生.高; y++) {
      切.画素.set(生.画素.subarray(y * 生.幅 + 左, y * 生.幅 + 右), y * 切.幅);
      切の平ら.画素.set(平ら.画素.subarray(y * 生.幅 + 左, y * 生.幅 + 右), y * 切.幅);
    }
    let 切の色;
    if (色 && Math.abs(角度) <= 1.5 && 色.data.length === 生.幅 * 生.高 * 色.ch) {
      const ch = 色.ch;
      切の色 = { data: new Uint8Array((右 - 左) * 生.高 * ch), ch };
      for (let y = 0; y < 生.高; y++) 切の色.data.set(色.data.subarray((y * 生.幅 + 左) * ch, (y * 生.幅 + 右) * ch), y * 切.幅 * ch);
    }
    // この板の列の間隔（束の中心の間の中央値）。印の大きさの見当に使う
    const この板の束 = 束.filter((c) => c.中心 >= 左端 && c.中心 < 右端).map((c) => c.中心 - 左);
    const 間たち = この板の束.slice(1).map((v, j) => v - この板の束[j]).sort((a, z) => a - z);
    const マスの見当 = 間たち.length ? 間たち[Math.floor(間たち.length / 2)] : undefined;
    出.push({
      格子: await 格子({ ...切, 色: 切の色 }, { 人数: 板の人数たち[i], 行数: 注文.行数, 回す: 注文.回す, 下ごしらえ済み: true, 平ら: 切の平ら, マスの見当, 角度: 0 }),
      左,
      切: { ...切, 色: 切の色, 平ら: 切の平ら, マスの見当 },
    });
    左端 = 右端;
  }
  // 行を共有する。同じ写真の板は同じ高さに並んでいることが多い（同じ板の左右の半分は
  // 必ず同じ）。行が欠けた板（下の段に空の行がある＝置き方が決まっていない）は、
  // 欠けが無い板の行をそのまま使って立て直す
  // 手本は、行の欠けが無く、埋まった行がいちばん多い板（行数の6割以上）
  const 埋まった数 = (b) => (b.格子.行ごとの列数 || []).filter((n) => n > 0).length;
  const 手本 = 出
    .filter((b) => b.格子.行の欠け === 0 && 埋まった数(b) >= 注文.行数 * 0.6)
    .sort((a, z) => 埋まった数(z) - 埋まった数(a))[0];
  if (手本) {
    // 手本のいちばん下の行より、半行より下にあるかたまりは、名札（白い紙の氏名）の字。
    // 板は同じ高さに並ぶので、手本の下の行より下に印の行は無い。右半分の板が名札の行を
    // 印の行として取り、行が1つ下へずれた（9/13 の途中の板で、右の4人が 19/32）。
    // 行の欠けが無くても（名札の行で埋まって見える）手本と比べる
    const 手本の行 = 手本.格子.行.位置;
    const 手本の下 = 手本の行[手本の行.length - 1] + (手本の行.length >= 2 ? (手本の行[手本の行.length - 1] - 手本の行[0]) / (手本の行.length - 1) : 手本.格子.印の幅) * 0.5;
    for (let i = 0; i < 出.length; i++) {
      const b = 出[i];
      if (b === 手本) continue;
      // 手本の行のほうが、この板の印をよく支えるときだけ使う（同じ板の左右でも、斜めから
      // 撮ると右半分の行は少し縮む。自分の行のほうが合っているなら替えない）
      const 許し = b.格子.印の幅 * 0.55;
      const 印たち = b.格子.印.filter((p) => p.y <= 手本の下);
      const 支え = (位置たち) => 印たち.filter((p) => 位置たち.some((y) => Math.abs(p.y - y) <= 許し)).length;
      if (process.env.OCR_WAKE) console.error('行の共有', i, '手本の支え', 支え(手本.格子.行.位置), '自分の支え', 支え(b.格子.行.位置), '手本の行', 手本.格子.行.位置.map((v) => v.toFixed(0)).join(','));
      // 自分の行が詰まって置かれていると、破片を余分に拾って支えが少し多く出る。1割は見る。
      // ただし行の欠けが無い（自分の置き方が決まっている）板は、手本が同じ以上に支える
      // ときだけ（9/6 の板は左右で少し縮んでいて、1割の余裕で右の板が左の行を取り 318 → 312）
      // 自分の行が手本の下の行より半行以上下まで伸びているなら、名札の行を取っている疑いが
      // 強いので、こちらも 1 割見る
      const 自分 = 支え(b.格子.行.位置);
      const 下へはみ出た = b.格子.行.位置[b.格子.行.位置.length - 1] > 手本の下;
      const 余裕 = b.格子.行の欠け > 0 || 下へはみ出た ? Math.max(2, 自分 * 0.1) : 0;
      if (支え(手本.格子.行.位置) < 自分 - 余裕) continue;
      出[i] = {
        格子: await 格子(b.切, { 人数: 板の人数たち[i], 行数: 注文.行数, 回す: 注文.回す, 下ごしらえ済み: true, 平ら: b.切.平ら, マスの見当: b.切.マスの見当, 角度: 0, 行の位置: 手本.格子.行.位置 }),
        左: b.左,
      };
    }
  }
  for (const b of 出) delete b.切;
  return 出;
}

/**
 * 箱（○×のマスの範囲。Gemini が返す box_2d、画像を 0〜1000 に正規化した [上, 左, 下, 右]）の
 * 中を、人数×行数に等分して格子にする。
 *
 * ■ なぜ
 *   相手校の板は印がマスいっぱいで、上下の印と触れて1つのかたまりになる。計の列や題の列も
 *   射手の列と同じ間隔で並ぶ。かたまりで格子を立てるやり方（格子）は列も行も選べなかった。
 *   Gemini は射手の列だけの範囲を 1% ほどの精度で返せる（9/13 の相手校の板 2 枚で実測）ので、
 *   範囲は Gemini、中の割り方はこちらで決める。
 *
 * ■ 割り方
 *   列は箱の幅を人数で等分。行は箱の高さを行数で等分。どちらも、境の近く（±15%）に
 *   罫線（暗い画素が縦／横に長く並ぶ所）があればそこへ寄せる。無ければ等分のまま
 *  （1マス2射の板は、帯の中の2行のあいだに線が無い）。
 *   箱の外側に 3% の余白を付けて切り抜く（Gemini の箱は端の印を少し欠くことがある）
 */
export function 箱で格子(生, 箱, 注文) {
  const [上n, 左n, 下n, 右n] = 箱.map((v) => Math.max(0, Math.min(1000, Number(v) || 0)) / 1000);
  const 箱の幅 = (右n - 左n) * 生.幅;
  const 箱の高 = (下n - 上n) * 生.高;
  if (!(箱の幅 > 8 * 注文.人数) || !(箱の高 > 8 * 注文.行数)) throw new Error('箱が小さすぎます');
  const 余白x = Math.round(箱の幅 * 0.03);
  const 余白y = Math.round(箱の高 * 0.03);
  const 左 = Math.max(0, Math.round(左n * 生.幅) - 余白x);
  const 上 = Math.max(0, Math.round(上n * 生.高) - 余白y);
  const 右 = Math.min(生.幅, Math.round(右n * 生.幅) + 余白x);
  const 下 = Math.min(生.高, Math.round(下n * 生.高) + 余白y);
  const 幅 = 右 - 左;
  const 高 = 下 - 上;
  const 画素 = new Uint8Array(幅 * 高);
  for (let y = 0; y < 高; y++) for (let x = 0; x < 幅; x++) 画素[y * 幅 + x] = 生.画素[(上 + y) * 生.幅 + 左 + x];
  const 切 = { 画素, 幅, 高 };
  // 罫線の位置。暗い画素の数を列／行ごとに数え、まわりより飛び出た所
  const { 横, 縦 } = 墨の量(切);
  const 針 = (並び, 幅の目安) => {
    const 出 = new Float64Array(並び.length);
    const w = Math.max(3, Math.round(幅の目安 * 0.15));
    for (let i = 0; i < 並び.length; i++) {
      const まわり = [];
      for (let j = Math.max(0, i - w); j <= Math.min(並び.length - 1, i + w); j++) まわり.push(並び[j]);
      まわり.sort((a, z) => a - z);
      出[i] = 並び[i] - まわり[Math.floor(まわり.length / 2)];
    }
    return 出;
  };
  // 等分の境を、近くの罫線へ寄せる。寄せるのは、はっきり飛び出た針（長さの 25% 以上）だけ。
  // 罫線が無ければ、墨のいちばん少ない所（印と印の谷。±20%）へ寄せる。印が小さい板では
  // 谷がはっきりしていて、等分のままより行が合う（9/6 の板の箱で 282 → 294）。
  // 外側の 2 本（箱の縁）は寄せない（箱の外の字や罫線へ引かれる）
  const 境たち = (長さ, 本数, 並び, 向こうの長さ, 余白) => {
    const 間隔 = (長さ - 余白 * 2) / 本数;
    const 出 = [];
    const 飛び = 針(並び, 間隔);
    // 谷を見るための、ならした墨の量（幅は間隔の 1 割）
    const w = Math.max(1, Math.round(間隔 * 0.1));
    const ならし = new Float64Array(並び.length);
    for (let i = 0; i < 並び.length; i++) {
      let 和 = 0;
      let n = 0;
      for (let j = Math.max(0, i - w); j <= Math.min(並び.length - 1, i + w); j++) {
        和 += 並び[j];
        n++;
      }
      ならし[i] = 和 / n;
    }
    for (let k = 0; k <= 本数; k++) {
      const p = 余白 + 間隔 * k;
      let 最 = p;
      let 高さ = 0;
      const 幅 = Math.round(間隔 * 0.15);
      for (let j = Math.max(0, Math.round(p) - 幅); j <= Math.min(並び.length - 1, Math.round(p) + 幅); j++) {
        if (飛び[j] > 高さ) {
          高さ = 飛び[j];
          最 = j;
        }
      }
      if (高さ >= 向こうの長さ * 0.25) {
        出.push(最);
        continue;
      }
      if (k === 0 || k === 本数) {
        出.push(p);
        continue;
      }
      let 谷 = p;
      let 少 = Infinity;
      const 探す = Math.round(間隔 * 0.16);
      for (let j = Math.max(0, Math.round(p) - 探す); j <= Math.min(並び.length - 1, Math.round(p) + 探す); j++) {
        if (ならし[j] < 少) {
          少 = ならし[j];
          谷 = j;
        }
      }
      出.push(谷);
    }
    return { 境: 出, 間隔 };
  };
  const 列境 = 境たち(幅, 注文.人数, 横, 高, 余白x);
  const 行境 = 境たち(高, 注文.行数, 縦, 幅, 余白y);
  const 列の中心 = [];
  for (let i = 0; i < 注文.人数; i++) 列の中心.push((列境.境[i] + 列境.境[i + 1]) / 2);
  const 行の中心 = [];
  for (let i = 0; i < 注文.行数; i++) 行の中心.push((行境.境[i] + 行境.境[i + 1]) / 2);
  const 印の幅 = Math.round(Math.min(列境.間隔, 行境.間隔) * 0.8);
  return {
    幅,
    高,
    札の上: 高,
    印の幅,
    列: 列の中心.map((x) => ({ 中心: x, 数: 注文.行数, ずれ: 0 })),
    行: { 位置: 行の中心, 間隔: 行境.間隔, 始め: 行の中心[0] },
    印: [],
    角度: 0,
    生: 切,
    立て方: '箱',
    箱の左: 左,
    行の欠け: 0,
    上の字の行: 0,
  };
}

/**
 * 板と板の切れ目を選ぶ。隙間の広い順に試し、どの板にもその人数ぶんの束が
 * 残る切り方を取る。どれも合わなければ、昔どおり広い順
 */
function 切れ目を選ぶ(束, 隙間, 板の人数たち, 強い束の下限 = 2) {
  const 枚数 = 板の人数たち.length;
  if (枚数 <= 1 || 隙間.length < 枚数 - 1) return [];
  const 強い = 束.map((c) => (c.強さ == null ? true : c.強さ >= 強い束の下限));
  const 広い順 = 隙間.slice().sort((a, z) => z.幅 - a.幅);
  // 上から 6 つの隙間の組み合わせだけ見る（板は 2〜3 枚。組み合わせは少ない）
  const 候補 = 広い順.slice(0, Math.min(広い順.length, 6));
  const 組み合わせ = (k, 始) => {
    if (k === 0) return [[]];
    const 出 = [];
    for (let i = 始; i < 候補.length; i++) for (const 残り of 組み合わせ(k - 1, i + 1)) 出.push([候補[i], ...残り]);
    return 出;
  };
  // 板ごとに「等間隔に並んだ強い束の連なり」の長さが人数にいちばん近い切り方を取る。
  // 同じなら隙間の広いほう。射手の列は等間隔に並ぶが、小計の列（半分の間隔）や
  // 板の外の字・物は並びに乗らない。「強い束の数が人数以上」だと、写真の端の菓子の箱や
  // 数字の列まで数えて、2px 広いだけの隙間で切った（9/13 の寄りの写真）
  const 連なりの長さ = (始, 終) => {
    const 中心たち = [];
    for (let k = 始; k < 終; k++) if (強い[k]) 中心たち.push(束[k].中心);
    let 最長 = Math.min(1, 中心たち.length);
    for (let i = 0; i < 中心たち.length; i++) {
      let 長さ = 1;
      let 間 = 0;
      for (let j = i + 1; j < 中心たち.length; j++) {
        const d = 中心たち[j] - 中心たち[j - 1];
        if (!間) 間 = d;
        else if (d < 間 * 0.75 || d > 間 * 1.25) break;
        長さ++;
      }
      if (長さ > 最長) 最長 = 長さ;
    }
    return 最長;
  };
  let 最良 = null;
  for (const 組 of 組み合わせ(枚数 - 1, 0)) {
    const 並べた = 組.slice().sort((a, z) => a.番 - z.番);
    let 前 = 0;
    let ずれ = 0;
    for (let i = 0; i < 枚数; i++) {
      const 次 = i < 並べた.length ? 並べた[i].番 : 束.length;
      ずれ += Math.abs(連なりの長さ(前, 次) - 板の人数たち[i]);
      前 = 次;
    }
    const 狭さ = Math.min(...組.map((g) => g.幅));
    if (!最良 || ずれ < 最良.ずれ || (ずれ === 最良.ずれ && 狭さ > 最良.狭さ)) 最良 = { 組: 並べた, 狭さ, ずれ };
  }
  const 組 = 最良 ? 最良.組 : 広い順.slice(0, 枚数 - 1).sort((a, z) => a.番 - z.番);
  return 組.map((g) => g.位置);
}
