/**
 * 板の写真から、マスを1つずつ切り出す。学習用の札も一緒に貼る。
 *
 *   node scripts/ocr-cells/kiridasu.mjs <画像> <射手の人数> <1人あたりのマス数> [出し先]
 *   node scripts/ocr-cells/kiridasu.mjs 板.jpg 8 10 out --正解 910280:男子リーグ --起点 下から --列 0-7
 *
 * ■ どうやって格子を見つけるか
 * 罫線は薄くて写真では拾えない（実測）。○×そのものが規則正しく並んでいるので、
 * 濃いかたまりを拾い、その並びから格子を復元する。行の本数は分かっている
 *（射数と1マスの射数で決まる）ので、その本数の等間隔をいちばんよく合う位置に置く。
 *
 * ■ 名札の帯を外す
 * 名札は色の枠に入っている。彩度の高い帯を見つけて、そこから下は見ない。
 * 板の上端の数字（各人の的中数）も印ではないので、いちばん上の帯も外す。
 */
import { 暗さの境, かたまりを拾う, 束ねる, 明暗を伸ばす, 傾きを測る } from './koushi.mjs';
import { 等間隔を当てはめる } from './atehameru.mjs';

/** 色の濃い（彩度の高い）帯を探す。名札はここに在る */
export function 色の帯を探す(色, 幅, 高) {
  const data = 色.data;
  const ch = 色.ch;
  const 彩度 = new Array(高).fill(0);
  for (let y = 0; y < 高; y++) {
    let 合 = 0;
    for (let x = 0; x < 幅; x++) {
      const i = (y * 幅 + x) * ch;
      const r = data[i];
      const g = data[i + 1];
      const b = data[i + 2];
      const 最大 = Math.max(r, g, b);
      const 最小 = Math.min(r, g, b);
      合 += 0 === 最大 ? 0 : (最大 - 最小) / 最大;
    }
    彩度[y] = 合 / 幅;
  }
  const 平均 = 彩度.reduce((a, b) => a + b, 0) / 高;
  // 下から見ていき、色の濃い帯が続く間は札とみなす
  let 札の上 = 高;
  for (let y = 高 - 1; y > 高 * 0.5; y--) {
    if (彩度[y] > 平均 * 1.6) 札の上 = y;
  }
  return { 札の上, 彩度の平均: 平均 };
}

/**
 * 格子を組み立てる。
 *
 * @param {{画素: Uint8Array, 幅: number, 高: number, 色?: {data:Uint8Array, ch:number}}} 元
 *   明るさの並び。色があれば名札の帯を外すのに使う（Node は gazou-node の 画を読む）
 * @param {{人数:number, 行数:number, 上を除く?:number, 角度?:number, 回す?:Function}} 注文
 *   角度 … 度。渡せばその角度で起こす。渡さなければ印の並びから測る
 *   回す … (生, 度) => 生。傾きを起こすときに使う。無ければ起こさない
 * @returns 列・行のほかに、起こしたあとの明るさ（生）と角度を返す。
 *   角度が付いたときは 列・行 の座標は起こしたあとの画に対するものなので、
 *   マスを切るときは 生 から切ること（元の写真から切るとずれる）
 */
export async function 格子(元, 注文) {
  let 生 = { 画素: 元.画素, 幅: 元.幅, 高: 元.高 };
  let 札の上 = 生.高;
  if (元.色) 札の上 = 色の帯を探す(元.色, 生.幅, 生.高).札の上;

  // 明暗を伸ばしてから見る。暗い写真・薄い印・照り返しのむらは、
  // 暗さの境を1つ決めるやり方だと印を取りこぼす（実測で、暗くした写真は
  // 印が半分しか拾えなかった）。端の何割かを切ったところで伸ばすと揃う
  生 = { 画素: 明暗を伸ばす(生.画素), 幅: 生.幅, 高: 生.高 };

  // 印の大きさの見当は、画像の幅ではなく「1マスがどれくらいか」から取る。
  // 人数が少ない板ほどマスは大きい。幅だけで決めると、4人の板で印が
  // 大きすぎて網に掛からず、数字の列を射手の列と取り違えた（実測）。
  // 列は 射手＋立ごとの小計＋合計＋余白 でおよそ 人数×1.35+2 本
  const 印を拾う = (画) => {
    const 期待するマス = 画.幅 / (注文.人数 * 1.35 + 2);
    const 最小 = Math.max(6, Math.round(期待するマス * 0.22));
    const 最大 = Math.round(期待するマス * 1.15);
    // 板の上端の数字（各人の的中数）は印ではない。上の何割かは見ない
    const 上限 = 注文.上を除く == null ? 画.高 * 0.13 : 注文.上を除く;
    const 印 = かたまりを拾う(画, 暗さの境(画.画素)).filter(
      (b) =>
        b.幅 >= 最小 && b.幅 <= 最大 && b.高 >= 最小 && b.高 <= 最大 &&
        b.幅 / b.高 > 0.45 && b.幅 / b.高 < 2.2 &&
        b.数 > 最小 * 最小 * 0.12 &&
        b.y < 札の上 - 最小 && b.y > 上限
    );
    return { 印, 最小 };
  };
  let { 印, 最小 } = 印を拾う(生);
  if (印.length < 注文.人数 * 3) {
    // 印が大きくて隣どうしや罫線とつながっていると、かたまりとしては拾えない
    //（4人立ちの板の実物で、40マスのうち8個しか拾えなかった）。
    // そのときは罫線を探し、罫線も無ければ墨の量の並びの周期から格子を立てる
    return 罫線で格子(生, 注文, 注文.角度 || 0) || 墨の並びで格子(生, 注文, 注文.角度 || 0);
  }

  // 傾きを測って起こす。斜めに撮った写真では、列のxが上下で1マス以上ずれ、
  // xで束ねるやり方が丸ごと崩れる（10度で1000pxの高さなら176pxずれる）。
  // 印の並びがいちばん縦横に揃う角度を探し、その角度で画ごと回してから
  // 拾い直す。1.5度未満なら回さない。回すと少しぼけて網の読みが鈍るし、
  // それくらいの傾きは行の当てはめと列ごとのずれで吸収できる
  //（実測で、1.45度を回したら写真の読みが 320 → 316 に落ちた）
  const 角度 = 注文.角度 != null ? 注文.角度 : 傾きを測る(印, 最小);
  if (Math.abs(角度) > 1.5 && 注文.回す) {
    生 = await 注文.回す(生, 角度);
    // 回すと札の帯の位置も動くので、帯は当てにしない
    札の上 = 生.高;
    ({ 印, 最小 } = 印を拾う(生));
    if (印.length < 注文.人数 * 3) {
      throw new Error('起こしたあと、印が少なすぎます（' + 印.length + '個）');
    }
  }

  const 印の幅 = 印.map((b) => b.幅).sort((a, z) => a - z)[Math.floor(印.length / 2)];
  const 全列 = 束ねる(印.map((b) => b.x), 印の幅 * 0.7);

  // 射手の列を選ぶ。数だけで選ぶと、小計や合計の数字の列を拾ってしまう
  //（数字も、大きさだけ見れば印と変わらない）。
  // 射手の列は「行が上から下まで埋まっている」ことで見分ける。
  // 数字はところどころにしか書かれない。
  //
  // 「間隔の揃った連続する列を取る」やり方も試されたが、4人ごとに小計の列が
  // 挟まる板で崩れる（描いた板30枚で 30/30 → 17/30 に落ちた）。
  // 4人ずつの切り抜きなら両方とも通るので、そちらだけ見ていると気づけない
  const 埋まり具合 = (列) => {
    const この列 = 印.filter((b) => Math.abs(b.x - 列.中心) <= 印の幅 * 0.8);
    if (この列.length < 2) return 0;
    const 行 = 等間隔を当てはめる(この列.map((b) => b.y), 注文.行数, 印の幅 * 0.45);
    let 埋 = 0;
    for (const y of 行.位置) {
      if (この列.some((b) => Math.abs(b.y - y) <= Math.max(印の幅 * 0.5, 行.間隔 * 0.45))) 埋++;
    }
    return 埋 / 注文.行数;
  };
  // 合計の列は毎行に数字があり、埋まり具合では射手の列と見分けられない
  //（ブラウザによる復号の僅かな差で入れ替わり、右の板で合計の列を取った）。
  // 数字は細長く、印（○・◎・×）は丸い。列のかたまりの「丸さ」を点に掛ける
  const 丸さ = (列) => {
    const この列 = 印.filter((b) => Math.abs(b.x - 列.中心) <= 印の幅 * 0.8);
    if (!この列.length) return 0;
    let 丸い = 0;
    for (const b of この列) if (b.幅 / b.高 >= 0.7 && b.幅 / b.高 <= 1.45 && b.幅 >= 印の幅 * 0.6) 丸い++;
    return 丸い / この列.length;
  };
  const 点数つき = 全列.map((c) => ({ 列: c, 埋: 埋まり具合(c), 丸: 丸さ(c), 点: 0 }));
  for (const x of 点数つき) x.点 = x.埋 * (0.5 + x.丸);
  if (process.env.OCR_RETSU) console.error('列の点', 点数つき.map((x) => `${x.列.中心.toFixed(0)}:${x.点.toFixed(2)}(埋${x.埋.toFixed(2)}丸${x.丸.toFixed(2)}数${x.列.数})`).join(' '));
  // 射手の列らしい列の数（人数を当てにしない見当）。Gemini の行の数が板の列の数と
  // 違うとき（相手校の板で 8列を 10行にした）、人数ぶんの列を取ると小計の列まで
  // 射手にしてしまい、印が黙ってずれる。本物の板で射手の列は 0.93〜1.50、
  // 小計や合計の列は 0.61 以下だったので、0.75 で切る。
  // まだ途中の板（行の半分しか埋まっていない）は全部の点が下がるので、
  // いちばん高い点の6割も認める（本物の板でも 0.81〜0.90 で同じ切れ目）
  const 最高点 = Math.max(0, ...点数つき.map((x) => x.点));
  const 列の見当 = 点数つき.filter((x) => x.点 >= Math.min(0.75, 最高点 * 0.6)).length;
  const 射手の列 = 点数つき
    .slice()
    .sort((a, z) => z.埋 * (0.5 + z.丸) - a.埋 * (0.5 + a.丸) || z.列.数 - a.列.数)
    .slice(0, 注文.人数)
    .map((x) => x.列)
    .sort((a, z) => a.中心 - z.中心);

  const 射手の印 = 印.filter((b) => 射手の列.some((c) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8));
  // 行は「射手の列の6割以上に印がある行」がいちばん多い置き方を選ぶ。
  // 印の数だけで選ぶと、上端の的中数の数字と下の名前に引かれて、10行を
  // 広い間隔で当てはめてしまう（板1枚まるごと渡した実物で、右の板の行間隔が
  // 105 のところ 121 になり、読みが 316 → 284 に落ちた）。
  // 1行を強く数える（印の総数より重く）ので、埋まった行が多い置き方が勝つ
  const 埋まった行の数 = (位置たち) => {
    let n = 0;
    for (const y of 位置たち) {
      let 列の数 = 0;
      for (const c of 射手の列) {
        if (射手の印.some((b) => Math.abs(b.x - c.中心) <= 印の幅 * 0.8 && Math.abs(b.y - y) <= 印の幅 * 0.45)) 列の数++;
      }
      if (列の数 >= 射手の列.length * 0.6) n++;
    }
    return n * 射手の印.length;
  };
  const 行 = 等間隔を当てはめる(射手の印.map((b) => b.y), 注文.行数, 印の幅 * 0.45, undefined, 埋まった行の数);

  // 起こしても、板ぜんぶに1つの格子を当てると端の列ほど上下にずれる
  //（手書きの罫線は真っ直ぐではない。実測で、右端の列の印が下で切れていた）。
  // 列ごとに「どれだけ下にずれているか」を測って持たせる。
  // 10行ぶんの印から決めるので、1行ずつ寄せるのと違ってぶれない
  for (const 列 of 射手の列) {
    const 残り = [];
    for (const b of 射手の印) {
      if (Math.abs(b.x - 列.中心) > 印の幅 * 0.8) continue;
      let 近さ = Infinity;
      for (const y of 行.位置) {
        const d = b.y - y;
        if (Math.abs(d) < Math.abs(近さ)) 近さ = d;
      }
      if (Math.abs(近さ) <= 行.間隔 * 0.42) 残り.push(近さ);
    }
    if (残り.length < 4) {
      列.ずれ = 0;
      continue;
    }
    残り.sort((a, z) => a - z);
    const 真ん中 = 残り[Math.floor(残り.length / 2)];
    列.ずれ = Math.max(-行.間隔 * 0.3, Math.min(行.間隔 * 0.3, 真ん中));
  }

  return { 幅: 生.幅, 高: 生.高, 札の上, 印の幅, 列: 射手の列, 列の見当, 行, 印: 射手の印, 角度, 生 };
}

/**
 * 罫線から格子を立てる（印がマスいっぱいで、かたまりが拾えないときの代わり）。
 *
 * 罫線は細くて長い。縦横それぞれの墨の量を並べると、罫線のところだけ
 * 細い針のような山が立つ。印の丸や×は幅の広いなだらかな山になるので、
 * 「まわりの中央値からの飛び出し」を取れば罫線だけが残る。
 * 罫線は マスの本数+1 本、等間隔に並ぶので、その本数で当てはめる。
 *
 * 印がマスいっぱいの板では、墨の量の周期からは立てられない（丸は中が空で、
 * 隣と触れているので山谷が無い。実測で半マスずれた）。罫線ならそれでも立つ。
 */
/**
 * 縦横の墨の量を並べる（罫線探しの元）。
 */
export function 墨の量(生) {
  const 境 = 暗さの境(生.画素);
  const 横 = new Float64Array(生.幅);
  const 縦 = new Float64Array(生.高);
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] < 境) {
        横[x]++;
        縦[y]++;
      }
    }
  }
  return { 横, 縦 };
}

/**
 * 墨の量の並びから、等間隔の罫線を 本数+1 本見つける。
 *
 * 罫線は細くて長い。墨の量を並べると、罫線のところだけ細い針のような山が立つ。
 * 印の丸や×は幅の広いなだらかな山になるので、「まわりの中央値からの飛び出し」を
 * 取れば罫線だけが残る。
 *
 * 間隔と起点を総当たりし、各線の位置での針の高さ（±3px の最大）を足した点で選ぶ。
 * 「合った針の本数」で選ぶと、印の縁が作る弱い針を細かい間隔が拾って勝つ
 *（実測で本当は55.6の間隔が48.6に取られ、下の行ほどずれた）。
 *
 * @param {Float64Array} 並び 墨の量
 * @param {number} 本数 マスの数（罫線は本数+1）
 * @param {number} 長さの向こう 直交する向きの画の長さ（針の高さの目安）
 * @param {number} [見当の指定] 間隔のあたり。無ければ 画の長さ÷本数
 * @returns {{位置:number[], 間隔:number, 始め:number}|null}
 */
export function 罫線を拾う(並び, 本数, 長さの向こう, 見当の指定, 探す範囲, 寄せる, 起点の範囲) {
  // 起点の範囲 … [下, 上]。最初の線の位置が分かっているとき（外枠で正した紙は
  // 左端・上端が枠の線）に渡す。置き方の取り違えが無くなる
  // 探す範囲は見当に掛ける倍率。紙の記録用紙は表の右に小計の列が写るので、
  // 画の幅÷人数では見当が大きすぎる（実測で本当は33pxのところ49〜81pxを探していた）
  const [狭, 広] = 探す範囲 || [0.75, 1.25];
  const 見当 = 見当の指定 || 並び.length / 本数;
  const 幅 = Math.max(2, Math.round(見当 * 0.15));
  const 飛び出し = new Float64Array(並び.length);
  for (let i = 0; i < 並び.length; i++) {
    const まわり = [];
    for (let j = Math.max(0, i - 幅); j <= Math.min(並び.length - 1, i + 幅); j++) まわり.push(並び[j]);
    まわり.sort((a, z) => a - z);
    飛び出し[i] = 並び[i] - まわり[Math.floor(まわり.length / 2)];
  }
  // 罫線は画の端から端まで 本数+1 本、ほぼ等間隔。間隔と起点を総当たりし、
  // 各線の位置での針の高さ（±3px の最大）を足した点で選ぶ。
  // 「合った針の本数」で選ぶと、印の縁が作る弱い針を細かい間隔が拾って勝つ
  //（実測で本当は55.6の間隔が48.6に取られ、下の行ほどずれた）。
  // 高さの合計なら、濃い罫線に乗った置き方しか高い点にならない
  const 高さ = (i) => {
    let 最 = 0;
    for (let j = Math.max(0, i - 3); j <= Math.min(並び.length - 1, i + 3); j++) if (飛び出し[j] > 最) 最 = 飛び出し[j];
    return 最;
  };
  let 最良 = null;
  for (let 間隔 = 見当 * 狭; 間隔 <= 見当 * 広; 間隔 += 0.25) {
    // 最初の罫線は画の端とは限らない（左に番号の列が28px在る実物があり、
    // 回した紙の切り抜きには余白が2マスぶん付く）。起点は画の全体から探す。
    // 点は針の高さの合計なので、表の中の線に乗った置き方しか高くならない
    const 始 = 起点の範囲 ? 起点の範囲[0] : -間隔;
    const 終 = 起点の範囲 ? 起点の範囲[1] : 並び.length - 間隔 * (本数 - 0.5);
    for (let 起点 = 始; 起点 <= 終; 起点 += 1) {
      // マスの中心（線と線の真ん中）は、ぜんぶ画の中に在ること。
      // 端の罫線が画の外にあると点が同じ置き方が2つでき、先に見つかった
      // ほうが勝って1行ずれた（実測）
      if (起点 + 間隔 * 0.5 < 0 || 起点 + 間隔 * (本数 - 0.5) > 並び.length) continue;
      let 点 = 0;
      let 乗った = 0;
      for (let k = 0; k <= 本数; k++) {
        const p = Math.round(起点 + 間隔 * k);
        if (p < 0 || p >= 並び.length) continue;
        const h = 高さ(p);
        点 += h;
        if (h > 長さの向こう * 0.06) 乗った++;
      }
      // 置き方の外側、1本ぶん離れたところにも線があるなら、その線を捨てて
      // 別の線を取っている置き方なので減点する。紙では小計の右端の線が
      // 射手の列の線と同じ強さで、左端を捨てて小計の線を取る置き方が勝った
      //（実測で4度傾けた紙の列が1本ずれた）
      // 相手が画の端から3px外に出ていても、端の線は拾う（正した紙の外枠は
      // 端から3pxのところにあり、-2px に落ちて減点が効かなかった）
      for (const p of [Math.round(起点 - 間隔), Math.round(起点 + 間隔 * (本数 + 1))]) {
        if (p >= -3 && p < 並び.length + 3) 点 -= 高さ(Math.max(0, Math.min(並び.length - 1, p))) * 0.8;
      }
      if (!最良 || 点 > 最良.点) 最良 = { 点, 間隔, 起点, 乗った };
    }
  }
  if (!最良 || 最良.乗った < (本数 + 1) * 0.5) return null;
  // 等間隔に置いたあと、頼まれたら線ごとに近くの針へ寄せる。斜めから撮ると
  // 遠い側ほど間隔が縮み、等間隔のままでは端の線が数px外れる（紙の実物で
  // 117→126 と広がり、マス30pxに対して端が5pxずれていた）。
  // 印がマスいっぱいの板では丸の縁も針になり、寄せると逆に崩れる（4人立ちの
  // 実物で2列が外れた）ので、罫線が濃く印が細い紙だけが頼む
  const 位置 = [];
  const 寄せ幅 = 寄せる ? Math.max(2, Math.round(最良.間隔 * 0.12)) : 0;
  for (let k = 0; k <= 本数; k++) {
    const p = Math.round(最良.起点 + 最良.間隔 * k);
    let 最 = p;
    let 高 = -1;
    for (let j = Math.max(0, p - 寄せ幅); j <= Math.min(並び.length - 1, p + 寄せ幅); j++) {
      if (飛び出し[j] > 高) {
        高 = 飛び出し[j];
        最 = j;
      }
    }
    位置.push(寄せる && 高 > 長さの向こう * 0.06 ? 最 : p);
  }
  return { 位置, 間隔: 最良.間隔, 始め: 位置[0] };
}

/**
 * 罫線から格子を立てる（印がマスいっぱいで、かたまりが拾えないときの代わり）。
 * 縦横とも、マスごとに罫線が引かれている板が前提。
 *
 * 印がマスいっぱいの板では、墨の量の周期からは立てられない（丸は中が空で、
 * 隣と触れているので山谷が無い。実測で半マスずれた）。罫線ならそれでも立つ。
 */
function 罫線で格子(生, 注文, 角度) {
  const { 横, 縦 } = 墨の量(生);
  // 見当は画の長さ÷本数（画に写っているのが印の部分だけ、という前提）。
  // 候補の端から端で取ると、印の縁の針に引かれて狂う（実測で 51 が 37 になった）。
  // マスは正方形とは限らない（実測の板で 47×55）ので、列の間隔を行に流用しない
  const 列 = 罫線を拾う(横, 注文.人数, 生.高);
  const 行 = 罫線を拾う(縦, 注文.行数, 生.幅);
  if (!列 || !行) return null;
  const 列の中心 = [];
  for (let i = 0; i < 注文.人数; i++) 列の中心.push(列.位置[i] + 列.間隔 / 2);
  const 行の中心 = [];
  for (let i = 0; i < 注文.行数; i++) 行の中心.push(行.位置[i] + 行.間隔 / 2);
  const 印の幅 = Math.round(Math.min(列.間隔, 行.間隔) * 0.8);
  return {
    幅: 生.幅,
    高: 生.高,
    札の上: 生.高,
    印の幅,
    列: 列の中心.map((x) => ({ 中心: x, 数: 注文.行数, ずれ: 0 })),
    行: { 位置: 行の中心, 間隔: 行.間隔, 始め: 行の中心[0] },
    印: [],
    角度,
    生,
    立て方: '罫線',
  };
}

/**
 * 墨の量の並びから格子を立てる（かたまりが拾えないときの代わり）。
 *
 * マスの真ん中は墨が多く、マスの境は白いか細い罫線しかない。縦横それぞれの
 * 墨の量を並べると、マスの本数ぶんの山と谷が等間隔に並ぶ。
 * 本数は分かっているので、間隔と起点を総当たりして、山が真ん中に来て谷が境に
 * 来る置き方を選ぶ。
 *
 * 前提: 画に写っているのが印の部分だけであること（見出しや名前が入ると
 * 周期が崩れる）。かたまりで立てる方式と違い、数字の列を見分ける力はない。
 */
function 墨の並びで格子(生, 注文, 角度) {
  const 境 = 暗さの境(生.画素);
  const 横 = new Float64Array(生.幅);
  const 縦 = new Float64Array(生.高);
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] < 境) {
        横[x]++;
        縦[y]++;
      }
    }
  }
  const 当てる = (並び, 本数) => {
    const 長さ = 並び.length;
    let 最良 = null;
    for (let 間隔 = (長さ / 本数) * 0.7; 間隔 <= (長さ / 本数) * 1.05; 間隔 += 0.5) {
      for (let 起点 = 0; 起点 < 間隔; 起点 += 1) {
        // 本数ぶん並べたとき、端が画からはみ出しすぎるものは捨てる
        const 終わり = 起点 + 間隔 * 本数;
        if (終わり > 長さ + 間隔 * 0.3) break;
        let 点 = 0;
        for (let i = 0; i < 本数; i++) {
          const 左 = 起点 + 間隔 * i;
          const 右 = 左 + 間隔;
          // 真ん中6割の墨を足し、境の1割の墨を引く
          for (let t = Math.max(0, Math.floor(左 + 間隔 * 0.2)); t < Math.min(長さ, 右 - 間隔 * 0.2); t++) 点 += 並び[t];
          for (let t = Math.max(0, Math.floor(左 - 間隔 * 0.05)); t < Math.min(長さ, 左 + 間隔 * 0.05); t++) 点 -= 並び[t] * 2;
        }
        if (!最良 || 点 > 最良.点) 最良 = { 点, 間隔, 起点 };
      }
    }
    const 位置 = [];
    for (let i = 0; i < 本数; i++) 位置.push(最良.起点 + 最良.間隔 * (i + 0.5));
    return { 位置, 間隔: 最良.間隔 };
  };
  const 列 = 当てる(横, 注文.人数);
  const 行 = 当てる(縦, 注文.行数);
  // 印の幅は、マスの大きさから見当を付ける（印はマスの8割ほど）
  const 印の幅 = Math.round(Math.min(列.間隔, 行.間隔) * 0.8);
  return {
    幅: 生.幅,
    高: 生.高,
    札の上: 生.高,
    印の幅,
    列: 列.位置.map((x) => ({ 中心: x, 数: 注文.行数, ずれ: 0 })),
    行: { 位置: 行.位置, 間隔: 行.間隔, 始め: 行.位置[0] },
    印: [],
    角度,
    生,
    立て方: '墨の並び',
  };
}

/**
 * 1マスを切り出す箱の大きさ。
 *
 * 学習側と本物側で別々に書いていたら、片方が 行の間隔×0.37、もう片方が
 * ×0.48 になっていた。同じ写真から違う大きさで切っていたので、網が見ている
 * ものが食い違っていた。ここ一箇所で決める。
 */
export function 箱の大きさ(格子の中身) {
  // 箱はマスの間隔を超えない。印がマスいっぱいに書かれた板では、印の幅から
  // 決めた箱が隣のマスにかぶり、×の箱に上下の丸が入って「丸に線」と読み違えた
  //（4人立ちの板の実物）。これまでの板では印がマスの半分ほどなので、
  // 間隔の縛りは掛からず、数字は変わらない
  const 列 = 格子の中身.列;
  const 列の間隔 =
    列.length >= 2
      ? 列.slice(1).map((c, i) => c.中心 - 列[i].中心).sort((a, z) => a - z)[Math.floor((列.length - 1) / 2)]
      : Infinity;
  const 半幅 = Math.round(Math.min(格子の中身.印の幅 * (Number(process.env.OCR_HABA) || 0.85), 列の間隔 * 0.48));
  const 半高 = Math.round(
    Math.min(格子の中身.行.間隔 * (Number(process.env.OCR_TAKA) || 0.48), 格子の中身.印の幅 * 0.9)
  );
  return { 半幅, 半高 };
}


/**
 * 写真に板が何枚か写っているとき、板ごとに分けて格子を立てる。
 *
 * 印を拾って x で束ね、束と束の間がいちばん広いところで切る（板と板の間は
 * マス何個ぶんも空く）。板の枚数は 板の人数たち の長さ。板ごとに、その人数で
 * 格子を立てる。板は左から順に並んでいるものとする。
 *
 * @param {{画素:Uint8Array, 幅:number, 高:number, 色?:object}} 元
 * @param {{板の人数たち:number[], 行数:number, 回す?:Function}} 注文
 * @returns {Promise<{格子:object, 左:number}[]>} 板ごとの格子と、切り出した左端
 */
export async function 板ごとの格子(元, 注文) {
  const 板の人数たち = 注文.板の人数たち;
  if (板の人数たち.length === 1) {
    return [{ 格子: await 格子(元, { 人数: 板の人数たち[0], 行数: 注文.行数, 回す: 注文.回す }), 左: 0 }];
  }
  const 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
  const 全人数 = 板の人数たち.reduce((a, b) => a + b, 0);
  // 印の大きさの見当。列は 人数×1.35+2 本が板ごと（板の数だけ余白も増える）
  const 期待するマス = 生.幅 / (全人数 * 1.35 + 2 * 板の人数たち.length + 1);
  const 最小 = Math.max(6, Math.round(期待するマス * 0.22));
  const 最大 = Math.round(期待するマス * 1.15);
  const 印 = かたまりを拾う(生, 暗さの境(生.画素)).filter(
    (b) =>
      b.幅 >= 最小 && b.幅 <= 最大 && b.高 >= 最小 && b.高 <= 最大 &&
      b.幅 / b.高 > 0.45 && b.幅 / b.高 < 2.2 &&
      b.数 > 最小 * 最小 * 0.12
  );
  if (印.length < 全人数 * 3) throw new Error('印が少なすぎます（' + 印.length + '個）');
  const 印の幅 = 印.map((b) => b.幅).sort((a, z) => a - z)[Math.floor(印.length / 2)];
  const 束 = 束ねる(印.map((b) => b.x), 印の幅 * 0.7).filter((c) => c.数 >= 3);
  // 束と束の隙間。広い順に 板の枚数-1 個を切れ目にする
  const 隙間 = [];
  for (let i = 1; i < 束.length; i++) 隙間.push({ 幅: 束[i].端[0] - 束[i - 1].端[1], 位置: (束[i].端[0] + 束[i - 1].端[1]) / 2 });
  const 切れ目 = 隙間
    .slice()
    .sort((a, z) => z.幅 - a.幅)
    .slice(0, 板の人数たち.length - 1)
    .map((g) => g.位置)
    .sort((a, z) => a - z);
  const 出 = [];
  let 左端 = 0;
  for (let i = 0; i < 板の人数たち.length; i++) {
    const 右端 = i < 切れ目.length ? 切れ目[i] : 生.幅;
    // 板の範囲は、その区間の印の端に余白を足したもの
    const その板 = 印.filter((b) => b.x >= 左端 && b.x < 右端);
    if (その板.length < 板の人数たち[i] * 3) throw new Error(`${i + 1}枚目の板の印が少なすぎます（${その板.length}個）`);
    const 左 = Math.max(0, Math.floor(Math.min(...その板.map((b) => b.x)) - 印の幅 * 1.5));
    const 右 = Math.min(生.幅, Math.ceil(Math.max(...その板.map((b) => b.x)) + 印の幅 * 1.5));
    const 切 = { 画素: new Uint8Array((右 - 左) * 元.高), 幅: 右 - 左, 高: 元.高 };
    for (let y = 0; y < 元.高; y++) 切.画素.set(元.画素.subarray(y * 元.幅 + 左, y * 元.幅 + 右), y * 切.幅);
    let 色;
    if (元.色) {
      const ch = 元.色.ch;
      色 = { data: new Uint8Array((右 - 左) * 元.高 * ch), ch };
      for (let y = 0; y < 元.高; y++) 色.data.set(元.色.data.subarray((y * 元.幅 + 左) * ch, (y * 元.幅 + 右) * ch), y * 切.幅 * ch);
    }
    出.push({ 格子: await 格子({ ...切, 色 }, { 人数: 板の人数たち[i], 行数: 注文.行数, 回す: 注文.回す }), 左 });
    左端 = 右端;
  }
  return 出;
}
