/**
 * ○×の印を、手書きのゆらぎを真似て描き起こす。学習用の見本を作るため。
 *
 * ■ なぜ描くのか
 * 本物の札付きデータは80マスしかない（写真が1枚しか無い）。それを全部
 * 学習に使うと、効いたかどうかを確かめるぶんが残らない。
 * 描いたもので学習させ、本物80マスは確かめ用に取っておく。
 *
 * ■ 何を真似るか（本物の板を見て決めた）
 *   ・丸は閉じきらないことがある。始点と終点がずれる
 *   ・線の太さが一定でない。筆圧で濃さも変わる
 *   ・中の丸は、外の丸の真ん中とは限らない
 *   ・斜線は45度ぴったりではない。丸からはみ出すことも、届かないこともある
 *   ・板の照り返しで、背景が一様な白ではない
 */

const 逆 = String.fromCharCode(92);

/** 0〜1の乱数。渡した種から作る（同じ種なら同じ絵が出る） */
export function 乱数をつくる(種) {
  let s = 種 >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

/** 幅×高の明るさの板を作る。背景はほぼ白 */
function 板をつくる(幅, 高, 乱, 明るさ) {
  const 画 = new Float32Array(幅 * 高);
  // 板の照り返し。ゆるやかな傾きを入れる
  const 傾きx = (乱() - 0.5) * 30;
  const 傾きy = (乱() - 0.5) * 30;
  for (let y = 0; y < 高; y++) {
    for (let x = 0; x < 幅; x++) {
      const u = x / 幅 - 0.5;
      const v = y / 高 - 0.5;
      画[y * 幅 + x] = 明るさ + 傾きx * u + 傾きy * v + (乱() - 0.5) * 6;
    }
  }
  // 板の罫線。薄く、まっすぐ。切り出したマスにも端が写り込む
  const 本数 = 乱() < 0.45 ? 1 : 0;
  for (let i = 0; i < 本数; i++) {
    const 薄さ = 4 + 乱() * 9;
    if (乱() < 0.5) {
      const x0 = Math.floor(乱() * 幅);
      for (let y = 0; y < 高; y++) {
        const x = x0 + Math.round((乱() - 0.5) * 1.5);
        if (x >= 0 && x < 幅) 画[y * 幅 + x] -= 薄さ;
      }
    } else {
      const y0 = Math.floor(乱() * 高);
      for (let x = 0; x < 幅; x++) {
        const y = y0 + Math.round((乱() - 0.5) * 1.5);
        if (y >= 0 && y < 高) 画[y * 幅 + x] -= 薄さ;
      }
    }
  }
  return 画;
}

/**
 * 描くときの傾き。写真は正面から撮るとは限らないので、少し回す。
 * 斜線の向きを見分ける課題なので、回しすぎると別の記号になる。±12度まで。
 */
let 回す = { 角: 0, 中: 32 };
export function 傾きを決める(角, 中) {
  回す = { 角, 中 };
}
function 回した(x, y) {
  if (!回す.角) return [x, y];
  const c = Math.cos(回す.角);
  const s = Math.sin(回す.角);
  const dx = x - 回す.中;
  const dy = y - 回す.中;
  return [回す.中 + dx * c - dy * s, 回す.中 + dx * s + dy * c];
}

/** 点を、太さぶんの丸で押す */
export function 押す(画, 幅, 高, x0生, y0生, 太さ, 濃さ) {
  const [x, y] = 回した(x0生, y0生);
  const r = 太さ / 2;
  const x0 = Math.max(0, Math.floor(x - r - 1));
  const x1 = Math.min(幅 - 1, Math.ceil(x + r + 1));
  const y0 = Math.max(0, Math.floor(y - r - 1));
  const y1 = Math.min(高 - 1, Math.ceil(y + r + 1));
  for (let yy = y0; yy <= y1; yy++) {
    for (let xx = x0; xx <= x1; xx++) {
      const d = Math.sqrt((xx - x) * (xx - x) + (yy - y) * (yy - y));
      if (d > r + 0.7) continue;
      // ふちは薄くする
      const 効き = d <= r ? 1 : Math.max(0, 1 - (d - r) / 0.7);
      const i = yy * 幅 + xx;
      画[i] = Math.min(画[i], 画[i] - 濃さ * 効き < 0 ? 0 : 画[i] - 濃さ * 効き);
    }
  }
}

/** 手で引いた線。少しゆらぐ */
export function 線をひく(画, 幅, 高, x1, y1, x2, y2, 太さ, 濃さ, 乱, 途切れ) {
  const 長さ = Math.hypot(x2 - x1, y2 - y1);
  const 歩 = Math.max(2, Math.ceil(長さ * 2));
  // 白板の筆は擦れる。線が点々に途切れることがある（本物の板で見た）。
  // 途切れた線を丸の中に描くと、学習していないと ◎ と読み違える
  const 抜け = [];
  if (途切れ) {
    const 数 = 1 + Math.floor(乱() * 3);
    for (let i = 0; i < 数; i++) {
      const 始 = 乱() * 0.85;
      抜け.push([始, 始 + 0.05 + 乱() * 0.16]);
    }
  }
  // 真ん中がふくらむ（手で引くと少し反る）
  const 反り = (乱() - 0.5) * 太さ * 1.5;
  const 法線x = -(y2 - y1) / 長さ;
  const 法線y = (x2 - x1) / 長さ;
  for (let i = 0; i <= 歩; i++) {
    const t = i / 歩;
    const ふくらみ = Math.sin(t * Math.PI) * 反り;
    const x = x1 + (x2 - x1) * t + 法線x * ふくらみ + (乱() - 0.5) * 0.8;
    const y = y1 + (y2 - y1) * t + 法線y * ふくらみ + (乱() - 0.5) * 0.8;
    if (抜け.some(([a, b]) => t >= a && t <= b)) continue;
    const 太 = 太さ * (0.85 + 0.3 * Math.sin(t * Math.PI));
    押す(画, 幅, 高, x, y, 太, 濃さ * (0.85 + 0.3 * 乱()));
  }
}

/** 手で描いた丸。閉じきらないことがある */
export function 丸をかく(画, 幅, 高, cx, cy, rx, ry, 太さ, 濃さ, 乱) {
  const 始め = 乱() * Math.PI * 2;
  // 閉じ足りない／描きすぎる
  const 回る = Math.PI * 2 * (0.93 + 乱() * 0.14);
  const 歩 = Math.max(24, Math.ceil((rx + ry) * 1.6));
  // 少しいびつにする
  const ゆがみ = 0.06 + 乱() * 0.1;
  const 位相 = 乱() * Math.PI * 2;
  for (let i = 0; i <= 歩; i++) {
    const t = i / 歩;
    const a = 始め + 回る * t;
    const のび = 1 + ゆがみ * Math.sin(a * 2 + 位相);
    const x = cx + Math.cos(a) * rx * のび + (乱() - 0.5) * 0.9;
    const y = cy + Math.sin(a) * ry * のび + (乱() - 0.5) * 0.9;
    const 太 = 太さ * (0.8 + 0.4 * 乱());
    押す(画, 幅, 高, x, y, 太, 濃さ * (0.8 + 0.4 * 乱()));
  }
}

/**
 * 印を1つ描く。
 *
 * @param {'◎'|'○\\'|'○/'|'×'|'○'} 記号
 * @param {number} 種
 * @param {number} [大きさ] 画の1辺
 */
export function 印をえがく(記号, 種, 大きさ) {
  const N = 大きさ || 64;
  const 乱 = 乱数をつくる(種);
  const 明るさ = 200 + 乱() * 40;
  const 画 = 板をつくる(N, N, 乱, 明るさ);
  // 本物の板は、線が細く、薄い印も混じる（下の立ほど薄いことがあった）
  const 濃さ = 45 + 乱() * 125;
  const 太さ = N * (0.028 + 乱() * 0.04);
  傾きを決める(((乱() - 0.5) * 12 * Math.PI) / 180, N / 2);

  // 印の置き場所と大きさ
  const 半 = N * (0.28 + 乱() * 0.09);
  const cx = N / 2 + (乱() - 0.5) * N * 0.08;
  const cy = N / 2 + (乱() - 0.5) * N * 0.08;
  const 縦横 = 0.85 + 乱() * 0.3;

  if (記号 === '×') {
    // 2本の線が交わる。丸は無い
    const の = 半 * (1.0 + 乱() * 0.25);
    const ずれ = () => (乱() - 0.5) * 半 * 0.35;
    線をひく(画, N, N, cx - の + ずれ(), cy - の + ずれ(), cx + の + ずれ(), cy + の + ずれ(), 太さ, 濃さ, 乱);
    線をひく(画, N, N, cx + の + ずれ(), cy - の + ずれ(), cx - の + ずれ(), cy + の + ずれ(), 太さ, 濃さ, 乱);
    return { 画, 幅: N, 高: N };
  }

  丸をかく(画, N, N, cx, cy, 半, 半 * 縦横, 太さ, 濃さ, 乱);

  if (記号 === '◎') {
    // 内側の丸。真ん中とは限らず、大きさもまちまち
    const 内半 = 半 * (0.2 + 乱() * 0.25);
    const 内cx = cx + (乱() - 0.5) * 半 * 0.4;
    const 内cy = cy + (乱() - 0.5) * 半 * 0.4;
    丸をかく(画, N, N, 内cx, 内cy, 内半, 内半 * (0.85 + 乱() * 0.3), 太さ * (0.8 + 乱() * 0.3), 濃さ, 乱);
    return { 画, 幅: N, 高: N };
  }

  if (記号 === '○') return { 画, 幅: N, 高: N };

  // 丸に線。45度ぴったりではなく、丸からはみ出したり届かなかったり
  const 下がりか = 記号 === '○' + 逆;
  const 角 = (下がりか ? 45 : 135) + (乱() - 0.5) * 22;
  const ラジアン = (角 * Math.PI) / 180;
  // 斜線が丸からどれだけはみ出すかは、まちまち。片端だけ長いこともある。
  // 実測で、本物には丸の1.8倍ほど引かれたものがあり、1.35倍までしか描いて
  // いなかったせいで、その1枚を最後まで取り違えていた
  const のび = () => 半 * (0.9 + 乱() * 1.0);
  const 手前 = のび();
  const 奥 = のび();
  const dx = Math.cos(ラジアン);
  const dy = Math.sin(ラジアン);
  const ずれx = (乱() - 0.5) * 半 * 0.25;
  const ずれy = (乱() - 0.5) * 半 * 0.25;
  線をひく(
    画, N, N,
    cx - dx * 手前 + ずれx, cy - dy * 手前 + ずれy, cx + dx * 奥 + ずれx, cy + dy * 奥 + ずれy,
    太さ, 濃さ, 乱
  );
  return { 画, 幅: N, 高: N };
}

/**
 * 好きな板の、好きな場所へ印を1つ描く。
 *
 * @param {Float32Array} 画
 * @param {number} 幅
 * @param {number} 高
 * @param {string} 記号
 * @param {{cx:number, cy:number, 半:number, 濃さ:number, 太さ:number, 乱:Function}} 注文
 */
export function 印をそこへ描く(画, 幅, 高, 記号, 注文) {
  const { cx, cy, 半, 濃さ, 太さ, 乱 } = 注文;
  傾きを決める(0, 0);
  // 縦つぶれ … 縦の伸びを掛ける。紙では大きな丸に挟まれた×が上下に潰れる
  const つぶれ = 注文.縦つぶれ || 1;
  const 縦横 = (0.85 + 乱() * 0.3) * つぶれ;

  if (記号 === '×') {
    // 印がマスいっぱいのときは、×はマスの角まで（それ以上は隣に食い込みすぎる）
    const 詰まり = 注文.詰まり || 0;
    // 小さく書かれた × もある（本物で、マスの4割ほどの細い × を ○＼ と読んだ）。
    // ぎっしりの板では小さくしない
    const 小ささ = !詰まり && 乱() < 0.25 ? 0.5 + 乱() * 0.4 : 1;
    const の = 半 * (1.0 + 乱() * (0.25 - 0.15 * 詰まり)) * 小ささ;
    const 縦の = の * つぶれ;
    const ずれ = () => (乱() - 0.5) * 半 * (0.35 - 0.2 * 詰まり);
    // × も細いペンで書かれることがある。丸の線だけを細く描いて学ばせると、
    // 「細い線＝丸の線」と覚えて、細い × を ○＼ と読んだ（本物で 0.99）
    const 細い = 乱() < (注文.別のペン || 0);
    const ばつの太さ = 細い ? 太さ * (0.3 + 乱() * 0.4) : 太さ;
    const ばつの濃さ = 細い ? 濃さ * (0.4 + 乱() * 0.4) : 濃さ;
    線をひく(画, 幅, 高, cx - の + ずれ(), cy - 縦の + ずれ(), cx + の + ずれ(), cy + 縦の + ずれ(), ばつの太さ, ばつの濃さ, 乱);
    線をひく(画, 幅, 高, cx + の + ずれ(), cy - 縦の + ずれ(), cx - の + ずれ(), cy + 縦の + ずれ(), ばつの太さ, ばつの濃さ, 乱);
    return;
  }
  if (記号 === '') return;

  丸をかく(画, 幅, 高, cx, cy, 半, 半 * 縦横, 太さ, 濃さ, 乱);
  if (記号 === '◎') {
    const 内半 = 半 * (0.2 + 乱() * 0.25);
    丸をかく(
      画, 幅, 高,
      cx + (乱() - 0.5) * 半 * 0.4, cy + (乱() - 0.5) * 半 * 0.4,
      内半, 内半 * (0.85 + 乱() * 0.3), 太さ * (0.8 + 乱() * 0.3), 濃さ, 乱
    );
    return;
  }
  if (記号 === '○') return;

  const 下がりか = 記号 === '○' + 逆;
  const 角 = ((下がりか ? 45 : 135) + (乱() - 0.5) * 22) * (Math.PI / 180);
  // 斜線が丸からどれだけはみ出すかは、まちまち。片端だけ長いこともある。
  // 実測で、本物には丸の1.8倍ほど引かれたものがあり、1.35倍までしか描いて
  // いなかったせいで、その1枚を最後まで取り違えていた
  const のび = () => 半 * (0.9 + 乱() * 1.0);
  const 手前 = のび();
  const 奥 = のび();
  const dx = Math.cos(角);
  const dy = Math.sin(角);
  let ずれx = (乱() - 0.5) * 半 * 0.25;
  let ずれy = (乱() - 0.5) * 半 * 0.25;
  // 線は丸と別のペンで引かれることが多い（使う人の板ではよくある書き方）。
  // 丸より細く薄く、真ん中を外れて（線と直角の向きに丸の半径の4割まで）引かれる。
  // これを描かずに学ばせた網は、本物のそういうマスを丸ぜんぶ見たうえで ◎ と読んだ
  let 線の太さ = 太さ;
  let 線の濃さ = 濃さ;
  if (乱() < (注文.別のペン || 0)) {
    線の太さ = 太さ * (0.3 + 乱() * 0.4);
    線の濃さ = 濃さ * (0.4 + 乱() * 0.4);
    const 外れ = (乱() - 0.5) * 半 * 0.8;
    ずれx += -dy * 外れ;
    ずれy += dx * 外れ;
  }
  線をひく(
    画, 幅, 高,
    cx - dx * 手前 + ずれx, cy - dy * 手前 + ずれy, cx + dx * 奥 + ずれx, cy + dy * 奥 + ずれy,
    線の太さ, 線の濃さ, 乱,
    乱() < 0.3
  );
}

/** Float32 の板を、0-255 の白黒に直す */
export function 画にする(板) {
  const 出 = new Uint8Array(板.画.length);
  for (let i = 0; i < 板.画.length; i++) {
    const v = 板.画[i];
    出[i] = v < 0 ? 0 : v > 255 ? 255 : Math.round(v);
  }
  return { 画: 出, 幅: 板.幅, 高: 板.高 };
}
