/**
 * 紙の記録用紙を描き起こす。学習用の見本を作るため。
 *
 * ■ 何を真似るか（女子リーグの用紙の実物を見て決めた）
 *   ・列は射手。幅は 25〜60px（写真の大きさで変わる）
 *   ・縦に立のかたまり。1かたまりは 立のマス 個の射を縦に重ねる。射の境に罫線は無い
 *   ・列の罫線とかたまりの罫線は細く、濃い（印刷）
 *   ・印はボールペン。線は細く、色はやや薄い。丸はマスの縦いっぱいで、上下の印と触れる
 *   ・上に各人の的中数、右に小計の列（斜線と数字）
 *   ・紙の地はほぼ白。写真の照りで少し傾く
 */
import { 乱数をつくる, 印をそこへ描く, 画にする } from './egaku.mjs';

/**
 * @param {{種:number, 人数?:number, 立数?:number, 立のマス?:number, マス幅?:number}} 注文
 * @returns {{白黒:Uint8Array, 幅:number, 高:number, 答え:object}}
 *   答え.マス[列][射番] … 射番 0 が1射目（いちばん下）。中身は '○' か '×'
 */
export function 紙をえがく(注文) {
  const o = 注文 || {};
  const 乱 = 乱数をつくる(o.種 || 1);
  const 人数 = o.人数 || 4;
  const 立数 = o.立数 || 5;
  const 立のマス = o.立のマス || 4;
  const マス幅 = o.マス幅 || Math.round(25 + 乱() * 35);
  // マスは横長でも縦長でもある（実物は 33×30）
  const マス高 = Math.round(マス幅 * (0.8 + 乱() * 0.35));
  const 小計幅 = Math.round(マス幅 * (1.8 + 乱() * 0.8));
  const 余白 = Math.round(マス幅 * 0.6);
  const 見出し高 = Math.round(マス高 * 1.2);
  const 表の左 = 余白;
  const 表の上 = 余白 + 見出し高;
  const 表の右 = 表の左 + マス幅 * 人数 + 小計幅;
  const 表の下 = 表の上 + マス高 * 立のマス * 立数;
  const 幅 = 表の右 + 余白;
  const 高 = 表の下 + 余白;

  const 画 = new Float32Array(幅 * 高);
  const 明るさ = 215 + 乱() * 35;
  const 傾きx = (乱() - 0.5) * 25;
  const 傾きy = (乱() - 0.5) * 25;
  for (let y = 0; y < 高; y++) {
    for (let x = 0; x < 幅; x++) {
      画[y * 幅 + x] = 明るさ + 傾きx * (x / 幅 - 0.5) + 傾きy * (y / 高 - 0.5) + (乱() - 0.5) * 6;
    }
  }

  // 罫線（印刷なので細くて濃い。太さ1〜2px）
  const 線の濃さ = 110 + 乱() * 80;
  const 線の太さ = 乱() < 0.5 ? 1 : 2;
  const 縦線 = (x0) => {
    for (let t = 0; t < 線の太さ; t++) {
      const x = x0 + t;
      if (x < 0 || x >= 幅) continue;
      for (let y = 表の上 - 見出し高; y <= 表の下; y++) 画[y * 幅 + x] -= 線の濃さ;
    }
  };
  const 横線 = (y0, 左, 右) => {
    for (let t = 0; t < 線の太さ; t++) {
      const y = y0 + t;
      if (y < 0 || y >= 高) continue;
      for (let x = 左; x <= 右; x++) 画[y * 幅 + x] -= 線の濃さ;
    }
  };
  for (let c = 0; c <= 人数; c++) 縦線(表の左 + c * マス幅);
  縦線(表の右);
  横線(表の上 - 見出し高, 表の左, 表の右);
  for (let t = 0; t <= 立数; t++) 横線(表の上 + t * マス高 * 立のマス, 表の左, 表の右);

  // 印。ボールペンなので細く、やや薄い。丸はマスの縦いっぱい
  const 濃さ = 90 + 乱() * 90;
  const 太さ = Math.max(1.2, マス幅 * (0.035 + 乱() * 0.03));
  const 答え = [];
  for (let c = 0; c < 人数; c++) {
    const この列 = [];
    for (let t = 0; t < 立数; t++) {
      // かたまりの中で、印は高さを分け合う。丸は大きく（1.15）、×は狭く（0.75）取り、
      // 合計をかたまりの高さにそろえる。実物では大きな丸に挟まれた×が上下に
      // 潰れていて、等分で描いた網はそれを丸と読んだ（80マス中2マス）
      const 記号たち = [];
      for (let r = 0; r < 立のマス; r++) 記号たち.push(乱() < 0.55 ? '○' : '×');
      const 分け = 記号たち.map((k) => (k === '○' ? 1.15 + 乱() * 0.15 : 0.6 + 乱() * 0.3));
      const 和 = 分け.reduce((a, b) => a + b, 0);
      const かたまりの高 = マス高 * 立のマス;
      let 下 = 表の下 - t * かたまりの高;
      for (let r = 0; r < 立のマス; r++) {
        const 記号 = 記号たち[r];
        この列.push(記号);
        const 帯 = (かたまりの高 * 分け[r]) / 和;
        const cx = 表の左 + (c + 0.5) * マス幅 + (乱() - 0.5) * マス幅 * 0.12;
        const cy = 下 - 帯 / 2 + (乱() - 0.5) * 帯 * 0.08;
        下 -= 帯;
        // 実物では、×はマスの角から角まで引かれ、丸はマスの縦いっぱい。
        // ×を小さく描いていたら、本物の×を丸と読んだ（80マス中4マス）
        // 丸はほぼ丸いまま（帯に収まる大きさ）。×は横はマスいっぱい、縦は帯に潰す
        const 横半 = 記号 === '×' ? マス幅 * (0.42 + 乱() * 0.1) : Math.min(マス幅 * 0.46, 帯 * 0.48) * (0.9 + 乱() * 0.1);
        印をそこへ描く(画, 幅, 高, 記号, {
          cx,
          cy,
          半: 横半,
          縦つぶれ: 記号 === '×' ? Math.min(1.1, (帯 * 0.5) / 横半) : 1,
          濃さ: 濃さ * (0.7 + 乱() * 0.3),
          太さ: 太さ * (0.8 + 乱() * 0.5),
          詰まり: 1,
          乱,
        });
      }
    }
    答え.push(この列);
  }

  // 上の的中数と、右の小計（数字らしい走り書きと斜線）
  const 走り書き = (cx, cy, 大きさ) => {
    const n = 2 + Math.floor(乱() * 4);
    let x = cx - 大きさ * 0.3;
    let y = cy - 大きさ * 0.3;
    for (let i = 0; i < n; i++) {
      const x2 = cx + (乱() - 0.5) * 大きさ * 0.7;
      const y2 = cy + (乱() - 0.5) * 大きさ * 0.7;
      const 歩 = Math.ceil(Math.hypot(x2 - x, y2 - y));
      for (let k = 0; k <= 歩; k++) {
        const px = Math.round(x + ((x2 - x) * k) / 歩);
        const py = Math.round(y + ((y2 - y) * k) / 歩);
        if (px >= 0 && px < 幅 && py >= 0 && py < 高) 画[py * 幅 + px] -= 濃さ;
      }
      x = x2;
      y = y2;
    }
  };
  for (let c = 0; c < 人数; c++) 走り書き(表の左 + (c + 0.5) * マス幅, 表の上 - 見出し高 / 2, マス高 * 0.7);
  for (let t = 0; t < 立数; t++) {
    const 上 = 表の上 + t * マス高 * 立のマス;
    const cx = 表の左 + 人数 * マス幅 + 小計幅 / 2;
    走り書き(cx - 小計幅 * 0.2, 上 + マス高 * 立のマス * 0.35, マス高 * 0.8);
    走り書き(cx + 小計幅 * 0.2, 上 + マス高 * 立のマス * 0.7, マス高 * 0.8);
  }

  const 白黒 = 画にする({ 画, 幅, 高 }).画;
  return {
    白黒,
    幅,
    高,
    答え: {
      人数,
      立数,
      立のマス,
      マス幅,
      マス高,
      列のx: Array.from({ length: 人数 }, (_, c) => 表の左 + (c + 0.5) * マス幅),
      // 射番ごとの y（0 が1射目 ＝ いちばん下）
      射のy: Array.from({ length: 立数 * 立のマス }, (_, s) => 表の下 - s * マス高 - マス高 / 2),
      マス: 答え,
    },
  };
}
