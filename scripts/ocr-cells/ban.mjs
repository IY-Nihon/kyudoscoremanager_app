/**
 * 板ぜんぶを描き起こす。切り出しの仕組みを試す相手をつくるため。
 *
 * ■ なぜ板ごと作るか
 * 切り出し（罫線の代わりに印の並びから格子を復元するやり方）は、本物の板
 * 1枚でしか確かめていない。人数が違う板、行数が違う板、傾いた板、薄い板で
 * 立つのかが分からない。答えの分かっている板をいくらでも作れれば、そこを測れる。
 *
 * ■ 何を描くか（本物の板に合わせて）
 *   ・薄い罫線の表（列＝射手、行＝マス）
 *   ・各マスの印（◎ / 丸に＼ / 丸に／ / ×）
 *   ・立の切れ目に「小計」、右端に「合計」の数字の列
 *   ・上端に、各人の的中数
 *   ・下端に、色枠のネームプレート
 *   ・板の照り返し、影、少しの傾き
 *
 * 答え（どのマスが何か、列と行がどこか）も一緒に返す。
 */
import { 乱数をつくる, 押す, 線をひく, 印をそこへ描く, 画にする } from './egaku.mjs';

const 逆 = String.fromCharCode(92);
const 種類 = ['×', '◎', '○' + 逆, '○/'];

/** 数字らしい走り書きを、小さく描く */
function 数字らしく(画, 幅, 高, cx, cy, 大きさ, 濃さ, 乱) {
  const 本数 = 1 + Math.floor(乱() * 2);
  for (let i = 0; i < 本数; i++) {
    const x = cx + (i - (本数 - 1) / 2) * 大きさ * 0.8;
    const 画数 = 2 + Math.floor(乱() * 3);
    for (let j = 0; j < 画数; j++) {
      const x1 = x + (乱() - 0.5) * 大きさ * 0.7;
      const y1 = cy + (乱() - 0.5) * 大きさ;
      const x2 = x + (乱() - 0.5) * 大きさ * 0.7;
      const y2 = cy + (乱() - 0.5) * 大きさ;
      線をひく(画, 幅, 高, x1, y1, x2, y2, 大きさ * 0.13, 濃さ, 乱);
    }
  }
}

/** 文字らしい走り書きを、四角の中に描く */
function 文字らしく(画, 幅, 高, cx, cy, 大きさ, 濃さ, 乱) {
  const 画数 = 4 + Math.floor(乱() * 5);
  for (let j = 0; j < 画数; j++) {
    const x1 = cx + (乱() - 0.5) * 大きさ * 0.8;
    const y1 = cy + (乱() - 0.5) * 大きさ * 0.9;
    const 横か = 乱() < 0.6;
    const 長 = 大きさ * (0.25 + 乱() * 0.45);
    const x2 = 横か ? x1 + 長 : x1 + (乱() - 0.5) * 大きさ * 0.2;
    const y2 = 横か ? y1 + (乱() - 0.5) * 大きさ * 0.2 : y1 + 長;
    線をひく(画, 幅, 高, x1, y1, x2, y2, 大きさ * 0.09, 濃さ, 乱);
  }
}

/**
 * 板を1枚つくる。
 *
 * @param {{種:number, 人数?:number, 行数?:number, 立の人数?:number, 幅?:number, マス?:number, 書き方?:'ふつう'|'ぎっしり'}} 注文
 *   マス … 1マスの大きさ（px）。渡すと幅はそこから決まる（小さい写真を真似るとき）
 *   書き方 … 'ぎっしり' は、印がマスいっぱいで隣と触れ、罫線が濃い板
 *  （4人立ちの板の実物。1マス50pxで、×の腕が上下の丸に届いていた）
 * @returns {{画:Uint8Array, 色:Uint8Array, 幅:number, 高:number, 答え:object}}
 */
export function 板をえがく(注文) {
  const o = 注文 || {};
  const 乱 = 乱数をつくる(o.種 || 1);
  const 人数 = o.人数 || 8;
  const 行数 = o.行数 || 10;
  const 立の人数 = o.立の人数 || 4;
  const ぎっしり = o.書き方 === 'ぎっしり';
  const 列の本数 = 人数 + Math.ceil(人数 / 立の人数) + 2;
  // 表の寸法。マスは正方形に近い。マスの大きさを渡されたら幅をそこから決める
  const 幅 = o.マス ? Math.round(o.マス * 列の本数 * 1.05) : o.幅 || 2000;
  const マス = o.マス || Math.round(幅 / 列の本数 / 1.05);
  const 表の左 = Math.round(マス * 0.8);
  const 表の上 = Math.round(マス * 1.6);
  // 列の並び：射手が 立の人数 ごとに並び、その後ろに小計、最後に合計
  const 列たち = [];
  let x = 表の左;
  for (let i = 0; i < 人数; i++) {
    列たち.push({ 種: '射手', 番: i, x: x + マス / 2 });
    x += マス;
    if ((i + 1) % 立の人数 === 0) {
      列たち.push({ 種: '小計', x: x + マス / 2 });
      x += マス;
    }
  }
  列たち.push({ 種: '合計', x: x + マス / 2 });
  x += マス;
  const 表の右 = x;
  const 表の下 = 表の上 + マス * 行数;
  const 札の上 = 表の下 + Math.round(マス * 0.15);
  const 札の下 = 札の上 + Math.round(マス * 1.5);
  const 高 = 札の下 + Math.round(マス * 0.9);

  const 画 = new Float32Array(幅 * 高);
  const 色 = new Uint8Array(幅 * 高 * 3);

  // 白板の地。照り返しの傾きと、ゆるい影
  const 明るさ = 195 + 乱() * 45;
  const 傾きx = (乱() - 0.5) * 40;
  const 傾きy = (乱() - 0.5) * 40;
  const 影x = 乱();
  const 影y = 乱();
  for (let y = 0; y < 高; y++) {
    for (let xx = 0; xx < 幅; xx++) {
      const u = xx / 幅 - 0.5;
      const v = y / 高 - 0.5;
      const 影 = 18 * Math.exp(-(((xx / 幅 - 影x) ** 2 + (y / 高 - 影y) ** 2) / 0.08));
      画[y * 幅 + xx] = 明るさ + 傾きx * u + 傾きy * v - 影 + (乱() - 0.5) * 5;
    }
  }

  // 罫線。ふつうは薄い。ぎっしりの板は罫線がはっきりしている
  const 線の濃さ = ぎっしり ? 45 + 乱() * 60 : 12 + 乱() * 26;
  const 引く = (x1, y1, x2, y2) => {
    const 歩 = Math.ceil(Math.hypot(x2 - x1, y2 - y1));
    for (let i = 0; i <= 歩; i++) {
      const t = i / 歩;
      const xx = Math.round(x1 + (x2 - x1) * t + (乱() - 0.5) * 1.2);
      const yy = Math.round(y1 + (y2 - y1) * t + (乱() - 0.5) * 1.2);
      if (xx < 0 || xx >= 幅 || yy < 0 || yy >= 高) continue;
      画[yy * 幅 + xx] -= 線の濃さ;
    }
  };
  for (let i = 0; i <= 列たち.length; i++) {
    const xx = 表の左 + i * マス;
    引く(xx, 表の上, xx, 札の下);
  }
  for (let r = 0; r <= 行数; r++) 引く(表の左, 表の上 + r * マス, 表の右, 表の上 + r * マス);
  引く(表の左, 札の上, 表の右, 札の上);
  引く(表の左, 札の下, 表の右, 札の下);

  // 印を置く
  const 濃さの基 = 70 + 乱() * 90;
  const 太さの基 = ぎっしり ? マス * (0.05 + 乱() * 0.035) : マス * (0.035 + 乱() * 0.03);
  const 半の基 = ぎっしり ? 0.40 + 乱() * 0.06 : 0.27 + 乱() * 0.08;
  const 印の幅たち = [];
  const 答えのマス = [];
  for (let i = 0; i < 人数; i++) {
    const 列 = 列たち.find((c) => c.種 === '射手' && c.番 === i);
    const この人 = [];
    // 人によって筆圧が変わる（下の立ほど薄い、ということも在る）
    for (let r = 0; r < 行数; r++) {
      const 記号 = 種類[Math.floor(乱() * 種類.length)];
      この人.push(記号);
      const 薄まり = 0.55 + 0.45 * (乱() < 0.25 ? 乱() : 1);
      const 半 = マス * (半の基 + (乱() - 0.5) * 0.04);
      印の幅たち.push(半 * 2);
      印をそこへ描く(画, 幅, 高, 記号, {
        cx: 列.x + (乱() - 0.5) * マス * (ぎっしり ? 0.05 : 0.12),
        cy: 表の上 + (r + 0.5) * マス + (乱() - 0.5) * マス * (ぎっしり ? 0.05 : 0.12),
        半,
        濃さ: 濃さの基 * 薄まり,
        太さ: 太さの基 * (0.8 + 乱() * 0.5),
        詰まり: ぎっしり ? 1 : 0,
        // 丸に引く線を別のペン（細く薄く、中心を外して）にする率。学習では 0.5
        別のペン: o.別のペン || 0,
        乱,
      });
    }
    答えのマス.push(この人);
  }

  // 上端の的中数
  for (let i = 0; i < 人数; i++) {
    const 列 = 列たち.find((c) => c.種 === '射手' && c.番 === i);
    数字らしく(画, 幅, 高, 列.x, 表の上 - マス * 0.5, マス * 0.45, 濃さの基, 乱);
  }
  // 小計・合計の数字。行ごとに全部は書かない
  for (const c of 列たち) {
    if (c.種 === '射手') continue;
    for (let r = 0; r < 行数; r++) {
      if (乱() > 0.45) continue;
      数字らしく(画, 幅, 高, c.x, 表の上 + (r + 0.5) * マス, マス * 0.4, 濃さの基 * 0.8, 乱);
    }
  }

  // ネームプレート（色枠）
  const 色たち = [
    [220, 60, 60],
    [110, 190, 60],
    [60, 140, 230],
    [240, 200, 60],
    [150, 90, 200],
  ];
  for (let i = 0; i < 人数; i++) {
    const 列 = 列たち.find((c) => c.種 === '射手' && c.番 === i);
    const c = 色たち[Math.floor(乱() * 色たち.length)];
    const 左 = Math.round(列.x - マス * 0.4);
    const 右 = Math.round(列.x + マス * 0.4);
    for (let y = 札の上; y <= 札の下; y++) {
      for (let xx = 左; xx <= 右; xx++) {
        if (xx < 0 || xx >= 幅 || y < 0 || y >= 高) continue;
        const ふち =
          xx < 左 + マス * 0.1 || xx > 右 - マス * 0.1 || y < 札の上 + マス * 0.1 || y > 札の下 - マス * 0.1;
        const i2 = (y * 幅 + xx) * 3;
        if (ふち) {
          色[i2] = c[0];
          色[i2 + 1] = c[1];
          色[i2 + 2] = c[2];
        } else {
          色[i2] = 250;
          色[i2 + 1] = 250;
          色[i2 + 2] = 252;
        }
      }
    }
    文字らしく(画, 幅, 高, 列.x, (札の上 + 札の下) / 2, マス * 0.75, 150 + 乱() * 60, 乱);
  }
  // 立ち位置の札（大前・二的…）
  for (let i = 0; i < 人数; i++) {
    const 列 = 列たち.find((c) => c.種 === '射手' && c.番 === i);
    文字らしく(画, 幅, 高, 列.x, 札の下 + マス * 0.45, マス * 0.4, 130 + 乱() * 60, 乱);
  }

  // 白黒を色に混ぜる（札の枠だけは色を残す）
  const 出色 = new Uint8Array(幅 * 高 * 3);
  for (let i = 0; i < 幅 * 高; i++) {
    const g = 画[i] < 0 ? 0 : 画[i] > 255 ? 255 : 画[i];
    const 枠か = 色[i * 3] || 色[i * 3 + 1] || 色[i * 3 + 2];
    if (枠か) {
      // 札の上に書いた字は、色の上にも乗せる
      const 暗さ = Math.max(0, 明るさ - 画[i]) / 255;
      出色[i * 3] = Math.round(色[i * 3] * (1 - 暗さ));
      出色[i * 3 + 1] = Math.round(色[i * 3 + 1] * (1 - 暗さ));
      出色[i * 3 + 2] = Math.round(色[i * 3 + 2] * (1 - 暗さ));
    } else {
      出色[i * 3] = g;
      出色[i * 3 + 1] = g;
      出色[i * 3 + 2] = g;
    }
  }

  return {
    色: 出色,
    白黒: 画にする({ 画, 幅, 高 }).画,
    幅,
    高,
    答え: {
      人数,
      行数,
      立の人数,
      マス,
      印の幅: Math.round(印の幅たち.sort((a, z) => a - z)[Math.floor(印の幅たち.length / 2)]),
      ぎっしり,
      列のx: 列たち.filter((c) => c.種 === '射手').map((c) => c.x),
      行のy: Array.from({ length: 行数 }, (_, r) => 表の上 + (r + 0.5) * マス),
      札の上,
      マスの中身: 答えのマス,
    },
  };
}
