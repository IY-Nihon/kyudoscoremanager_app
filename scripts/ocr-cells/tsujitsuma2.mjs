/**
 * 板ぜんぶの辻褄を、縦と横の両方で合わせる。
 *
 * ■ 縦だけでは足りない
 * 1列の的中数だけを合わせると、同じ列の中で「1つ増えて1つ減る」取り違えが
 * 素通りしてしまう。実測で、残った外れ8枚のうち6枚がこれだった
 *（◎ を ○/ と読み、代わりに × を ○/ と読む、など）。
 *
 * ■ 縦と横
 * 板には、立ごとの小計も書いてある。
 *   縦 … 射手ごとの的中数（10マスぶん）
 *   横 … 立ごとの小計（その立の、4人ぶん＝8マス）
 * 片方だけを狂わせる取り違えは、もう片方で捕まる。
 *
 * ■ 解き方
 * 立ごとに、4人がそれぞれ何中したかの組み合わせを総当たりし、
 * 「射手ごとに、ここまで何中したか」を持ち越しながら端から埋める。
 * 持ち越しの数は 的中数+1 の掛け算ぶん（4人で5万通りほど）に収まるので、
 * すぐ終わる。組み合わせが多くなりすぎる板では、縦だけの辻褄合わせに戻す。
 */
import { 的中数 } from './tsujitsuma.mjs';

const 上限の手 = 4_000_000;

/**
 * @param {Float32Array[][]} 見立て [射手][行] の、種類ごとの確からしさ
 * @param {string[]} 種類
 * @param {number[]} 的中たち 射手ごとの的中数
 * @param {number[]} 立の小計 立ごとの、その4人ぶんの的中数
 * @param {number} 立のマス 1立が何マスか（4射なら2マス）
 * @returns {{番: number[][]|null, 訳: string}}
 */
export function 縦横で合わせる(見立て, 種類, 的中たち, 立の小計, 立のマス) {
  const 人数 = 見立て.length;
  const 行数 = 見立て[0].length;
  const 立数 = 立の小計.length;
  if (行数 !== 立数 * 立のマス) return { 番: null, 訳: '行の数が立と合いません' };
  const 点 = 種類.map((s) => 的中数[s]);
  const 立の上限 = 立のマス * 2;

  const 縦の和 = 的中たち.reduce((a, b) => a + b, 0);
  const 横の和 = 立の小計.reduce((a, b) => a + b, 0);
  if (縦の和 !== 横の和) return { 番: null, 訳: `縦の合計${縦の和}と横の合計${横の和}が合いません` };

  // 持ち越しの数は、机上では 的中数+1 の掛け算ぶんある（4人で5万通りほど）。
  // 実際に届くのはその一部なので、走らせながら数えて、膨らんだらやめる

  // 一番よい：[射手][立][その立で何中] → 確からしさ（対数）と、選ぶ記号
  const 一番よい = [];
  for (let a = 0; a < 人数; a++) {
    const 立ごと = [];
    for (let k = 0; k < 立数; k++) {
      const 値 = new Float64Array(立の上限 + 1).fill(-Infinity);
      const 選 = new Array(立の上限 + 1).fill(null);
      const 掘る = (i, 合, 印, 並び) => {
        if (i === 立のマス) {
          if (印 > 値[合]) {
            値[合] = 印;
            選[合] = 並び.slice();
          }
          return;
        }
        const o = 見立て[a][k * 立のマス + i];
        for (let c = 0; c < 種類.length; c++) {
          並び.push(c);
          掘る(i + 1, 合 + 点[c], 印 + Math.log(Math.max(1e-9, o[c])), 並び);
          並び.pop();
        }
      };
      掘る(0, 0, 0, []);
      立ごと.push({ 値, 選 });
    }
    一番よい.push(立ごと);
  }

  // 持ち越しは「射手ごとに、ここまで何中したか」。桁をずらして1つの数にする
  const 桁 = [];
  let かけ = 1;
  for (let a = 0; a < 人数; a++) {
    桁.push(かけ);
    かけ *= 的中たち[a] + 1;
  }
  let いま = new Map([[0, { 値: 0, 道: [] }]]);
  let 手 = 0;
  for (let k = 0; k < 立数; k++) {
    const 次 = new Map();
    // その立の、人ごとの中り数の組み合わせ（合計が小計になるもの）
    const 組 = [];
    const 掘る = (a, 残, 並び) => {
      if (a === 人数) {
        if (残 === 0) 組.push(並び.slice());
        return;
      }
      for (let h = 0; h <= Math.min(立の上限, 残); h++) {
        並び.push(h);
        掘る(a + 1, 残 - h, 並び);
        並び.pop();
      }
    };
    掘る(0, 立の小計[k], []);

    手 += いま.size * 組.length;
    if (手 > 上限の手) return { 番: null, 訳: '組み合わせが多すぎます' };
    for (const [鍵, もと] of いま) {
      for (const 組み of 組) {
        let 次の鍵 = 鍵;
        let 値 = もと.値;
        let 通る = true;
        for (let a = 0; a < 人数; a++) {
          const これまで = Math.floor(鍵 / 桁[a]) % (的中たち[a] + 1);
          const 後 = これまで + 組み[a];
          if (後 > 的中たち[a] || 一番よい[a][k].値[組み[a]] === -Infinity) {
            通る = false;
            break;
          }
          次の鍵 += 組み[a] * 桁[a];
          値 += 一番よい[a][k].値[組み[a]];
        }
        if (!通る) continue;
        const 前 = 次.get(次の鍵);
        if (!前 || 値 > 前.値) 次.set(次の鍵, { 値, 道: もと.道.concat([組み]) });
      }
    }
    いま = 次;
    if (!いま.size) return { 番: null, 訳: `立${k + 1}で行き止まりになりました` };
  }

  let 終い = 0;
  for (let a = 0; a < 人数; a++) 終い += 的中たち[a] * 桁[a];
  const 答 = いま.get(終い);
  if (!答) return { 番: null, 訳: '縦と横の両方に合う読み方がありません' };

  const 番 = [];
  for (let a = 0; a < 人数; a++) {
    const 列 = [];
    for (let k = 0; k < 立数; k++) 列.push(...一番よい[a][k].選[答.道[k][a]]);
    番.push(列);
  }
  return { 番, 訳: '合いました' };
}
