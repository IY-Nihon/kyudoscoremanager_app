/**
 * 素直な画像処理だけで、どこまで見分けられるかを測った道具。
 *
 * ■ 結論：これだけでは足りない（実測 51.3%）
 * アプリには組み込んでいない。学習させる値打ちが在るかを確かめるために置いてある。
 *
 * 切り出した1マスの絵から、○×の種類を見分ける。
 *
 * ■ なぜ模型に頼らないか
 *
 * 大きな模型（Gemini）は、板を1枚まるごと渡すとマスの種類を25%しか当てられず、
 * 列ごとに同じ並びを使い回した。1人ずつに絞れば種類は当たるが、
 * 線の向き（＼か／か＝2射のどちらが中りか）は最後まで読めなかった。
 *
 * いっぽう、切り出したマスを並べて見ると、4種類ははっきり分かれている。
 *   ×      … 丸が無く、2本の線が交わる
 *   ◎      … 丸の内側にもう1つ丸
 *   丸に＼  … 丸に、左上から右下への線（中り→外れ）
 *   丸に／  … 丸に、右上から左下への線（外れ→中り）
 *
 * 違いは「真ん中に墨があるか」と「どちらの対角線に墨が寄っているか」だけ。
 * 数えれば決まる。学習も模型の同梱も要らず、端末の中で完結し、検査もできる。
 */
'use strict';

/**
 * 明るさの並び（0-255、左上から右へ）から、墨のあるところを1にする。
 * 境目はその絵の中で決める（照明のむらに強い）。
 */
function 墨にする(明るさ, 幅, 高) {
  let 最小 = 255;
  let 最大 = 0;
  for (let i = 0; i < 明るさ.length; i++) {
    if (明るさ[i] < 最小) 最小 = 明るさ[i];
    if (明るさ[i] > 最大) 最大 = 明るさ[i];
  }
  // 濃淡の幅が小さい＝ほとんど何も書かれていない
  if (最大 - 最小 < 25) return { 墨: new Uint8Array(幅 * 高), 濃さ: 0 };
  const 境 = 最小 + (最大 - 最小) * 0.45;
  const 墨 = new Uint8Array(幅 * 高);
  let 数 = 0;
  for (let i = 0; i < 明るさ.length; i++) {
    if (明るさ[i] < 境) {
      墨[i] = 1;
      数++;
    }
  }
  return { 墨, 濃さ: 数 / (幅 * 高) };
}

/**
 * 1マスの絵から、見分けに使う数を取り出す。
 *
 * @param {Uint8Array|number[]} 明るさ 0-255 の並び（白黒）
 * @param {number} 幅
 * @param {number} 高
 */
function 特徴を取る(明るさ, 幅, 高) {
  const { 墨, 濃さ } = 墨にする(明るさ, 幅, 高);

  // 印はマスの真ん中に、余白をあけて書かれている。切り出しの箱に合わせて
  // 測ると、輪の位置が箱の大きさ次第でずれる（実測で、輪がほとんど拾えなかった）。
  // 墨の在る範囲を先に見つけて、それを枠として測る
  let 左 = 幅, 右 = -1, 上 = 高, 下 = -1;
  for (let y = 0; y < 高; y++) {
    for (let x = 0; x < 幅; x++) {
      if (!墨[y * 幅 + x]) continue;
      if (x < 左) 左 = x;
      if (x > 右) 右 = x;
      if (y < 上) 上 = y;
      if (y > 下) 下 = y;
    }
  }
  if (右 < 0) return { 濃さ: 0, 真ん中: 0, 輪: 0, 右下がり: 0, 右上がり: 0 };
  const 中x = (左 + 右) / 2;
  const 中y = (上 + 下) / 2;
  const 半 = Math.max(3, Math.max(右 - 左, 下 - 上) / 2);
  // 墨の広がりに対する濃さ。箱の大きさに左右されない
  const 枠の濃さ = (() => {
    let 数 = 0;
    for (let y = 上; y <= 下; y++) for (let x = 左; x <= 右; x++) if (墨[y * 幅 + x]) 数++;
    return 数 / Math.max(1, (右 - 左 + 1) * (下 - 上 + 1));
  })();

  let 真ん中 = 0;
  let 真ん中の数 = 0;
  let 輪 = 0;
  let 輪の数 = 0;
  // 対角の帯。＼は (x-中x) と (y-中y) の符号が同じ、／は逆
  let 右下がり = 0;
  let 右下がりの数 = 0;
  let 右上がり = 0;
  let 右上がりの数 = 0;

  for (let y = 0; y < 高; y++) {
    for (let x = 0; x < 幅; x++) {
      const dx = (x - 中x) / 半;
      const dy = (y - 中y) / 半;
      const r = Math.sqrt(dx * dx + dy * dy);
      const 墨か = 墨[y * 幅 + x];
      if (r <= 0.34) {
        真ん中の数++;
        if (墨か) 真ん中++;
      }
      if (r >= 0.62 && r <= 1.0) {
        輪の数++;
        if (墨か) 輪++;
      }
      // 対角線からの隔たり。線の太さぶんだけ見る
      if (r <= 0.95) {
        const 下がり = Math.abs(dx - dy) / Math.SQRT2; // ＼ からの隔たり
        const 上がり = Math.abs(dx + dy) / Math.SQRT2; // ／ からの隔たり
        if (下がり <= 0.16) {
          右下がりの数++;
          if (墨か) 右下がり++;
        }
        if (上がり <= 0.16) {
          右上がりの数++;
          if (墨か) 右上がり++;
        }
      }
    }
  }

  return {
    濃さ: 枠の濃さ,
    もとの濃さ: 濃さ,
    真ん中: 真ん中の数 ? 真ん中 / 真ん中の数 : 0,
    輪: 輪の数 ? 輪 / 輪の数 : 0,
    右下がり: 右下がりの数 ? 右下がり / 右下がりの数 : 0,
    右上がり: 右上がりの数 ? 右上がり / 右上がりの数 : 0,
  };
}

/**
 * 特徴から、マスの見た目を決める。
 *
 * @returns {'◎'|'○\\'|'○/'|'×'|'○'|''} ocrCells が受ける記号
 */
/**
 * 特徴から、マスの見た目を決める。
 *
 * 境目は実物の板80マスで測った平均の真ん中に置いてある:
 *   輪    … ×  0.074 / 丸のなかま 0.19〜0.21   → 0.13
 *   真ん中 … ◎ 0.261 / 丸に線 0.177〜0.182     → 0.22
 *   対角  … ＼ 0.258対0.152 ／ 0.139対0.238
 *
 * @returns {'◎'|'○\'|'○/'|'×'|'○'|''} ocrCells が受ける記号
 */
function 見た目を決める(特徴) {
  const f = 特徴;
  // 何も書かれていない。もとの濃さ（箱ぜんぶに対する割合）で見る
  if ((f.もとの濃さ == null ? f.濃さ : f.もとの濃さ) < 0.015) return '';

  if (f.輪 < 0.13) {
    // 丸が無い。2本の線が交われば×、1本だけなら線
    if (f.右下がり > 0.15 && f.右上がり > 0.15) return '×';
    if (f.右下がり > 0.15 || f.右上がり > 0.15) return '/';
    return '';
  }

  // 丸の内側にもう1つ丸があると、真ん中に墨が残る
  if (f.真ん中 > 0.22) return '◎';

  // 丸に線。どちらの対角に寄っているかで向きが決まる
  const 差 = f.右下がり - f.右上がり;
  if (差 > 0.02) return '○' + String.fromCharCode(92);
  if (差 < -0.02) return '○/';
  return '○';
}

export { 特徴を取る, 見た目を決める, 墨にする };
