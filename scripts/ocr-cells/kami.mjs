/**
 * 紙の記録用紙の格子。
 *
 * ■ 紙の形（関東学生の記録用紙。使う人に聞いた決まり）
 *   ・列は射手。右の列が大前（板の右側と同じ向き）
 *   ・縦に 立数 のかたまり。いちばん下が1立目
 *   ・1つのかたまりは 立のマス（4射なら4）に等分。下のマスが1射目
 *   ・1マス1射。○ か ×
 *   ・列の罫線と、かたまりの罫線は引かれている。かたまりの中の射の境には罫線が無い
 *
 * 罫線があるので、板と同じ「罫線を拾う」で列とかたまりを立て、かたまりの中を等分する。
 *
 * ■ 前提
 * 渡す画は、表の部分（列の罫線からかたまりの罫線まで）を切り抜いたもの。
 * 右に小計の列が写っていても、幅が違うので等間隔の当てはめから外れる。
 */
import { 明暗を伸ばす, 暗さの境 } from './koushi.mjs';
import { 墨の量, 罫線を拾う } from './kiridasu.mjs';
import { 写す式 } from './kuzusu.mjs';

/**
 * @param {{画素:Uint8Array, 幅:number, 高:number}} 元
 * @param {{人数:number, 立数:number, 立のマス:number, 角度?:number, 上を探す?:boolean}} 注文
 * @returns {{列:{中心:number}[], かたまり:{上:number,下:number}[], マス:{x:number,y:number,幅:number,高:number}[][], 生:object}}
 *   マス[列][射番] … 射番は 0 が1射目（いちばん下のかたまりの、いちばん下）
 */
export async function 紙の格子(元, 注文) {
  let 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
  // 遠近を戻す。斜めから撮ると表が台形になり、等間隔の当てはめが端で外れる
  //（実測で台形0.2の紙が 60/80）。表の外枠の4本の線を角度つきで探し、
  // 四隅を長方形へ写してから格子を立てる。外枠が見つからなければそのまま
  let 正した = null;
  if (注文.正す !== false) {
    正した = 外枠で正す(生, 注文.枠);
    if (正した) 生 = 正した;
  }
  // 傾きは画を回さずに扱う。罫線は縦横の墨の量の針で探すので、1.3度傾くだけで
  // 針が鈍り（高さ640pxで14pxばらける）、格子が立たなかった。かといって画を回すと
  // 1pxの罫線がぼけて、0.8度で回した紙が列を1本取り違えた（80/80 → 46/80）。
  // 代わりに、墨を数えるときに y に応じて x をずらす（斜めに足し込む）。
  // 縦線と横線で別々に、いちばん針が鋭くなる傾きを探す
  const 縦線の傾き = 注文.角度 != null ? 注文.角度 : 針が鋭い傾き(生, '縦線');
  const 横線の傾き = 注文.角度 != null ? 注文.角度 : 針が鋭い傾き(生, '横線');
  const 横 = 斜めに数える(生, '縦線', 縦線の傾き);
  const 縦 = 斜めに数える(生, '横線', 横線の傾き);
  // 右に小計の列が写るぶん、列の間隔は 画の幅÷人数 より狭い。狭いほうへ広く探す
  // 外枠で正したあとは、左端の線と上端の線が枠の位置（余白の3px）に在る。
  // 起点をそこに固定すると、「左端を捨てて小計の線を取る」置き方や、
  // 見出しの段を立と取り違える置き方が消える（実測で入れ替わりに落ちていた）
  const 端 = 正した ? [正した.余 - 2, 正した.余 + 2] : undefined;
  // 枠（表を探したときの左右の線）で正したなら、正した幅はちょうど射手の列ぶん。
  // 間隔はそこから決め打ちにする（探させると狭い間隔を選んで 39/80 に落ちた）
  const 列 = 正した && 注文.枠
    ? 罫線を拾う(横, 注文.人数, 生.高, (生.幅 - 正した.余 * 2) / 注文.人数, [0.9, 1.1], true, 端)
    : 罫線を拾う(横, 注文.人数, 生.高, undefined, [0.35, 1.1], true, 端);
  // 上を探す … 表の上端を 1 立目の上の線に決め打ちしない。男子の記録用紙（表が並ぶ用紙）は、表の上に各人の
  // 的中数の段があり、縦の罫線がそこまで続くので、正した表の上端は見出しの上になる（合成の用紙で 1 立ずれて半分外れた）
  const かたまり = 罫線を拾う(縦, 注文.立数, 生.幅, undefined, [0.5, 1.1], true, 注文.上を探す ? undefined : 端);
  if (!列) throw new Error('紙の列の罫線が見つかりません');
  if (!かたまり) throw new Error('紙の立の罫線が見つかりません');

  // 斜めに数えた座標は「y=0 での x」「x=0 での y」。マスの中心では傾きぶんを戻す
  const tc = Math.tan((縦線の傾き * Math.PI) / 180);
  const tr = Math.tan((横線の傾き * Math.PI) / 180);
  const マス = [];
  for (let c = 0; c < 注文.人数; c++) {
    const 左0 = 列.位置[c];
    const 右0 = 列.位置[c + 1];
    const この列 = [];
    // 立は下から。かたまりの中も下から
    for (let t = 0; t < 注文.立数; t++) {
      const 上0 = かたまり.位置[注文.立数 - 1 - t];
      const 下0 = かたまり.位置[注文.立数 - t];
      const 一つ = (下0 - 上0) / 注文.立のマス;
      // かたまりの中に罫線は無く、印は縦に積まれているだけなので、等分する。
      // 墨の薄い行へ境を寄せる手も試したが、丸は真ん中の行が薄いので谷が丸の
      // 中心に落ち、80/80 → 71/80 に崩れた。等分のまま、ずれは網に覚えさせる
      for (let r = 0; r < 注文.立のマス; r++) {
        const y0 = 下0 - 一つ * r - 一つ / 2;
        const x0 = (左0 + 右0) / 2;
        const x = x0 + y0 * tc;
        const y = y0 + x * tr;
        この列.push({ x, y, 幅: 右0 - 左0, 高: 一つ });
      }
    }
    マス.push(この列);
  }
  return {
    列: 列.位置.slice(0, -1).map((x, i) => ({ 中心: (x + 列.位置[i + 1]) / 2 })),
    かたまり,
    マス,
    生,
    列の間隔: 列.間隔,
    立の高さ: かたまり.間隔,
    角度: 縦線の傾き,
    横線の傾き,
  };
}

/**
 * 角度つきで線を集める。ink の画素ごとに、角度 θ で y=0（横線なら x=0）へ
 * 延ばした切片に票を入れる。線は (θ, 切片) の山として出る。
 */
export function 線を集める(生, 何, 度の幅, 刻み, 閾 = 0.35) {
  // 閾 … 向こう側の長さに対する、線とみなす最小の高さ。ページ全体から表を探すときは低くする
  const 境 = 暗さの境(生.画素);
  const 長さ = 何 === '縦線' ? 生.幅 : 生.高;
  const 向こう = 何 === '縦線' ? 生.高 : 生.幅;
  // 切片は画の外にも出る（傾いた線）。向こう側の長さ×tan ぶん余白を取る
  const 余白 = Math.ceil(向こう * Math.tan((度の幅 * Math.PI) / 180)) + 2;
  const 角度たち = [];
  for (let 度 = -度の幅; 度 <= 度の幅 + 1e-9; 度 += 刻み) 角度たち.push(度);
  const 票 = 角度たち.map(() => new Float64Array(長さ + 余白 * 2));
  const 傾き = 角度たち.map((d) => Math.tan((d * Math.PI) / 180));
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] >= 境) continue;
      for (let a = 0; a < 角度たち.length; a++) {
        const p = Math.round((何 === '縦線' ? x - y * 傾き[a] : y - x * 傾き[a]) + 余白);
        if (p >= 0 && p < 票[a].length) 票[a][p]++;
      }
    }
  }
  // 山を拾う。まわりの中央値からの飛び出しで測る（板の罫線探しと同じ）
  const 山 = [];
  const 幅 = Math.max(3, Math.round(長さ * 0.03));
  for (let a = 0; a < 角度たち.length; a++) {
    const 並び = 票[a];
    for (let i = 余白; i < 並び.length - 余白; i++) {
      if (並び[i] < 向こう * 閾) continue;
      let 最 = true;
      for (let j = Math.max(0, i - 幅); j <= Math.min(並び.length - 1, i + 幅); j++) {
        if (並び[j] > 並び[i] || (並び[j] === 並び[i] && j < i)) {
          最 = false;
          break;
        }
      }
      if (最) 山.push({ 度: 角度たち[a], 切片: i - 余白, 高さ: 並び[i] });
    }
  }
  return 山;
}

/**
 * 表の外枠の4本（左右の縦線、上下の横線）から四隅を求め、長方形へ写す。
 * 見つからなければ null。
 */
export function 外枠で正す(生, 枠) {
  // 枠 … 紙の表を探す が見つけた左右の線。あれば縦線はそれを使う
  //（切り抜きに他の枠の線が混じると、左端の線を取り違えた。8度傾けた紙で 45/80）
  const 縦 = 枠 ? [] : 線を集める(生, '縦線', 12, 0.5);
  const 横 = 線を集める(生, '横線', 12, 0.5);
  if ((!枠 && 縦.length < 2) || 横.length < 2) return null;
  // 同じ線が隣の角度でも山になるので、画の真ん中での位置でまとめ、いちばん高いものを残す
  const まとめる = (山たち, 向こう) => {
    const 出 = [];
    for (const 山 of 山たち.sort((a, z) => z.高さ - a.高さ)) {
      const 真ん中 = 山.切片 + (向こう / 2) * Math.tan((山.度 * Math.PI) / 180);
      if (出.some((o) => Math.abs(o.真ん中 - 真ん中) < 6)) continue;
      出.push({ ...山, 真ん中 });
    }
    return 出;
  };
  const 縦の線 = 枠 ? [] : まとめる(縦, 生.高);
  const 横の線 = まとめる(横, 生.幅);
  if ((!枠 && 縦の線.length < 2) || 横の線.length < 2) return null;
  // 外枠は、強い線のうち両端のもの
  const 強い縦 = 縦の線.filter((l) => l.高さ >= 縦の線[0].高さ * 0.4);
  const 強い横 = 横の線.filter((l) => l.高さ >= 横の線[0].高さ * 0.4);
  const 真ん中を = (l) => ({ ...l, 真ん中: l.切片 + (生.高 / 2) * Math.tan((l.度 * Math.PI) / 180) });
  const 左 = 枠 ? 真ん中を(枠.左の線) : 強い縦.reduce((a, b) => (b.真ん中 < a.真ん中 ? b : a));
  const 右 = 枠 ? 真ん中を(枠.右の線) : 強い縦.reduce((a, b) => (b.真ん中 > a.真ん中 ? b : a));
  const 上 = 強い横.reduce((a, b) => (b.真ん中 < a.真ん中 ? b : a));
  const 下 = 強い横.reduce((a, b) => (b.真ん中 > a.真ん中 ? b : a));
  if ((!枠 && 右.真ん中 - 左.真ん中 < 生.幅 * 0.3) || 下.真ん中 - 上.真ん中 < 生.高 * 0.3) return null;

  // 縦線: x = 切片 + y·tanθ、横線: y = 切片 + x·tanφ。交点を解く
  const 交点 = (v, h) => {
    const tv = Math.tan((v.度 * Math.PI) / 180);
    const th = Math.tan((h.度 * Math.PI) / 180);
    const y = (h.切片 + v.切片 * th) / (1 - tv * th);
    const x = v.切片 + y * tv;
    return [x, y];
  };
  const 隅 = [交点(左, 上), 交点(右, 上), 交点(右, 下), 交点(左, 下)];
  const 幅 = Math.round((Math.hypot(隅[1][0] - 隅[0][0], 隅[1][1] - 隅[0][1]) + Math.hypot(隅[2][0] - 隅[3][0], 隅[2][1] - 隅[3][1])) / 2);
  const 高 = Math.round((Math.hypot(隅[3][0] - 隅[0][0], 隅[3][1] - 隅[0][1]) + Math.hypot(隅[2][0] - 隅[1][0], 隅[2][1] - 隅[1][1])) / 2);
  if (幅 < 20 || 高 < 20) return null;
  // 外枠の外にも少し余白を残す（罫線そのものが切れないように）
  const 余 = 3;
  const 戻す = 写す式(
    [[余, 余], [幅 + 余, 余], [幅 + 余, 高 + 余], [余, 高 + 余]],
    隅
  );
  const 出幅 = 幅 + 余 * 2;
  const 出高 = 高 + 余 * 2;
  const 出 = new Uint8Array(出幅 * 出高);
  for (let y = 0; y < 出高; y++) {
    for (let x = 0; x < 出幅; x++) {
      const [sx, sy] = 戻す(x, y);
      if (sx < 0 || sy < 0 || sx > 生.幅 - 1 || sy > 生.高 - 1) {
        出[y * 出幅 + x] = 235;
        continue;
      }
      const x0 = Math.floor(sx);
      const y0 = Math.floor(sy);
      const x1 = Math.min(生.幅 - 1, x0 + 1);
      const y1 = Math.min(生.高 - 1, y0 + 1);
      const fx = sx - x0;
      const fy = sy - y0;
      const a = 生.画素[y0 * 生.幅 + x0];
      const b = 生.画素[y0 * 生.幅 + x1];
      const c = 生.画素[y1 * 生.幅 + x0];
      const d = 生.画素[y1 * 生.幅 + x1];
      出[y * 出幅 + x] = Math.round(a * (1 - fx) * (1 - fy) + b * fx * (1 - fy) + c * (1 - fx) * fy + d * fx * fy);
    }
  }
  return { 画素: 出, 幅: 出幅, 高: 出高, 隅, 余 };
}

/**
 * 墨の量を斜めに数える。
 * 縦線 … x' = x − y·tanθ ごとに数える（θ だけ傾いた縦線が1本の針になる）
 * 横線 … y' = y − x·tanθ ごとに数える
 */
export function 斜めに数える(生, 何, 度) {
  const t = Math.tan((度 * Math.PI) / 180);
  const 境 = 暗さの境(生.画素);
  const 長さ = 何 === '縦線' ? 生.幅 : 生.高;
  const 出 = new Float64Array(長さ);
  for (let y = 0; y < 生.高; y++) {
    for (let x = 0; x < 生.幅; x++) {
      if (生.画素[y * 生.幅 + x] >= 境) continue;
      const p = Math.round(何 === '縦線' ? x - y * t : y - x * t);
      if (p >= 0 && p < 長さ) 出[p]++;
    }
  }
  return 出;
}

/**
 * 針がいちばん鋭くなる傾き（度）。二乗和がいちばん大きい角度を ±10度で探す。
 * 速さのため、画を半分に間引いて測る（傾きは変わらない）
 */
export function 針が鋭い傾き(生, 何) {
  const 間引き = 生.幅 > 300 ? 2 : 1;
  let 小 = 生;
  if (間引き > 1) {
    const 幅 = Math.floor(生.幅 / 間引き);
    const 高 = Math.floor(生.高 / 間引き);
    const 画素 = new Uint8Array(幅 * 高);
    for (let y = 0; y < 高; y++) for (let x = 0; x < 幅; x++) 画素[y * 幅 + x] = 生.画素[y * 間引き * 生.幅 + x * 間引き];
    小 = { 画素, 幅, 高 };
  }
  let 最良 = 0;
  let 最大 = -1;
  for (let 度 = -10; 度 <= 10; 度 += 0.25) {
    const 並び = 斜めに数える(小, 何, 度);
    let 点 = 0;
    for (const v of 並び) 点 += v * v;
    if (点 > 最大) {
      最大 = 点;
      最良 = 度;
    }
  }
  return 最良;
}

/** 1マスを切る箱。マスより少しだけ小さく（罫線と隣の印を入れない） */
export function 紙の箱(マス) {
  return { 半幅: Math.round(マス.幅 * 0.46), 半高: Math.round(マス.高 * 0.5) };
}

/**
 * ページ全体から、表の罫線になりうる縦線を集める（紙の表を探す・紙の表たちを探す で使う）。
 * 線ごとに 度・切片・中（画の真ん中の高さでの x）・上・下（暗い画素が続く範囲）・線らしさ を持つ
 * 淡い線も … 暗さを写真全体の境ではなく、まわり（25px 四方）の平均より 12 暗いかで見る。男子の記録用紙は
 *   外枠が太く、内側の罫線は細くて薄い。透明なファイルに入れた紙は照り返しで上のほうが白ける（10/1 の写真で、
 *   内側の罫線は表の上半分で境に届かず、線が名前の欄の高さでしか続かなかった）
 */
function 表の縦線を集める(生, 淡い線も = false) {
  const 境 = 暗さの境(生.画素);
  // 縦線を角度つきで集める。ページ全体なので、表の線は高さの1割ほどにしかならない
  // 角度は ±10度を 0.25度刻みで（8度傾けた紙で見つからなかった。0.5刻みだと線に沿って歩くときに外れる）
  const 山 = 線を集める(生, '縦線', 10, 0.25, 0.08);
  const 線 = [];
  for (const s of 山.sort((a, z) => z.高さ - a.高さ)) {
    const 中 = s.切片 + (生.高 / 2) * Math.tan((s.度 * Math.PI) / 180);
    if (線.some((o) => Math.abs(o.中 - 中) < 5)) continue;
    線.push({ ...s, 中 });
  }
  const 局所に暗い = 淡い線も ? 局所の暗さ(生, 12, 12) : null;
  // 線ごとに、暗い画素が続く上下の範囲（20px以上途切れたら別）。いちばん長い区間を取る
  // 線ごとに、暗い画素が続く上下の範囲と、細さを測る。
  // 印の列も「暗い画素が縦に続く筋」になる（丸が縦に触れ合うので、列の中を
  // 通る線はどの角度でも暗い）。罫線は細く、両脇 6px は白い。暗い行のうち
  // 両脇が白い行の割合を「線らしさ」とし、低いものは印の列なので外す
  for (const l of 線) {
    const t = Math.tan((l.度 * Math.PI) / 180);
    const 暗 = new Uint8Array(生.高);
    const 細 = new Uint8Array(生.高);
    // 暗さは「境からどれだけ下か」の合計で見る。境をわずかに下回る画素が1つ
    // あるだけでは暗い行にしない（ざらつき25で余白の行の半分が暗くなっていた）。
    // 真っ黒な画素1つ分（境の高さ）の半分を超えたら暗い
    const 墨たち = new Float64Array(生.高);
    for (let y = 0; y < 生.高; y++) {
      const x = Math.round(l.切片 + y * t);
      let 墨 = 0;
      for (let dx = -2; dx <= 2; dx++) {
        const xx = x + dx;
        if (xx >= 0 && xx < 生.幅) 墨 += Math.max(0, 境 - 生.画素[y * 生.幅 + xx]);
      }
      墨たち[y] = 墨;
    }
    for (let y = 0; y < 生.高; y++) {
      const x = Math.round(l.切片 + y * t);
      const 左脇 = x - 6;
      const 右脇 = x + 6;
      if (淡い線も) {
        for (let dx = -2; dx <= 2; dx++) if (局所に暗い(x + dx, y)) 暗[y] = 1;
        if (暗[y] && 左脇 >= 0 && 右脇 < 生.幅 && !局所に暗い(左脇, y) && !局所に暗い(右脇, y)) 細[y] = 1;
        continue;
      }
      if (墨たち[y] >= 境 * 0.5) 暗[y] = 1;
      if (暗[y] && 左脇 >= 0 && 右脇 < 生.幅 && 生.画素[y * 生.幅 + 左脇] >= 境 && 生.画素[y * 生.幅 + 右脇] >= 境) 細[y] = 1;
    }
    // 行ごとの暗さは、ざらつきで飛び飛びに暗くなる（ざらつき25で、表の下の余白を
    // 抜けて線が倍の長さになり、上端もそろわなくなった）。前後10行の暗い割合で見る。
    // 罫線の上ではほぼ全行が暗く、ざらついた余白でも半分ほど（5px幅のどれかが暗ければ暗い行なので）
    const 窓 = 10;
    let 累 = 0;
    const 累積 = new Int32Array(生.高 + 1);
    for (let y = 0; y < 生.高; y++) 累積[y + 1] = 累 += 暗[y];
    let 始 = -1;
    let 最長 = [0, 0];
    for (let y = 0; y <= 生.高; y++) {
      let 続く = false;
      if (y < 生.高) {
        const a = Math.max(0, y - 窓);
        const z = Math.min(生.高, y + 窓 + 1);
        続く = (累積[z] - 累積[a]) / (z - a) >= 0.85;
      }
      if (続く) {
        if (始 < 0) 始 = y;
      } else if (始 >= 0) {
        if (y - 始 > 最長[1] - 最長[0]) 最長 = [始, y];
        始 = -1;
      }
    }
    // 窓で見た範囲は端が内側に寄る（始まりは窓の半分ほど遅れ、終わりは早まる）。
    // そこから暗い行を辿って、本当の端まで戻す（1行の途切れは越える。ざらつきでは行の半分が暗いので、広く越えると余白を進んでしまう）
    let 上 = Math.min(最長[0] + 窓, 最長[1]);
    let 下 = Math.max(最長[1] - 窓, 上);
    const 続きがある = (y, 向き) => {
      for (let k = 1; k <= 2; k++) {
        const yy = y + k * 向き;
        if (yy >= 0 && yy < 生.高 && 暗[yy]) return true;
      }
      return false;
    };
    while (上 > 0 && 続きがある(上, -1)) 上--;
    while (下 < 生.高 && 続きがある(下 - 1, 1)) 下++;
    l.上 = 上;
    l.下 = 下;
    let 暗い行 = 0;
    let 細い行 = 0;
    for (let y = l.上; y < l.下; y++) {
      暗い行 += 暗[y];
      細い行 += 細[y];
    }
    l.線らしさ = 暗い行 ? 細い行 / 暗い行 : 0;
  }
  return 線
    .filter((l) => l.下 - l.上 >= 生.高 * 0.2 && l.線らしさ >= 0.4)
    .sort((a, z) => a.中 - z.中);
}

/**
 * ページ全体の写真から、記録表（射手の列）の場所を探す。
 *
 * 表の列の罫線は、人数+1 本が等間隔に並び、上下の続く範囲がそろっている。
 * ページには他の枠（選手変更の欄、名前の欄）もあるが、本数と間隔と範囲の
 * 3つがそろうのは表だけ（実測で、左の枠の線は範囲が 659〜1148 と表より短い）。
 *
 * @param {{画素:Uint8Array, 幅:number, 高:number}} 元 ページ全体（明るさ）
 * @param {{人数:number}} 注文
 * @returns {{left:number, top:number, width:number, height:number}|null} 切り抜く四角（小計の列まで含む）
 */
export function 紙の表を探す(元, 注文) {
  const 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
  const 候補 = 表の縦線を集める(生);
  const 本数 = 注文.人数 + 1;
  if (候補.length < 本数) return null;
  const 最良 = 罫線の組たち(候補, 本数, false)[0];
  if (!最良) return null;
  // 右は小計の列（射手の列の2.5倍ほど）まで入れる。無ければ余白が入るだけ
  return 四角にする(生, 最良.組, 最良.間隔, 3);
}

/**
 * まわり（(2半+1) 四方）の平均より 差 以上暗いか、を返す関数を作る（積み上げの表で平均を速く出す）
 */
function 局所の暗さ(生, 半, 差) {
  const { 幅, 高, 画素 } = 生;
  const 積 = new Float64Array((幅 + 1) * (高 + 1));
  for (let y = 0; y < 高; y++) {
    let 行 = 0;
    for (let x = 0; x < 幅; x++) {
      行 += 画素[y * 幅 + x];
      積[(y + 1) * (幅 + 1) + x + 1] = 積[y * (幅 + 1) + x + 1] + 行;
    }
  }
  return (x, y) => {
    if (x < 0 || x >= 幅 || y < 0 || y >= 高) return false;
    const x0 = Math.max(0, x - 半);
    const x1 = Math.min(幅, x + 半 + 1);
    const y0 = Math.max(0, y - 半);
    const y1 = Math.min(高, y + 半 + 1);
    const 平均 = (積[y1 * (幅 + 1) + x1] - 積[y0 * (幅 + 1) + x1] - 積[y1 * (幅 + 1) + x0] + 積[y0 * (幅 + 1) + x0]) / ((x1 - x0) * (y1 - y0));
    return 画素[y * 幅 + x] < 平均 - 差;
  };
}

/**
 * 1 枚の用紙に表が並ぶとき（男子の記録用紙は 後立・前立 の 4 人ずつが、合計の列をはさんで並ぶ）、
 * 表ごとの場所を左から探す。
 *
 * 用紙の列は [小計][射手 4][合計][射手 4][小計] がどれも同じ幅で並ぶので（2026-10-01 の写真で 12 本の罫線が
 * ほぼ等間隔）、等間隔の罫線をつながる限り拾い、どの列が射手かは列の墨の量で決める。射手の列は ○×（と下の
 * 名前）で埋まり、合計・小計の列は数字だけで薄い。
 *
 * @param {{画素:Uint8Array, 幅:number, 高:number}} 元 ページ全体（明るさ）
 * @param {{人数たち:number[]}} 注文 表ごとの人数（左から）
 * @returns {{left:number, top:number, width:number, height:number, 間隔:number, 枠:object}[]|null}
 */
export function 紙の表たちを探す(元, 注文) {
  const 生 = { 画素: 明暗を伸ばす(元.画素), 幅: 元.幅, 高: 元.高 };
  const 候補 = 表の縦線を集める(生, true);
  const 人数たち = 注文.人数たち;
  // 表と表の間には少なくとも 1 列（合計）
  const 要る列 = 人数たち.reduce((a, b) => a + b, 0) + 人数たち.length - 1;
  if (候補.length < 要る列 + 1) return null;
  const 境 = 暗さの境(生.画素);
  let 最良 = null;
  for (const 鎖 of 罫線の組たち(候補, 要る列 + 1, true)) {
    const 墨 = [];
    for (let i = 0; i + 1 < 鎖.組.length; i++) 墨.push(列の墨(生, 境, 鎖.組[i], 鎖.組[i + 1]));
    const 置き方 = 射手の列を置く(墨, 人数たち);
    if (!置き方 || !置き方.はっきり) continue;
    // 表らしさ（罫線の長さ）が同じくらいなら、射手の列と間の列の墨の差がはっきりしたほう
    const 点 = 鎖.点 * (1 + 置き方.差);
    if (!最良 || 点 > 最良.点) 最良 = { 点, 鎖, 置き方 };
  }
  if (!最良) return null;
  const { 組 } = 最良.鎖;
  return 最良.置き方.始めたち.map((始, k) => {
    const 線たち = 組.slice(始, 始 + 人数たち[k] + 1);
    const 間隔 = (線たち[線たち.length - 1].中 - 線たち[0].中) / 人数たち[k];
    return 四角にする(生, 線たち, 間隔, 0.5);
  });
}

/**
 * 同じ表の罫線どうしか（隣り合う 2 本で見る）。上下の範囲が重なり、角度と上端がそろう。
 * 斜めから撮ると遠近で罫線の角度が端から端へ少しずつ変わる（10/1 の男子の用紙で −4.75° 〜 +8.75°、
 * 1 列ごとに 1.25° ずつ）。表の最初の線と比べると外れるので、隣の線と比べ、3 本目からは前の 2 本の
 * 角度の変わり方からも外れないこと（印の列から出た偽の線は角度がばらばら）
 */
function 隣の罫線か(a, b, 前) {
  const 長 = Math.min(a.下 - a.上, b.下 - b.上);
  if (Math.min(a.下, b.下) - Math.max(a.上, b.上) < 0.8 * 長) return false;
  if (Math.abs(a.度 - b.度) > 2) return false;
  if (前 && Math.abs(b.度 - (a.度 + (a.度 - 前.度))) > 1.5) return false;
  // 表の上端は罫線と直角なので、罫線が右下がり（tan が負）なら右の線ほど上端は下がる
  const 見込み = a.上 - (b.中 - a.中) * Math.tan((a.度 * Math.PI) / 180);
  return Math.abs(b.上 - 見込み) <= 長 * 0.08;
}

/**
 * 等間隔に並ぶ罫線の組を、点の高い順に返す。
 * 伸ばす … false なら 本数 本ちょうど、true なら 本数 本以上でつながる限り右へ伸ばす
 */
function 罫線の組たち(候補, 本数, 伸ばす) {
  // 線らしさが低い線（印の列が線に見えているだけ）は組に入っても点にしない。
  // 本物の罫線は印が横切っても 0.55 以上、印の列は 0.45 以下だった
  const 重み = (l) => (l.線らしさ >= 0.5 ? l.線らしさ : 0);
  const 出 = [];
  for (let i = 0; i < 候補.length; i++) {
    for (let j = i + 1; j < 候補.length; j++) {
      const 最初の間隔 = 候補[j].中 - 候補[i].中;
      if (最初の間隔 < 8 || !隣の罫線か(候補[i], 候補[j], null)) continue;
      const 組 = [候補[i], 候補[j]];
      while (伸ばす || 組.length < 本数) {
        // 本数ちょうどの組は最初の 2 本の間隔のまま。つながる限り伸ばすときは、直前の間隔と、拾った線の平均の間隔の
        // 両方で見込み、どちらかの近くの線を拾う。遠近や台形で列の幅は端から端へ少しずつ変わり、平均だけでは追いつかない
        //（台形 0.2 の合成の用紙で表の左の 2 列を取りこぼした）。直前だけだと、少し広い列（10/1 の用紙の合計の列は
        // 54px、ほかは 48〜53px）の次で見込みを外す
        const 平均 = (組[組.length - 1].中 - 組[0].中) / (組.length - 1);
        const 直前 = 組[組.length - 1].中 - 組[組.length - 2].中;
        const 間隔たち = 伸ばす ? [直前, 平均] : [最初の間隔];
        const 外れ = (l) => Math.min(...間隔たち.map((d) => Math.abs(l.中 - (組[組.length - 1].中 + d)) / d));
        const 近い = 候補
          .filter((l) => l.中 > 組[組.length - 1].中 && 外れ(l) <= 0.12 && 隣の罫線か(組[組.length - 1], l, 組[組.length - 2]))
          .sort((a, z) => 外れ(a) - 外れ(z))[0];
        if (!近い) break;
        組.push(近い);
      }
      if (組.length < 本数) continue;
      // 点は「線らしさで重み付けした長さ」の合計
      const 点 = 組.reduce((a, l) => a + (l.下 - l.上) * 重み(l), 0);
      出.push({ 組, 間隔: 伸ばす ? (組[組.length - 1].中 - 組[0].中) / (組.length - 1) : 最初の間隔, 点 });
    }
  }
  return 出.sort((a, z) => z.点 - a.点);
}

/** 罫線 a と b の間の列の墨の割合（罫線の太さぶん内側。上下は 2 本の重なる範囲） */
function 列の墨(生, 境, a, b) {
  const ta = Math.tan((a.度 * Math.PI) / 180);
  const tb = Math.tan((b.度 * Math.PI) / 180);
  const 上 = Math.max(0, Math.round(Math.max(a.上, b.上)));
  const 下 = Math.min(生.高, Math.round(Math.min(a.下, b.下)));
  let 暗い = 0;
  let 全 = 0;
  for (let y = 上; y < 下; y += 2) {
    const x0 = Math.max(0, Math.round(a.切片 + y * ta) + 3);
    const x1 = Math.min(生.幅, Math.round(b.切片 + y * tb) - 3);
    for (let x = x0; x < x1; x++) {
      全++;
      if (生.画素[y * 生.幅 + x] < 境) 暗い++;
    }
  }
  return 全 ? 暗い / 全 : 0;
}

/**
 * 列の墨から、表ごとの射手の列の置き場（左から何列目に始まるか）を決める。
 * 表と表の間は 1 列以上あける。射手の列の墨の和から、間の列の墨の和を引いた点がいちばん高い置き方。
 * 差 … 射手の列の墨の平均と、それ以外の列の墨の平均の比（はっきり分かれているほど大きい）
 */
function 射手の列を置く(墨, 人数たち) {
  let 最良 = null;
  const 置く = (k, 次の始め, 始めたち) => {
    if (k === 人数たち.length) {
      const 射手 = new Set();
      始めたち.forEach((始, i) => { for (let c = 始; c < 始 + 人数たち[i]; c++) 射手.add(c); });
      let 点 = 0;
      for (let i = 0; i < 始めたち.length; i++) {
        for (let c = 始めたち[i]; c < 始めたち[i] + 人数たち[i]; c++) 点 += 墨[c];
        if (i + 1 < 始めたち.length) for (let c = 始めたち[i] + 人数たち[i]; c < 始めたち[i + 1]; c++) 点 -= 墨[c];
      }
      if (!最良 || 点 > 最良.点) 最良 = { 点, 始めたち: 始めたち.slice(), 射手 };
      return;
    }
    const 残り = 人数たち.slice(k).reduce((a, b) => a + b, 0) + (人数たち.length - k - 1);
    for (let 始 = 次の始め; 始 + 残り <= 墨.length; 始++) 置く(k + 1, 始 + 人数たち[k] + 1, [...始めたち, 始]);
  };
  置く(0, 0, []);
  if (!最良) return null;
  const 射手の墨 = [...最良.射手].map((c) => 墨[c]);
  const ほか = 墨.filter((_, c) => !最良.射手.has(c));
  const 平均 = (a) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
  const 差 = ほか.length ? 平均(射手の墨) / Math.max(1e-3, 平均(ほか)) - 1 : 0;
  // はっきり … いちばん薄い射手の列が、表と表の間の列（合計）のいちばん濃いものの 1.3 倍より濃い。
  // そうでなければ列の取り違え（射手の列を 1 列ずらして当てた。台形の合成の用紙で、射手と置いた列 0.02 に対し
  // 間の列 0.20 で 71/160）なので使わない。10/1 の用紙は合計の列にも数字の手書きがあり、射手 0.116〜0.179・合計 0.067
  const 間 = [];
  for (let i = 0; i + 1 < 最良.始めたち.length; i++) for (let c = 最良.始めたち[i] + 人数たち[i]; c < 最良.始めたち[i + 1]; c++) 間.push(墨[c]);
  const はっきり = !間.length || Math.min(...射手の墨) > 1.3 * Math.max(...間);
  return { 始めたち: 最良.始めたち, 差: Math.max(0, Math.min(1, 差 / 4)), はっきり };
}

/** 罫線の組から、切り抜く四角と、外枠を正すときに使う左右の線を作る。右の余り … 右の線の外に入れる列の数 */
function 四角にする(生, 組, 間隔, 右の余り) {
  const 上 = Math.max(0, Math.round(Math.min(...組.map((l) => l.上)) - 間隔 * 0.3));
  const 下 = Math.min(生.高, Math.round(Math.max(...組.map((l) => l.下)) + 間隔 * 0.3));
  // 傾いた表では、線の x が上端と下端で違う。四角はその両方を含める
  //（真ん中の x だけで決めたら、8度で端が切れて 52/80 に落ちた）
  const xの端 = (l) => {
    const t = Math.tan((l.度 * Math.PI) / 180);
    return [l.切片 + 上 * t, l.切片 + 下 * t];
  };
  const 左 = Math.max(0, Math.round(Math.min(...xの端(組[0])) - 間隔 * 0.5));
  const 右 = Math.min(生.幅, Math.round(Math.max(...xの端(組[組.length - 1])) + 間隔 * 右の余り));
  // 左右の線を、切り抜きの座標で持たせる（外枠を正すときに、探し直さずに使う）。
  // 右は小計の列の外側の線ではなく、射手の列の右端の線。外枠として使うと表の右が
  // 小計の手前で切れるが、射手の列はぜんぶ入るので読みには困らない
  const 移す = (l) => {
    const t = Math.tan((l.度 * Math.PI) / 180);
    return { 度: l.度, 切片: l.切片 + 上 * t - 左 };
  };
  return {
    left: 左,
    top: 上,
    width: 右 - 左,
    height: 下 - 上,
    間隔,
    枠: { 左の線: 移す(組[0]), 右の線: 移す(組[組.length - 1]) },
  };
}
