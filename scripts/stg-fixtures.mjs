/** 検証専用の合言葉。台帳の団体はすべてこれ */
export const 合言葉 = 'StgTest!2026';

const 台帳 = new Map(団体たち.map((g) => [g.id, g]));

/**
 * 団体を借りる。持ち主が違えば止める。
 *
 * @param id     団体ID
 * @param 呼び出し元 スクリプトのファイル名（'seed-empty-group.mjs' など）
 * @returns 台帳の1件
 */
export function 団体を借りる(id, 呼び出し元) {
  const g = 台帳.get(id);
  if (!g) {
    console.error(
      `停止：団体 ${id} は台帳にありません。\n` +
        `  scripts/stg-fixtures.mjs へ足してから使ってください。\n` +
        `  いま使われているID: ${団体たち.map((x) => x.id).join(', ')}`
    );
    process.exit(1);
  }
  if (g.持ち主 !== 呼び出し元) {
    console.error(
      `停止：団体 ${id}（${g.名}）の持ち主は ${g.持ち主} です。\n` +
        `  用途: ${g.用途}\n` +
        `  ${呼び出し元} から書き換えると、そちらの検証が壊れます。\n` +
        `  別のIDを台帳へ足してください。`
    );
    process.exit(1);
  }
  return g;
}

/** 読むだけのとき（書かないので持ち主は問わない） */
export function 団体を見る(id) {
  return 台帳.get(id) || null;
}
