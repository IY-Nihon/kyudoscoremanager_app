/**
 * 立ちの中の「どこからどこまでが、どのチームか」を決める。
 *
 * ■ どう決めるか
 *
 * 区切り（間隔）にチーム名を持たせる。区切りより左が、そのチーム。
 * （記録表は右から左へ並ぶ。並びの上では「区切りより後ろ」にあたる）
 * 次の区切りが来るまで続く。いちばん左（最初の区切りより前）は自団体。
 *
 *   [自校A][自校B] │◯◯大学│ [山田][鈴木] │△△大学│ [佐藤]
 *    ~~~~~~~~~~~~            ~~~~~~~~~~~~            ~~~~
 *      自団体                  ◯◯大学                △△大学
 *
 * リーグでは立ちがチームごとに並ぶので、区切りを1つ置いて名前を入れるだけで
 * 複数人にまとめて付く。射手を一人ずつ設定しなくてよい。
 *
 * ■ 色
 *
 * チーム名から決める。同じ名前なら、いつでも・どの画面でも同じ色になる。
 * 色は分析の比較で使っているものと同じ並び（色覚によって同じに見える組を
 * 避けて選んである）。名前を数に直して選ぶので、覚えておく必要がない。
 */
'use strict';

/** 自団体（最初の区切りより前）を表す印。名前が付いていないことを示す */
const 自団体 = null;

/**
 * チームの色。分析の比較と同じ並びを使う。
 * 色覚によって同じに見える組を避けて選んだもの（scripts で測って決めた）
 */
const チームの色たち = ['#FF2D55', '#248A3D', '#C93400', '#AF52DE', '#056B7A', '#5856D6', '#0000CF'];

/**
 * 名前から色を決める。
 *
 * 同じ名前なら必ず同じ色。並び順や登録順が変わっても色が入れ替わらないので、
 * 「昨日は赤だったのに今日は青」ということが起きない。
 */
function チームの色(名前) {
  const s = String(名前 == null ? '' : 名前).trim();
  if (!s) return null;
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return チームの色たち[h % チームの色たち.length];
}

/**
 * 区切りに付けたチーム名を読む。
 *
 * 既定の '---' は「名前が付いていない区切り」なので、チーム名とは見なさない。
 * 空白だけのものも同じ扱い。
 */
function 区切りのチーム名(射手) {
  if (!射手 || !射手.isSeparator) return null;
  const 名 = String(射手.teamName == null ? '' : 射手.teamName).trim();
  if (!名 || 名 === '---') return null;
  return 名;
}

/**
 * 立ちの並びから、射手ごとのチーム名を割り当てる。
 *
 * 返すのは射手の id をたどれる配列。区切りと合計の列には null を入れる
 * （どちらもチームに属さない）。
 *
 * @param {Array} 射手たち 立ちの並び
 * @returns {Array<{id:string, チーム:(string|null), 色:(string|null)}>}
 */
function チームを割り当てる(射手たち) {
  const 並び = Array.isArray(射手たち) ? 射手たち : [];
  let いまのチーム = 自団体;
  return 並び.map((x) => {
    if (!x) return { id: null, チーム: null, 色: null };
    if (x.isSeparator) {
      // 区切り自身はチームに属さない。ただしここから先の持ち主が変わる
      // （並びの上では後ろ、画面では区切りより左）。
      // 名前の付いていない区切り（ただの間隔）は、持ち主を変えない
      const 名 = 区切りのチーム名(x);
      if (名) いまのチーム = 名;
      return { id: x.id, チーム: null, 色: null };
    }
    if (x.isTotalCalculator) return { id: x.id, チーム: null, 色: null };
    return { id: x.id, チーム: いまのチーム, 色: いまのチーム ? チームの色(いまのチーム) : null };
  });
}

/**
 * その立ちに出てくるチーム名を、出た順に並べて返す。
 * 見出しや凡例に使う。自団体（名前なし）は含めない
 */
function 出てくるチーム(射手たち) {
  const 出 = [];
  for (const x of Array.isArray(射手たち) ? 射手たち : []) {
    const 名 = 区切りのチーム名(x);
    if (名 && !出.includes(名)) 出.push(名);
  }
  return 出;
}

module.exports = {
  チームを割り当てる,
  チームの色,
  区切りのチーム名,
  出てくるチーム,
  チームの色たち,
};

/**
 * 合計の列が数える中り数を返す。
 *
 * ふつうの「計」は隣から左へ数え、区切りに当たると止まる（1立ぶん）。
 * 「総計」（またぐ合計）は区切りで止まらず、端まで数える（複数立ちの合計）。
 * どちらも、別の合計の列に当たったら止める——合計の合計を数えて
 * 二重にならないようにするため。
 *
 * @param {Array} 射手たち 立ちの並び
 * @param {number} 位置 合計の列の場所
 * @returns {number} 中り数
 */
function 合計を数える(射手たち, 位置) {
  const 並び = Array.isArray(射手たち) ? 射手たち : [];
  const 自分 = 並び[位置];
  if (!自分 || !自分.isTotalCalculator) return 0;
  let 数 = 0;
  for (let i = 位置 - 1; i >= 0; i--) {
    const x = 並び[i];
    if (!x || x.isTotalCalculator) break;
    if (x.isSeparator) {
      if (自分.またぐ合計) continue;
      break;
    }
    数 += (x.marks || []).filter((m) => '○' === m).length;
  }
  return 数;
}

module.exports.合計を数える = 合計を数える;
