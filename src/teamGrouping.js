/**
 * 立ちの中の「どこからどこまでが、どのチームか」を決める。
 *
 * ■ どう決めるか
 *
 * 区切り（間隔）にチーム名を持たせる。区切りより左が、そのチーム。
 * （記録表は右から左へ並ぶ。並びの上では「区切りより後ろ」にあたる）
 * 次の区切りが来るまで続く。いちばん左（最初の区切りより前）は自団体。
 *
 *   [自校A][自校B] │◯◯大学│ [山田][鈴木] │△△大学│ [佐藤]
 *    ~~~~~~~~~~~~            ~~~~~~~~~~~~            ~~~~
 *      自団体                  ◯◯大学                △△大学
 *
 * リーグでは立ちがチームごとに並ぶので、区切りを1つ置いて名前を入れるだけで
 * 複数人にまとめて付く。射手を一人ずつ設定しなくてよい。
 *
 * ■ 色
 *
 * チーム名から決める。同じ名前なら、いつでも・どの画面でも同じ色になる。
 * 色は分析の比較で使っているものと同じ並び（色覚によって同じに見える組を
 * 避けて選んである）。名前を数に直して選ぶので、覚えておく必要がない。
 */
'use strict';

/** 自団体（最初の区切りより前）を表す印。名前が付いていないことを示す */
const 自団体 = null;

/**
 * チームの色。分析の比較と同じ並びを使う。
 * 色覚によって同じに見える組を避けて選んだもの（scripts で測って決めた）
 */
const チームの色たち = ['#FF2D55', '#248A3D', '#C93400', '#AF52DE', '#056B7A', '#5856D6', '#0000CF'];

/**
 * 名前から色を決める。
 *
 * 同じ名前なら必ず同じ色。並び順や登録順が変わっても色が入れ替わらないので、
 * 「昨日は赤だったのに今日は青」ということが起きない。
 */
function チームの色(名前) {
  const s = String(名前 == null ? '' : 名前).trim();
  if (!s) return null;
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return チームの色たち[h % チームの色たち.length];
}

/**
 * 区切りに付けたチーム名を読む。
 *
 * 既定の '---' は「名前が付いていない区切り」なので、チーム名とは見なさない。
 * 空白だけのものも同じ扱い。
 */
function 区切りのチーム名(射手) {
  if (!射手 || !射手.isSeparator) return null;
  const 名 = String(射手.teamName == null ? '' : 射手.teamName).trim();
  if (!名 || 名 === '---') return null;
  return 名;
}

/**
 * 立ちの並びから、射手ごとのチーム名を割り当てる。
 *
 * 返すのは射手の id をたどれる配列。区切りと合計の列には null を入れる
 * （どちらもチームに属さない）。
 *
 * @param {Array} 射手たち 立ちの並び
 * @returns {Array<{id:string, チーム:(string|null), 色:(string|null)}>}
 */
function チームを割り当てる(射手たち) {
  const 並び = Array.isArray(射手たち) ? 射手たち : [];
  let いまのチーム = 自団体;
  return 並び.map((x) => {
    if (!x) return { id: null, チーム: null, 色: null };
    if (x.isSeparator) {
      // 区切り自身はチームに属さない。ただしここから先の持ち主が変わる
      // （並びの上では後ろ、画面では区切りより左）。
      // 名前の付いていない区切り（ただの間隔）は、持ち主を変えない
      const 名 = 区切りのチーム名(x);
      if (名) いまのチーム = 名;
      return { id: x.id, チーム: null, 色: null };
    }
    if (x.isTotalCalculator) return { id: x.id, チーム: null, 色: null };
    return { id: x.id, チーム: いまのチーム, 色: いまのチーム ? チームの色(いまのチーム) : null };
  });
}

/**
 * その立ちに出てくるチーム名を、出た順に並べて返す。
 * 見出しや凡例に使う。自団体（名前なし）は含めない
 */
function 出てくるチーム(射手たち) {
  const 出 = [];
  for (const x of Array.isArray(射手たち) ? 射手たち : []) {
    const 名 = 区切りのチーム名(x);
    if (名 && !出.includes(名)) 出.push(名);
  }
  return 出;
}

module.exports = {
  チームを割り当てる,
  チームの色,
  区切りのチーム名,
  出てくるチーム,
  チームの色たち,
};

/**
 * 合計の列が受け持つ射手を、近い順に返す。
 *
 * 止まる場所は2つ。**間隔（区切り）は、どちらの合計でも越えない。**
 *
 *   ・ふつうの「計」… 間隔でも、手前の計でも止まる（1立ぶん）
 *   ・「総計」（またぐ合計）… 手前の計は飛び越えるが、間隔では止まる
 *
 * つまり「立ちごとに計を置き、その並びの端に総計を置く」と、総計はその
 * ひとまとまりぶんを数える。間隔を入れれば、そこが総計の切れ目になる。
 *
 * 経緯（2026-09-08）。もとは総計を「間隔もまたいで端まで」にしていたが、
 * 手前の計でも止めていたので、計と一緒に使うと総計がいつも0になっていた。
 * まず計を飛び越えるようにし、そのうえで**間隔では止める**と決め直した。
 * 間隔は立ちの切れ目そのもので、そこを越えて足すと別々の記録が混ざるため。
 *
 * 飛び越えても二重にならない。数えているのは**射手のマスだけ**で、合計の列の
 * 値は足していないので、一人ぶんを一度しか数えない。
 *
 * この規則は、上の「計」の欄（合計を数える）と、表の中の立ごとの行、
 * そして**間隔の鍵**（ArcherColumnView）で使う。以前は同じ規則を2か所に
 * 写していて、片方だけ直したせいで欄と行で数が食い違った。増やさずここだけを
 * 直すこと。
 *
 * 間隔（区切り）も受け持ちを持つ。鍵ボタンは間隔と計の列に付いていて、
 * 押すと自分より手前の射手をまとめて閉じるため。間隔の受け持ちは、
 * ふつうの「計」と同じ（間隔でも計でも止まる）。ここを合計の列だけに
 * 絞ってしまい、間隔の自動の鍵がかからなくなったことがある（2026-09-08）。
 *
 * @param {Array} 射手たち 立ちの並び
 * @param {number} 位置 その列の場所
 * @returns {Array} 受け持つ射手（その列自身・間隔・別の合計は含まない）
 */
function 合計が受け持つ射手(射手たち, 位置) {
  const 並び = Array.isArray(射手たち) ? 射手たち : [];
  const 自分 = 並び[位置];
  if (!自分 || !(自分.isTotalCalculator || 自分.isSeparator)) return [];
  const 集めた = [];
  for (let i = 位置 - 1; i >= 0; i--) {
    const x = 並び[i];
    if (!x) break;
    // 間隔は、総計でも越えない。立ちの切れ目そのものなので、
    // 越えて足すと別々の記録が混ざる
    if (x.isSeparator) break;
    // 手前の計は、総計だけ飛び越える（間隔の受け持ちは、ふつうの計と同じ）
    if (x.isTotalCalculator) {
      if (自分.isTotalCalculator && 自分.またぐ合計) continue;
      break;
    }
    集めた.push(x);
  }
  return 集めた;
}

/**
 * 合計の列が数える中り数を返す。受け持つ射手の○を全部足したもの。
 *
 * 間隔にも受け持ちは在る（鍵のため）が、数は出さない。
 *
 * @param {Array} 射手たち 立ちの並び
 * @param {number} 位置 合計の列の場所
 * @returns {number} 中り数
 */
function 合計を数える(射手たち, 位置) {
  const 並び = Array.isArray(射手たち) ? 射手たち : [];
  if (!並び[位置] || !並び[位置].isTotalCalculator) return 0;
  return 合計が受け持つ射手(射手たち, 位置).reduce(
    (数, x) => 数 + (x.marks || []).filter((m) => '○' === m).length,
    0
  );
}

module.exports.合計が受け持つ射手 = 合計が受け持つ射手;
module.exports.合計を数える = 合計を数える;
