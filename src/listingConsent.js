/**
 * 「使っている部として、紹介に載せてよいか」の許可（2026-10-09 に本人と決めた形）。
 *
 * ■ 何を聞くか
 *   何を載せるか：団体名 ／ 地域だけ（例：関東の大学） ／ 載せない
 *   どこに載せるか：ホームページ ／ 他校へのご案内（DM）。最初はどちらもチェックが入っている（本人の指示）
 *   載せるのは団体名か地域だけ。記録や部員の名前は出さない
 *
 * ■ いつ聞くか
 *   使い始めで聞くと断られる（本人）。使い慣れた団体（記録 10 回以上・最初の記録から 14 日以上）に、
 *   記録を保存した直後、閉じられる札で聞く。団体ログインだけ（決める立場の人）。
 *   「あとで」か ✕ なら 14 日あけて、また保存の直後に。聞くのは 3 回まで。
 *   設定の項目は、一度でも札で聞いた団体にだけ出す（案内が来ていない団体には出さない。本人）。
 *
 * ■ どこに残すか
 *   groups/{団体ID}/config/listing。決まり（firestore.rules）で団体の持ち主だけが書ける（部員は読むだけ）。
 *   app_settings に入れないのは、全部の同期が app_settings を merge なしで上書きするため。
 *   運営者は scripts/list-listing-consent.mjs で一覧にする。答えた日時と、聞いた文の版も残す。
 *
 * 画面にも Firebase にも触れない純粋な関数だけ。test/listingConsent.test.js
 */
'use strict';

/** 札と設定で聞いている文の版。文を変えたら上げる（誰がどの文に答えたかを後から言えるように） */
const 聞いた文の版 = '2026-10-09';
/** 使い慣れたとみなす記録の数と日数 */
const 聞く記録数 = 10;
const 聞く日数 = 14;
/** 「あとで」のあと、次に聞くまでの日数と、聞く回数の上限 */
const あとでの日数 = 14;
const 聞く回数の上限 = 3;

const 一日 = 24 * 60 * 60 * 1000;

const 載せ方たち = ['団体名', '地域', '載せない'];

/** 日時を数（ミリ秒）に。Firestore の日時型・Date・数・文字のどれでも */
function ミリ秒(値) {
  if (null == 値 || '' === 値) return null;
  if ('number' === typeof 値) return Number.isFinite(値) ? 値 : null;
  if (値 instanceof Date) return 値.getTime();
  if ('function' === typeof 値.toMillis) return 値.toMillis();
  if ('number' === typeof 値.seconds) return 値.seconds * 1000 + Math.floor((値.nanoseconds || 0) / 1e6);
  const t = Date.parse(String(値));
  return Number.isFinite(t) ? t : null;
}

/** 数えてよい記録（ゴミ箱に入ったものは数えない） */
function 記録の数と始まり(記録たち) {
  let 数 = 0;
  let 始まり = null;
  for (const 記録 of Array.isArray(記録たち) ? 記録たち : []) {
    if (!記録 || 記録.deletedAt || 記録.isDeleted) continue;
    数 += 1;
    const t = ミリ秒(記録.date);
    if (null != t && (null == 始まり || t < 始まり)) 始まり = t;
  }
  return { 数, 始まり };
}

/** もう答えたか */
function 答えたか(許可) {
  return !!(許可 && 許可.載せ方 && 載せ方たち.includes(許可.載せ方));
}

/**
 * 記録を保存した直後に、札を出してよいか。
 * @param {{役割?:string, 記録たち?:any[], 許可?:object|null, いま?:number, 止める?:boolean}} 材料
 *   止める：ライブで見るだけ・案内の途中・履歴の直しなど、札を出したくない場面
 */
function 札を出すか(材料) {
  const { 役割, 記録たち, 許可, いま = Date.now(), 止める = false } = 材料 || {};
  if (止める || 'group' !== 役割) return false;
  if (答えたか(許可)) return false;
  const 回数 = Number((許可 && 許可.聞いた回数) || 0);
  if (回数 >= 聞く回数の上限) return false;
  const 次 = ミリ秒(許可 && 許可.次に聞く日時);
  if (null != 次 && いま < 次) return false;
  const { 数, 始まり } = 記録の数と始まり(記録たち);
  if (数 < 聞く記録数 || null == 始まり) return false;
  return いま - 始まり >= 聞く日数 * 一日;
}

/** 札を出したときに残すもの（何回目か・初めて聞いた日時）。答えるまでは「あとで」と同じ扱いで次の日時も置く */
function 聞いた記録(許可, いま = Date.now()) {
  const 前 = 許可 || {};
  return {
    聞いた回数: Number(前.聞いた回数 || 0) + 1,
    初めて聞いた日時: ミリ秒(前.初めて聞いた日時) || いま,
    次に聞く日時: いま + あとでの日数 * 一日,
    聞いた文の版,
  };
}

/** 設定に「紹介への掲載」を出すか（一度でも札で聞いた団体だけ） */
function 設定に出すか(役割, 許可) {
  return 'group' === 役割 && !!(許可 && (ミリ秒(許可.初めて聞いた日時) || 答えたか(許可)));
}

/** 札・設定の最初の選び。載せる先は最初はどちらもチェック（本人の指示） */
function 最初の選び(許可, 団体名) {
  const 前 = 許可 || {};
  const 答えた = 答えたか(前);
  return {
    載せ方: 答えた ? 前.載せ方 : null,
    載せる名前: String(前.載せる名前 || 団体名 || ''),
    地域: String(前.地域 || ''),
    ホームページ: 答えた ? !!前.ホームページ : true,
    他校への案内: 答えた ? !!前.他校への案内 : true,
  };
}

/**
 * 選んだ中身を確かめ、保存する形に整える。だめなら { 誤り } を返す（画面に出す文）。
 * @returns {{ 中身?: object, 誤り?: string }}
 */
function 答えを整える(選び, いま = Date.now()) {
  const 選 = 選び || {};
  if (!載せ方たち.includes(選.載せ方)) return { 誤り: '何を載せるかを選んでください' };
  const 名前 = String(選.載せる名前 || '').trim();
  const 地域 = String(選.地域 || '').trim();
  if ('載せない' !== 選.載せ方) {
    if ('団体名' === 選.載せ方 && !名前) return { 誤り: '載せる名前を入れてください' };
    if ('地域' === 選.載せ方 && !地域) return { 誤り: '地域を入れてください（例：関東の大学）' };
    if (!選.ホームページ && !選.他校への案内) return { 誤り: '載せる先を1つ以上選んでください' };
  }
  const 載せる = '載せない' !== 選.載せ方;
  return {
    中身: {
      載せ方: 選.載せ方,
      載せる名前: '団体名' === 選.載せ方 ? 名前 : '',
      地域: '地域' === 選.載せ方 ? 地域 : '',
      ホームページ: 載せる && !!選.ホームページ,
      他校への案内: 載せる && !!選.他校への案内,
      答えた日時: いま,
      聞いた文の版,
      次に聞く日時: null,
    },
  };
}

/**
 * 運営者の一覧に出す形。載せる先ごとに、載せてよい表示（団体名か地域）を返す。答えていない・載せないなら null
 * @returns {{ 表示: string, ホームページ: boolean, 他校への案内: boolean } | null}
 */
function 載せる表示(許可) {
  if (!答えたか(許可) || '載せない' === 許可.載せ方) return null;
  const 表示 = '団体名' === 許可.載せ方 ? String(許可.載せる名前 || '').trim() : String(許可.地域 || '').trim();
  if (!表示 || (!許可.ホームページ && !許可.他校への案内)) return null;
  return { 表示, ホームページ: !!許可.ホームページ, 他校への案内: !!許可.他校への案内 };
}

module.exports = {
  聞いた文の版,
  聞く記録数,
  聞く日数,
  あとでの日数,
  聞く回数の上限,
  載せ方たち,
  ミリ秒,
  記録の数と始まり,
  答えたか,
  札を出すか,
  聞いた記録,
  設定に出すか,
  最初の選び,
  答えを整える,
  載せる表示,
};
