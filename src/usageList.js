/** 役割に合わせた一覧。個人で入ったときは 団体だけ の項目・部分を外す */
function 使い方の一覧(役割) {
  const 団体 = 役割 === 'group';
  const 出す = (物) => 団体 || !物.団体だけ;
  return まとまりたち
    .map((組) => ({
      ...組,
      項目: 組.項目.filter(出す).map((項) => ({ ...項, 部分: 項.部分.filter(出す) })),
    }))
    .map((組) => ({ ...組, 項目: 組.項目.filter((項) => 項.部分.length > 0) }))
    .filter((組) => 組.項目.length > 0);
}

module.exports = { 使い方の一覧, まとまりたち, 困りごと };
