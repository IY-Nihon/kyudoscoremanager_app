/**
 * 役割と役に合わせた一覧（上の「出し分け」）。文の 1 行は字だけにして返す。
 * @param 役割 'group' なら団体の口座。それ以外は個人で入った人
 * @param 部品 個人で入った人の役の部品（src/yaku.js の 自分の部品）。団体の口座では見ない。省略すると部員（自分）
 * @param 役id 個人で入った人の役の id（src/yaku.js の 自分の役id）。役を決める（運営だけ）を出すかに使う
 */
function 使い方の一覧(役割, 部品 = 役.役の中身(null, 役.既定の役).部品, 役id = null) {
  const 団体 = 役割 === 'group';
  const 出す = (物) => {
    if (typeof 物 === 'string') return true;
    if (団体) return !物.役だけ && !物.持たない;
    if (物.団体だけ) return false;
    if (物.管理者モード && !役.部品で管理者モードに入れるか(部品)) return false;
    if (物.持たない && [].concat(物.持たない).some((名) => 役.役で持つか(役id, 部品, 名))) return false;
    return !物.操作 || [].concat(物.操作).every((名) => 役.役で持つか(役id, 部品, 名));
  };
  const 字だけ = (文) => 文.filter(出す).map((一つ) => (typeof 一つ === 'string' ? 一つ : 一つ.字));
  return まとまりたち
    .map((組) => ({
      ...組,
      項目: 組.項目.filter(出す).map((項) => ({
        ...項,
        部分: 項.部分
          .filter(出す)
          .map((部) => ({ ...部, 文: 字だけ(部.文) }))
          .filter((部) => 部.文.length > 0),
      })),
    }))
    .map((組) => ({ ...組, 項目: 組.項目.filter((項) => 項.部分.length > 0) }))
    .filter((組) => 組.項目.length > 0);
}

module.exports = { 使い方の一覧, まとまりたち, 困りごと };
