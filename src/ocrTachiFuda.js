/**
 * 立ち順の板で、「壱」「弐」などの立の番号の札をもとに、空きで分かれた組を立にまとめる。
 *
 * ■ なぜ
 * 札 1 枚に、空きをはさんだ名札の組が 2 つ付いている板がある（10/17・10/19 の本番の写真）。
 * 「札から次の札の手前までが 1 つの立」と Gemini に頼むと、札がどちらの組に付くかを
 * 取り違えて区切りがずれた（10/19 の写真で 5 回中 1 回しか合わない）。
 * Gemini には空きごとの組と、組の大前の端に付いた札（fuda）と段（row）だけを出させ、
 * まとめ方は端末で決める。
 * 11/20 からは、札を組に付けさせず、札だけの項目（seats が []）として並びの中の札の位置に出させる。
 * 札が両隣の組に接している板で、札を落の側の組に付けて区切りがずれたため（11/6 の本番の写真。
 * 手で区切りを動かしていた）。並べる順は名前の順と同じく読み違えないので、どちらの組に付くかは端末が決める。
 * 札の付いた組（前の形）が来ても同じようにまとまる。
 *
 * ■ まとめ方
 *   ・同じ段の中で、札の無い組は、すぐ前（大前の側）の組・札と同じ立に入れる
 *   ・段の頭で札の無い組は、それだけで立を始める（写っていない札の立）
 *   ・立は札の番号の順。札の無い立は、札のある立より前に、読んだ順で置く
 *   ・札が 1 枚も無いときは、組をそのまま立として返す（これまでどおり空きで分ける）
 *   ・人のいない立（あとに組の無い札だけ・空欄 "" だけの組）は返さない。空欄は、名前のある立の中では位置として残す
 */

const { 半角にする } = require('./totonoeru');

// 漢数字（大字も）→ 1〜9
const 一桁の数字 = Object.fromEntries(
  ['一壱', '二弐貳', '三参', '四肆', '五伍', '六陸', '七漆', '八捌', '九玖'].flatMap((字たち, 番) =>
    [...字たち].map((字) => [字, 番 + 1])
  )
);
const 十の字 = new Set(['十', '拾']);
// 丸数字（①〜㊿・黒丸・二重丸など）の字の番号の範囲と、その範囲の最初の字の数
const 丸数字の範囲 = [
  [0x2460, 0x2473, 1], // ①〜⑳
  [0x3251, 0x325f, 21], // ㉑〜㉟
  [0x32b1, 0x32bf, 36], // ㊱〜㊿
  [0x2776, 0x277f, 1], // 黒丸の 1〜10
  [0x2780, 0x2789, 1], // 丸の 1〜10（飾りの字）
  [0x278a, 0x2793, 1], // 黒丸の 1〜10（飾りの字）
  [0x24eb, 0x24f4, 11], // 黒丸の 11〜20
  [0x24f5, 0x24fe, 1], // 二重丸の 1〜10
];
const 丸数字の数 = (字) => {
  const 番 = 字.codePointAt(0);
  const 範囲 = 丸数字の範囲.find(([頭, 尾]) => 番 >= 頭 && 番 <= 尾);
  return 範囲 ? 番 - 範囲[0] + 範囲[2] : null;
};

/**
 * 札の字から番号を取る。読めなければ null。
 * 数字（全角も）・丸数字・漢数字（十一〜九十九も。「十二」は 12、「二十」は 20）。
 * 漢数字は最初に出てきた連なりだけを読む（「第十一立」は 11）
 */
function 札の番号(札) {
  // \s は全角空白（U+3000）も含む。全角の数字は半角に
  const 字 = 半角にする(String(札 == null ? '' : 札).replace(/\s/g, ''));
  if (!字) return null;
  for (const c of 字) {
    const 丸 = 丸数字の数(c);
    if (丸 != null) return 丸;
  }
  const 算 = 字.match(/\d+/);
  if (算) return Number(算[0]);
  let 値 = 0;
  let 今の桁 = 0;
  let 始まった = false;
  for (const c of 字) {
    if (一桁の数字[c]) {
      今の桁 = 一桁の数字[c];
      始まった = true;
    } else if (十の字.has(c)) {
      値 += (今の桁 || 1) * 10;
      今の桁 = 0;
      始まった = true;
    } else if (始まった) {
      break;
    }
  }
  return 始まった ? 値 + 今の桁 : null;
}

// 名前の入った席が 1 つでもあるか（空欄 "" だけの立は、名札の無い行。格子の板の使っていない 四之立 など）
const 人がいる = (x) => x.seats.some((席) => String(席 == null ? '' : 席).trim() !== '');

/**
 * @param {Array<{seats:string[], fuda?:string, row?:number}>} 組たち Gemini が返した tachi
 * @returns {Array<{seats:string[]}>}
 */
// 札だけの項目（seats が空で、番号の読める札）か
const 札だけか = (x) => 札の番号(x.fuda) != null && !人がいる(x);
const 段の番号 = (x) => (x.row == null ? 0 : x.row);

/**
 * 札だけの項目を組の後ろに並べて答えた段（組で始まり、札だけの項目で終わる段）は、札をその前の組たちの前へ移す。
 * 札は立の大前の側の端にあるので、読む順では組の前に来るはずだが、10/26 のノートの写真（名前の右に「壱之立」と書く）で、
 * 模型が札を組の後ろに置いて答え、区切りがずれた（11/20 に中継で測った）。組で始まる段に限るので、札で始まる段（ふつうの板）や、
 * 札の見えない組で始まり組で終わる段（11/7 の板）は変わらない
 */
function 札を前へ寄せる(組) {
  const 出 = [];
  for (let i = 0; i < 組.length;) {
    let j = i;
    while (j < 組.length && 段の番号(組[j]) === 段の番号(組[i])) j++;
    const 段の項目 = 組.slice(i, j);
    const 頭 = 段の項目[0];
    const 尻 = 段の項目[段の項目.length - 1];
    if (段の項目.length > 1 && 札の番号(頭.fuda) == null && 札だけか(尻)) {
      let 溜め = [];
      for (const x of 段の項目) {
        if (札だけか(x)) {
          出.push(x, ...溜め);
          溜め = [];
        } else 溜め.push(x);
      }
      出.push(...溜め);
    } else 出.push(...段の項目);
    i = j;
  }
  return 出;
}

function 札で立にまとめる(組たち) {
  const 組 = 札を前へ寄せる((Array.isArray(組たち) ? 組たち : []).filter((x) => x && Array.isArray(x.seats)));
  if (!組.some((x) => 札の番号(x.fuda) != null)) return 組.filter(人がいる).map((x) => ({ seats: x.seats }));
  const 立たち = [];
  let 前 = null;
  組.forEach((x, 順) => {
    const 番号 = 札の番号(x.fuda);
    const 段 = x.row == null ? 0 : x.row;
    if (番号 == null && 前 && 前.段 === 段) {
      前.seats.push(...x.seats);
      return;
    }
    前 = { 番号, 段, 順, seats: [...x.seats] };
    立たち.push(前);
  });
  return 立たち
    .filter(人がいる)
    .sort((a, b) => (a.番号 == null ? 0 : a.番号) - (b.番号 == null ? 0 : b.番号) || a.順 - b.順)
    .map((x) => ({ seats: x.seats }));
}

module.exports = { 札で立にまとめる, 札の番号 };
