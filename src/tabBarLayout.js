/**
 * 上のバー（記録・履歴・分析・メンバー・出欠・設定）の並べ方を決める。
 *
 *   ぜんぶ … どのタブも「絵＋名前」。画面に収まるとき（最近の携帯の 360px 以上は収まる）。
 *   絵だけ … どのタブも絵だけ。今いるタブだけ「絵＋名前」。それより狭くて収まらないとき。
 *
 * 画面や React に触れない純粋な関数なので、そのまま検査できる（test/tabBarLayout.test.js）。
 *
 * ■ 幅は見積もりで決める
 *   名前は全角の字（記録・メンバー・ー も 1 字 = 字の大きさ ぶん）なので、字数 × 字の大きさ で
 *   ほぼ正確に出る。測ってから切り替えると、最初の 1 コマで溢れた帯が見えてしまう。
 *   見積もりなら描く前に決まり、切り替えの 1 コマも出ない。ゆとり を少し持たせてある。
 *
 * ■ 切り替えは今いるタブに左右されない
 *   「絵だけ」で収まるかは、いちばん長い名前（メンバー）が今のタブだったときの幅で見る。
 *   タブを移るたびに ぜんぶ ⇔ 絵だけ が入れ替わったり、帯が溢れたりしない。
 */
'use strict';

/** 絵の大きさ（px）。携帯でも名前と並べられるよう、小さめにしてある */
const 絵の大きさ = 16;
/** 絵と名前の間（px） */
const 絵と字の間 = 3;
/** 名前の字の大きさ（px）。MainNavigator の tabText と同じ */
const 字の大きさ = 12;
/** 帯の左右の余白（tabBarContainer の paddingHorizontal 8 × 2） */
const 外の余白 = 16;
/** タブを包む丸い枠の内側の余白（tabItems の padding 3 × 2） */
const 枠の内側 = 6;
/** 字の幅の見積もりの誤差と、画面の縁に寄りすぎないためのゆとり（px） */
const ゆとり = 6;
/** 「ぜんぶ」のときの、タブの左右の余白。広いほうから、収まるものを選ぶ（px） */
const ぜんぶの余白たち = [6, 5, 4];
/** 「絵だけ」のときの、タブの左右の余白。広いほうから、収まるものを選ぶ */
const 絵だけの余白たち = [11, 8, 5];
/** どれでも収まらない狭さのときの余白 */
const いちばん狭い余白 = 4;

/** 名前の幅（px）。全角の字が 1 字ぶん。拡大 は端末の文字の拡大率（web は 1） */
function 字の幅(名前, 拡大 = 1) {
  return [...String(名前)].length * 字の大きさ * (拡大 > 0 ? 拡大 : 1);
}

/** 「ぜんぶ」で並べたときの帯の幅 */
function ぜんぶの幅(名前たち, 余白, 拡大) {
  return 名前たち.reduce((計, 名) => 計 + 余白 * 2 + 絵の大きさ + 絵と字の間 + 字の幅(名, 拡大), 枠の内側);
}

/** 「絵だけ」で並べたときの帯の幅。今いるタブが、いちばん長い名前のとき */
function 絵だけの幅(名前たち, 余白, 拡大) {
  const いちばん長い = Math.max(0, ...名前たち.map((名) => 字の幅(名, 拡大)));
  return 枠の内側 + 名前たち.length * (余白 * 2 + 絵の大きさ) + 絵と字の間 + いちばん長い;
}

/**
 * @param {{名前たち: string[], 幅: number, 拡大?: number}} 引数
 *   名前たち … タブの名前（左から）
 *   幅 … 帯が使える横幅（px）。分からないとき（0 や数でない）は 絵だけ にする
 *   拡大 … 端末の文字の拡大率（useWindowDimensions().fontScale）。web は 1
 * @returns {{型: 'ぜんぶ'|'絵だけ', 余白: number, 必要な幅: number}}
 */
function 並べ方を決める(引数) {
  const { 名前たち = [], 幅, 拡大 = 1 } = 引数 || {};
  const 名前 = (Array.isArray(名前たち) ? 名前たち : []).map(String);
  if (!名前.length) return { 型: 'ぜんぶ', 余白: ぜんぶの余白たち[0], 必要な幅: 0 };
  if (!(幅 > 0)) {
    return { 型: '絵だけ', 余白: 絵だけの余白たち[1], 必要な幅: 絵だけの幅(名前, 絵だけの余白たち[1], 拡大) };
  }
  const 使える = 幅 - 外の余白 - ゆとり;
  for (const 余白 of ぜんぶの余白たち) {
    const 必要 = ぜんぶの幅(名前, 余白, 拡大);
    if (必要 <= 使える) return { 型: 'ぜんぶ', 余白, 必要な幅: 必要 };
  }
  for (const 余白 of 絵だけの余白たち) {
    const 必要 = 絵だけの幅(名前, 余白, 拡大);
    if (必要 <= 使える) return { 型: '絵だけ', 余白, 必要な幅: 必要 };
  }
  return { 型: '絵だけ', 余白: いちばん狭い余白, 必要な幅: 絵だけの幅(名前, いちばん狭い余白, 拡大) };
}

module.exports = {
  並べ方を決める,
  字の幅,
  絵の大きさ,
  絵と字の間,
  字の大きさ,
  外の余白,
  ゆとり,
};
