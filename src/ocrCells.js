/**
 * Module ID: ocrCells
 *
 * 読み取ったマスの見た目を、1射ずつの○×に開く。
 *
 * ■ なぜ分けるか
 *
 * ホワイトボードでは、1つのマスに2射ぶんが重ねて書かれる。
 *
 *   1本目を外す → 右上から左下へ線
 *   そのあと2本目を中てる → その上に丸（線の入った丸）
 *   1本目を中てる → 丸
 *   そのあと2本目を外す → その上に左上から右下へ線（線の入った丸）
 *   2本とも中てる → 丸の内側にもう1つ丸（◎）
 *   2本とも外す → 線が交わって ×
 *
 * この展開まで模型に任せると、的中数が倍になったり、全部○になったりした
 *（2026-09-09、実物の写真で 45.8% しか合わなかった）。
 * 模型には「マスがどう見えるか」だけを答えさせ、開くのはこちらでやる。
 * 決まりきった変換なので、機械のほうが確実で、検査もできる。
 */
'use strict';

/**
 * マスの見た目 → 2射ぶんの○×。
 *
 * 記号は指示文で決めたものだけを受ける。知らない記号は「読めなかった」に倒す。
 */
const 二射のマス = {
  '◎': ['○', '○'],
  // 丸に「左上から右下」の線。1本目 中り → 2本目 外れ
  '○\\': ['○', '×'],
  // 丸に「右上から左下」の線。1本目 外れ → 2本目 中り
  '○/': ['×', '○'],
  '×': ['×', '×'],
  // まだ2本目を引いていない
  '○': ['○', ''],
  '/': ['×', ''],
  '': ['', ''],
};

/** 1射だけのマス（紙の横書きの表） */
const 一射のマス = {
  '○': ['○'],
  '×': ['×'],
  '': [''],
};

/** 書き方の揺れを、決めた記号に寄せる */
function 記号を整える(生) {
  const s = String(生 == null ? '' : 生).trim();
  if (!s) return '';
  // 丸の仲間
  const 丸 = '○◯〇●';
  const 二重丸 = '◎';
  if (二重丸.includes(s)) return '◎';
  if (丸.includes(s)) return '○';
  if ('×✕✖x✗X'.includes(s)) return '×';
  // 丸に線。線の向きは「＼」（左上→右下）と「／」（右上→左下）
  const 頭 = s[0];
  const 尾 = s.slice(1);
  if (丸.includes(頭) || 二重丸.includes(頭)) {
    if (/[\\＼]/.test(尾)) return '○\\';
    if (/[/／]/.test(尾)) return '○/';
    if (丸.includes(尾)) return '◎';
    return 二重丸.includes(頭) ? '◎' : '○';
  }
  if (/^[\\＼]$/.test(s)) return '/'; // 線1本は「1本目を外した」だけ
  if (/^[/／]$/.test(s)) return '/';
  return '';
}

/**
 * マスの並びを、1射ずつの○×に開く。
 *
 * @param {string[]} マスたち 読み取ったマスの見た目
 * @param {'2射'|'1射'} 一マスの射数
 * @returns {string[]} '○' | '×' | '' の並び
 */
function マスを開く(マスたち, 一マスの射数) {
  const 表 = '1射' === 一マスの射数 ? 一射のマス : 二射のマス;
  const 出 = [];
  for (const 生 of Array.isArray(マスたち) ? マスたち : []) {
    const 記号 = 記号を整える(生);
    const 開いた = 表[記号] || ('1射' === 一マスの射数 ? [''] : ['', '']);
    for (const x of 開いた) 出.push(x);
  }
  return 出;
}

/**
 * 射数に合わせて長さを整える。足りなければ空で埋め、多ければ切る。
 *
 * 写真に見える射数と、アプリの設定が食い違うことがある。読み取りを捨てず、
 * 位置を保ったまま合わせる。
 */
function 射数にそろえる(印たち, 射数) {
  const 並び = Array.isArray(印たち) ? 印たち.slice(0, 射数) : [];
  while (並び.length < 射数) 並び.push('');
  return 並び;
}

/**
 * 見えるとおりに並んだマスを、1射目からの順に直す。
 *
 * 板は下から書き足されることがある。実物で確かめた（2026-09-09、団体910280 の
 * 板）。1番の列は、下から読むと10マスすべて正解と一致した。合計の欄も下から
 * 22→44→65→88→107 と増えており、いちばん新しい立が上にある。
 *
 * どちらから書くかは道場によって違うので、読む前に選んでもらう。
 * 模型には「見えるとおりの順」だけを答えさせ、時間の順に直すのはここでやる。
 *
 * @param {string[]} マスたち 写真で上から下（横書きなら左から右）の順
 * @param {'上から'|'下から'} 起点 1射目がどちら側か
 */
function 一射目からの順にする(マスたち, 起点) {
  const 並び = Array.isArray(マスたち) ? マスたち.slice() : [];
  return '下から' === 起点 ? 並び.reverse() : 並び;
}

module.exports = { マスを開く, 記号を整える, 射数にそろえる, 一射目からの順にする, 二射のマス, 一射のマス };
