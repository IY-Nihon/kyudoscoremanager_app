/** Q&A の答えを、一覧で読む文の並びにする。「（Q55）」のような Q&A どうしの参照は外す */
function 答えの文(番) {
  const 一つ = qaData.find((x) => new RegExp(`^${番}:`).test(x.t));
  if (!一つ) return [];
  const 答え = (一つ.t.split('\nA: ')[1] || '').replace(/（Q\d+）/g, '');
  return 答え
    .split(/(?<=。)/)
    .map((行) => 行.trim())
    .filter(Boolean);
}

/**
 * 一覧に出す項目。案内の手順（まとまりの一覧）に、足す項目をまとまりごとに後ろへ足し、困りごとを最後に置く
 * @param 一覧 まとまりの一覧 が返すもの（[{名, 題たち}]）
 * @returns {Array<{名: string, 項目: Array<{鍵, 名, 文?, 動画?, 案内の題?}>}>}
 */
function 使い方の一覧(一覧, 役割) {
  const 団体 = 役割 === 'group';
  const 足す = 足す項目.filter((項) => 団体 || !項.団体だけ);
  const 名たち = [...一覧.map((組) => 組.名), 困りごと];
  return 名たち
    .map((名) => ({
      名,
      案内の題たち: (一覧.find((組) => 組.名 === 名) || { 題たち: [] }).題たち,
      足す: 足す
        .filter((項) => 項.まとまり === 名)
        .map((項) => ({ 鍵: 'x:' + 項.名, 名: 項.名, 文: 項.文 || 答えの文(項.qa), 動画: 項.動画 || null })),
    }))
    .filter((組) => 組.案内の題たち.length + 組.足す.length > 0);
}

