/**
 * 確認・お知らせを「帯」で流すか「窓」で止めるかを決める純粋な関数。
 *
 * 画面にも Firebase にも触れないので、node --test で手元だけで確かめられる
 * （test/dialogRules.test.js）。AppDialog.js から読み込んで使う。
 *
 * 元はブラウザの window.confirm / window.alert を使っていた。見た目がアプリと
 * 揃わず、出る位置も機種で違うので、すべてアプリの中の窓へ寄せた。そのとき
 * 「ボタンが無いものは帯で流す」だけにしたら、団体IDの控えのような大事な文まで
 * 2.6秒で消えてしまった。読み切れる長さかどうかで分ける必要がある。
 */
'use strict';

/** 帯が最初から出ている時間（ミリ秒） */
const 帯の下限 = 2600;
/** 帯を出しておく上限 */
const 帯の上限 = 6000;
/** 1字あたり足す時間。日本語は1秒に10字ほどしか読めない */
const 一字あたり = 80;
/** これを超えたら帯では読み切れないと見なす字数 */
const 帯で読める字数 = 40;

/**
 * 窓（押して閉じる）で止めるべきか。false なら帯（自動で消える）。
 * @param {{文?: string, ボタン?: Array}} 要求
 */
function 窓で止めるか(要求) {
  const ボタン = (要求 && 要求.ボタン) || [];
  if (ボタン.length >= 2) return true; // 選ばせる確認は必ず止める
  const 文 = String((要求 && 要求.文) || '');
  if (文.indexOf('\n') >= 0) return true; // 改行つき＝箇条書きや控え
  return 文.length > 帯で読める字数;
}

/** 帯を出しておく長さ（ミリ秒）。短い一言は素早く、長めの文は少し長く */
function 帯の長さ(文) {
  const ミリ秒 = 帯の下限 + String(文 || '').length * 一字あたり;
  return Math.min(ミリ秒, 帯の上限);
}

/**
 * 帯を消す時計。掛け直すときは必ず前のぶんを止める。
 *
 * 止め忘れると、続けて知らせが来たときに前の時計が後の帯を早く消す。
 * 画面の外に出しておけば、時計を差し替えて手元で確かめられる。
 *
 * @param {(f: Function, ms: number) => any} 掛ける関数  setTimeout
 * @param {(札: any) => void} 止める関数                clearTimeout
 */
function 帯の時計をつくる(掛ける関数, 止める関数) {
  let 札 = null;
  return {
    /** 消すまでの時計を掛け直す。前のぶんは必ず止める */
    掛ける(ミリ秒, 消す) {
      if (札 !== null) 止める関数(札);
      札 = 掛ける関数(() => {
        札 = null;
        消す();
      }, ミリ秒);
    },
    /** 画面から外すときに呼ぶ */
    片付ける() {
      if (札 !== null) 止める関数(札);
      札 = null;
    },
    /** 検査用。時計を持っているか */
    掛かっているか() {
      return 札 !== null;
    },
  };
}

module.exports = { 窓で止めるか, 帯の長さ, 帯の時計をつくる, 帯で読める字数, 帯の下限, 帯の上限 };
