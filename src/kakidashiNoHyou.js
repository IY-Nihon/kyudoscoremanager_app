/**
 * 設定の「Excel形式で書き出し」の中身づくり（窓は src/SettingsExport.js）。
 * 記録を範囲と条件で選び、シート（見出し・行・列の幅・見た目）にする。
 * 窓の部品の中にあったものを、検査できるようにここへ出した（2026-10-25）。
 *
 * 数え方は分析画面と同じ（src/statsRules.js）：途中交代は人ごとの区間に分け、分母は実際に引いた数。
 * 「集計に含めない」にした記録は本表から外し、別のシートに残す。
 */
'use strict';

const 集 = require('./statsRules');
const 学 = require('./gakunen');

const 二桁 = (数) => String(数).padStart(2, '0');
/** 2026-08-05 の形。Excel が日付として解釈でき、文字列で並べても崩れない */
function csvDate(時刻) {
  const 日 = new Date(時刻);
  return `${日.getFullYear()}-${二桁(日.getMonth() + 1)}-${二桁(日.getDate())}`;
}
/** 2026/08/05 の形。言葉の絞り込みを日付にも当てるときと、印刷向けの日付の列に使う */
function 日付の文(時刻) {
  const 日 = new Date(時刻);
  return `${日.getFullYear()}/${二桁(日.getMonth() + 1)}/${二桁(日.getDate())}`;
}
/** 名前の後ろの「(2)」のような重なりよけを外す */
const 名を整える = (名) => (名 || '').replace(/\s*\(\d+\)$/, '').trim();
/** 的中率（%・小数 1 桁）。射数が 0 なら 0 */
const 率 = (的中, 射数) => (射数 > 0 ? Number(((的中 / 射数) * 100).toFixed(1)) : 0);

/** 記録の中の射手の列（区切りと計を除く） */
const 射手の列たち = (記録) =>
  (Array.isArray(記録 && 記録.archers) ? 記録.archers : []).filter(
    (射手) => 射手 && !射手.isSeparator && !射手.isTotalCalculator
  );

/**
 * 個人ログインで、自分の分が入っている列か。列の持ち主が自分か（名前だけで入った列は名前で）、
 * 交代で入ったか。交代を見ていなかったので、交代で入っただけの記録が書き出しから丸ごと落ちていた
 */
function 自分の分がある列か(射手, 自分id, 自分名) {
  return (
    !!射手 &&
    (射手.memberId === 自分id ||
      (!!自分名 && !射手.memberId && 名を整える(射手.name) === 自分名) ||
      Object.values(射手.substitutionIds || {}).includes(自分id))
  );
}
function 自分の分がある記録か(記録, 自分id, 自分名) {
  return (
    !!記録 &&
    Array.isArray(記録.archers) &&
    記録.archers.some((射手) => 自分の分がある列か(射手, 自分id, 自分名))
  );
}

/**
 * 書き出す記録を選ぶ。
 * @param {Array} 記録たち
 * @param {object} 条件
 *   範囲 'all' | 'fiscal'（年度） | 'custom'（詳しい条件）、年度、
 *   始め・終わり・選んだタグ・タグの論理（'AND' | 'OR'）・選んだ言葉・言葉の絞り（custom のときだけ見る）、
 *   自分id・自分名（個人ログインのとき。自分の分がある記録だけにする）
 */
function 書き出す記録を選ぶ(記録たち, 条件) {
  const {
    範囲,
    年度,
    始め,
    終わり,
    選んだタグ = [],
    タグの論理 = 'AND',
    選んだ言葉 = [],
    言葉の絞り = '',
    自分id,
    自分名,
  } = 条件;
  // 言葉は題・メモ・日付（2026/08/05）のどれかに入っていれば当たり
  const 当たる = (記録, 言葉) => {
    const 小 = 言葉.toLowerCase();
    return [記録.title, 記録.note, 日付の文(記録.date)].some((文) => (文 || '').toLowerCase().includes(小));
  };
  return (記録たち || []).filter((記録) => {
    if (!記録) return false;
    if (自分id && !自分の分がある記録か(記録, 自分id, 自分名)) return false;
    if (範囲 === 'fiscal') return 学.年度(new Date(記録.date)) === 年度;
    if (範囲 !== 'custom') return true;
    const 日付 = new Date(記録.date);
    const 頭 = new Date(始め);
    頭.setHours(0, 0, 0, 0);
    const 尾 = new Date(終わり);
    尾.setHours(23, 59, 59, 999);
    if (日付 < 頭 || 日付 > 尾) return false;
    if (選んだタグ.length > 0) {
      const 有る = (タグ) => (記録.tags || []).includes(タグ);
      if (タグの論理 === 'AND' ? !選んだタグ.every(有る) : !選んだタグ.some(有る)) return false;
    }
    if (選んだ言葉.length > 0 && !選んだ言葉.some((言葉) => 当たる(記録, 言葉))) return false;
    if (言葉の絞り && !当たる(記録, 言葉の絞り)) return false;
    return true;
  });
}

/**
 * その区間（1 人ぶんの射）を書くか。絞り込みは列ではなく人ごとに見る（列で見ると、交代で入った人が
 * 自分の書き出しから丸ごと落ちる。列の持ち主は別人のため）。
 * 個人は自分だけ。団体の詳しい条件では、選んだ人か、名前の絞りに当たる人
 */
function この人を書くか(区間, 条件) {
  const { 範囲, 自分id, 自分名, 選んだ部員 = [], 部員名の絞り = 'all' } = 条件;
  if (自分id) {
    return (
      String(区間.部員id || '') === String(自分id) ||
      (!!自分名 && !区間.部員id && 名を整える(区間.名前) === 自分名)
    );
  }
  if (範囲 !== 'custom') return true;
  if (選んだ部員.length > 0) return 選んだ部員.includes(名を整える(区間.名前));
  return 部員名の絞り === 'all' || (区間.名前 || '').toLowerCase().includes(部員名の絞り.toLowerCase());
}

/** 列を人ごとの区間に分ける。○×が 1 つも入っていない列も、誰が立っていたかは残す */
function 人ごとの区間(射手) {
  const 区間たち = 集.射手を区間に分ける(射手);
  return 区間たち.length ? 区間たち : [{ 部員id: 射手.memberId, 名前: 射手.name || '', 的中: 0, 射数: 0 }];
}

/** 名簿の人を memberId（無ければ氏名）で引く。学年・性別・期の補完に使う */
function 名簿から引く(部員id, 名前, 名簿) {
  const 整えた名 = 名を整える(名前);
  return (
    名簿.find((人) => (部員id && 人.id === 部員id) || (人.name && 名を整える(人.name) === 整えた名)) || null
  );
}

/** 標準形式：1 行に 1 人・1 記録 */
function 標準の表(記録たち, 条件, 名簿) {
  const 行たち = [];
  記録たち.forEach((記録) => {
    射手の列たち(記録).forEach((射手) => {
      人ごとの区間(射手).forEach((区間) => {
        if (!この人を書くか(区間, 条件)) return;
        // 交代で入った人の学年や性別は、その人の名簿から引く。
        // 名簿に無いときは射手側の値を使うが、それが使えるのは列の持ち主のときだけ
        //（交代で入った人に列の持ち主の学年を当てると別人の情報になる）
        const 人 = 名簿から引く(区間.部員id, 区間.名前, 名簿);
        const 列の持ち主か = 区間.名前 === (射手.name || '');
        const 学年 = 人 && 人.grade != null ? 人.grade : 列の持ち主か && 射手.grade != null ? 射手.grade : '';
        const 性別 = 人 && 人.gender ? 人.gender : 列の持ち主か ? 射手.gender || '' : '';
        行たち.push([
          csvDate(記録.date),
          記録.title || '',
          名を整える(区間.名前 || 射手.name),
          // 学年は名前で（高1・M1・自分で決めた名前。値のままだと中高一貫の高1 が 4 と出る）
          学年 === '' ? '' : 学.学年の名前(Object.assign({}, 人 || {}, { grade: 学年 })),
          性別,
          人 && 人.termKi != null ? 人.termKi : '',
          // 分母は実際に引いた数。記録の射数（割り当て）だと、途中で帰った人の的中率が低く出る
          区間.的中,
          区間.射数,
          率(区間.的中, 区間.射数),
          (記録.tags || []).join(' '),
          記録.note || '',
          // 本表は集計する記録だけなので、いつも「対象」（TRUE / FALSE では何の真偽か伝わらない）
          '対象',
        ]);
      });
    });
  });
  return {
    name: '記録',
    headers: [
      '日付',
      'タイトル',
      '射手名',
      '学年',
      '性別',
      '期',
      '的中数',
      '総矢数',
      '的中率',
      'タグ',
      'メモ',
      '集計対象',
    ],
    rows: 行たち,
    widths: [12, 22, 14, 6, 8, 6, 9, 9, 10, 18, 26, 10],
    // 的中率の列は「38.9%」と見せる。中身は 38.9 のままなので、表計算の式や並べ替えはこれまでどおり使える
    formats: ['', '', '', '', '', '', '', '', '率'],
  };
}

/**
 * 印刷向け形式：メンバーを行、日付を列にして「的中/射数」を置く。
 * 人は区間から集める（交代で入っただけの人も行に出す）。数えるのは部員 id が分かる人だけ
 */
function 印刷向けの表(記録たち, 条件, 名簿) {
  const 日付たち = [...new Set(記録たち.map((記録) => 日付の文(記録.date)))].sort();
  const 人たち = new Map();
  記録たち.forEach((記録) =>
    射手の列たち(記録).forEach((射手) =>
      人ごとの区間(射手).forEach((区間) => {
        if (!この人を書くか(区間, 条件)) return;
        const 名 = 名を整える(区間.名前) || '不明';
        const 鍵 = 区間.部員id || 名;
        if (!人たち.has(鍵)) 人たち.set(鍵, { id: 区間.部員id || '', name: 名 });
      })
    )
  );
  // 名簿にいる人は、名簿の名前と学年で出す
  人たち.forEach((人) => {
    const 部員 = 名簿.find((名簿の人) => 名簿の人.id === 人.id || 名簿の人.name === 人.name);
    if (部員) {
      人.grade = 部員.grade;
      人.name = 部員.name;
    }
  });
  const 並べた人たち = [...人たち.values()].sort(
    (甲, 乙) => 学.学年の順(甲) - 学.学年の順(乙) || 甲.name.localeCompare(乙.name, 'ja-JP')
  );
  const 行たち = 並べた人たち.map((人) => {
    let 的中の計 = 0;
    let 射数の計 = 0;
    const 日ごと = 日付たち.map((その日) => {
      let 的中 = 0;
      let 射数 = 0;
      let 引いた = false;
      記録たち
        .filter((記録) => 日付の文(記録.date) === その日)
        .forEach((記録) =>
          射手の列たち(記録).forEach((射手) =>
            集.射手を区間に分ける(射手).forEach((区間) => {
              if (!人.id || String(区間.部員id) !== String(人.id)) return;
              引いた = true;
              的中 += 区間.的中;
              射数 += 区間.射数;
            })
          )
        );
      if (!引いた) return '';
      的中の計 += 的中;
      射数の計 += 射数;
      return `${的中}/${射数}`;
    });
    return [
      人.name,
      人.grade != null ? 学.学年の名前(人) : '',
      率(的中の計, 射数の計),
      的中の計,
      射数の計,
      ...日ごと,
    ];
  });
  return {
    name: '集計',
    headers: ['氏名', '学年', '的中率', '的中数', '総矢数'].concat(
      日付たち.map((日) => {
        const [, 月, 日にち] = 日.split('/');
        return `${Number(月)}月${Number(日にち)}日`;
      })
    ),
    rows: 行たち,
    widths: [16, 7, 9, 9, 9].concat(日付たち.map(() => 9)),
    formats: ['', '', '率'],
  };
}

/** 「集計に含めない」にした記録のシート。本表から外したぶんを、何が外れたか確かめられるよう残す */
function 含めない記録の表(記録たち, 条件) {
  const 行たち = [];
  記録たち.forEach((記録) => {
    射手の列たち(記録).forEach((射手) => {
      集.射手を区間に分ける(射手).forEach((区間) => {
        // 本表と同じ人の絞りをかける（前はかけておらず、個人の書き出しに他の人の成績が入っていた）
        if (!この人を書くか(区間, 条件)) return;
        行たち.push([
          csvDate(記録.date),
          記録.title || '',
          名を整える(区間.名前 || 射手.name),
          区間.的中,
          区間.射数,
          率(区間.的中, 区間.射数),
          (記録.tags || []).join(' '),
          記録.note || '',
        ]);
      });
    });
  });
  return {
    name: '集計に含めない記録',
    headers: ['日付', '題', '氏名', '的中数', '射数', '的中率', 'タグ', 'メモ'],
    rows: 行たち,
    widths: [12, 22, 14, 9, 9, 10, 18, 26],
    formats: ['', '', '', '', '', '率'],
  };
}

/**
 * 書き出すシートを作る。
 * @param {Array} 記録たち
 * @param {object} 条件 書き出す記録を選ぶ・この人を書くか の条件に、形（'standard' | 'matrix'）を足したもの
 * @param {Array} 名簿 メンバーと卒業生
 * @returns {{ 記録の数: number, シートたち: Array }} 記録の数は条件に当たった記録の数（0 なら書き出すものが無い）
 */
function 書き出しのシートを作る(記録たち, 条件, 名簿) {
  const 対象 = 書き出す記録を選ぶ(記録たち, 条件);
  // 「集計に含めない」にした記録は、本表から外して別のシートに回す。
  // 混ぜると分析画面の数字と食い違う（画面はこれを外して数えている）
  const 集計する = 対象.filter((記録) => 集.集計に入れるか(記録));
  const 集計しない = 対象.filter((記録) => !集.集計に入れるか(記録));
  const 本表 =
    条件.形 === 'matrix' ? 印刷向けの表(集計する, 条件, 名簿 || []) : 標準の表(集計する, 条件, 名簿 || []);
  const 外した表 = 含めない記録の表(集計しない, 条件);
  return { 記録の数: 対象.length, シートたち: 外した表.rows.length ? [本表, 外した表] : [本表] };
}

module.exports = { 書き出しのシートを作る, 書き出す記録を選ぶ, 自分の分がある記録か, csvDate };
