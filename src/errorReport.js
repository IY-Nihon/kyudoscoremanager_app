/**
 * Module ID: errorReport
 *
 * 不具合の便り。「何が起きたか」と「その直前に何をしていたか」を控えて送る。
 *
 * これまでは設定に「同期エラーを通知」の切り替えがあるだけで、失敗したことは
 * 本人の画面に一度出るきり、こちらには何も残らなかった。しかも切り替えは
 * 保存されていなかったので、切っても次に開くと元に戻っていた。
 *
 * 電波が切れている最中にこそ失敗するので、送れなかった便りは端末に貯めて、
 * つながったときに出し直す。貯めは件数で頭打ちにし、同じ不具合が短い間に
 * 何度も起きたときは1件にまとめて回数だけ増やす（同じ便りで埋まらないように）。
 *
 * 行動の控えに、部員の氏名・的中・記録の中身は入れない。入れると、不具合を
 * 送るだけで名簿が外に出ることになる。控えるのは「どの画面で何をしたか」の
 * 名前と、数など人を特定しない手がかりだけ。呼ぶ側もこれを守ること。
 *
 * 画面にも Firebase にも触れない純粋な関数なので、そのまま検査できる
 * （test/errorReport.test.js）。送る手立ては 送り係をつくる に外から渡す。
 */
'use strict';

/** 行動の控えを何件持つか。多すぎると1件の便りが重くなる */
const 控えの数 = 30;
/** 送れずに貯める便りの上限。古いものから捨てる */
const 貯めの上限 = 20;
/** 同じ不具合をまとめる間隔（ミリ秒） */
const まとめる間隔 = 60000;
/**
 * 1回の起動で送る上限。
 *
 * 描画の繰り返しの中で落ちると、同じ不具合が毎秒のように起きる。
 * 歯止めが無いと Firestore へ何百通も書きにいってしまい、直すのに要る
 * 情報は最初の数通で足りているのに、料金と一覧の見通しだけが悪くなる。
 */
const 一度に送る上限 = 20;

const 跡の上限 = 2000;
const 文の上限 = 300;

// ── 行動の控え ───────────────────────────────────

let 行動たち = [];

/**
 * 「どの画面で何をしたか」を1つ控える。
 *
 * @param {string} 名 短い名前（例: '記録を保存', '分析を開く'）
 * @param {*} 中身 人を特定しない手がかりだけ（件数、状態の名前など）
 */
function 行動を残す(名, 中身) {
  if (!名) return;
  行動たち.push({
    時刻: Date.now(),
    名: String(名).slice(0, 60),
    中身: null == 中身 ? '' : String(中身).slice(0, 120),
  });
  if (行動たち.length > 控えの数) 行動たち = 行動たち.slice(-控えの数);
}

/** 控えの写しを返す。渡した先で書き換えられても困らないように写す */
function 行動の控え() {
  return 行動たち.map((x) => ({ 時刻: x.時刻, 名: x.名, 中身: x.中身 }));
}

/** 控えを捨てる。検査と、ログアウトのときに使う */
function 行動を捨てる() {
  行動たち = [];
}

// ── 便りを組む ───────────────────────────────────

function 短く(値, 長さ) {
  const s = null == 値 ? '' : String(値);
  return s.length > 長さ ? s.slice(0, 長さ) + '…' : s;
}

/**
 * 不具合の便りを組む。送る形はここだけで決める。
 *
 * @param {Error|string|object} 誤り 捕まえたもの
 * @param {object} 付帯 出どころ・団体id・役割・版・端末・回線・時刻
 * @returns {object} そのまま Firestore に入れられる形
 */
function 不具合の便を組む(誤り, 付帯) {
  const p = 付帯 || {};
  const 中 = 誤り && 'object' == typeof 誤り ? 誤り : { message: 誤り };
  const 時刻 = p.時刻 || Date.now();
  return {
    id: p.id || 時刻 + '-' + Math.random().toString(36).slice(2, 8),
    時刻,
    出どころ: 短く(p.出どころ || '不明', 60),
    起きたこと: 短く(中.message || (誤り && 誤り.toString ? 誤り.toString() : ''), 文の上限),
    符号: 短く(中.code || '', 60),
    跡: 短く(中.stack || '', 跡の上限),
    行動: 行動の控え(),
    団体id: 短く(p.団体id || '', 40),
    役割: 短く(p.役割 || '', 20),
    版: 短く(p.版 || '', 40),
    端末: 短く(p.端末 || '', 200),
    回線: !1 === p.回線 ? 'つながっていない' : 'つながっている',
    回数: 1,
  };
}

/** 同じ不具合とみなすか。出どころと起きたことが同じで、間隔が短いもの */
function 同じ不具合か(a, b, いま) {
  if (!a || !b) return !1;
  if (a.出どころ !== b.出どころ || a.起きたこと !== b.起きたこと) return !1;
  return Math.abs((いま || Date.now()) - a.時刻) < まとめる間隔;
}

/**
 * 貯めに1件足す。同じ不具合が続いたときは回数だけ増やす。
 * 上限を超えたら古いほうから捨てる（新しいほうが今の様子に近い）。
 */
function 貯めに足す(貯め, 便, いま) {
  const 元 = (Array.isArray(貯め) ? 貯め : []).map((x) => Object.assign({}, x));
  for (const x of 元) {
    if (同じ不具合か(x, 便, いま)) {
      x.回数 = (x.回数 || 1) + 1;
      return 元;
    }
  }
  元.push(便);
  return 元.length > 貯めの上限 ? 元.slice(-貯めの上限) : 元;
}

/** 貯めから1件消す。送れたときに使う */
function 貯めから消す(貯め, id) {
  return (Array.isArray(貯め) ? 貯め : []).filter((x) => x && x.id !== id);
}

// ── 送り係 ───────────────────────────────────────

/**
 * 待ちすぎたら諦める。
 *
 * Firestore の書き込みは、電波が無いときに「失敗」ではなく「返ってこない」に
 * なる。そのまま待っていると、アプリを閉じた時点で便りごと消える。
 * 一定の時間で見切りをつけて貯めに回し、つながったときに出し直す。
 *
 * 出し直しで同じ便りが2通届くことはあるが、便りには id があるので
 * 読むときにまとめられる。届かないより、2通届くほうがよい。
 *
 * @param {Promise} 約束
 * @param {number} ミリ秒
 * @param {Function} [仕掛け] setTimeout の代わり（検査用）
 */
function 間に合わなければ諦める(約束, ミリ秒, 仕掛け) {
  const 仕 = 仕掛け || setTimeout;
  return new Promise((応, 否) => {
    let 済み = !1;
    const 札 = 仕(() => {
      if (済み) return;
      済み = !0;
      否(new Error('時間内に送れなかった'));
    }, ミリ秒);
    Promise.resolve(約束).then(
      (x) => {
        if (済み) return;
        ((済み = !0), clearTimeout(札), 応(x));
      },
      (e) => {
        if (済み) return;
        ((済み = !0), clearTimeout(札), 否(e));
      }
    );
  });
}

/**
 * 送り係を組み立てる。送る手立てと貯め場所は外から渡す。
 *
 * @param {{送る:Function, 読む:Function, 書く:Function, いま?:Function, 上限?:number}} 道具
 *   送る(便) … 送れたら解決する約束。失敗は投げる
 *   読む()   … 貯めの配列を返す
 *   書く(貯め) … 貯めを保存する
 *   上限     … 1回の起動で送る数の上限（既定は 一度に送る上限）
 */
function 送り係をつくる(道具) {
  const { 送る, 読む, 書く } = 道具 || {};
  const いま = (道具 && 道具.いま) || (() => Date.now());
  const 上限 = (道具 && 道具.上限) || 一度に送る上限;
  let 流している = !1;
  // この起動で送った数と、直近に送ったもの。
  // 描画の繰り返しの中で落ちると、同じ不具合が毎秒のように起きる。
  // 歯止めが無いと、そのまま Firestore へ何百通も書きにいってしまう
  let 送った数 = 0;
  let 直近 = [];

  /** すでに送ったばかりの不具合か。同じ便りで埋めない */
  function 送ったばかりか(便) {
    const 時 = いま();
    直近 = 直近.filter((x) => 時 - x.時刻 < まとめる間隔);
    return 直近.some((x) => 同じ不具合か(x, 便, 時));
  }

  /** 1件出す。送れなければ貯める（捨てない） */
  async function 出す(便) {
    if (送ったばかりか(便) || 送った数 >= 上限) return !1;
    try {
      await 送る(便);
      送った数++;
      直近.push({ 時刻: いま(), 出どころ: 便.出どころ, 起きたこと: 便.起きたこと });
      return !0;
    } catch (e) {
      try {
        書く(貯めに足す(読む() || [], 便, いま()));
      } catch (_) {
        // 貯めることすらできない端末では、これ以上できることがない
      }
      return !1;
    }
  }

  /**
   * 貯まっているぶんを出し直す。つながったときに呼ぶ。
   * 1件でも失敗したらそこで止める（つながっていないのに残りを叩かない）。
   */
  async function 溜まりを流す() {
    if (流している) return 0;
    流している = !0;
    let 出せた = 0;
    try {
      let 貯め = 読む() || [];
      for (const 便 of 貯め.slice()) {
        try {
          await 送る(便);
          貯め = 貯めから消す(貯め, 便.id);
          書く(貯め);
          出せた++;
        } catch (e) {
          break;
        }
      }
    } catch (_) {
      // 読めない・書けないときは何もしない
    } finally {
      流している = !1;
    }
    return 出せた;
  }

  return { 出す, 溜まりを流す };
}

/**
 * 送るときの形に直す。中では日本語の名前で扱い、外へ出すときだけ英字にする。
 *
 * Firestore の決まり（firestore.rules）は日本語の項目名を確実に扱えるとは
 * 限らないうえ、決まりの中で項目を1つずつ確かめる必要がある。
 * 送る形をここに閉じ込めておけば、中の名前を変えても決まりは動かさずに済む。
 */
function 外向きの形(便) {
  const b = 便 || {};
  return {
    id: b.id || '',
    at: b.時刻 || 0,
    where: b.出どころ || '',
    message: b.起きたこと || '',
    code: b.符号 || '',
    stack: b.跡 || '',
    trail: (Array.isArray(b.行動) ? b.行動 : []).map((x) => ({
      at: x.時刻 || 0,
      name: x.名 || '',
      detail: x.中身 || '',
    })),
    groupId: b.団体id || '',
    role: b.役割 || '',
    version: b.版 || '',
    device: b.端末 || '',
    online: 'つながっていない' !== b.回線,
    count: b.回数 || 1,
  };
}

