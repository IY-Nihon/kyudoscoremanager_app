/**
 * 写真の読み取りを待つ間の決まり（読み取りの窓 OCRRecordModal と、記録画面の「読み取りが届きました」の帯）。
 *
 * ■ なぜ（2026-11-20 本人「閉じても読み続ける」）
 * Gemini が混む日は、読み取りに 1〜3 分かかる。答えが届く前に窓を閉じたのが 2 回（51 秒・214 秒）あり、
 * どちらも答えは合っていたが捨てていた。待つ間は「読み取っています」とぐるぐるだけで、何秒たったか・
 * 閉じたらどうなるかが分からなかった。閉じても読み続け、届いたら記録画面で知らせる。
 * また iPhone の Safari は、答えの頭が来ないまま 70〜100 秒たつと通信を切る（詳しく/ai-log-review-1023）。
 * そのとき「電波の良い場所で」と出していたが、電波ではなく AI の遅さなので、長く待ったあとの切れは文を分ける。
 */
'use strict';

/** 待つ間の説明を出し始める秒（すぐ届く日は出さない） */
const 説明を出す秒 = 10;
/** 長く待ったあとの通信の切れを、電波ではなく AI の遅さとみなす長さ（ミリ秒。中継の 待ちきったか と同じ 60 秒） */
const 遅さとみなす長さ = 60 * 1000;
/** 閉じたあとに届いた読み取りの帯を出しておく長さ（ミリ秒）。過ぎたら帯を消し、預けた結果も捨てる */
const 帯を出しておく長さ = 15 * 60 * 1000;

/**
 * 待つ間の説明（説明を出す秒を過ぎたら）。改行は見せた案のとおり
 * （2 行目を「…届いたら記録画面でお知らせします。」にすると、幅 390 の画面で「す。」だけ次の行に落ちた）
 */
const 待つ間の説明 =
  '混んでいる日は 1〜3 分かかります。\n閉じても読み続け、届いたら\n記録画面でお知らせします。';

/**
 * 読み取りが失敗したときに出す文。
 * @param {unknown} 誤りの字 誤りの message
 * @param {number} 待った長さ 読み取りを始めてからの長さ（ミリ秒）
 */
function 読み取りの誤りの文(誤りの字, 待った長さ) {
  const 字 = String(誤りの字 == null ? '' : 誤りの字);
  if (字.includes('429')) return 'AIの利用制限に達しました。しばらく待ってから再度お試しください。';
  // 模型が混んでいる（high demand）。中継とアプリで待って送り直したうえでの 503
  if (字.includes('503')) return 'ただいまAIが混み合っています。しばらく待ってからもう一度お試しください。';
  if (字.includes('401') || 字.includes('ログインしていない'))
    return 'ログインの証が確かめられませんでした。ログインし直してから再度お試しください。';
  if (/network|fetch|Load failed/i.test(字))
    return Number(待った長さ) >= 遅さとみなす長さ
      ? 'AIの答えが遅く、通信が途中で切れました。混み合っている可能性があります。少し待ってからもう一度お試しください。'
      : '通信エラーが発生しました。電波の良い場所で再度お試しください。';
  return '画像の解析に失敗しました。再度お試しいただくか、手動で入力してください。';
}

/**
 * 記録画面の帯の文。
 * @param {{成功?: boolean, モード?: string}} 届いた
 */
function 届いた帯の文(届いた) {
  const 何 = 届いた && 届いた.モード === 'record' ? '記録表' : '立ち順';
  return 届いた && 届いた.成功 ? `${何}の読み取りが届きました` : `${何}の読み取りができませんでした`;
}

module.exports = {
  説明を出す秒,
  遅さとみなす長さ,
  帯を出しておく長さ,
  待つ間の説明,
  読み取りの誤りの文,
  届いた帯の文,
};
