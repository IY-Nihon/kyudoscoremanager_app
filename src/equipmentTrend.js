/**
 * Module ID: equipmentTrend
 *
 * 弓具を変えた前後で、的中率がどう動いたかを並べる。
 *
 * ■ 何のために
 * 弓力を上げた直後に的中が落ちていないか、弦を替えてから戻ったか。
 * 道具と射術は両方が絡むので、いつ何を替えたかと成績を並べて見たい。
 *
 * ■ 数え方は書き直さない
 * 射数の数え方には、交代した人の射をどちらに付けるか、「集計に含めない」
 * にした記録を外すか、といった決まりがある。ここで書き直すと、分析画面や
 * AIの答えと数字が食い違う。chatStats の 全員の成績 をそのまま呼ぶ。
 *
 * ■ 数字は「因果」ではない
 * 前後で率が動いても、弓具のせいとは限らない（時期・体調・相手）。
 * 射数が少なければなおさら揺れる。だから射数も必ず一緒に返し、
 * 画面でもそう伝える。
 *
 * Firebase にも画面にも触れないので、そのまま検査できる
 * （test/equipmentTrend.test.js）。
 */
'use strict';

const 統 = require('./chatStats');

/** これを下回る射数では、率を出さない。揺れが大きすぎて読み違える */
const 率を出す最小射数 = 20;

/**
 * その人の、ある期間の成績
 * @param {{id:string|number, name?:string, grade?:any, equipments?:Array}} 人
 * @param {Array} 記録たち
 * @param {number} 始め
 * @param {number} 終わり
 * @returns {{的中:number, 射数:number, 的中率:number|null}}
 */
function 期間の成績(人, 記録たち, 始め, 終わり) {
  const 出 = 統.全員の成績([人], 記録たち, {
    期間: { 始め, 終わり },
    最小射数: 0,
  });
  // 全員の成績 が返すのは { 並び, 人数, 全体, 一覧 } で、配列ではない
  const x = (出 && Array.isArray(出.一覧) && 出.一覧[0]) || { 的中: 0, 射数: 0, 的中率: null };
  return {
    的中: x.的中 || 0,
    射数: x.射数 || 0,
    // 射数が少ないときは率を出さない。3射で100%を「良くなった」と読ませない
    的中率: (x.射数 || 0) >= 率を出す最小射数 ? x.的中率 : null,
  };
}

/**
 * その弓具を使っていた間の成績。
 *
 * 始めはその弓具に変えた日、終わりは次に変えた日の前日。
 * いちばん新しい弓具はいまも使っているので、終わりを置かない。
 *
 * 変えた日そのものは、その弓具の側に入れる。その日から新しい道具で
 * 引いているため。
 *
 * @param {{id:string|number, name?:string, grade?:any, equipments?:Array}} 人
 * @param {Array} 記録たち
 * @param {number} 始め
 * @param {number} 終わり 次に変えるまで。無ければ Infinity
 * @returns {{的中:number, 射数:number, 的中率:number|null}}
 */
function 弓具の期間の成績(人, 記録たち, 始め, 終わり) {
  return 期間の成績(人, 記録たち, 始め, 終わり);
}

/** 2つの期間の的中率の差。どちらかが出せないときは出さない */
function 率の差(前, 後) {
  if (!前 || !後 || 前.的中率 == null || 後.的中率 == null) return null;
  return Number((後.的中率 - 前.的中率).toFixed(1));
}

/**
 * その人の弓具の移り変わりを、新しい順に並べる。
 *
 * 弓具は { id, date, weight, note, kind } の形（kind が無いものは弓力の変更）
 */
/**
 * @typedef {{的中:number, 射数:number, 的中率:number|null}} 成績の形
 * @typedef {{変更:any, 種類:string, 始め:number, 終わり:number,
 *   成績:成績の形, 前の成績:成績の形|null, 前の変更:any, 差:number|null}} 一件の形
 */

/**
 * @param {{id:string|number, equipments?:Array}|null} 人
 * @param {Array} 記録たち
 * @returns {一件の形[]} 新しい順
 */
function 弓具の移り変わり(人, 記録たち) {
  const 弓具 = Array.isArray(人 && 人.equipments) ? 人.equipments : [];
  // 古い順に並べて、隣どうしで期間を切る
  const 並び = 弓具
    .filter((x) => x && 'number' == typeof x.date)
    .slice()
    .sort((a, b) => a.date - b.date);

  /** @type {一件の形[]} */
  const 期間たち = 並び.map((変更, i) => {
    const 始め = 変更.date;
    // 次に変えた日の前日まで。いちばん新しいものは、いまも使っている
    const 終わり = i + 1 < 並び.length ? 並び[i + 1].date - 1 : Infinity;
    return {
      変更,
      種類: 変更.kind || '弓力',
      始め,
      終わり,
      成績: 弓具の期間の成績(人, 記録たち, 始め, 終わり),
      // 前との突き合わせは、全部の期間を出してから入れる（下）
      前の成績: null,
      前の変更: null,
      差: null,
    };
  });

  // 前の弓具との差。いちばん古いものには「前」が無い
  期間たち.forEach((x, i) => {
    x.前の成績 = i > 0 ? 期間たち[i - 1].成績 : null;
    x.前の変更 = i > 0 ? 期間たち[i - 1].変更 : null;
    x.差 = 率の差(x.前の成績, x.成績);
  });

  // 画面には新しい順で出す
  return 期間たち.reverse();
}

/**
 * 画面に出す一言。数字の読み違えを防ぐための添え書き。
 *
 * 「上がった／下がった」だけを出すと、弓具のせいだと読まれる。
 * 射数が足りないときはそう言い、足りていても言い切らない
 */
function 見立ての言葉(一件) {
  if (!一件 || !一件.成績) return '';
  const { 成績, 前の成績, 差 } = 一件;
  // この弓具のあいだの成績。射数が足りなければ率は出さない
  const いま =
    成績.的中率 == null
      ? `この弓具のあいだ ${成績.射数}射（${率を出す最小射数}射を超えると的中率を出します）`
      : `この弓具のあいだ ${成績.的中率}％（${成績.射数}射）`;
  if (!前の成績) return `${いま}。ここから前は、弓具の記録がありません`;
  if (差 == null)
    return `${いま}。前の弓具は${前の成績.射数}射で、比べるには射数が足りません`;
  const 向き = 差 > 0 ? '上がっています' : 差 < 0 ? '下がっています' : '変わっていません';
  return `${いま}。前の弓具は${前の成績.的中率}％（${前の成績.射数}射）で、${向き}が、弓具だけが理由とは限りません`;
}

module.exports = {
  弓具の期間の成績,
  率の差,
  期間の成績,
  弓具の移り変わり,
  見立ての言葉,
  率を出す最小射数,
};
