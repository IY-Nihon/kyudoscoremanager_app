'use strict';

/**
 * ライブのリンクの期限を延ばす（2026-11-26 B3 本人「見本のとおり」）。画面は src/LiveExtend.js。
 *
 * リンク（配った枝）は変えずに、期限だけを今から 12時間／24時間／7日間 に選び直す（期限なしにはできない・短くはできない）。
 * 延ばすのは中継の POST /enchou（kyudo-chukei の src/enchou.mjs）：中継が所属を確かめてから書く。延ばせるのは
 * 団体アカウントと在籍している部員（配った人も同じ道）。退部・卒業した人とリンクで来た部外の人は延ばせない（11/25 ⑤）。
 * 延ばすと、ライブに入っている全員の端末に新しい期限が届く（盤面の 期限。storeShared.js の 期限を控える）。
 */
const 共 = require('./liveShare');

/** 延ばすときに選べる長さ（配るときの選択肢から「期限なし」を除く） */
const 延ばせる選択肢 = 共.期限の選択肢.filter((選) => 選.値 > 0);
/** 下の帯を出す残り（11/26 本人「残り 30 分で下の帯」） */
const 帯を出す残り = 30 * 60 * 1000;

/** その長さで延ばすと今の期限より後になるか（短くはできない） */
const 延ばせる長さか = (持ち, 今の期限, 今 = Date.now()) => 今 + 持ち > (Number(今の期限) || 0);

/** 期限を延ばせる人か（団体アカウントか個人ログイン。リンクで来た部外の人は除く。在籍しているかは中継が確かめる） */
function 延ばせる人か(状態) {
  if (!状態 || 状態.共有の来客) return false;
  return (状態.activeRole === 'group' || 状態.activeRole === 'member') && !!状態.activeGroupId;
}

/** いま入っているライブが、期限つきで配られたものか（延ばす欄・帯を出すか） */
function 期限つきのライブか(状態, 今 = Date.now()) {
  const 期 = 状態 && 状態.いまのライブの期限;
  return !!(状態 && 状態.isLiveActive && 状態.liveSessionName && typeof 期 === 'number' && 期 > 今);
}

/** 下の帯を出すか（期限つきのライブの中・残りが 30 分以下・この期限では閉じていない） */
function 帯を出すか(状態, 閉じた期限, 今 = Date.now()) {
  if (!延ばせる人か(状態) || !期限つきのライブか(状態, 今)) return false;
  const 期 = 状態.いまのライブの期限;
  return 期 - 今 <= 帯を出す残り && 閉じた期限 !== 期;
}

/** 帯の文（残りの分は切り上げ） */
function 帯の文(期限, 今 = Date.now()) {
  const 分 = Math.max(1, Math.ceil((期限 - 今) / 60000));
  return `ライブのリンクはあと${分}分で切れます。続けるときは期限を延ばしてください`;
}

/**
 * 中継の /enchou を呼ぶ。
 * @returns {Promise<{結果: '延ばした', 期限: number} | {結果: string, 文: string}>}
 */
async function 延ばす(団体, 名前, 持ち, 道具 = {}) {
  const 中継 = 道具.中継 || require('./geminiChukei');
  const 古い = { 結果: '古い中継', 文: 'いまは延ばせません。続けるときは、新しくライブを配ってください' };
  if (!中継 || !中継.中継がある()) return 古い;
  let 返り;
  try {
    返り = await 中継.中継へfetch('/enchou', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ 団体, 名前, 持ち }),
    });
  } catch {
    return { 結果: '届かない', 文: '通信できませんでした。電波の良い場所でもう一度お試しください' };
  }
  const 中身 = await Promise.resolve()
    .then(() => 返り.json())
    .catch(() => ({}));
  if (返り.ok && 中身 && 中身.結果 === '延ばした' && typeof 中身.期限 === 'number')
    return { 結果: '延ばした', 期限: 中身.期限 };
  const 断り = (中身 && typeof 中身.error === 'string' && 中身.error) || '';
  if (返り.status === 403)
    return {
      結果: '延ばせない',
      文: 断り || '期限を延ばせるのは、団体のアカウントと在籍しているメンバーだけです',
    };
  if (返り.status === 409) return { 結果: '短い', 文: '今の期限より短くはできません' };
  if (返り.status === 410)
    return { 結果: '切れた', 文: 'リンクの期限が切れています。続けるときは、新しくライブを配ってください' };
  if (返り.status === 429) return { 結果: '待つ', 文: 断り || '少し待ってからお試しください' };
  if (返り.status === 401 && 中身 && 中身.印 === 'appcheck')
    return {
      結果: '届かない',
      文: 'この端末の確かめに失敗しました。ブラウザを新しくして読み込み直してください',
    };
  // 中継が古い（/enchou が無い）・配っていないライブ・鍵が無いとき
  if (返り.status === 404)
    return 断り === 'このライブは配られていません' ? { 結果: '配っていない', 文: 断り } : 古い;
  return { 結果: '届かない', 文: 'いまは延ばせません。少し待ってからお試しください' };
}

module.exports = {
  延ばせる選択肢,
  帯を出す残り,
  延ばせる長さか,
  延ばせる人か,
  期限つきのライブか,
  帯を出すか,
  帯の文,
  延ばす,
};
