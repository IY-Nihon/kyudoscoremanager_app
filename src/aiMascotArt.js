/**
 * AIアシスタントのキャラクターの絵（ドット）。
 * 画面の部品（AIMascot.js）から切り離した、ただの文字の並び。絵を直したときに、
 * 段の幅がずれていないか・弓を握る手が合っているかを node で確かめられるようにするため
 * （test/aiMascotArt.test.js）。
 *
 *   W … 体（白。明るい地の上では青）  R … 鉢巻（赤）  K … 目（濃い色）
 *   N … 袴（紺）  n … 袴のひだと、腰の紐の結び目（明るい紺）
 *   B … 弓（木の色）  S … 弦  . … 何も無い
 *
 * 弓道の装い。白い道着（体）に紺の袴をはき、鉢巻をして、右手で弓を握っている
 * （弓は縦に持ち、弦は体の側）。袴は腰から裾へ広がり、ひだが 2 本入る。足袋は体と同じ色。
 */
'use strict';

/** 体（幅 11）。12 段。上の 6 段が頭、下の 6 段が道着と袴 */
const 体の絵 = [
  '...WWWWW...',
  '..WWWWWWW..',
  '.RRRRRRRRR.',
  '.WWWWWWWWW.',
  '.WWKWWWKWW.',
  '.WWKWWWKWWW', // 右手（腕）を弓の握りまで伸ばす
  '.WWWWWWWWW.', // 道着（胸）
  '.NNNNnNNNN.', // 袴の腰。真ん中の n は紐の結び目
  '.NNnNNNnNN.', // 袴。n はひだ
  'NNNnNNNnNNN', // 裾が広がる
  'NNNnNNNnNNN',
  '..WW...WW..', // 足（足袋）
];
/** 弓（幅 4）。9 段。体の上端にそろえる。握り（手）は 6 段目 */
const 弓の絵 = ['.B..', '.SB.', '.SB.', '.S.B', '.S.B', 'WWWB', '.S.B', '.SB.', '.B..'];

/** 目のある段（0 から数える）。まばたきで、この段だけ閉じる */
const 目の段 = 4;

/** 体と弓を、段ごとにつないで 1 枚の絵にする。弓より下の段は空ける */
const 絵を作る = (目を閉じる) =>
  体の絵.map((行, i) => (目を閉じる && i === 目の段 ? 行.replace(/K/g, 'W') : 行) + (弓の絵[i] || '....'));

/** 開いた目の絵 と 閉じた目（1 段だけ残る細い目）の絵 */
const 開いた絵 = 絵を作る(false);
const 閉じた絵 = 絵を作る(true);

/**
 * 1 段の絵を、同じ記号が横に続くところごとにまとめる。描く図形（View）の数を減らすため
 * （1 マスずつ描くと 1 体で 120 個、まとめると 50 個。答えのたびに 1 体並ぶので、長い会話で効く）。
 * 'NNnNN' → [{ 字: 'N', 始め: 0, 長さ: 2 }, { 字: 'n', 始め: 2, 長さ: 1 }, { 字: 'N', 始め: 3, 長さ: 2 }]
 * '.'（何も無い）は含めない
 * @param {string} 行
 * @returns {Array<{字: string, 始め: number, 長さ: number}>}
 */
const 連なりにする = (行) => {
  const 出 = [];
  let 始め = 0;
  while (始め < 行.length) {
    const 字 = 行[始め];
    let 終わり = 始め + 1;
    while (終わり < 行.length && 行[終わり] === 字) 終わり++;
    if (字 !== '.') 出.push({ 字, 始め, 長さ: 終わり - 始め });
    始め = 終わり;
  }
  return 出;
};
/** 段ごとの連なり。描くたびに作り直さないよう、ここで 1 度だけ作る */
const 開いた連なり = 開いた絵.map(連なりにする);
const 閉じた連なり = 閉じた絵.map(連なりにする);

const 色 = {
  W: '#FFFFFF',
  R: '#FF3B30',
  K: '#1C1C1E',
  B: '#C8874B',
  S: '#E5E5EA',
  N: '#1F2D57',
  n: '#3A4D85',
};

/** 絵の大きさ（マスの数）。幅 15 × 高さ 12 */
const 幅のマス = 開いた絵[0].length;
const 高さのマス = 開いた絵.length;

module.exports = {
  体の絵,
  弓の絵,
  目の段,
  絵を作る,
  開いた絵,
  閉じた絵,
  連なりにする,
  開いた連なり,
  閉じた連なり,
  色,
  幅のマス,
  高さのマス,
};
