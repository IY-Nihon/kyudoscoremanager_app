/**
 * AIアシスタントのキャラクターの絵（ドット）。
 * 画面の部品（AIMascot.js）から切り離した、ただの文字の並び。絵を直したときに、
 * 段の幅がずれていないか・弓を握る手が合っているかを node で確かめられるようにするため
 * （test/aiMascotArt.test.js）。
 *
 *   W … 体（白。明るい地の上では青）  R … 鉢巻（赤）  K … 目（濃い色）
 *   C … 道着の襟（白い体の上では紺、青い体の上では白。置き場で変える）
 *   N … 袴（濃い紺。ほぼ黒）  n … 袴のひだと、腰の紐の結び目（明るい紺）
 *   B … 弓（木の色）  S … 弦  . … 何も無い
 *
 * 弓道の装い。道着（上衣）に袴をはき、鉢巻をして、右手で弓を握っている
 * （弓は縦に持ち、弦は体の側）。
 *
 * ■ 形を決めた理由（作り直しを重ねて決めた。崩さないこと）
 *   ・顔は元のまま（鉢巻と目の間に 1 段）。服だけを着せる。顔の段を詰めると、顔つきが変わる
 *   ・袴は、腰の結び目から裾へ大きく広がる（幅 7 → 11 → 13）。裾は頭（幅 9）よりずっと広い。
 *     細い台形だと、ただの短いスカートに見える。ひだは結び目から扇のように開く。足は袴に隠れる
 *   ・道着は、顔の下に首の段（幅 3）をはさみ、肩（幅 11）から V の襟を 3 段。襟は濃い色でよい。
 *     首の段が顔と襟を切り離す（首が無いと、顔の下の濃い V が、泣き顔や口ひげに見える）
 *   ・袖を広げない（羽のように見える）。胴の色を顔と変えない（顔の下半分が、マスクに見える）
 *   ・13 段。丸いボタンには、整数のマスのまま置く（倍率で縮めると、マスの継ぎ目に線が出る）
 */
'use strict';

/** 体（幅 13）。13 段。上の 6 段が頭、次の 4 段が首と道着、下の 3 段が袴 */
const 体の絵 = [
  '....WWWWW....',
  '...WWWWWWW...',
  '..RRRRRRRRR..',
  '..WWWWWWWWW..',
  '..WWKWWWKWW..',
  '..WWKWWWKWWWW', // 右手（腕）を弓の握りまで伸ばす
  '.....WWW.....', // 首
  '.WWCWWWWWCWW.', // 肩（幅 11）。襟の上端（目の列より 1 マス外）
  '..WWCWWWCWW..', // 襟
  '..WWWCWCWWW..', // 襟
  '...NNNnNNN...', // 袴の腰（幅 7）。真ん中の n は紐の結び目（襟の先）
  '.NNNNnNnNNNN.', // 幅 11。n は、結び目から垂れる紐とひだ
  'NNNNnNNNnNNNN', // 裾（幅 13）
];
/** 弓（幅 3）。9 段。握り（手）は 6 段目（腕の段）。1 段目は空ける（上端が「AI」のバッジに隠れないように） */
const 弓の絵 = ['...', 'B..', 'SB.', 'S.B', 'S.B', 'WWB', 'S.B', 'SB.', 'B..'];

/** 目のある段（0 から数える）。まばたきで、この段だけ閉じる（次の段は細い目として残る） */
const 目の段 = 4;

/** 体と弓を、段ごとにつないで 1 枚の絵にする。弓より下の段は、弓の幅のぶん空ける */
const 絵を作る = (目を閉じる) =>
  体の絵.map(
    (行, i) =>
      (目を閉じる && i === 目の段 ? 行.replace(/K/g, 'W') : 行) + (弓の絵[i] || '.'.repeat(弓の絵[0].length))
  );

/** 開いた目の絵 と 閉じた目（1 段だけ残る細い目）の絵 */
const 開いた絵 = 絵を作る(false);
const 閉じた絵 = 絵を作る(true);

/**
 * 1 段の絵を、同じ記号が横に続くところごとにまとめる。描く図形（View）の数を減らすため
 * （1 マスずつ描くと 1 体で 120 個前後、まとめると半分以下。答えのたびに 1 体並ぶので、長い会話で効く）。
 * 'NNnNN' → [{ 字: 'N', 始め: 0, 長さ: 2 }, { 字: 'n', 始め: 2, 長さ: 1 }, { 字: 'N', 始め: 3, 長さ: 2 }]
 * '.'（何も無い）は含めない
 * @param {string} 行
 * @returns {Array<{字: string, 始め: number, 長さ: number}>}
 */
const 連なりにする = (行) => {
  const 出 = [];
  let 始め = 0;
  while (始め < 行.length) {
    const 字 = 行[始め];
    let 終わり = 始め + 1;
    while (終わり < 行.length && 行[終わり] === 字) 終わり++;
    if (字 !== '.') 出.push({ 字, 始め, 長さ: 終わり - 始め });
    始め = 終わり;
  }
  return 出;
};
/** 段ごとの連なり。描くたびに作り直さないよう、ここで 1 度だけ作る */
const 開いた連なり = 開いた絵.map(連なりにする);
const 閉じた連なり = 閉じた絵.map(連なりにする);

const 色 = {
  W: '#FFFFFF',
  R: '#FF3B30',
  K: '#1C1C1E',
  B: '#C8874B',
  S: '#E5E5EA',
  // 襟。白い体の上の既定は紺。青い体の上では白にする（AIMascot の 襟）
  C: '#141A33',
  N: '#141A33',
  n: '#3B4A7A',
};

/** 絵の大きさ（マスの数）。幅 16 × 高さ 13 */
const 幅のマス = 開いた絵[0].length;
const 高さのマス = 開いた絵.length;

module.exports = {
  体の絵,
  弓の絵,
  目の段,
  絵を作る,
  開いた絵,
  閉じた絵,
  連なりにする,
  開いた連なり,
  閉じた連なり,
  色,
  幅のマス,
  高さのマス,
};
