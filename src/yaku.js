/** 履歴・分析・メンバー・書き出し・AI を自分の分だけにするか（個人ログインで「全員を見る」が無い） */
const 自分の分だけか = (状態) =>
  !!状態 && 状態.activeRole === 'member' && !自分の部品(状態).includes('全員を見る');

/** 確かめの文（役を作るとき）。「この役の人は、…ことができます。…ことはできません。」 */
function 役の文(部品) {
  const 持つ = 形の良い部品(部品);
  const できる = [];
  const できない = [];
  for (const 項 of 部品の一覧) {
    if (持つ.includes(項.鍵)) できる.push(項.文 + (項.合言葉 ? '（管理者の合言葉が要る）' : ''));
    else if (項.無いとき) できる.push(項.無いとき);
    else できない.push(項.文);
  }
  // 「見る」だけはいつも できる に入る（全員か自分か）。付けるも無ければ、見るだけの役
  const 前 = `この役の人は、${できる.join('、')}ことができます。`;
  return できない.length ? `${前}${できない.join('、')}ことはできません。` : 前;
}

/** 札に出す短い説明（役の一覧）。例「全員の記録を見る、記録を付ける」 */
function 役の短い文(部品) {
  const 持つ = 形の良い部品(部品);
  const 見る = 持つ.includes('全員を見る') ? '全員の記録を見る' : '自分の記録を見る';
  const ほか = 部品の一覧.filter((項) => 項.鍵 !== '全員を見る' && 持つ.includes(項.鍵)).map((項) => 項.文);
  return [見る, ...ほか].join('、');
}

/** 役の名の形が足りないときの文。足りていれば '' */
function 役の名の形の文(名, 設定, 自分のid) {
  const 字 = String(名 ?? '').trim();
  if (!字) return '役の名前を入れてください';
  if ([...字].length > 役の名の長さ) return `役の名前は ${役の名の長さ} 字までにしてください`;
  if (役の一覧(設定).some((役) => 役.名 === 字 && 役.id !== 自分のid)) return '同じ名前の役があります';
  return '';
}

