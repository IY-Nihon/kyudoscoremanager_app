/**
 * Module ID: ocrPrompts
 *
 * 画像の読み取りを頼むときの指示文。画面から切り離してあるので、
 * そのまま検査から叩ける（scripts/try-ocr.mjs、test/ocrPrompts.test.js）。
 *
 * 指示文が画面の中に埋まっていたころは、実物の写真で試すたびに画面を
 * 動かす必要があり、正解と突き合わせながら詰められなかった。
 */
'use strict';

const 改 = String.fromCharCode(10);
/** ＼（左上から右下）。文字として直に書くと、隣の引用符を殺してしまう */
const 逆スラッシュ = String.fromCharCode(92);

/**
 * 選んでもらった向きを、指示文に入れる説明にする。
 *
 * 大前がどちらの端かは道場や大会で違う。読み違えると並びが丸ごと逆になり、
 * 直すには全員を動かすことになるので、当てずっぽうにしない。
 *
 * @param {'右から'|'左から'|'左右から'} 向き
 */
function 向きの説明(向き) {
  if ('左右から' === 向き) {
    return [
      '',
      '【並びの向き】',
      '・写真には、向かい合った板（またはグリッド）が左右に2つ写っています。',
      '・左側の板は、左端が大前です。左から右へ読んでください。',
      '・右側の板は、右端が大前です。右から左へ読んでください。',
      '・2つの板は別々のチームです。teams を2つに分けて出力してください。',
      '・左側の板を先に、右側の板をあとに並べてください。',
      '',
      '・右側の板は「右端の人が最初の行」です。ここを取り違えると、その板の並びが',
      '  丸ごと逆になります。出力する前に、右側の板の1行目が、写真のいちばん右の',
      '  列の人になっているか必ず確かめてください。',
    ].join(改);
  }
  if ('左から' === 向き) {
    return [
      '',
      '【並びの向き】',
      '・左端が大前（一的）です。左から右へ、大前→落 の順で読んでください。',
    ].join(改);
  }
  return [
    '',
    '【並びの向き】',
    '・右端が大前（一的）です。右から左へ、大前→落 の順で読んでください。',
  ].join(改);
}

/**
 * ホワイトボードの○×の書き方。
 *
 * 1つのマスに2射ぶんが重ねて書かれる。教わったとおりに書き下す:
 *   1本目を外す → 右上から左下へ線を引く
 *   そのあと2本目を中てる → その上に丸を書く（線の入った丸）
 *   1本目を中てる → 丸を書く
 *   そのあと2本目を外す → その上に左上から右下へ線を引く（線の入った丸）
 *   1本目を中て、2本目も中てる → 丸の内側にもう1つ丸（◎）
 *   1本目を外し、2本目も外す → 2本の線が交わって ×
 *
 * この決まりを知らないと、◎を「1射の当たり」、線の入った丸を「外れ」と
 * 取り違える。的中数が半分になったり、並びがずれたりする。
 */
const 板の書き方 = [
  '',
  '【1つのマスに2射ぶんが入っていることがあります（重要）】',
  'ホワイトボードや大会の記録用紙では、1つのマスに2射ぶんの結果が重ねて書かれます。',
  '書き方の決まりは次のとおりです。',
  '',
  '  1本目を外す → 右上から左下へ線を引く',
  '  そのあと2本目を中てる → その線の上に丸を書く（線の入った丸になる）',
  '  1本目を中てる → 丸を書く',
  '  そのあと2本目を外す → その丸の上に左上から右下へ線を引く（線の入った丸になる）',
  '  1本目も2本目も中てる → 丸の内側にもう1つ丸を書く（◎になる）',
  '  1本目も2本目も外す → 2本の線が交わって × になる',
  '',
  'あなたは「そのマスがどう見えるか」だけを、次の記号で答えてください。',
  '2射ぶんに開くのはこちらで行います。開かないでください。',
  '',
  '  "◎"   … 丸の内側にもう1つ丸',
  '  "○' + 逆スラッシュ + '"  … 丸に「左上から右下」への線が入っている',
  '  "○/"  … 丸に「右上から左下」への線が入っている',
  '  "×"   … 線が2本交わっている（丸は無い）',
  '  "○"   … ただの丸（線も内側の丸も無い）',
  '  "/"   … 線が1本だけ（丸は無い）',
  '  ""    … 何も書かれていない空のマス',
  '',
  '線の向きを取り違えると、中りと外れが入れ替わります。丸に線が入っているマスは、',
  '線がどちらの角から始まっているかを必ず確かめてください。',
  'どうしても見分けられないマスは、当てずっぽうで書かず "" にしてください。',
  '',
  '・薄く書かれたマスがあります。うすい丸の中に、さらに小さな丸が書かれていることが',
  '  よくあります。丸を見つけたら、必ず内側にもう1つ丸があるかを確かめてください',
  '（実物で、薄い ◎ を「ただの丸」と読み違えました）。',
  '・列ごとに答えを使い回さないでください。人によって並びは違います。',
  '  同じ並びが2列以上続いたら、それは見ずに埋めた合図です。もう一度その列を見てください。',
].join(改);

/**
 * 名簿の手がかり。渡さないと、模型は写真の字だけを頼りに書き起こす。
 * 手書きの氏名は誤読の主因で、「三山→大山」「篠田→簑田」のように崩れる。
 *
 * @param {string[]} 部員 名前の一覧
 * @param {string[]} 卒業生 名前の一覧
 */
function 名簿の手がかり(部員, 卒業生) {
  const 現 = (部員 || []).filter(Boolean);
  const 卒 = (卒業生 || []).filter(Boolean);
  if (!現.length && !卒.length) return '';
  const 行 = ['', '【この部の名簿（読み取りの候補）】'];
  if (現.length) 行.push('部員: ' + 現.join('、'));
  if (卒.length) 行.push('卒業生: ' + 卒.join('、'));
  行.push('似た字で迷ったときの手がかりに使ってください。写真の氏名がこの名簿に無くても構いません。');
  行.push(
    '名簿に合わせようとして、読み取れた名前を書き換えたり空欄にしたりしないでください。読めた文字をそのまま書いてください。'
  );
  return 行.join(改);
}

/**
 * 的中記録の指示文。紙の記録表でも、ホワイトボードでも同じものを使う。
 *
 * 紙は「1行が1人・左から1射目」、板は「1列が1人・1マスに2射」と並びが
 * 直交しているが、どちらか一方だけを説明すると、もう一方で総崩れになる。
 * 両方の形を説明して、写真に合うほうを選ばせる。
 *
 * @param {{手がかり?:string, 射数?:number, 枚数?:number, 向き?:string}} 注文
 */
function 記録の指示文(注文) {
  const o = 注文 || {};
  const 手がかり = o.手がかり || '';
  const 射数 = o.射数 || 20;
  const 枚数 = o.枚数 || 1;
  const 向き = o.向き || '右から';

  return `あなたは弓道の「的中記録表」を読み取るOCRアシスタントです。${手がかり}
添付された${枚数}枚の画像は、同じ記録表の続き（1枚目の続きが2枚目...）です。すべてを1つの記録として結合してください。

【表の形は2通りあります。写真を見て、どちらかを判断してください】

(A) 横書きの表（紙に多い）
・1行が1人の射手で、行の先頭付近に氏名が書かれています。
・氏名の横に、1射ごとの結果が横に並んでいます。

(B) 縦書きの表（ホワイトボードや大会の記録用紙に多い）
・1列が1人の射手で、列の下端（または上端）に氏名が書かれています。
・その人の結果は、列を上から下へ読みます。
・氏名の並びの下に「大前」「二的」「落前」「大落」などの立ち位置が書かれていることがあります。これは氏名ではありません。

【立ち位置の札があれば、それに従ってください（いちばん確かな手がかり）】
・「大前」「二的」「三的」「落前」「大落」「落」などの札が書かれているときは、
  左右のどちら側かではなく、その札の順に並べてください。
・順は 大前 → 二的 → 三的 → 落前 → 大落（または落）です。
・札が読めるのに、左右の位置だけで並べ替えることは絶対にしないでください。
・札が無いときだけ、下の【並びの向き】に従ってください。
${向きの説明(向き)}
${板の書き方}

【的中記号の読み取り（横書きの表の場合）】
・的中（当たり）は ○ ◯ 〇 ● などの丸印で書かれます。→ "○" として出力
・外れは × ✕ ✖ ／ ＼ ・ などで書かれます。→ "×" として出力
・まだ引いていない・空欄のマスは "" （空文字列）として出力
・判読できない場合は無理に推測せず "" にしてください。
・大切なのは「位置」です。空欄があっても詰めず、順に位置を保ったまま出力してください。

【読み飛ばすもの】
・「小計」「合計」「計」などの集計列・集計行の数字は、結果ではありません。読み飛ばしてください。
・各射手の上や横に書かれた的中数（12、15 など）も読み飛ばしてください。marks から数え直します。
・表の外側のメモ書き、日付、署名、矢取りの図などは無視してください。

【射数】
・このアプリの設定では1人あたり${射数}射です。
・表に見える射数がこれと違う場合は、写真に見えるとおりの数だけ出力してください（こちらで整えます）。

【立の区切り】
・射手は「立」ごとにまとまっています。ふつうは4人（大前・二的・落前・大落）で1立です。
・立の切れ目には「小計」の列（または行）が入っていることが多く、そこが切れ目の目印になります。
・1立に並ぶ人数を tachiPeople に入れてください（分からなければ 0）。射数ではなく人数です。

【出力形式】
以下のJSON形式のみを出力してください（説明文やMarkdownは一切不要）:
{"teams":[{"name":"チーム名（分かれば。無ければ空文字）","cellStyle":"2射","tachiPeople":4,"rows":[{"name":"氏名","roster":"名簿の表記か null","cells":["◎","×","",...]}]}]}
・cellStyle は、1つのマスに何射ぶん入っているかです。"2射" か "1射" のどちらかを必ず入れてください。
・cells は、その人のマスを「写真で上から下へ」（横書きの表なら左から右へ）、見えるとおりの順で並べてください。
　どちらが1射目かは考えなくて構いません。時間の順に直すのはこちらで行います。見えるとおりの順のまま出してください。
・cells に入れてよいのは、上で決めた記号だけです。数字や「中」「外」などは入れないでください。
・チーム（板・グリッド）が1つだけなら、teams は1つだけにしてください。
・rows は大前から落の順に並べてください（上の【並びの向き】に従ってください）。
・氏名が読み取れない行は name を "" にし、cells はそのまま出力してください。

【名簿との照合（roster）】
・写真の氏名が上の名簿の誰かだと（字の形を見て）確信できるときだけ、roster に名簿の表記をそのまま入れてください。
・名簿に無い人（相手校の選手など）や、似ているだけで確信が持てないときは null にしてください。名簿に無い人が写っていることはよくあります。名簿が無いときも null です。
・name は読めた文字のまま。roster に合わせて name を書き換えないでください。1文字だけの名字（関、瀧、林 など）もそのまま書いてください。
・写真に見える氏名の数だけ rows を作ってください。名簿にある名前でも、写真に無ければ足さないでください。

【マスの数の目安】
・1人あたり${射数}射の設定です。1つのマスが2射ぶんなら、マスは1人あたり${Math.ceil(射数 / 2)}個になるはずです。
・数が合わないときは、見落とした行か、余分に数えた行がないか見直してください。`;
}

/**
 * 立ち順表（名前だけ）の指示文。
 *
 * @param {{手がかり?:string, 枚数?:number, 向き?:string}} 注文
 */
function 立ち順の指示文(注文) {
  const o = 注文 || {};
  const 手がかり = o.手がかり || '';
  const 枚数 = o.枚数 || 1;
  const 向き = o.向き || '右から';
  const 順 =
    '左から' === 向き
      ? '左端（大前）から右へ'
      : '左右から' === 向き
        ? '板ごとに、外側の端（大前）から内側へ'
        : '右端（大前）から左へ';

  return `あなたは弓道の立ち順表（ホワイトボード）を読み取るOCRアシスタントです。${手がかり}
添付された${枚数}枚の画像は、同じ記録表の続き（1枚目の続きが2枚目...）です。すべてを1つの記録として結合してください。

【読み取り対象】
ホワイトボード上の「立ち順表」のグリッド部分のみを対象とします。矢取りの図やメモ書き、磁石の跡など、グリッド外の要素は完全に無視してください。
${向きの説明(向き)}

【グリッド構造】
・縦方向が「立」（壱之立、弐之立、参之立...）、横方向が「的」です。
・各セルにはネームプレート（氏名）が入っています。手書き・印刷どちらもあります。
・プレート内で名前が2行に分かれていても、改行を無視して1つの名前として結合してください。
・空欄（プレートが無い「選択」状態のマス）は空文字列 "" として、位置を保持したまま出力してください（詰めないでください）。
・字がかすれていても、一部だけでも読めたなら、その読めた文字を書いてください。
・1文字だけの名字（関、槙、林 など）もそのまま出力してください。短いからといって飛ばさないでください。
・どうしても読めないときだけ空文字列にしてください。読めないマスに、当てずっぽうの文字や意味のない文字を書くことは絶対にしないでください。空欄のほうがましです。
・撮影が斜めで歪んでいる場合は、行と列の対応関係を論理的に解釈してください。

【出力形式】
以下のJSON形式のみを出力してください（説明文やMarkdownは一切不要）:
{"tachi":[{"seats":["一的の名前","二的の名前","...","御落の名前"]},{"seats":[...]}]}
seatsは各立ちについて、${順}の順で、グリッドに見える通りの人数分を配列にしてください。立ちごとに人数が異なっていても構いません。`;
}

module.exports = { 記録の指示文, 立ち順の指示文, 名簿の手がかり, 向きの説明, 板の書き方 };
