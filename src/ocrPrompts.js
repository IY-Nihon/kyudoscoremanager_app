/**
 * 画像の読み取りを頼むときの指示文。画面から切り離してあるので、
 * そのまま検査から叩ける（scripts/try-ocr.mjs、test/ocrKatachiShijibun.test.js）。
 *
 * 指示文が画面の中に埋まっていたころは、実物の写真で試すたびに画面を
 * 動かす必要があり、正解と突き合わせながら詰められなかった。
 */
/* eslint-disable no-irregular-whitespace -- 指示文の字下げに全角空白を使う（Gemini に送る中身なので変えない） */
'use strict';

const 改 = String.fromCharCode(10);
/** ＼（左上から右下）。文字として直に書くと、隣の引用符を殺してしまう */
const 逆スラッシュ = String.fromCharCode(92);

/**
 * 選んでもらった向きを、指示文に入れる説明にする。
 *
 * 大前がどちらの端かは道場や大会で違う。読み違えると並びが丸ごと逆になり、
 * 直すには全員を動かすことになるので、当てずっぽうにしない。
 *
 * @param {'右から'|'左から'|'左右から'} 向き
 */
function 向きの説明(向き) {
  if (向き === '左右から') {
    return [
      '',
      '【並びの向き】',
      '・写真には、向かい合った板（またはグリッド）が左右に2つ写っています。',
      '・左側の板は、左端が大前です。左から右へ読んでください。',
      '・右側の板は、右端が大前です。右から左へ読んでください。',
      '・2つの板は別々のチームです。teams を2つに分けて出力してください。',
      '・左側の板を先に、右側の板をあとに並べてください。',
      '',
      '・右側の板は「右端の人が最初の行」です。ここを取り違えると、その板の並びが',
      '  丸ごと逆になります。出力する前に、右側の板の1行目が、写真のいちばん右の',
      '  列の人になっているか必ず確かめてください。',
    ].join(改);
  }
  // 板が2枚以上のときの teams の順は、写真の左の板から。端末は板を左から順に読むので、
  // 順が違うと右の板の○×が左の板の名前に付く（右端が大前で、相手校の板 2 枚で実際に起きた）
  if (向き === '左から') {
    return [
      '',
      '【並びの向き】',
      '・左端が大前です。左から右へ、大前→落 の順で読んでください。',
      '・板が2枚以上写っているときは、それぞれの板で左端が大前です。teams は写真の左の板から順に並べてください。',
    ].join(改);
  }
  return [
    '',
    '【並びの向き】',
    '・右端が大前です。右から左へ、大前→落 の順で読んでください。',
    '・板が2枚以上写っているときは、それぞれの板で右端が大前です。teams は写真の左の板から順に並べてください（読む向きとは別です）。',
  ].join(改);
}

/**
 * ホワイトボードの○×の書き方。
 *
 * 1つのマスに2射ぶんが重ねて書かれる。教わったとおりに書き下す:
 *   1本目を外す → 右上から左下へ線を引く
 *   そのあと2本目を中てる → その上に丸を書く（線の入った丸）
 *   1本目を中てる → 丸を書く
 *   そのあと2本目を外す → その上に左上から右下へ線を引く（線の入った丸）
 *   1本目を中て、2本目も中てる → 丸の内側にもう1つ丸（◎）
 *   1本目を外し、2本目も外す → 2本の線が交わって ×
 *
 * この決まりを知らないと、◎を「1射の当たり」、線の入った丸を「外れ」と
 * 取り違える。的中数が半分になったり、並びがずれたりする。
 */
const 板の書き方 = [
  '',
  '【1つのマスに2射ぶんが入っていることがあります（重要）】',
  'ホワイトボードや大会の記録用紙では、1つのマスに2射ぶんの結果が重ねて書かれます。',
  '書き方の決まりは次のとおりです。',
  '',
  '  1本目を外す → 右上から左下へ線を引く',
  '  そのあと2本目を中てる → その線の上に丸を書く（線の入った丸になる）',
  '  1本目を中てる → 丸を書く',
  '  そのあと2本目を外す → その丸の上に左上から右下へ線を引く（線の入った丸になる）',
  '  1本目も2本目も中てる → 丸の内側にもう1つ丸を書く（◎になる）',
  '  1本目も2本目も外す → 2本の線が交わって × になる',
  '',
  'あなたは「そのマスがどう見えるか」だけを、次の記号で答えてください。',
  '2射ぶんに開くのはこちらで行います。開かないでください。',
  '',
  '  "◎"   … 丸の内側にもう1つ丸',
  '  "○' + 逆スラッシュ + '"  … 丸に「左上から右下」への線が入っている',
  '  "○/"  … 丸に「右上から左下」への線が入っている',
  '  "×"   … 線が2本交わっている（丸は無い）',
  '  "○"   … ただの丸（線も内側の丸も無い）',
  '  "/"   … 線が1本だけ（丸は無い）',
  '  ""    … 何も書かれていない空のマス',
  '',
  '線の向きを取り違えると、中りと外れが入れ替わります。丸に線が入っているマスは、',
  '線がどちらの角から始まっているかを必ず確かめてください。',
  'どうしても見分けられないマスは、当てずっぽうで書かず "" にしてください。',
  '',
  '・薄く書かれたマスがあります。うすい丸の中に、さらに小さな丸が書かれていることが',
  '  よくあります。丸を見つけたら、必ず内側にもう1つ丸があるかを確かめてください',
  '（実物で、薄い ◎ を「ただの丸」と読み違えました）。',
  '・列ごとに答えを使い回さないでください。人によって並びは違います。',
  '  同じ並びが2列以上続いたら、それは見ずに埋めた合図です。もう一度その列を見てください。',
].join(改);

/**
 * 名簿の手がかり。渡さないと、模型は写真の字だけを頼りに書き起こす。
 * 手書きの氏名は誤読の主因で、「三山→大山」「篠田→簑田」のように崩れる。
 *
 * @param {string[]} 部員 名前の一覧
 * @param {string[]} 卒業生 名前の一覧
 */
function 名簿の手がかり(部員, 卒業生) {
  const 現 = (部員 || []).filter(Boolean);
  const 卒 = (卒業生 || []).filter(Boolean);
  if (!現.length && !卒.length) return '';
  const 行 = ['', '【この部の名簿（読み取りの候補）】'];
  if (現.length) 行.push('部員: ' + 現.join('、'));
  if (卒.length) 行.push('卒業生: ' + 卒.join('、'));
  行.push('似た字で迷ったときの手がかりに使ってください。写真の氏名がこの名簿に無くても構いません。');
  行.push(
    '名簿に合わせようとして、読み取れた名前を書き換えたり空欄にしたりしないでください。読めた文字をそのまま書いてください。'
  );
  return 行.join(改);
}

/**
 * 的中記録の指示文。紙の記録表でも、ホワイトボードでも同じものを使う。
 *
 * 紙は「1行が1人・左から1射目」、板は「1列が1人・1マスに2射」と並びが
 * 直交しているが、どちらか一方だけを説明すると、もう一方で総崩れになる。
 * 両方の形を説明して、写真に合うほうを選ばせる。
 *
 * @param {{手がかり?:string, 射数?:number, 枚数?:number, 向き?:string}} 注文
 */
function 記録の指示文(注文) {
  const o = 注文 || {};
  const 手がかり = o.手がかり || '';
  const 枚数 = o.枚数 || 1;
  const 向き = o.向き || '右から';
  // 端末が写真から数えた、板ごとの射手の列の数（左の板から順）。Gemini が名札の読めない列を
  // 落としたり（4列を3行にした）、2枚の板を1つにまとめたりしたときに、もう一度だけ
  // これを添えて読み直す。人数が合わないと端末の○×を使えず、Gemini の読み（線の向きが
  // 当たらない）のままになる
  const 列の数たち = Array.isArray(o.列の数たち) && o.列の数たち.length ? o.列の数たち : null;
  // 板の数だけ分かっているとき（板が2つ（外側が大前）を選んだのに teams が1つで返ったとき）
  const 板の数 = 列の数たち ? 列の数たち.length : Number(o.板の数) > 1 ? Number(o.板の数) : 0;
  const 列の数の指示 = 列の数たち
    ? `
【板ごとの人数（写真を機械で数えたもの。必ずこれに合わせてください）】
・この写真には板（teams）が ${列の数たち.length} つあり、左の板から順に ${列の数たち.map((n, i) => `${i + 1}つ目の板は ${n} 人`).join('、')} の列があります。
・名札が無い・読めない・空の列も、その板の人数に含まれています。読めない列は name を "" にして、必ず人数ぶんの rows を出してください。
・teams の数も ${列の数たち.length} つにしてください。板をまとめたり分けたりしないでください。
`
    : 板の数
      ? `
【板の数（必ずこれに合わせてください）】
・この写真には板が ${板の数} 枚（左右に並んで）写っています。teams は必ず ${板の数} つにし、板ごとに rows を分けてください。1つにまとめないでください。
・名札が無い・読めない・空の列も、印のある列は rows に含め、name を "" にしてください。
`
      : '';

  return `あなたは弓道の「的中記録表」を読み取るOCRアシスタントです。${手がかり}
添付された${枚数}枚の画像は、同じ記録表の続き（1枚目の続きが2枚目...）です。すべてを1つの記録として結合してください。

【表の形は2通りあります。写真を見て、どちらかを判断してください】

(A) 横書きの表（紙に多い）
・1行が1人の射手で、行の先頭付近に氏名が書かれています。
・氏名の横に、1射ごとの結果が横に並んでいます。

(B) 縦書きの表（ホワイトボードや大会の記録用紙に多い）
・1列が1人の射手で、列の下端（または上端）に氏名が書かれています。
・その人の結果は、列を上から下へ読みます。
・氏名の並びの下に「大前」「二的」「中」「落前」「落」などの立ち位置が書かれていることがあります。これは氏名ではありません。

【立ち位置の札があれば、それに従ってください（いちばん確かな手がかり）】
・「大前」「二的」「中」「落前」「落」などの札が書かれているときは、
  左右のどちら側かではなく、その札の順に並べてください。
・順は、4人の立ちなら 大前 → 二的 → 落前 → 落、5人の立ちなら 大前 → 二的 → 中 → 落前 → 落 です。
・札が読めるのに、左右の位置だけで並べ替えることは絶対にしないでください。
・札が無いときだけ、下の【並びの向き】に従ってください。
${向きの説明(向き)}
${板の書き方}

【的中記号の読み取り（横書きの表の場合）】
・的中（当たり）は ○ ◯ 〇 ● などの丸印で書かれます。→ "○" として出力
・外れは × ✕ ✖ ／ ＼ ・ などで書かれます。→ "×" として出力
・まだ引いていない・空欄のマスは "" （空文字列）として出力
・判読できない場合は無理に推測せず "" にしてください。
・大切なのは「位置」です。空欄があっても詰めず、順に位置を保ったまま出力してください。

【読み飛ばすもの】
・「小計」「合計」「計」などの集計列・集計行の数字は、結果ではありません。読み飛ばしてください。
・各射手の上や横に書かれた的中数（12、15 など）も読み飛ばしてください。marks から数え直します。
・表の外側のメモ書き、署名、矢取りの図などは無視してください（日付は下の date にだけ入れてください）。

${列の数の指示}
【マスの数】
・cells の数は、写真の表に見えるマスの数そのものにしてください。設定の射数に合わせて増やしたり減らしたりしないでください（射数はこちらで写真に合わせます）。
・空のマスも "" として数に入れ、位置を保ってください。
・あわせて、その表の○×の範囲が太い横線（縦書きの表なら太い縦線）で何個の帯（立）に区切られているか（bands）と、1つの帯の中に1人あたりマスがいくつ並んでいるか（marks_per_band。ふつう1か2）を数えてください。区切りの線が無い表や分からないときは 0 にしてください。

【立の区切り】
・射手は「立」ごとにまとまっています。ふつうは4人（大前・二的・落前・落）で1立です。
・立の切れ目には「小計」の列（または行）が入っていることが多く、そこが切れ目の目印になります。
・1立に並ぶ人数を tachiPeople に入れてください（分からなければ 0）。射数ではなく人数です。

【出力形式】
以下のJSON形式のみを出力してください（説明文やMarkdownは一切不要）:
{"teams":[{"name":"チーム名（分かれば。無ければ空文字）","date":"4/6","cellStyle":"2射","layout":"縦","tachiPeople":4,"omae":"右","bands":5,"marks_per_band":2,"rows":[{"name":"氏名","roster":"名簿の表記か null","x":512,"cells":["◎","×","",...]}]}]}
・cellStyle は、1つのマスに何射ぶん入っているかです。"2射" か "1射" のどちらかを必ず入れてください。
・layout は表の形です。(B) の縦書きの表（1列が1人）なら "縦"、(A) の横書きの表（1行が1人）なら "横" を必ず入れてください。縦の表は下のマスが1射目、横の表は左のマスが1射目として、こちらで時間の順に直します。
・cells は、その人のマスを「写真で上から下へ」（横書きの表なら左から右へ）、見えるとおりの順で並べてください。
　どちらが1射目かは考えなくて構いません。時間の順に直すのはこちらで行います。見えるとおりの順のまま出してください。
・cells に入れてよいのは、上で決めた記号だけです。数字や「中」「外」などは入れないでください。
・チーム（板・グリッド）が1つだけなら、teams は1つだけにしてください。
・date には、その表（組）の近くに書かれた日付を「月/日」の形で入れてください（例 "4/6"）。書かれていなければ "" にしてください。
・1枚の写真に、日付の違う表（組）が並んでいるとき（ノートの見開きなど）は、日付ごとに teams を分け、写真の左の組から順に並べてください。
・rows は大前から落の順に並べてください（上の【並びの向き】に従ってください）。
・omae は、その板（チーム）で大前が写真のどちらの端かです。"右" か "左" を入れてください。
　板に「大前」「落」などの札や字が書いてあればそれで決め（札が指示と食い違うときは札を優先）、
　無ければ上の【並びの向き】のとおりにしてください。rows の順（大前から）と必ず合わせてください。
・氏名が読み取れない行は name を "" にし、cells はそのまま出力してください。
・x は、その人の列（縦書きの表）の真ん中の横の位置です。写真の左端を 0、右端を 1000 とした整数で入れてください。横書きの表なら行の真ん中の縦の位置（上端 0・下端 1000）です。

【名簿との照合（roster）】
・写真の氏名が上の名簿の誰かだと（字の形を見て）確信できるときだけ、roster に名簿の表記をそのまま入れてください。
・名簿に無い人（相手校の選手など）や、似ているだけで確信が持てないときは null にしてください。名簿に無い人が写っていることはよくあります。名簿が無いときも null です。
・name は読めた文字のまま。roster に合わせて name を書き換えないでください。1文字だけの名字（関、森、林 など）もそのまま書いてください。
・写真に見える氏名の数だけ rows を作ってください。名簿にある名前でも、写真に無ければ足さないでください。

【マスの数の確かめ】
・同じ表の人は、みな同じ数のマスを持っています。人によって cells の数が違ったら、見落とした行か余分に数えた行がないか見直してください。`;
}

/**
 * 立ち順表（名前だけ）の指示文。
 *
 * @param {{手がかり?:string, 枚数?:number, 向き?:string}} 注文
 */
function 立ち順の指示文(注文) {
  const o = 注文 || {};
  const 手がかり = o.手がかり || '';
  const 枚数 = o.枚数 || 1;
  const 向き = o.向き || '右から';
  const 順 =
    向き === '左から'
      ? '左端（大前）から右へ'
      : 向き === '左右から'
        ? '板ごとに、外側の端（大前）から内側へ'
        : '右端（大前）から左へ';

  return `あなたは弓道の立ち順表（ホワイトボード）を読み取るOCRアシスタントです。${手がかり}
添付された${枚数}枚の画像は、同じ記録表の続き（1枚目の続きが2枚目...）です。すべてを1つの記録として結合してください。

【読み取り対象】
ホワイトボード上の「立ち順表」のグリッド部分のみを対象とします。矢取りの図やメモ書き、磁石の跡など、グリッド外の要素は完全に無視してください。
${向きの説明(向き)}

【グリッド構造】
・縦方向が「立」（壱之立、弐之立、参之立...）、横方向が「的」です。
・各セルにはネームプレート（氏名）が入っています。手書き・印刷どちらもあります。
・プレート内で名前が2行に分かれていても、改行を無視して1つの名前として結合してください。
・空欄（プレートが無い「選択」状態のマス）は空文字列 "" として、位置を保持したまま出力してください（詰めないでください）。
・字がかすれていても、一部だけでも読めたなら、その読めた文字を書いてください。
・1文字だけの名字（関、槙、林 など）もそのまま出力してください。短いからといって飛ばさないでください。
・どうしても読めないときだけ空文字列にしてください。読めないマスに、当てずっぽうの文字や意味のない文字を書くことは絶対にしないでください。空欄のほうがましです。
・撮影が斜めで歪んでいる場合は、行と列の対応関係を論理的に解釈してください。
・格子が無く、名札が横一列に並んでいるだけの板もあります。その場合、名札と名札の間に、名札の幅の半分以上の空きがあるところは立の区切りです。空きで分かれたまとまりを、それぞれ別の立として出してください（空きの無い一続きの並びは1つの立です）。「壱」「弐」「参」「壱之立」のような立の番号の札や、「A立」「B立」「男子選手立」「女子選手立」「控え」のような組や区分の札は名前ではないので、seats に入れないでください。立の番号の札が名札の並びの間にあるところは、そこから次の立が始まる区切りです（空きが無くても分けてください）。組や区分の札が名札の並びの間に挟まっているところは、区切りではなく同じ立の続きとして扱ってください。
・立の番号の札（「壱」「弐」「参」「四」など）は、どの組の大前の端（並びの始まりの側）に付いているかを見て、その組の fuda に札の字を入れてください。札の付いていない組の fuda は "" です。札は、空きで分かれた組のすぐ大前の側の隣にあります。1枚の札のあとに、札の無い組が続くことがあります（そのまま札の無い組として出してください。立にまとめるのは後でします）。
・板が上下の段に分かれているときは、row に段の番号（いちばん上の段が1、その下が2…）を入れてください。1段だけなら全部 1 です。組は、段ごとに大前の側から順に、上の段から出してください。
・紙の立順表で「前立」「後立」のように分かれているときは、それぞれを別の組として、写っている人を全員出してください（fuda は ""）。
・写真が2枚以上のときは、写真ごとに別の組にし（別の写真の人を1つの組にまとめない）、1枚目の写真の組から順に出してください。

【出力形式】
以下のJSON形式のみを出力してください（説明文やMarkdownは一切不要）:
{"tachi":[{"fuda":"壱","row":1,"seats":["大前の名前","二的の名前","...","落の名前"]},{"fuda":"","row":1,"seats":[...]}]}
tachi の1つは、空きで分かれた組1つです。
seatsは各立ちについて、${順}の順で、グリッドに見える通りの人数分を配列にしてください。立ちごとに人数が異なっていても構いません。`;
}

/**
 * 板ごとの「○×のマスの範囲」の箱と、段の数の手がかり（帯の数×帯の中の印の数）を返させる指示文。
 *
 * 印がマスいっぱいで隣と触れ合う板（相手校の板）は、端末がかたまりから格子を立てられない。
 * 範囲だけを Gemini に出させ（9/13 の相手校の板 2 枚で 1% ほどの精度だった）、
 * 中を人数×段数に等分して読む（scripts/ocr-cells/kiridasu.mjs 箱で格子）。
 * 端末の読み取りが立たなかったときにだけ、2 度目の呼び出しで使う。
 *
 * @param {{板の数:number}} 注文
 */
function 板の箱の指示文(注文) {
  const 板の数 = Math.max(1, Number(注文 && 注文.板の数) || 1);
  return (
    'この写真には弓道の的中記録の板が写っています。' +
    `板は ${板の数} 枚です（左から順に）。` +
    '板ごとに、○×の印が書かれたマスの領域（射手の列だけ。合計・計・小計の列、大学名や題の列、名前の欄、上端の的中数の数字は含めない）の外接矩形を返してください。\n' +
    // 段の数は Gemini に直接数えさせると 4・5・16・20 と揺れた（印が 10 段並ぶ板で）。
    // 太い横線で区切られた帯の数と、帯の中の印の数（1 か 2）なら 5 回とも合った
    'あわせて、その領域が太い横線で何個の帯（立）に区切られているか（bands）と、' +
    '1つの帯の中に1人あたり印（○・◎・×・丸に線）が縦に何個並んでいるか（marks_per_band。ふつう1か2）を数えてください。\n' +
    'その領域に入っている射手の列の数（people）も数えてください。\n' +
    'JSON のみ: {"boards":[{"box_2d":[ymin,xmin,ymax,xmax],"people":射手の列の数,"bands":帯の数,"marks_per_band":帯の中の印の数}]}\n' +
    'box_2d は画像全体を 0〜1000 に正規化した座標。boards は左の板から順に、' +
    `必ず ${板の数} 個返してください。`
  );
}

/**
 * 記録表の「形」だけを読ませる指示文（○× は書かせない）。○× は端末の網で読む。
 *
 * 2026-10-14：○× を書かせないと、ノートで答えが 2100 → 800 トークン・考える量が半分以下になり、
 * 17 人のノートの組の分け方も 4 回とも正しかった（○× ありは 3.8 で 2 組を 1 つにまとめた）。
 * 浮いた分で、Gemini でしか読めないもの（名前・日付）と、端末が頼っている形（人数・板の分け目・列の位置）を強める。
 * これまでの読み違い：名札の無い列を落とす／列の x を等間隔に詰めて名前が 1 人ずつずれる（10/13 のノート）／
 * 8+8 の板を 1 つにまとめる・1 枚の板を 4+4 に割る（10/14 の試し）。
 *
 * @param {{手がかり?:string, 枚数?:number, 向き?:string, 列の数たち?:number[], 板の数?:number}} 注文
 */
function 記録の形の指示文(注文) {
  const o = 注文 || {};
  const 手がかり = o.手がかり || '';
  const 枚数 = o.枚数 || 1;
  const 向き = o.向き || '右から';
  const 列の数たち = Array.isArray(o.列の数たち) && o.列の数たち.length ? o.列の数たち : null;
  const 板の数 = 列の数たち ? 列の数たち.length : Number(o.板の数) > 1 ? Number(o.板の数) : 0;
  const 決まった人数 = 列の数たち
    ? `
【板ごとの人数（写真を機械で数えたもの。必ずこれに合わせてください）】
・板（teams）は ${列の数たち.length} つで、左の板から順に ${列の数たち.map((n, i) => `${i + 1}つ目は ${n} 人`).join('、')} です。名札の無い列も人数に入っています。
`
    : 板の数
      ? `
【板の数（必ずこれに合わせてください）】
・この写真には板が ${板の数} 枚写っています。teams は必ず ${板の数} つにしてください。
`
      : '';
  return `あなたは弓道の「的中記録表」の写真から、表の形と名前を読み取るアシスタントです。${手がかり}
添付された${枚数}枚の画像は、同じ記録表の続きです（1枚目の続きが2枚目...）。すべてを1つの記録として結合してください。

【この読み取りの役割分担（大事）】
・○や×などの的中の印は、こちらの機械が写真から読みます。あなたは印を書き写さないでください。
・あなたには、機械では読めないもの・機械が頼りにするものを、時間をかけて正確に読んでもらいます。
  1. 氏名（手書きの字）  2. 日付  3. 人数と、板（組）の分け方  4. 一人ひとりの列の位置  5. マスの数と区切り
・印を読まない分、上の 1〜5 を一つずつ確かめてから答えてください。

【表の形は2通りあります】
(A) 横書きの表（紙に多い）… 1行が1人。行の先頭付近に氏名。
(B) 縦書きの表（ホワイトボード・大会の記録用紙・手書きのノートに多い）… 1列が1人。列の下端（または上端）に氏名。
・氏名の並びの下に「大前」「二的」「中」「落前」「落」などの立ち位置の札があることがあります。札は氏名ではありません。

【立ち位置の札があれば、それに従ってください】
・札があるときは、左右の位置ではなく札の順（大前 → 二的 →（中）→ 落前 → 落）に並べてください。
・札が無いときだけ、下の【並びの向き】に従ってください。
${向きの説明(向き)}

【人数の数え方（いちばん大事）】
・人数は、名前の数ではなく「印が書かれた列（横書きなら行）の数」で数えてください。
・名札が無い・名前が読めない・途中から空になっている列も、印が1つでもあれば1人です。name を "" にして必ず rows に入れてください。
・逆に、次の列は人ではありません。rows に入れないでください：「小計」「計」「合計」「総計」の列、的中数だけが書かれた列、立ち位置の札だけの列、何も書かれていない列。
・数え終わったら、左端から右端まで指でなぞるように、もう一度数え直してください。

【板（組）の分け方】
・枠（ホワイトボードの縁、表の太い外枠）が別なら、別の板です。teams を分けてください。1つの枠の中は、途中に「小計」の列があっても1つの板です。割らないでください。
・左右に2枚の板が並んでいるとき、2枚を1つにまとめないでください。板ごとに teams を作り、写真の左の板から順に並べてください。
・手書きのノートの見開きで、日付の違う組が並んでいるときは、日付ごとに teams を分けてください（写真の左の組から順に）。
・x0・x1 には、その板（組）の印の範囲の左端と右端を、写真の左端 0〜右端 1000 の整数で入れてください。

【列の位置（x）の測り方】
・x は、その人の列の真ん中の横の位置です。写真の左端を 0、右端を 1000 とした整数です（横書きの表なら行の真ん中の縦の位置。上端 0・下端 1000）。
・等間隔に割り振らないでください。一人ずつ、写真の中でその列の真ん中がどこにあるかを見て決めてください。
  板と板の間・組と組の間には空きがあります。その空きも x に表れるはずです。
・同じ板の中で x は大前から落まで一方向に並びます。隣どうしの x が入れ替わっていないか確かめてください。

【名前の読み方】
・名前は、列の下端（または上端）の名札・書き込みから、読めた字のまま書いてください。縦書きの名前は上から下へ読みます。
・名札の色や、名前の横の小さな字（ふりがな・学年）は名前に入れないでください。

【日付】
・date には、その表（組）の近くに書かれた日付を「月/日」の形で入れてください（例 "4/6"）。曜日は入れません。書かれていなければ "" にしてください。
・ノートでは、組の横や上に縦書きで「3月7日(木)」のように書かれていることがあります。必ず探してください。

【マスの数と区切り】
・ncells には、その人のマスの数を入れてください（空のマスも数えます）。同じ板の人は、ふつう同じ数です。
・cellStyle は、1つのマスに何射ぶん入るかです。ホワイトボードや大会の用紙のように、1つのマスに丸と線が重なって書かれる（◎・丸に線が見える）なら "2射"、1マスに1つの印なら "1射" です。
・bands は、印の範囲が太い線で何個の帯（立）に区切られているか、marks_per_band は1つの帯の中に1人あたりマスがいくつ並ぶか（ふつう1か2。ノートは4）です。分からなければ 0。
・tachiPeople は1立に並ぶ人数です（分からなければ 0）。
${決まった人数}
【出力形式】
以下のJSON形式のみを出力してください（説明文やMarkdownは一切不要）:
{"teams":[{"name":"チーム名（無ければ空文字）","date":"4/6","cellStyle":"2射","layout":"縦","tachiPeople":4,"omae":"右","bands":5,"marks_per_band":2,"x0":120,"x1":480,"rows":[{"name":"氏名","roster":"名簿の表記か null","x":150,"ncells":10}]}]}
・cells は出力しないでください。
・layout は "縦"（1列が1人）か "横"（1行が1人）。omae は、その板で大前が写真のどちらの端か（"右" か "左"）。rows の順（大前から）と必ず合わせてください。
・チーム（板）が1つだけなら、teams は1つだけにしてください。

【名簿との照合（roster）】
・写真の氏名が上の名簿の誰かだと（字の形を見て）確信できるときだけ、roster に名簿の表記をそのまま入れてください。名簿に無い人（相手校の選手など）や、確信が持てないときは null です。
・name は読めた文字のまま。roster に合わせて書き換えないでください。名簿にある名前でも、写真に無ければ足さないでください。

【出す前の確かめ】
1. 板ごとに、印の書かれた列の数と rows の数が同じか。名札の無い列を落としていないか。計の列を人にしていないか。
2. x が等間隔の作り物になっていないか。板と板・組と組の間の空きが x に出ているか。
3. 2枚の板を1つにしていないか。1枚の板を2つに割っていないか。
4. 日付を探したか。`;
}

