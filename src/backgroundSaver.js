/**
 * Module ID: backgroundSaver
 *
 * 裏に回っているあいだ、Realtime Database との接続を休ませる。
 *
 * ■ なぜ off() ではなく goOffline() なのか
 * 無料枠（Spark）の同時接続の上限は100。ここで数えているのは「接続」であって
 * 「見張り（listener）」ではない。off() で見張りを外しても、つないでいる線は
 * そのまま残るので、接続数は1台ぶんも減らない。減らすには線そのものを
 * 切る（goOffline）必要がある。
 *
 * 共有リンクで観戦者が増えると、その100に近づく。画面を消したまま鞄に入って
 * いる端末が枠を握り続けるのは、いちばんもったいない。
 *
 * ■ すぐには切らない
 * 記録係が数秒だけ他のアプリを見て戻る、という使い方は普通にある。
 * そこで切ると、在席から消えて相手に「落ちた」と見え、戻るまで○×も
 * 送られない。裏に回ってしばらく経ってから切る。
 *
 * 切っているあいだの書き込みは Realtime Database が溜めておき、つなぎ直した
 * ときに送られる。だから○×が失われることはない。
 *
 * 時計も接続も外から渡すので、そのまま検査できる（test/backgroundSaver.test.js）。
 */
'use strict';

/**
 * 裏に回ってから接続を切るまでの間（ミリ秒）。
 *
 * 短くすると、少し他のアプリを見ただけで在席から消える。
 * 長くすると、鞄の中の端末が接続の枠を握り続ける。
 */
const 休むまでの間 = 60000;

/**
 * 見張りを作る。
 *
 * 渡すもの：
 *   切る／つなぐ … Realtime Database の goOffline / goOnline
 *   待つ／やめる … setTimeout / clearTimeout（検査では作り物を渡す）
 */
function 見張りを作る(手立て) {
  const { 切る, つなぐ } = 手立て || {};
  const 待つ = (手立て && 手立て.待つ) || ((f, ms) => setTimeout(f, ms));
  const やめる = (手立て && 手立て.やめる) || ((t) => clearTimeout(t));
  const 間 = (手立て && 手立て.休むまでの間) || 休むまでの間;

  let 予約 = null;
  let 休んでいる = !1;

  const 取り消す = () => {
    (予約 && やめる(予約), (予約 = null));
  };

  return {
    /** 裏に回った。すぐには切らず、しばらく経ってから切る */
    裏に回った() {
      if (休んでいる || 予約) return;
      予約 = 待つ(() => {
        ((予約 = null), (休んでいる = !0));
        try {
          切る && 切る();
        } catch (t) {
          // 切れなくても、画面の動きには関わらせない
          休んでいる = !1;
        }
      }, 間);
    },

    /** 表に戻った。切っていればつなぎ直す */
    表に戻った() {
      取り消す();
      if (!休んでいる) return;
      休んでいる = !1;
      try {
        つなぐ && つなぐ();
      } catch (t) {
        /* つなぎ直せなくても、次に戻ったときにまた試す */
      }
    },

    /** 見張りをやめる。切っていたらつなぎ直してから */
    片付ける() {
      (取り消す(), this.表に戻った());
    },

    /** いま休んでいるか（検査と画面の表示に使う） */
    休んでいるか: () => 休んでいる,
  };
}

module.exports = { 見張りを作る, 休むまでの間 };
