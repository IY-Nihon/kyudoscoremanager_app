/**
 * 並べる順の数。在籍の学年は若い順、その他（値が無い人も）は後ろ、卒業生・退部した人はいちばん後ろ。
 * 「(甲, 乙) => 学年の順(甲) - 学年の順(乙)」のように使う
 */
function 学年の順(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 状態 = 在籍の状態(人, 決);
  if (状態 === 在籍.卒業) return 1000;
  if (状態 === 在籍.退部) return 1001;
  if (その他か(人, 決)) return 99;
  return 学年の値(人, 決);
}

/**
 * 種類を変えると学年が外れる人（新しい種類に無い学年の現役。6 年制から高校へ変えたときの 4〜6 年など）。
 * 学年の無い団体へ変えるときは誰も外さない（学年は出さないだけ。学校に戻せば元の学年が出る）
 */
function 学年がはみ出す人(部員たち, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (決.学年なし) return [];
  return (部員たち || []).filter(
    (部員) => 現役か(部員, 決) && その他か(部員, 決) && 決.その他の学年 !== 学年の値(部員, 決)
  );
}

/**
 * 人を選ぶ窓（記録の射手・写真の読み取りの名前）の組。学校の部は学年ごと（若い順、その他/ゲストは後ろ）、
 * 学年の無い団体は区分ごと（区分が無ければ全員を 1 組）。組の中の人の並びは渡した順のまま。
 * 返すのは [{ 鍵, 題, 人たち }]（鍵は組の開け閉めを覚える字）
 */
function 選ぶ組(人たち, 決まり, 区分たち) {
  const 決 = 決まりを使う(決まり);
  const 全員 = (人たち || []).filter(Boolean);
  if (決.学年なし) {
    const 一覧 = 区.区分たち(区分たち);
    if (!一覧.length) return 全員.length ? [{ 鍵: '全員', 題: 決.呼び方.部員, 人たち: 全員 }] : [];
    return 区.区分でまとめる(全員, 一覧).map((組) => ({ 鍵: 組.id || 'なし', 題: 組.題, 人たち: 組.人たち }));
  }
  const 組 = new Map();
  全員.forEach((人) => {
    const 値 = その他か(人, 決) ? 決.その他の学年 : 学年の値(人, 決);
    if (!組.has(値)) 組.set(値, []);
    組.get(値).push(人);
  });
  return [...組.keys()]
    .sort((甲, 乙) => 学年の順({ grade: 甲 }, 決) - 学年の順({ grade: 乙 }, 決))
    .map((値) => ({
      鍵: String(値),
      題: 学年の値の名前(値, 決, { 生: true, その他: 'その他/ゲスト' }),
      人たち: 組.get(値),
    }));
}

/**
 * 人の説明の行（「53期 / 男子 / 3年 / 一般」）。メンバー・分析・出欠の一覧で使う。
 * 学年の無い団体は「2019年入会 / 男性 / 一般」（退会した人は「退会」も入る）。
 * 注文.期を使う … 期を出すか（団体の設定の useTerm）。注文.区分たち … 区分の一覧（src/kubun.js）
 */
function 人の説明(人, 決まり, 注文) {
  if (!人) return '';
  const 決 = 決まりを使う(決まり);
  const 頼み = 注文 || {};
  const 区分 = 区.人の区分の名前(人, 頼み.区分たち);
  const 欄 = 決.学年なし
    ? [
        人.joinedYear ? `${人.joinedYear}年入会` : '',
        性別の名前(人.gender, 決),
        退部した人か(人, 決) ? 在籍の名前(在籍.退部, 決) : '',
        区分,
      ]
    : [頼み.期を使う && 人.termKi ? `${人.termKi}期` : '', 人.gender || '', 学年の名前(人, 決), 区分];
  return 欄.filter(Boolean).join(' / ');
}

/** 進級の窓で、何もしなければ卒業する人か（最後の学年。院生もいる部は 4 年と M2） */
function 卒業する学年か(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (!現役か(人, 決) || その他か(人, 決)) return false;
  return 決.卒業する学年.includes(学年の値(人, 決));
}

/** 前の名前（段 1・2）。卒業する学年か と同じ */
const 最後の学年か = 卒業する学年か;

/** その人が押すと院へ進める学年なら、進む先の学年の値（院生もいる部の 4 年 → M1）。無ければ null */
function 院へ進む先(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (!現役か(人, 決) || その他か(人, 決)) return null;
  const 先 = 決.院へ[学年の値(人, 決)];
  return 先 === undefined ? null : 先;
}

/** 進級したら次に行く学年の値（並びの次）。最後の学年なら null */
function 次の学年の値(学年, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 位置 = 決.在籍の学年.indexOf(Number(学年));
  return 位置 < 0 || 位置 === 決.在籍の学年.length - 1 ? null : 決.在籍の学年[位置 + 1];
}

/**
 * 年度の始まりの進級で、その人に書く変更。変わらない人は null。
 * 在籍の学年は 1 つ上がり、卒業する学年（ふつうは最後の学年）は卒業（学年はそのまま、在籍を '卒業'、leftYear に前の年度）。
 * 卒業しない団体（自分で決めるで切った団体）の最後の学年は、そのまま留まる。
 * その他・卒業生・退部した人・上げない人（選び が '残す' か true）はそのまま。
 * @param {object} 人 部員
 * @param {boolean|'残す'|'院へ'|null} 選び 進級の窓で選んだこと（'院へ' は院生もいる部の 4 年 → M1）
 * @param {number} 前の年度 進級する前の年度（2027 年 4 月の進級なら 2026）
 */
function 進級の変更(人, 選び, 前の年度, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (選び === true || 選び === '残す' || !現役か(人, 決) || その他か(人, 決)) return null;
  const 学年 = 学年の値(人, 決);
  if (選び === '院へ') {
    const 先 = 院へ進む先(人, 決);
    if (先 !== null) return { grade: 先 };
  }
  if (決.卒業する学年.includes(学年)) return { enrollment: 在籍.卒業, leftYear: 前の年度 };
  const 次 = 次の学年の値(学年, 決);
  return 次 === null ? null : { grade: 次 };
}

/** 今の 1 年生の期から、その学年の期（並びの 2 番目の学年なら 1 つ前の期） */
function 学年の期(今の一年生の期, 学年, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 位置 = 決.在籍の学年.indexOf(Number(学年));
  return Number(今の一年生の期) - (位置 < 0 ? Number(学年) - 1 : 位置);
}

/** その学年の値に期を付けてよいか（在籍の学年だけ。その他には付けない） */
function 期を付ける学年か(学年, 決まり) {
  return 決まりを使う(決まり).在籍の学年.includes(Number(学年));
}

/**
 * その期の人が現役でいる最後の年度（卒業する年度）。今の 1 年生が 今の一年生の期 で、今日の年度が 今年度 のとき。
 * 4 年制なら、1 年生（今の期）は 3 年後の年度の 3 月に卒業する。今年度 は画面で選んだ年度ではなく、今日の年度。
 * （出欠の画面の元の式は、画面で選んだ年度を基準にし、期の差の向きも逆だった。卒業生がまだいないので表に出ていなかった）
 */
function 卒業の年度(期, 今の一年生の期, 今年度, 決まり) {
  const 年数 = 決まりを使う(決まり).在籍の学年.length;
  return 今年度 + (Number(期) - Number(今の一年生の期)) + (年数 - 1);
}

/** その日の年度（年度の始まりの月から。省くと今の団体の月、既定は 4 月） */
function 年度(日, 始まりの月) {
  const 日付 = 日 || new Date();
  const 月 = 始まりの月 === undefined ? 今の決まり.始まりの月 : 始まりの月を整える(始まりの月);
  return 日付.getMonth() + 1 >= 月 ? 日付.getFullYear() : 日付.getFullYear() - 1;
}

/** その年度の初めの日と終わりの日（終わりは次の年度の始まりの前の日） */
function 年度の範囲(年度の年, 始まりの月) {
  const 月 = 始まりの月 === undefined ? 今の決まり.始まりの月 : 始まりの月を整える(始まりの月);
  return { 始め: new Date(年度の年, 月 - 1, 1), 終わり: new Date(年度の年 + 1, 月 - 1, 0) };
}

/**
 * 団体の設定（app_settings）から、学年まわりの店の値を読む。段 1 より前の団体には項目が無いので、前の項目から決める:
 * ・進級の確認（promotionCheck）… 前の「4月1日の自動進級」（autoPromotionEnabled。無ければ入）
 * ・期を使う（useTerm）… 今の 1 年生の期を 2 以上に決めてあれば使う（決めていない団体は既定の 1 のまま）
 * ・区分（divisions）… 無ければ空（src/kubun.js）
 */
function 設定から読む(設定) {
  const 中身 = 設定 || {};
  return {
    groupType: typeof 中身.groupType === 'string' ? 中身.groupType : null,
    promotionCheck:
      typeof 中身.promotionCheck === 'boolean' ? 中身.promotionCheck : 中身.autoPromotionEnabled !== false,
    useTerm:
      typeof 中身.useTerm === 'boolean'
        ? 中身.useTerm
        : typeof 中身.currentFreshmanTerm === 'number' && 中身.currentFreshmanTerm > 1,
    divisions: 区.区分たち(中身.divisions),
    customGrades: 自分の学年たち(中身.customGrades),
    customGraduate: 中身.customGraduate !== false,
    customWording: 中身.customWording === 'club' ? 'club' : 'school',
    yearStartMonth: 始まりの月を整える(中身.yearStartMonth),
  };
}

/**
 * 設定に段 1 の項目を書き足すべきか。書き足すときは autoPromotionEnabled を false にする。
 * 古い版のアプリは autoPromotionEnabled を見て 4 月 1 日に 4 年制の決まりで進級させる（学年 5 を書く）ので、
 * 新しい版は進級の確認（promotionCheck）で扱い、古い版には何もさせない
 */
function 設定を書き足すか(設定) {
  const 中身 = 設定 || {};
  return (
    typeof 中身.promotionCheck !== 'boolean' ||
    typeof 中身.useTerm !== 'boolean' ||
    中身.autoPromotionEnabled !== false
  );
}

/**
 * 進級を待っている年（その年の 4 月 1 日の進級）。進級の確認が入っていて、4 月 1 日を過ぎ、
 * まだその年の進級をしていなければその年。無ければ null。
 * 前に進級した年（lastPromotionYear）が無い団体は null（店がその年を書き留めるだけにする。進級はしない）
 */
function 進級待ちの年(今日, 前に進級した年, 進級の確認, 始まりの月) {
  if (!進級の確認 || typeof 前に進級した年 !== 'number') return null;
  const 日付 = 今日 || new Date();
  const 年 = 日付.getFullYear();
  const 月 = 始まりの月 === undefined ? 今の決まり.始まりの月 : 始まりの月を整える(始まりの月);
  if (日付.getMonth() + 1 < 月) return null;
  return 前に進級した年 < 年 ? 年 : null;
}

