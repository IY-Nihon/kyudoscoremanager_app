/** 学年の幅（「1年〜4年」。学年の無い団体は「学年なし」） */
function 学年の幅の名前(決まりか種類) {
  const 決 = typeof 決まりか種類 === 'string' ? 決まりを作る(決まりか種類) : 決まりを使う(決まりか種類);
  if (決.自分で決める && 決.学年なし) return '学年を自分で並べる';
  if (決.学年なし) return '学年なし';
  if (決.幅の名前) return 決.幅の名前;
  const 名前 = 学年の名前たち(決);
  if (決.自分で決める && 名前.length <= 4) return 名前.join('・');
  return 名前.length === 1 ? 名前[0] : `${名前[0]}〜${名前[名前.length - 1]}`;
}

/** 種類の名前と学年の幅（「大学（1年〜4年）」「社会人の会・道場（学年なし）」）。決まり か種類の id を渡す */
