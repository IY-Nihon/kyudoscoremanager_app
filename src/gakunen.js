'use strict';

/**
 * 学年の決まり。団体の種類・卒業生か・現役か・学年の名前・並べる順・進級・期の計算を、ここ 1 か所で決める。
 *
 * これまでは「学年 5 は卒業生」「1〜4 年が現役」が約 40 か所に直に書かれ、場所ごとに少しずつ
 * 書き方が違っていた（2026-10-16 に集めた）。同じ日に、団体の種類（中学・高校・高専・短大・大学・6 年制）と、
 * 卒業を学年ではなく在籍の項目で持つ形を足した（docs/plans/group-types-and-grades.md の段 1）。
 *
 * 学年の値：1〜（種類の年数）… 在籍の学年、0 … その他（コーチ・ゲストなど。進級も卒業もしない現役）。
 * 値が無い人・種類の学年に無い値の人は「その他」と同じに扱う。
 *
 * 在籍（部員の enrollment）：'在籍'・'卒業'・'退部'。項目が無い人は在籍。
 * 卒業した年度・退部した年度は leftYear（その人が現役だった最後の年度）。
 * 前の形（学年 5 が卒業生・卒業生の表 alumni の isAlumni・graduationYear）も卒業生と読む。
 * 本番には前の形の卒業生はいない（2026-10-16 に確かめた）が、古い版のアプリが学年 5 を書くことがある。
 *
 * 各関数の 決まり を省くと、今の団体の決まり（店が 決まりを置く で置く）を使う。
 */

/** 団体の種類。並びは選ぶ画面の並び */
const 種類たち = Object.freeze([
  Object.freeze({ id: 'school3', 名前: '中学・高校', 年数: 3 }),
  Object.freeze({ id: 'kosen5', 名前: '高専', 年数: 5 }),
  Object.freeze({ id: 'college2', 名前: '短大・専門学校', 年数: 2 }),
  Object.freeze({ id: 'univ4', 名前: '大学', 年数: 4 }),
  Object.freeze({ id: 'univ6', 名前: '6年制の大学', 年数: 6 }),
]);

/** 種類が決まっていない団体（2026-10-16 より前に作った団体はみな）は大学 */
const 既定の種類 = 'univ4';

/** 在籍の値 */
const 在籍 = Object.freeze({ 在籍: '在籍', 卒業: '卒業', 退部: '退部' });

/** 種類の id から決まりを作る。知らない id・空なら大学 */
function 決まりを作る(種類ID) {
  const 種類 = 種類たち.find((一つ) => 一つ.id === 種類ID) || 種類たち.find((一つ) => 一つ.id === 既定の種類);
  return Object.freeze({
    種類: 種類.id,
    種類の名前: 種類.名前,
    /** 在籍の学年（並べる順） */
    在籍の学年: Object.freeze(Array.from({ length: 種類.年数 }, (_, 番) => 番 + 1)),
    /** その他（学年の無い現役）を表す学年の値 */
    その他の学年: 0,
    /** 前の形の卒業生の印（学年 5）。大学だけ。ほかの種類では 5 年生がいる */
    古い卒業の学年: 種類.id === 'univ4' ? 5 : null,
  });
}

/** 大学の 4 年制 */
const 四年制 = 決まりを作る('univ4');

let 今の決まり = 四年制;

/** 今の団体の種類を置く（店が団体の設定を読んだとき・種類を変えたときに呼ぶ）。置いた決まりを返す */
function 決まりを置く(種類ID) {
  今の決まり = 決まりを作る(種類ID);
  return 今の決まり;
}

/** 今の団体の決まり */
function 今の決まりを見る() {
  return 今の決まり;
}

const 決まりを使う = (決まり) => 決まり || 今の決まり;

/** 学年の値を数に。値が無い・数でないときは その他 の値 */
function 学年の値(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 値 = 人 && 人.grade;
  if (値 === undefined || 値 === null || 値 === '') return 決.その他の学年;
  const 数 = Number(値);
  return Number.isFinite(数) ? 数 : 決.その他の学年;
}

/** 在籍の状態（'在籍'・'卒業'・'退部'）。前の形の卒業生の印も '卒業' と読む */
function 在籍の状態(人, 決まり) {
  if (!人) return 在籍.在籍;
  // 在籍の項目があればそれが正（在籍に戻した人は、前の形の印があっても在籍）
  if (人.enrollment === 在籍.在籍 || 人.enrollment === 在籍.卒業 || 人.enrollment === 在籍.退部)
    return 人.enrollment;
  const 決 = 決まりを使う(決まり);
  const 古い印 = 決.古い卒業の学年 !== null && 学年の値(人, 決) >= 決.古い卒業の学年;
  return 古い印 || 人.isAlumni || 人.graduationYear ? 在籍.卒業 : 在籍.在籍;
}

/** 卒業生か */
function 卒業生か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.卒業;
}

/** 退部した人か */
function 退部した人か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.退部;
}

/** 現役か（在籍している人。その他の人も現役） */
function 現役か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.在籍;
}

/** その他（学年の無い現役）か */
function その他か(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  return 現役か(人, 決) && !決.在籍の学年.includes(学年の値(人, 決));
}

/** 学年の値の名前（「3年」）。値が種類の学年に無ければ「その他」 */
function 学年だけの名前(値, 決まり, 注文) {
  const 決 = 決まりを使う(決まり);
  const 頼み = 注文 || {};
  const 数 = 学年の値({ grade: 値 }, 決);
  if (!決.在籍の学年.includes(数)) return 頼み.その他 || 'その他';
  return `${数}年${頼み.生 ? '生' : ''}`;
}

/**
 * 学年の名前。注文.生 なら「3年生」、無ければ「3年」。卒業生は「卒業生」、退部した人は「退部」。
 * 注文.その他 … その他の人の名前（既定は「その他」。名簿の見出しでは「その他/ゲスト」）
 */
function 学年の名前(人, 決まり, 注文) {
  const 決 = 決まりを使う(決まり);
  const 状態 = 在籍の状態(人, 決);
  if (状態 === 在籍.卒業) return '卒業生';
  if (状態 === 在籍.退部) return '退部';
  return 学年だけの名前(人 && 人.grade, 決, 注文);
}

/** 学年の値から名前（人が手元に無く、値だけあるとき。まとめた組の見出しなど） */
function 学年の値の名前(値, 決まり, 注文) {
  return 学年の名前({ grade: 値 }, 決まり, 注文);
}

/** 選べる学年の名前の一覧（分析の絞り込みなど）。大学なら「1年」〜「4年」 */
function 学年の名前たち(決まり) {
  return 決まりを使う(決まり).在籍の学年.map((学年) => `${学年}年`);
}

/** 種類の名前と学年の幅（「大学（1年〜4年）」）。決まり か種類の id を渡す */
function 種類の説明(決まりか種類) {
  const 決 = typeof 決まりか種類 === 'string' ? 決まりを作る(決まりか種類) : 決まりを使う(決まりか種類);
  const 学年 = 決.在籍の学年;
  return `${決.種類の名前}（${学年[0]}年〜${学年[学年.length - 1]}年）`;
}

/**
 * 並べる順の数。在籍の学年は若い順、その他（値が無い人も）は後ろ、卒業生・退部した人はいちばん後ろ。
 * 「(甲, 乙) => 学年の順(甲) - 学年の順(乙)」のように使う
 */
function 学年の順(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 状態 = 在籍の状態(人, 決);
  if (状態 === 在籍.卒業) return 1000;
  if (状態 === 在籍.退部) return 1001;
  if (その他か(人, 決)) return 99;
  return 学年の値(人, 決);
}

/** 進級の窓で、その人が最後の学年か（「上げない」が「卒業しない」になる） */
function 最後の学年か(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (!現役か(人, 決) || その他か(人, 決)) return false;
  return 学年の値(人, 決) === 決.在籍の学年[決.在籍の学年.length - 1];
}

/**
 * 年度の始まりの進級で、その人に書く変更。変わらない人は null。
 * 在籍の学年は 1 つ上がり、最後の学年は卒業（学年はそのまま、在籍を '卒業'、leftYear に前の年度）。
 * その他・卒業生・退部した人・上げない人（残す が真）はそのまま。
 * @param {object} 人 部員
 * @param {boolean} 残す 進級の窓で「上げない／卒業しない」を選んだか
 * @param {number} 前の年度 進級する前の年度（2027 年 4 月の進級なら 2026）
 */
function 進級の変更(人, 残す, 前の年度, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (残す || !現役か(人, 決) || その他か(人, 決)) return null;
  const 学年 = 学年の値(人, 決);
  const 位置 = 決.在籍の学年.indexOf(学年);
  if (位置 === 決.在籍の学年.length - 1) return { enrollment: 在籍.卒業, leftYear: 前の年度 };
  return { grade: 決.在籍の学年[位置 + 1] };
}

/** 今の 1 年生の期から、その学年の期（2 年生なら 1 つ前の期） */
function 学年の期(今の一年生の期, 学年) {
  return Number(今の一年生の期) - (Number(学年) - 1);
}

/** その学年の値に期を付けてよいか（在籍の学年だけ。その他には付けない） */
function 期を付ける学年か(学年, 決まり) {
  return 決まりを使う(決まり).在籍の学年.includes(Number(学年));
}

/**
 * その期の人が現役でいる最後の年度（卒業する年度）。今の 1 年生が 今の一年生の期 で、今日の年度が 今年度 のとき。
 * 4 年制なら、1 年生（今の期）は 3 年後の年度の 3 月に卒業する。今年度 は画面で選んだ年度ではなく、今日の年度。
 * （出欠の画面の元の式は、画面で選んだ年度を基準にし、期の差の向きも逆だった。卒業生がまだいないので表に出ていなかった）
 */
function 卒業の年度(期, 今の一年生の期, 今年度, 決まり) {
  const 年数 = 決まりを使う(決まり).在籍の学年.length;
  return 今年度 + (Number(期) - Number(今の一年生の期)) + (年数 - 1);
}

/** その日の年度（4 月始まり） */
function 年度(日) {
  const 日付 = 日 || new Date();
  return 日付.getMonth() + 1 >= 4 ? 日付.getFullYear() : 日付.getFullYear() - 1;
}

/**
 * 団体の設定（app_settings）から、学年まわりの店の値を読む。段 1 より前の団体には項目が無いので、前の項目から決める:
 * ・進級の確認（promotionCheck）… 前の「4月1日の自動進級」（autoPromotionEnabled。無ければ入）
 * ・期を使う（useTerm）… 今の 1 年生の期を 2 以上に決めてあれば使う（決めていない団体は既定の 1 のまま）
 */
function 設定から読む(設定) {
  const 中身 = 設定 || {};
  return {
    groupType: typeof 中身.groupType === 'string' ? 中身.groupType : null,
    promotionCheck:
      typeof 中身.promotionCheck === 'boolean' ? 中身.promotionCheck : 中身.autoPromotionEnabled !== false,
    useTerm:
      typeof 中身.useTerm === 'boolean'
        ? 中身.useTerm
        : typeof 中身.currentFreshmanTerm === 'number' && 中身.currentFreshmanTerm > 1,
  };
}

/**
 * 設定に段 1 の項目を書き足すべきか。書き足すときは autoPromotionEnabled を false にする。
 * 古い版のアプリは autoPromotionEnabled を見て 4 月 1 日に 4 年制の決まりで進級させる（学年 5 を書く）ので、
 * 新しい版は進級の確認（promotionCheck）で扱い、古い版には何もさせない
 */
function 設定を書き足すか(設定) {
  const 中身 = 設定 || {};
  return (
    typeof 中身.promotionCheck !== 'boolean' ||
    typeof 中身.useTerm !== 'boolean' ||
    中身.autoPromotionEnabled !== false
  );
}

/**
 * 進級を待っている年（その年の 4 月 1 日の進級）。進級の確認が入っていて、4 月 1 日を過ぎ、
 * まだその年の進級をしていなければその年。無ければ null。
 * 前に進級した年（lastPromotionYear）が無い団体は null（店がその年を書き留めるだけにする。進級はしない）
 */
function 進級待ちの年(今日, 前に進級した年, 進級の確認) {
  if (!進級の確認 || typeof 前に進級した年 !== 'number') return null;
  const 日付 = 今日 || new Date();
  const 年 = 日付.getFullYear();
  if (日付.getMonth() + 1 < 4) return null;
  return 前に進級した年 < 年 ? 年 : null;
}

