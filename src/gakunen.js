'use strict';

/**
 * 学年の決まり。卒業生か・現役か・学年の名前・並べる順・次の学年・期の計算を、ここ 1 か所で決める。
 *
 * これまでは「学年 5 は卒業生」「1〜4 年が現役」が約 40 か所に直に書かれ、場所ごとに少しずつ
 * 書き方が違っていた（2026-10-16 に集めた）。いまは大学の 4 年制だけを扱う。
 * いろいろな団体（高校・高専・6 年制・社会人の会など）で使えるようにするときは、各関数の 決まり に
 * 団体の決まりを渡す形に広げる（docs/plans/group-types-and-grades.md）。渡さなければ大学の 4 年制。
 *
 * 学年の値：1〜4 … 現役の学年、5 … 卒業生、0 … その他（コーチ・ゲストなど。進級も卒業もしない現役）。
 * 値が無い人は「その他」と同じに扱う。
 */

/** 大学の 4 年制。いまの全部の団体がこれ */
const 四年制 = Object.freeze({
  /** 現役の学年（並べる順） */
  在籍の学年: Object.freeze([1, 2, 3, 4]),
  /** 卒業生を表す学年の値 */
  卒業の学年: 5,
  /** その他（学年の無い現役）を表す学年の値 */
  その他の学年: 0,
});

const 決まりを使う = (決まり) => 決まり || 四年制;

/** 学年の値を数に。値が無い・数でないときは その他 の値 */
function 学年の値(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 値 = 人 && 人.grade;
  if (値 === undefined || 値 === null || 値 === '') return 決.その他の学年;
  const 数 = Number(値);
  return Number.isFinite(数) ? 数 : 決.その他の学年;
}

/**
 * 卒業生か。学年が卒業の値以上か、卒業生の印（卒業生の表から来た isAlumni・卒業年度 graduationYear）がある。
 * isAlumni・graduationYear は段 1 で使うのをやめる（本番では誰にも値が無い。2026-10-16 に確かめた）
 */
function 卒業生か(人, 決まり) {
  if (!人) return false;
  const 決 = 決まりを使う(決まり);
  return 学年の値(人, 決) >= 決.卒業の学年 || !!人.isAlumni || !!人.graduationYear;
}

/** 現役か（卒業生でない人。その他の人も現役） */
function 現役か(人, 決まり) {
  return !!人 && !卒業生か(人, 決まり);
}

/** その他（学年の無い現役）か */
function その他か(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  return 現役か(人, 決) && !決.在籍の学年.includes(学年の値(人, 決));
}

/**
 * 学年の名前。注文.生 なら「3年生」、無ければ「3年」。
 * 注文.その他 … その他の人の名前（既定は「その他」。名簿の見出しでは「その他/ゲスト」）
 */
function 学年の名前(人, 決まり, 注文) {
  const 決 = 決まりを使う(決まり);
  const 頼み = 注文 || {};
  if (卒業生か(人, 決)) return '卒業生';
  if (その他か(人, 決)) return 頼み.その他 || 'その他';
  return `${学年の値(人, 決)}年${頼み.生 ? '生' : ''}`;
}

/** 学年の値から名前（人が手元に無く、値だけあるとき。選ぶ欄の表示など） */
function 学年の値の名前(値, 決まり, 注文) {
  return 学年の名前({ grade: 値 }, 決まり, 注文);
}

/** 選べる学年の名前の一覧（分析の絞り込みなど）。「1年」〜「4年」 */
function 学年の名前たち(決まり) {
  return 決まりを使う(決まり).在籍の学年.map((学年) => `${学年}年`);
}

/** 学年を選ぶ欄で上げ下げできる範囲（その他から卒業まで） */
function 学年の幅(決まり) {
  const 決 = 決まりを使う(決まり);
  return { 下: 決.その他の学年, 上: 決.卒業の学年 };
}

/**
 * 並べる順の数。現役の学年は若い順、その他（値が無い人も）は後ろ、卒業生はいちばん後ろ。
 * 「(甲, 乙) => 学年の順(甲) - 学年の順(乙)」のように使う
 */
function 学年の順(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  if (卒業生か(人, 決)) return 1000;
  if (その他か(人, 決)) return 99;
  return 学年の値(人, 決);
}

/**
 * 次の年度の学年（自動の進級）。現役の学年は 1 つ上がり、最後の学年は卒業する。
 * その他・卒業生・値が数でない人はそのまま（値を返す。数でなければ元の値のまま）
 */
function 次の学年(学年, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 数 = Number(学年);
  if (学年 === undefined || 学年 === null || 学年 === '' || !Number.isFinite(数)) return 学年;
  const 位置 = 決.在籍の学年.indexOf(数);
  if (位置 < 0) return 学年;
  return 位置 === 決.在籍の学年.length - 1 ? 決.卒業の学年 : 決.在籍の学年[位置 + 1];
}

/** 今の 1 年生の期から、その学年の期（2 年生なら 1 つ前の期） */
function 学年の期(今の一年生の期, 学年) {
  return Number(今の一年生の期) - (Number(学年) - 1);
}

/** その学年の値に期を付けてよいか（現役の学年と卒業生。その他には付けない） */
function 期を付ける学年か(学年, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 数 = Number(学年);
  return 決.在籍の学年.includes(数) || 数 === 決.卒業の学年;
}

/**
 * その期の人が現役でいる最後の年度（卒業する年度）。今の 1 年生が 今の一年生の期 で、今日の年度が 今年度 のとき。
 * 4 年制なら、1 年生（今の期）は 3 年後の年度の 3 月に卒業する。今年度 は画面で選んだ年度ではなく、今日の年度。
 * （出欠の画面の元の式は、画面で選んだ年度を基準にし、期の差の向きも逆だった。卒業生がまだいないので表に出ていなかった）
 */
function 卒業の年度(期, 今の一年生の期, 今年度, 決まり) {
  const 年数 = 決まりを使う(決まり).在籍の学年.length;
  return 今年度 + (Number(期) - Number(今の一年生の期)) + (年数 - 1);
}

module.exports = {
  四年制,
  学年の値,
  卒業生か,
  現役か,
  その他か,
  学年の名前,
  学年の値の名前,
  学年の名前たち,
  学年の幅,
  学年の順,
  次の学年,
  学年の期,
  期を付ける学年か,
  卒業の年度,
};
