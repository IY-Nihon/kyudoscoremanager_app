/** 学年の値を数に。値が無い・数でないときは その他 の値 */
function 学年の値(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  const 値 = 人 && 人.grade;
  if (値 === undefined || 値 === null || 値 === '') return 決.その他の学年;
  const 数 = Number(値);
  return Number.isFinite(数) ? 数 : 決.その他の学年;
}

/** 在籍の状態（'在籍'・'卒業'・'退部'）。前の形の卒業生の印も '卒業' と読む */
function 在籍の状態(人, 決まり) {
  if (!人) return 在籍.在籍;
  // 在籍の項目があればそれが正（在籍に戻した人は、前の形の印があっても在籍）
  if (人.enrollment === 在籍.在籍 || 人.enrollment === 在籍.卒業 || 人.enrollment === 在籍.退部)
    return 人.enrollment;
  const 決 = 決まりを使う(決まり);
  const 古い印 = 決.古い卒業の学年 !== null && 学年の値(人, 決) >= 決.古い卒業の学年;
  return 古い印 || 人.isAlumni || 人.graduationYear ? 在籍.卒業 : 在籍.在籍;
}

/** 卒業生か */
function 卒業生か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.卒業;
}

/** 退部した人か */
function 退部した人か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.退部;
}

/** 現役か（在籍している人。その他の人も現役） */
function 現役か(人, 決まり) {
  return !!人 && 在籍の状態(人, 決まり) === 在籍.在籍;
}

/** その他（学年の無い現役）か */
function その他か(人, 決まり) {
  const 決 = 決まりを使う(決まり);
  return 現役か(人, 決) && !決.在籍の学年.includes(学年の値(人, 決));
}

/** 学年の値の名前（「3年」）。値が種類の学年に無ければ「その他」 */
function 学年だけの名前(値, 決まり, 注文) {
  const 決 = 決まりを使う(決まり);
  const 頼み = 注文 || {};
  const 数 = 学年の値({ grade: 値 }, 決);
  if (!決.在籍の学年.includes(数)) return 頼み.その他 || 'その他';
  const 名 = 決.学年の表.get(数);
  // 「3年」は「3年生」に。中1・M1・自分で決めた名前には「生」を付けない
  return 頼み.生 && /年$/.test(名) ? `${名}生` : 名;
}

/**
 * 学年の名前。注文.生 なら「3年生」、無ければ「3年」。卒業生は「卒業生」、退部した人は「退部」。
 * 注文.その他 … その他の人の名前（既定は「その他」。名簿の見出しでは「その他/ゲスト」）
 */
function 学年の名前(人, 決まり, 注文) {
  const 決 = 決まりを使う(決まり);
  const 状態 = 在籍の状態(人, 決);
  if (状態 === 在籍.卒業) return '卒業生';
  if (状態 === 在籍.退部) return 決.呼び方.退部;
  if (決.学年なし) return 決.呼び方.部員;
  return 学年だけの名前(人 && 人.grade, 決, 注文);
}

/** 学年の値から名前（人が手元に無く、値だけあるとき。まとめた組の見出しなど） */
