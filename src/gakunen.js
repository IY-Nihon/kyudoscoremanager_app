/**
 * 種類の id から決まりを作る。知らない id・空なら大学。
 * 付け足し（{ customGrades, customGraduate, customWording, yearStartMonth }）を省くと、今の団体のもの（決まりを置く で置いたもの）
 */
function 決まりを作る(種類ID, 付け足し) {
  const 足し = 付け足し || 今の付け足し;
  // 種類ごとに持つ項目が違う（名前たち・卒業する学年・院へ・自分で）ので、型は広く取る
  const 種類 = /** @type {any} */ (
    種類たち.find((一つ) => 一つ.id === 種類ID) || 種類たち.find((一つ) => 一つ.id === 既定の種類)
  );
  const 自分の = 種類.自分で ? 自分の学年たち(足し.customGrades) : [];
  const 値たち = 種類.自分で
    ? 自分の.map((学年) => 学年.value)
    : Array.from({ length: 種類.年数 }, (_, 番) => 番 + 1);
  const 名前たち = 種類.自分で
    ? 自分の.map((学年) => 学年.name)
    : 種類.名前たち || 値たち.map((値) => `${値}年`);
  const 学年なし = 値たち.length === 0;
  // 卒業するか（自分で決めるは団体が選ぶ。既定は卒業する）。卒業しないなら最後の学年に留まる
  const 卒業あり = 種類.自分で ? 足し.customGraduate !== false : !学年なし;
  const 会風 = 種類.自分で ? 足し.customWording === 'club' : 学年なし;
  return Object.freeze({
    種類: 種類.id,
    種類の名前: 種類.名前,
    /** 在籍の学年の値（並べる順） */
    在籍の学年: Object.freeze(値たち),
    /** 学年の値 → 名前 */
    学年の表: new Map(値たち.map((値, 番) => [値, 名前たち[番]])),
    /** 進級の窓で、何もしなければ卒業する学年（ふつうは最後の学年。院生もいる部は 4 年と M2） */
    卒業する学年: Object.freeze(
      卒業あり ? 種類.卒業する学年 || (値たち.length ? [値たち[値たち.length - 1]] : []) : []
    ),
    /** 押すと院へ進める学年 → 進む先（院生もいる部の 4 年 → M1） */
    院へ: Object.freeze(Object.assign({}, 種類.院へ || {})),
    幅の名前: 種類.幅の名前 || null,
    自分で決める: !!種類.自分で,
    /** その他（学年の無い現役）を表す学年の値 */
    その他の学年: 0,
    /** 前の形の卒業生の印（学年 5）。大学だけ。ほかの種類では 5 年生がいる */
    古い卒業の学年: 種類.id === 'univ4' ? 5 : null,
    /** 学年の無い団体（社会人の会・道場。自分で決めるで学年を 1 つも並べていない団体も） */
    学年なし,
    呼び方: 会風 ? 会の呼び方 : 学校の呼び方,
    /** 年度の始まりの月（進級の窓を出す日・分析・出欠・書き出しの年度の区切り） */
    始まりの月: 始まりの月を整える(足し.yearStartMonth),
  });
}

