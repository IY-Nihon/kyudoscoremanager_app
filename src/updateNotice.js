/**
 * Module ID: updateNotice
 *
 * 新しい版が出たことを、開いたままの画面に知らせる。
 *
 * ■ 何が問題で、何が問題でないか
 * 「ブラウザの強いキャッシュで古い JS が残る」ことは、この repo では起きない。
 *   ・Service Worker（pwa/sw.js）はネットワーク優先で、キャッシュは
 *     通信できないときの後ろ盾にしか使わない
 *   ・index.html と sw.js は no-cache（firebase.json）
 *   ・束の名前には中身のハッシュが入るので、変われば別のファイルになる
 * だから読み込み直せば必ず新しくなる。
 *
 * 残る穴は1つだけで、**開いたままのタブ**。読み込み直すまで古い束が動き続ける。
 * ふだんは害が小さいが、ライブの置き場所（枝）が変わる回では、古いままの
 * 端末が別の枝を見て「相手の○×が出ない」という直しにくい形になる。
 *
 * ■ どうやって気づくか
 * 版を別に持たない。index.html を取り直して、そこに書かれた束の名前が
 * いま動いている束と違えば新しい版。版の番号を別に置くと、置き忘れたときに
 * 黙って知らせが出なくなる。束の名前は配信のたびに必ず変わる。
 *
 * ■ 電波が切れた瞬間に、古い控えで「新しい版」と言わない（2026-10-03）
 * 取り直した index.html は Service Worker（pwa/sw.js）を通る。通信できないと sw.js は控えの
 * /index.html を返すが、その控えは前の版のまま残っていることがある（配信のあとの最初の起動では、
 * 控えを書き直すのは「取り直しが通ったとき」だけ）。すると、更新したばかりの端末で、スマホを開き直した
 * 一瞬（電波がまだ戻っていない）に取り直しが失敗し、前の版の束の名前が返って
 * 「新しい版が出ています」が、更新したのにまた出た。
 * 違いが見つかったら、今動いている束のファイルがサーバーにまだあるかを HEAD で確かめる
 * （束がもう無い＝新しい版が出た）。HEAD は sw.js を通らないので、控えの古い答えは返らず、
 * 通信できなければ失敗する（失敗したら黙る）。束の名前は 束がもう無いか で判る。
 *
 * ■ しばらく離れて戻ってきたときだけ、自動で更新する（2026-10-03）
 * 「新しい版が出たら自動で更新してほしい」という声があった。画面が勝手に入れ替わると、入力の途中の
 * 字などが消えるので、いつでも更新はしない。次の 4 つがそろったときだけ、帯を出さずに読み込み直す。
 *   ・3 分以上、画面を離れていた（切り替えて戻っただけの短い間は、帯のまま）
 *   ・ライブ中でない・案内中でない
 *   ・字を入力している最中でない（入力欄に印が在る）
 *   ・その版へは、まだ自動で更新していない（読み込み直しても版が変わらないとき、繰り返さない）
 * 手元の記録は端末に残る（閉じる・離れるときに書き出す）ので、読み込み直しても戻ってくる。
 * 自動で更新できないときは、これまでどおり帯を出して、押されたときだけ読み込み直す。
 *
 * ■ 押し付けない
 * 勝手に読み込み直さない。記録の途中で画面が入れ替わると、何が起きたのか
 * 分からない。帯を出して、押されたときだけ読み込み直す。
 * 手元の記録は端末に残るので、読み込み直しても消えない。
 *
 * 画面にも Firebase にも触れない純粋な関数なので、そのまま検査できる
 * （test/updateNotice.test.js）。
 */
'use strict';

/** 見に行く間隔（ミリ秒）。30分。通信は index.html 1枚ぶんで小さい */
const 見に行く間隔 = 30 * 60 * 1000;

/** 自動で更新するのに、画面を離れていてほしい最短の長さ（ミリ秒）。3分 */
const 自動更新の最短の離席 = 3 * 60 * 1000;

/**
 * HTML から、読み込んでいる束の名前を取り出す。
 *
 * 束は1つだけ（Expo の web 書き出し）。複数あったら先頭を使う。
 *
 * @param {string|null|undefined} html
 * @returns {string|null}
 */
function 束の名前(html) {
  const s = String(html == null ? '' : html);
  const m = s.match(/src="([^"]*\/AppEntry-[^"]+\.js)"/) || s.match(/src="([^"]*\.js)"/);
  return m ? m[1] : null;
}

/**
 * 新しい版が出ているか。
 *
 * どちらかが読めないときは「出ていない」とする。取り違えて帯を出すと、
 * 押しても何も変わらず、そのうち誰も押さなくなる。
 * 束の名前は、どちらも AppEntry-… の形のときだけ比べる（Wi-Fi のログイン画面や通信の
 * 取り違えで返った HTML に、別の .js の名前があっても「新しい版」としない）。
 *
 * @param {string|null|undefined} いまの束 いま動いている束の名前
 * @param {string|null|undefined} 取ってきたHTML
 * @returns {boolean}
 */
function 新しい版が出たか(いまの束, 取ってきたHTML) {
  const いま = 名前だけにする(いまの束);
  const 向こう = 名前だけにする(束の名前(取ってきたHTML));
  if (!いま || !向こう) return false;
  if (!束の形か(いま) || !束の形か(向こう)) return false;
  return いま !== 向こう;
}

/** 配信された束の名前の形（AppEntry-中身の印.js）か */
function 束の形か(名前) {
  return /^AppEntry-[^/]+\.js$/.test(String(名前 || ''));
}

/**
 * 今動いている束のファイルが、サーバーにもう無いか。HEAD の答え（状態と中身の種類）で見る。
 *
 * 配信すると、前の束のファイルは消える。Firebase Hosting は無いファイルを index.html に回すので、
 * 消えた束への求めは 404 か、200 で text/html（index.html）が返る。まだあれば javascript が返る。
 * 通信の失敗・サーバーの不調（5xx）・読めない答えは「分からない」なので false（帯は出さない）。
 *
 * @param {{状態?: number, 種類?: string|null}|null|undefined} 返り
 * @returns {boolean}
 */
function 束がもう無いか(返り) {
  if (!返り || !Number.isFinite(返り.状態)) return false;
  const 状態 = Number(返り.状態);
  if (状態 === 404 || 状態 === 410) return true;
  if (状態 >= 200 && 状態 < 300) return /text\/html/i.test(String(返り.種類 || ''));
  return false;
}

/**
 * 道のうち、ファイル名だけを見る。
 *
 * 同じ束でも、住所の書き方が違うことがある（絶対と相対、問い合わせ付き）。
 * 名前で比べないと、中身が同じでも「新しい版」と言い続ける
 */
function 名前だけにする(道) {
  if (!道) return null;
  const s = String(道).split('?')[0].split('#')[0];
  const 名 = s.split('/').pop();
  return 名 || null;
}

/**
 * 帯を出さずに、自動で読み込み直してよいか（上の説明の 4 つ）。
 * @param {{離れていた時間?: number, ライブ中?: boolean, 案内中?: boolean, 入力中?: boolean, 新しい束?: string|null, 前に試した束?: string|null, 最短?: number}} 状況
 * @returns {boolean}
 */
function 自動で更新してよいか(状況) {
  const { 離れていた時間 = 0, ライブ中 = false, 案内中 = false, 入力中 = false, 新しい束 = null, 前に試した束 = null } = 状況 || {};
  const 最短 = Number.isFinite(状況 && 状況.最短) ? 状況.最短 : 自動更新の最短の離席;
  if (!(Number(離れていた時間) >= 最短)) return false;
  if (ライブ中 || 案内中 || 入力中) return false;
  if (!新しい束 || !束の形か(新しい束)) return false;
  if (前に試した束 && 前に試した束 === 新しい束) return false;
  return true;
}

module.exports = {
  束の名前,
  新しい版が出たか,
  束がもう無いか,
  束の形か,
  名前だけにする,
  見に行く間隔,
  自動更新の最短の離席,
  自動で更新してよいか,
};
