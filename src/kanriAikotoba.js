'use strict';

/**
 * 管理者の合言葉（2026-11-14 本人：管理者モードを決まりで守る）。中継（kyudo-chukei の POST /kanri）とやり取りする。
 *
 * 合言葉は中継だけが知る（ハッシュを中継の D1 に置く）。合っていたら、中継がこの口座に 12 時間の
 * 「管理者」の印（Firestore の admin_sessions/{団体}_{uid}）を書き、決まり（isGroupAdmin）が消す・名簿・設定を通す。
 *
 * 中継が無い・古い（/kanri が無く 404）ときは '古い中継' を返す。画面は前のとおりログインのパスワードで
 * 管理者モードに入れる（中継を配るまでのつなぎ。決まりで守るのは中継と決まりを配ってから）。
 *
 * 画面にも Firebase にも触れない作りにして、送り先を差し替えて検査できる（test/kanriAikotoba.test.js）。
 */

/** 合言葉の長さ（中継の src/kanri.mjs と同じ） */
const 合言葉の長さ = { 短い: 6, 長い: 64 };

/** 合言葉の形が足りないときの文。足りていれば '' */
function 合言葉の形の文(字) {
  const 長さ = [...String(字 ?? '')].length;
  if (!String(字 ?? '').trim()) return '合言葉を入れてください';
  if (長さ < 合言葉の長さ.短い) return `合言葉は ${合言葉の長さ.短い} 字以上にしてください`;
  if (長さ > 合言葉の長さ.長い) return `合言葉は ${合言葉の長さ.長い} 字までにしてください`;
  return '';
}

/**
 * 中継の /kanri を呼ぶ。
 * @param {string} 団体 groups の鍵
 * @param {object} 体 {操作, ...}
 * @param {{中継?: object, 証を新しく?: boolean}} 道具
 * @returns {Promise<{結果: string, 期限?: number, 残り?: number, 文?: string}>}
 */
async function 呼ぶ(団体, 体, 道具 = {}) {
  const 中継 = 道具.中継 || require('./geminiChukei');
  if (!中継 || !中継.中継がある()) return { 結果: '古い中継' };
  // 作る・忘れたときの作り直しは、入り直した直後の証（auth_time が新しい）が要る。入り直したあと証を取り直す
  if (道具.証を新しく && 中継.ログインの証) await 中継.ログインの証(true).catch(() => null);
  let 返り;
  try {
    返り = await 中継.中継へfetch('/kanri', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ 団体, ...体 }),
    });
  } catch {
    return { 結果: '届かない', 文: '通信できませんでした。電波の良い場所でお試しください' };
  }
  if (!返り || 返り.status === 404) return { 結果: '古い中継' };
  const 中身 = await Promise.resolve()
    .then(() => 返り.json())
    .catch(() => ({}));
  if (返り.status === 429)
    return { 結果: '待つ', 文: (中身 && 中身.error) || '少し待ってからお試しください' };
  if (返り.status === 403)
    return { 結果: '持ち主でない', 文: '団体のアカウントでログインしているときだけ使えます' };
  if (返り.status === 401 && 中身 && 中身.印 === 'appcheck')
    return {
      結果: '届かない',
      文: 'この端末の確かめに失敗しました。ブラウザを新しくして読み込み直してください',
    };
  if (返り.status === 400) return { 結果: '形が違う', 文: (中身 && 中身.error) || '合言葉の形が違います' };
  if (!返り.ok) return { 結果: '届かない', 文: 'いまは確かめられません。少し待ってからお試しください' };
  return 中身 || {};
}

const 様子を聞く = (団体, 道具) => 呼ぶ(団体, { 操作: '様子' }, 道具);
const 合言葉で入る = (団体, 合言葉, 道具) => 呼ぶ(団体, { 操作: '入る', 合言葉 }, 道具);
const 合言葉を作る = (団体, 新しい, 道具) =>
  呼ぶ(団体, { 操作: '作る', 新しい }, { ...道具, 証を新しく: true });
/** 今の合言葉で変える。今の が無いときは、入り直した直後の証で変える（忘れたとき） */
const 合言葉を変える = (団体, 新しい, 今の, 道具) =>
  呼ぶ(団体, { 操作: '変える', 新しい, ...(今の ? { 今の } : {}) }, { ...道具, 証を新しく: !今の });
const 管理者から出る = (団体, 道具) => 呼ぶ(団体, { 操作: '出る' }, 道具);

module.exports = {
  合言葉の長さ,
  合言葉の形の文,
  様子を聞く,
  合言葉で入る,
  合言葉を作る,
  合言葉を変える,
  管理者から出る,
};
