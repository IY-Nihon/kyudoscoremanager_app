'use strict';

/**
 * AI に部員の登録を頼まれたときの見張り（2026-11-08 本人「明確なインジェクションのようなものは拒否したい」）。
 *   ・名前は利用者が書いたものだけ。AI が作った名前（「部員1〜100」「連番で」など）は登録しない（本人）
 *   ・1 回のカードは 50 人まで。超えたら先の 50 人のカードを出し、残りはもう一度頼んでもらう（本人）
 * 名前は、利用者がこの会話で送った文に（空白を除いて）そのまま入っているかで見る。1 人でも入っていなければ、頼み全体を断る
 *（「100人、部員1」では部員1 だけが文に入っていて、1 枚だけカードが出てしまうため）。
 */
const 一度に登録できる人数 = 50;

const 空白を除く = (字) => String(字 || '').replace(/\s+/g, '');

/**
 * @param {object[]} 人たち      AI が addMember / addMembers に渡した人（{ name, grade, gender }）
 * @param {string[]} 利用者の文たち この会話で利用者が送った文
 * @returns {{ 通す: object[], 名前が無い: object[], 残り: object[] }}
 *   通す … カードを出す人（50 人まで）、名前が無い … 利用者が書いていない名前、残り … 51 人目から
 */
function 部員の頼みを確かめる(人たち, 利用者の文たち) {
  const 人 = (人たち || []).filter((一人) => 一人 && 空白を除く(一人.name));
  const 書いた文 = 空白を除く((利用者の文たち || []).join('\n'));
  const 書いた人 = [];
  const 名前が無い = [];
  for (const 一人 of 人) (書いた文.includes(空白を除く(一人.name)) ? 書いた人 : 名前が無い).push(一人);
  if (名前が無い.length) return { 通す: [], 名前が無い, 残り: [] };
  return {
    通す: 書いた人.slice(0, 一度に登録できる人数),
    名前が無い,
    残り: 書いた人.slice(一度に登録できる人数),
  };
}

/** AI へ返す断りの文（AI はこれを利用者に伝える）。断らないときは空 */
function 断りの文(結果) {
  if (結果.名前が無い.length)
    return '利用者が書いていない名前は登録しません（連番や仮の名前は作りません）。登録する人の名前を一人ずつ書いて送ってください、と利用者に伝えてください。カードは出していません。';
  return '';
}

/** 51 人目から残ったときに、カードの下に出す文 */
function 残りの文(結果) {
  const 残り = 結果.残り.length;
  if (!残り) return '';
  const 先頭 = 結果.残り[0] && 結果.残り[0].name;
  return `一度に登録できるのは${一度に登録できる人数}人までです。まず${一度に登録できる人数}人のカードを出しました。残りの${残り}人（${先頭}さんから）は、登録が済んだらもう一度頼んでください。`;
}

module.exports = { 部員の頼みを確かめる, 断りの文, 残りの文, 一度に登録できる人数 };
