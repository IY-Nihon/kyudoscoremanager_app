'use strict';

/**
 * AI に部員の登録を頼まれたときの見張り（2026-11-08 本人「明確なインジェクションのようなものは拒否したい」）。
 *   ・名前は利用者が書いたものだけ。AI が作った名前（「部員1〜100」「連番で」など）は登録しない（本人）
 *   ・1 回のカードは 50 人まで。超えたら先の 50 人のカードを出し、残りはもう一度頼んでもらう（本人）
 * 名前は、利用者がこの会話で送った文に（空白・全角半角・カタカナとひらがな・異体字をそろえて）入っているかで見る。1 人でも入っていなければ、頼み全体を断る
 *（「100人、部員1」では部員1 だけが文に入っていて、1 枚だけカードが出てしまうため）。
 */
const 一度に登録できる人数 = 50;

// 名字によく出る異体字を、ふだんの字にそろえる（AI が「髙橋」を「高橋」に直しても同じ人として見る。2026-11-08 本人）
const 異体字 = {
  髙: '高',
  﨑: '崎',
  嵜: '崎',
  齋: '斎',
  齊: '斎',
  斉: '斎',
  邊: '辺',
  邉: '辺',
  澤: '沢',
  濱: '浜',
  濵: '浜',
  櫻: '桜',
  廣: '広',
  德: '徳',
  國: '国',
  藏: '蔵',
  眞: '真',
  惠: '恵',
  榮: '栄',
  實: '実',
  龍: '竜',
  瀨: '瀬',
  冨: '富',
  槇: '槙',
  桒: '桑',
  籠: '篭',
};
const 異体字の形 = new RegExp(`[${Object.keys(異体字).join('')}]`, 'g');

/**
 * 名前を比べる形にする。空白を取り、全角と半角をそろえ（NFKC）、カタカナをひらがなに、異体字をふだんの字にする。
 * ひらがなを漢字に直された（「やまだ」→「山田」）ときは読みが分からないので同じ人と見られない。AI には書かれた字のまま
 * 登録するよう言ってある（src/chatKnowledge.js）
 */
const 比べる形 = (字) =>
  String(字 || '')
    .normalize('NFKC')
    .replace(/\s+/g, '')
    .replace(/[ァ-ヶ]/g, (カナ) => String.fromCharCode(カナ.charCodeAt(0) - 0x60))
    .replace(異体字の形, (古い) => 異体字[古い]);

/**
 * @param {object[]} 人たち      AI が addMember / addMembers に渡した人（{ name, grade, gender }）
 * @param {string[]} 利用者の文たち この会話で利用者が送った文
 * @param {object[]} [前のカード]   まだ押していない（待っている）部員登録のカードの人（args）。登録が済んだカードは入れない
 *                                （済んだあとに「あと2人」と頼まれて、同じ人数で名前を作られないように）
 * @returns {{ 通す: object[], 名前が無い: object[], 残り: object[], 直し?: boolean }}  直し … 前のカードの書き方の直しとして通した
 *   通す … カードを出す人（50 人まで）、名前が無い … 利用者が書いていない名前、残り … 51 人目から
 */
function 部員の頼みを確かめる(人たち, 利用者の文たち, 前のカード = []) {
  const 人 = (人たち || []).filter((一人) => 一人 && 比べる形(一人.name));
  const 書いた文 = 比べる形((利用者の文たち || []).join('\n'));
  const 書いた人 = [];
  const 名前が無い = [];
  for (const 一人 of 人) (書いた文.includes(比べる形(一人.name)) ? 書いた人 : 名前が無い).push(一人);
  // 利用者が前のカードの名前の書き方を直すよう頼んだ（「はしご高にして」「ひらがなにして」）ときは、AI が出し直した名前が
  // 文に無くても通す。前のカードと同じ人数のときだけ（人数を増やす頼みで名前を作らせない。2026-11-08 本人）
  if (名前が無い.length && 前のカード.length && 人.length === 前のカード.length)
    return { 通す: 人.slice(0, 一度に登録できる人数), 名前が無い: [], 残り: 人.slice(一度に登録できる人数), 直し: true };
  if (名前が無い.length) return { 通す: [], 名前が無い, 残り: [] };
  return {
    通す: 書いた人.slice(0, 一度に登録できる人数),
    名前が無い,
    残り: 書いた人.slice(一度に登録できる人数),
  };
}

/** AI へ返す断りの文（AI はこれを利用者に伝える）。断らないときは空 */
function 断りの文(結果) {
  if (結果.名前が無い.length)
    return '利用者が書いていない名前は登録しません（連番や仮の名前は作りません）。登録する人の名前を一人ずつ書いて送ってください、と利用者に伝えてください。カードは出していません。';
  return '';
}

/** 51 人目から残ったときに、カードの下に出す文 */
function 残りの文(結果) {
  const 残り = 結果.残り.length;
  if (!残り) return '';
  const 先頭 = 結果.残り[0] && 結果.残り[0].name;
  return `一度に登録できるのは${一度に登録できる人数}人までです。まず${一度に登録できる人数}人のカードを出しました。残りの${残り}人（${先頭}さんから）は、登録が済んだらもう一度頼んでください。`;
}

module.exports = { 部員の頼みを確かめる, 断りの文, 残りの文, 一度に登録できる人数, 比べる形 };
