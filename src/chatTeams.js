/**
 * AI の相談役の道具「組を作る」（makeBalancedTeams）の計算。
 *
 * 2026-10-17 の本番のやり取りで、AI が自分で組分けを考えたところ、
 *   ・ランキングの基準（射数の少ない人を外す）のまま一部の人を勝手に外し、
 *   ・人数を数え違え（27 人を 21 人と言った）、
 *   ・「均等」と言いながら組ごとの的中率がばらついた（聞き返されて組み直した）。
 * 数える・分ける・比べるはここで済ませ、AI には出来上がった組を伝えさせる。
 *
 * そろえるもの（2026-10-19 本人が決めた）：次に組で立ったときの「組で足した中り÷射数」の見込み。
 *   一人ひとりが同じ数を引くとみて、組の見込み＝一人ずつの見込みの平均。
 *   一人の見込みは、期間の中り・射数を部全体の的中率へ 寄せの射数 ぶん寄せたもの
 *   （少ない射数の 0% や 100% に振り回されない）。
 * 期間に一度も引いていない人：期間の外の記録から見込む（本人の指定）。それも無ければ部全体の的中率。
 * 割り切れないとき：余り の指定どおり（'足す'＝どこかの組に 1 人ずつ足す・'別に'＝組に入れず余りとして出す・
 *   '少ない組'＝1 人少ない組を作る）。
 *
 * 2026-10-25（本人「均等にするだけでなく、一番的中の出るチームを組むとかもっと色々」）に足した：
 *   ・目的 '強い順' … 見込みの高い人から 1 組目・2 組目…と組む（「いちばん当たる組」「1軍・2軍」）
 *   ・組の数 … その数だけ組む。足りない人は見込みの高い人から選び（必ず入れる人が先）、残りは 選ばなかった人
 *   ・だけ（この人たちだけで組む）・必ず入れる・同じ組（一緒にする人たち）・別の組（離す人たち）
 *   ・散らす（'学年'・'性別'）… 均等のとき、各組に学年や男女を散らす
 *   決まりは、均等の入れ替えのときに「開き＋破った決まり＋散らばりの偏り」を小さくする形で守る。
 *   守り切れなかった決まりは 守れなかった決まり で返す。強い順では、同じ組・別の組・散らすは見ない（そう返す）
 */
'use strict';

const { 全員の成績, 名前で選ぶ } = require('./chatStats');

const 寄せの射数 = 12;
const 余りの種類 = ['足す', '別に', '少ない組'];
const 目的の種類 = ['均等', '強い順'];
const 散らし方の種類 = ['学年', '性別'];

/** 決まりを破った重み（見込みの開きは 0〜1 なので、これを 1 つ破るより開きが広がるほうを選ぶ） */
const 破りの重み = 10;
/** 散らばりの偏り 1 人ぶんの重み（開きの 10 ポイントぶん。散らしてと言われたら、開きより散らすほうを先に見る） */
const 偏りの重み = 0.1;

const 丸める = (数) => Number((数 * 100).toFixed(1));

/**
 * 組の大きさを決める。
 * @returns {{大きさ: number[], 余りの人数: number}}
 */
function 組の大きさ(人数, 一組, 余り) {
  if (人数 <= 0 || 一組 <= 0) return { 大きさ: [], 余りの人数: 0 };
  if (人数 <= 一組) return { 大きさ: [人数], 余りの人数: 0 };
  const 割り = Math.floor(人数 / 一組);
  const 端 = 人数 - 割り * 一組;
  if (端 === 0) return { 大きさ: Array(割り).fill(一組), 余りの人数: 0 };
  if (余り === '別に') return { 大きさ: Array(割り).fill(一組), 余りの人数: 端 };
  if (余り === '少ない組') {
    // 組の数を 1 つ増やし、足りない人数ぶん 1 人少ない組を作る
    const 組数 = 割り + 1;
    const 足りない = 組数 * 一組 - 人数;
    return {
      大きさ: Array.from({ length: 組数 }, (無, 番) => (番 < 足りない ? 一組 - 1 : 一組)),
      余りの人数: 0,
    };
  }
  // 足す：端の人数ぶん、組に 1 人ずつ足す
  return { 大きさ: Array.from({ length: 割り }, (無, 番) => (番 < 端 ? 一組 + 1 : 一組)), 余りの人数: 0 };
}

const 平均 = (並び) => (並び.length ? 並び.reduce((和, 人) => 和 + 人.見込み, 0) / 並び.length : 0);

/** 人の、散らす切り口の値（学年は数、性別は 男子・女子 にそろえる） */
function 散らす値(人, 切り口) {
  const 元 = 人 && 人.元;
  if (切り口 === '学年') return String((元 && 元.grade) ?? '');
  const 文 = String((元 && 元.gender) || '');
  return /男|^male$/i.test(文) ? '男子' : /女|^female$/i.test(文) ? '女子' : '未設定';
}

/**
 * 組を配る。見込みの高い順に蛇行で配り、そのあと 2 人の入れ替えで
 * 「開き（いちばん高い組といちばん低い組の差）＋破った決まり＋散らばりの偏り」を縮める。
 * 組ごとの見込みの和を持ち、入れ替えの良し悪しは差分で見る（168 人の団体でも重くならないように）
 * @param {Array<{見込み:number}>} 人たち
 * @param {number[]} 大きさ
 * @param {{同じ?: Array<Array<object>>, 別?: Array<Array<object>>, 散らす?: string[]}} [決まり]
 */
function 均等に配る(人たち, 大きさ, 決まり) {
  const 決 = 決まり || {};
  const 同じ = (決.同じ || []).filter((組) => 組.length >= 2);
  const 別 = (決.別 || []).filter((組) => 組.length >= 2);
  const 散らす = (決.散らす || []).filter((x) => 散らし方の種類.includes(x));
  const 組数 = 大きさ.length;
  if (!組数) return [];

  // 蛇行で最初の割り当て
  const 並び = [...人たち].sort((甲, 乙) => 乙.見込み - 甲.見込み);
  const 所属 = new Map();
  const 組たち = 大きさ.map(() => []);
  let 向き = 1;
  let 番 = 0;
  const 進める = () => {
    番 += 向き;
    if (番 >= 組数) {
      番 = 組数 - 1;
      向き = -1;
    } else if (番 < 0) {
      番 = 0;
      向き = 1;
    }
  };
  for (const 人 of 並び) {
    let 試し = 0;
    while (組たち[番].length >= 大きさ[番] && 試し < 組数 * 2) {
      進める();
      試し++;
    }
    組たち[番].push(人);
    所属.set(人, 番);
    進める();
  }

  // 差分で比べるための控え
  const 和 = 組たち.map((組) => 組.reduce((計, 人) => 計 + 人.見込み, 0));
  const 人数 = 組たち.map((組) => 組.length);
  // 散らす切り口ごとに、組ごとの数と、全体での割合から決まる「各組にいてほしい数」
  const 散らしの数 = 散らす.map((切り口) => {
    const 全体 = new Map();
    for (const 人 of 人たち) {
      const 値 = 散らす値(人, 切り口);
      全体.set(値, (全体.get(値) || 0) + 1);
    }
    const 組ごと = 組たち.map((組) => {
      const 数 = new Map();
      for (const 人 of 組) 数.set(散らす値(人, 切り口), (数.get(散らす値(人, 切り口)) || 0) + 1);
      return 数;
    });
    return { 切り口, 全体, 組ごと, 全員: 人たち.length };
  });
  /** 1 つの組の偏り（いてほしい数との差の和） */
  const 組の偏り = (散, 組) => {
    let 計 = 0;
    for (const [値, 全] of 散.全体) {
      const ほしい = (全 * 人数[組]) / 散.全員;
      計 += Math.abs((散.組ごと[組].get(値) || 0) - ほしい);
    }
    return 計;
  };
  // 人 → その人が入っている決まり
  const 決まりの持ち主 = new Map();
  const 登録 = (組, 種) => {
    for (const 人 of 組) {
      if (!決まりの持ち主.has(人)) 決まりの持ち主.set(人, []);
      決まりの持ち主.get(人).push({ 組, 種 });
    }
  };
  同じ.forEach((組) => 登録(組, '同じ'));
  別.forEach((組) => 登録(組, '別'));
  /** 決まり 1 つの破り（同じ：散った組の数−1、別：同じ組に入った組み合わせの数） */
  const 破り = ({ 組, 種 }) => {
    if (種 === '同じ') return new Set(組.map((人) => 所属.get(人))).size - 1;
    let 数 = 0;
    for (let い = 0; い < 組.length; い++)
      for (let ろ = い + 1; ろ < 組.length; ろ++) if (所属.get(組[い]) === 所属.get(組[ろ])) 数++;
    return 数;
  };
  const 開き = () => {
    let 高 = -Infinity;
    let 低 = Infinity;
    for (let 組 = 0; 組 < 組数; 組++) {
      const 値 = 和[組] / 人数[組];
      if (値 > 高) 高 = 値;
      if (値 < 低) 低 = 値;
    }
    return 高 - 低;
  };
  /** 入れ替えに関わる 2 人の決まりと 2 つの組の偏り（入れ替えの前後で比べる部分） */
  const 関わる分 = (甲, 乙, 組甲, 組乙) => {
    let 計 = 0;
    const 見た = new Set();
    for (const 人 of [甲, 乙])
      for (const 決 of 決まりの持ち主.get(人) || []) {
        if (見た.has(決)) continue;
        見た.add(決);
        計 += 破りの重み * 破り(決);
      }
    for (const 散 of 散らしの数) 計 += 偏りの重み * (組の偏り(散, 組甲) + 組の偏り(散, 組乙));
    return 計;
  };
  const 入れ替える = (甲, 乙) => {
    const 組甲 = 所属.get(甲);
    const 組乙 = 所属.get(乙);
    組たち[組甲][組たち[組甲].indexOf(甲)] = 乙;
    組たち[組乙][組たち[組乙].indexOf(乙)] = 甲;
    所属.set(甲, 組乙);
    所属.set(乙, 組甲);
    和[組甲] += 乙.見込み - 甲.見込み;
    和[組乙] += 甲.見込み - 乙.見込み;
    for (const 散 of 散らしの数) {
      const 値甲 = 散らす値(甲, 散.切り口);
      const 値乙 = 散らす値(乙, 散.切り口);
      散.組ごと[組甲].set(値甲, 散.組ごと[組甲].get(値甲) - 1);
      散.組ごと[組甲].set(値乙, (散.組ごと[組甲].get(値乙) || 0) + 1);
      散.組ごと[組乙].set(値乙, 散.組ごと[組乙].get(値乙) - 1);
      散.組ごと[組乙].set(値甲, (散.組ごと[組乙].get(値甲) || 0) + 1);
    }
  };

  const 全員 = [...所属.keys()];
  for (let 回 = 0; 回 < 300; 回++) {
    const 今の開き = 開き();
    let 良い = null;
    for (let い = 0; い < 全員.length; い++)
      for (let ろ = い + 1; ろ < 全員.length; ろ++) {
        const 甲 = 全員[い];
        const 乙 = 全員[ろ];
        const 組甲 = 所属.get(甲);
        const 組乙 = 所属.get(乙);
        if (組甲 === 組乙) continue;
        const 前 = 関わる分(甲, 乙, 組甲, 組乙) + 今の開き;
        入れ替える(甲, 乙);
        const 後 = 関わる分(甲, 乙, 組甲, 組乙) + 開き();
        入れ替える(乙, 甲);
        const 減り = 前 - 後;
        if (減り > 1e-9 && (!良い || 減り > 良い.減り)) 良い = { 甲, 乙, 減り };
      }
    if (!良い) break;
    入れ替える(良い.甲, 良い.乙);
  }
  return 組たち;
}

/** 強い順に配る：見込みの高い人から、大きい組を先に 1 組目・2 組目…と埋める */
function 強い順に配る(人たち, 大きさ) {
  const 並び = [...人たち].sort((甲, 乙) => 乙.見込み - 甲.見込み);
  const 大きい順 = [...大きさ].sort((甲, 乙) => 乙 - 甲);
  const 組たち = [];
  let 頭 = 0;
  for (const 数 of 大きい順) {
    組たち.push(並び.slice(頭, 頭 + 数));
    頭 += 数;
  }
  return 組たち;
}

/**
 * 組を作る。
 * @param {Array} 部員たち
 * @param {Array} 記録たち
 * @param {{期間?: {始め?: number, 終わり?: number}, 一組の人数: number, 外す?: string[], 余り?: string,
 *   目的?: string, 組の数?: number, だけ?: string[], 必ず入れる?: string[], 同じ組?: string[][],
 *   別の組?: string[][], 散らす?: string[]}} 注文
 */
function 組を作る(部員たち, 記録たち, 注文) {
  const 設定 = 注文 || /** @type {any} */ ({});
  const 一組 = Math.max(1, Math.floor(Number(設定.一組の人数) || 0));
  const 余り = 余りの種類.includes(設定.余り) ? 設定.余り : '足す';
  const 目的 = 目的の種類.includes(設定.目的) ? 設定.目的 : '均等';
  const 組の数の指定 = Math.floor(Number(設定.組の数) || 0) > 0 ? Math.floor(Number(設定.組の数)) : null;
  const 人たち = (Array.isArray(部員たち) ? 部員たち : []).filter((人) => 人 && 人.name);

  // 名前で選ぶ（同じ名前が 2 人以上・見つからないは、そのまま伝える）
  const 見つからない = [];
  const 迷った = [];
  const 選ぶ = (名) => {
    const { 人, 候補 } = 名前で選ぶ(人たち, 名);
    if (人) return 人;
    if (候補.length > 1) 迷った.push({ 名前: 名, 候補: 候補.map((候) => 候.name) });
    else 見つからない.push(名);
    return null;
  };
  const 名前の並び = (値) => (Array.isArray(値) ? 値.map(String).filter(Boolean) : []);
  const 外す人 = new Set(名前の並び(設定.外す).map(選ぶ).filter(Boolean));
  const だけ = 名前の並び(設定.だけ);
  const だけの人 = だけ.length ? new Set(だけ.map(選ぶ).filter(Boolean)) : null;
  const 入れる人 = 人たち.filter((人) => !外す人.has(人) && (!だけの人 || だけの人.has(人)));

  const 期間の成績 = 全員の成績(入れる人, 記録たち, { 期間: 設定.期間, 最小射数: 0 }).一覧;
  const 全期間の成績 = 全員の成績(入れる人, 記録たち, { 最小射数: 0 }).一覧;
  const 名で = (一覧) => new Map(一覧.map((行) => [行.名前, 行]));
  const 期間表 = 名で(期間の成績);
  const 全期間表 = 名で(全期間の成績);
  const 部の中り = 期間の成績.reduce((和, 行) => 和 + 行.的中, 0);
  const 部の射数 = 期間の成績.reduce((和, 行) => 和 + 行.射数, 0);
  const 全の中り = 全期間の成績.reduce((和, 行) => 和 + 行.的中, 0);
  const 全の射数 = 全期間の成績.reduce((和, 行) => 和 + 行.射数, 0);
  const 部の率 = 部の射数 > 0 ? 部の中り / 部の射数 : 全の射数 > 0 ? 全の中り / 全の射数 : 0;

  const 見積もった人 = [];
  const 候補たち = 入れる人.map((人) => {
    const 期 = 期間表.get(人.name) || { 的中: 0, 射数: 0 };
    let 中り = 期.的中;
    let 射数 = 期.射数;
    let 見積もり = '';
    if (射数 === 0) {
      const 全 = 全期間表.get(人.name) || { 的中: 0, 射数: 0 };
      if (全.射数 > 0) {
        中り = 全.的中;
        射数 = 全.射数;
        見積もり = `期間に記録が無いので、期間の外の記録（${全.射数}射${全.的中}中）から見込んだ`;
      } else {
        見積もり = '記録が一つも無いので、部全体の的中率を見込みにした';
      }
      見積もった人.push({ 名前: 人.name, わけ: 見積もり });
    }
    const 見込み = (中り + 寄せの射数 * 部の率) / (射数 + 寄せの射数);
    return { 名前: 人.name, 中り: 期.的中, 射数: 期.射数, 見込み, 見積もり, 元: 人 };
  });
  const 候補で = new Map(候補たち.map((候) => [候.元, 候]));
  const 候補に = (名たち) =>
    名たち
      .map(選ぶ)
      .filter(Boolean)
      .map((人) => 候補で.get(人))
      .filter(Boolean);

  // 組む人と組の大きさ
  let 大きさ;
  let 余った = [];
  let 選ばなかった = [];
  let 配る人;
  const 必ず = 候補に(名前の並び(設定.必ず入れる));
  if (組の数の指定 && 組の数の指定 * 一組 < 候補たち.length) {
    // 組の数だけ組む。必ず入れる人を先に、残りは見込みの高い人から
    const 席 = 組の数の指定 * 一組;
    const 残り = 候補たち.filter((候) => !必ず.includes(候)).sort((甲, 乙) => 乙.見込み - 甲.見込み);
    配る人 = [...必ず, ...残り].slice(0, 席);
    選ばなかった = 候補たち.filter((候) => !配る人.includes(候)).sort((甲, 乙) => 乙.見込み - 甲.見込み);
    大きさ = Array(組の数の指定).fill(一組);
  } else {
    const 分け = 組の大きさ(候補たち.length, 一組, 余り);
    大きさ = 分け.大きさ;
    // 「別に」のときの余りは、記録のいちばん少ない人から（見込みのいちばん当てにならない人）
    const 並べ = [...候補たち].filter((候) => !必ず.includes(候)).sort((甲, 乙) => 甲.射数 - 乙.射数);
    余った = 分け.余りの人数 > 0 ? 並べ.slice(0, 分け.余りの人数) : [];
    配る人 = 候補たち.filter((人) => !余った.includes(人));
  }

  const 同じ組 = (Array.isArray(設定.同じ組) ? 設定.同じ組 : []).map((組) => 候補に(名前の並び(組)));
  const 別の組 = (Array.isArray(設定.別の組) ? 設定.別の組 : []).map((組) => 候補に(名前の並び(組)));
  const 散らす = 名前の並び(設定.散らす).filter((x) => 散らし方の種類.includes(x));
  const 配る中 = (組) => 組.filter((候) => 配る人.includes(候));
  const 組たち =
    目的 === '強い順'
      ? 強い順に配る(配る人, 大きさ)
      : 均等に配る(配る人, 大きさ, { 同じ: 同じ組.map(配る中), 別: 別の組.map(配る中), 散らす });

  // 守れなかった決まり（組に入らなかった人の決まりも含めて見る）
  const 所属 = new Map();
  組たち.forEach((組, 番) => 組.forEach((人) => 所属.set(人, 番)));
  const 守れなかった = [];
  for (const 組 of 同じ組) {
    if (組.length < 2) continue;
    const 組の番 = new Set(組.map((人) => 所属.get(人)));
    if (組の番.size > 1 || 組の番.has(undefined))
      守れなかった.push(`同じ組にする：${組.map((人) => 人.名前).join('・')}`);
  }
  for (const 組 of 別の組) {
    const 番たち = 組.map((人) => 所属.get(人)).filter((番) => 番 !== undefined);
    if (new Set(番たち).size < 番たち.length)
      守れなかった.push(`別の組にする：${組.map((人) => 人.名前).join('・')}`);
  }
  const 入らなかった必ず = 必ず.filter((人) => !所属.has(人));
  if (入らなかった必ず.length)
    守れなかった.push(`必ず入れる（席が足りない）：${入らなかった必ず.map((人) => 人.名前).join('・')}`);

  const 組の表 = 組たち.map((組, 番) => {
    const 中り = 組.reduce((和, 人) => 和 + 人.中り, 0);
    const 射数 = 組.reduce((和, 人) => 和 + 人.射数, 0);
    const 内訳 = (切り口) => {
      const 数 = {};
      for (const 人 of 組) 数[散らす値(人, 切り口)] = (数[散らす値(人, 切り口)] || 0) + 1;
      return 数;
    };
    return {
      組: 番 + 1,
      人数: 組.length,
      見込みの的中率: 丸める(平均(組)),
      期間の実績: { 的中: 中り, 射数, 的中率: 射数 > 0 ? 丸める(中り / 射数) : null },
      ...(散らす.includes('学年') ? { 学年の内訳: 内訳('学年') } : {}),
      ...(散らす.includes('性別') ? { 男女の内訳: 内訳('性別') } : {}),
      部員: 組.map((人) => ({
        名前: 人.名前,
        期間の的中: 人.中り,
        期間の射数: 人.射数,
        期間の的中率: 人.射数 > 0 ? 丸める(人.中り / 人.射数) : null,
        見込みの的中率: 丸める(人.見込み),
        ...(人.見積もり ? { 見積もり: 人.見積もり } : {}),
      })),
    };
  });
  const 見込みたち = 組の表.map((組) => 組.見込みの的中率);
  // 「3人の組 4・2人の組 1」。余りを 1 人少ない組にしたとき、模型が「3人ずつ5組」と言い違えた（2026-10-25 の確かめ）
  const 人数ごと = new Map();
  for (const 組 of 組の表) 人数ごと.set(組.人数, (人数ごと.get(組.人数) || 0) + 1);
  const 組の人数の内訳 = [...人数ごと.entries()]
    .sort((甲, 乙) => 乙[0] - 甲[0])
    .map(([人数, 数]) => `${人数}人の組 ${数}`)
    .join('・');
  const 強い順で見ない =
    目的 === '強い順' &&
    (同じ組.some((組) => 組.length >= 2) || 別の組.some((組) => 組.length >= 2) || 散らす.length);

  return {
    目的,
    分けた人数: 配る人.length,
    組の数: 組の表.length,
    一組の人数: 一組,
    組の人数の内訳,
    余りの扱い: 組の数の指定 && 選ばなかった.length ? '組の数の指定（余りは 選ばなかった人）' : 余り,
    組: 組の表,
    組の見込みの開き: 見込みたち.length
      ? Number((Math.max(...見込みたち) - Math.min(...見込みたち)).toFixed(1))
      : 0,
    部全体の的中率: 丸める(部の率),
    外した人: [...外す人].map((人) => 人.name),
    ...(だけの人 ? { この人たちだけで組んだ: [...だけの人].map((人) => 人.name) } : {}),
    ...(選ばなかった.length
      ? {
          選び方: '必ず入れる人を先に、残りは見込みの高い人から選んだ',
          選ばなかった人: 選ばなかった.map((人) => ({ 名前: 人.名前, 見込みの的中率: 丸める(人.見込み) })),
        }
      : {}),
    ...(散らす.length ? { 散らした: 散らす } : {}),
    守れなかった決まり: 強い順で見ない
      ? [...守れなかった, '強い順では、同じ組・別の組・散らすは見ていません（均等なら見ます）']
      : 守れなかった,
    見つからない名前: 見つからない,
    同じ名前が複数: 迷った,
    見積もった人,
    余った人: 余った.map((人) => 人.名前),
  };
}

/** 前の呼び方（組の見込みをそろえる）。検査と古い呼び出しのために残す */
function 組を均等に分ける(部員たち, 記録たち, 注文) {
  return 組を作る(部員たち, 記録たち, Object.assign({}, 注文, { 目的: '均等' }));
}

