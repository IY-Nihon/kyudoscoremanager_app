/**
 * Module ID: messages
 *
 * 言語ごとの言葉を、画面・部品ごとに分けて持ち、ここでまとめる。
 * src/i18n.js が引く。
 *
 * ■ なぜ1つのファイルにしないのか
 * 画面に直に書かれた日本語は2,389か所ある（npm run ops:scan-japanese）。
 * これを1つの辞書に流し込むと、1回の差分が巨大になって見きれない。
 * 画面ごとに分けておけば、**1画面ずつ移せる**。1画面を移す差分は
 *   ・その画面のファイル
 *   ・src/messages/<その画面>.js（新規）
 *   ・src/messages/index.js（1行）
 * だけになり、型検査と e2e をその画面ぶんだけ通せばよい。
 *
 * ■ なぜ JSON にしないのか
 * この repo では「なぜそう書いたか」を注釈で残すことにしている。
 * JSON には注釈が書けず、「大前を訳さない理由」のような、いちばん
 * 引き継ぎたいことが落ちる。形式より、消えないことを採る。
 *
 * ■ 1画面を移す手順
 *   1. その画面の日本語を数える（npm run ops:scan-japanese）
 *   2. src/messages/<画面>.js を作り、ja と en を書く
 *   3. ここの 束 に足す
 *   4. 画面の側を 訳('鍵') に置き換える。既定は日本語なので見た目は変わらない
 *   5. npm test（型検査・未定義の変数・単体）と、その画面の e2e を通す
 *   6. 次の画面へ
 *
 * 移す順は、読み上げ → 記録 → 設定 → 分析 の順を想定している。
 * 読み上げを先に済ませたのは、画面の字が読めない人にとって唯一の
 * 手がかりだから（src/a11yLabels.js）。
 *
 * ■ 鍵の付け方
 * 「どの画面の、何の言葉か」が分かる名前にする。日本語そのものを鍵に
 * すると、日本語を直したときに全言語の訳が外れる。
 * 鍵はファイルをまたいで重ならないこと（test/i18n.test.js で見ている）。
 *
 * ■ 数の入れ方
 * 文中の {n} に入る。英語のように単数と複数で形が変わるものは
 * { 一: '…', 多: '…' } と書く。0 は「多」。
 */
'use strict';

/** 画面・部品ごとの辞書。ここへ足していく */
const 束 = {
  a11y: require('./a11y'),
  live: require('./live'),
};

/** 扱う言語。ja は必ず埋まっていること（訳が無いときの落ち先） */
const 言語たち = ['ja', 'en'];

/**
 * 束をまとめて、言語ごとの平らな表にする。
 *
 * 鍵が重なったら、その場で止める。黙って上書きすると、どちらの言葉が
 * 出るかがファイルの並び順で決まり、追いかけようがなくなる
 */
function まとめる(束) {
  const 出 = {};
  for (const 言語 of 言語たち) 出[言語] = {};
  for (const 名 of Object.keys(束)) {
    const 一組 = 束[名] || {};
    for (const 言語 of 言語たち) {
      const 表 = 一組[言語] || {};
      for (const 鍵 of Object.keys(表)) {
        if (Object.prototype.hasOwnProperty.call(出[言語], 鍵))
          throw new Error(`言葉の鍵が重なっています: ${鍵}（${名}.js／${言語}）`);
        出[言語][鍵] = 表[鍵];
      }
    }
  }
  return 出;
}

const 言葉たち = まとめる(束);

module.exports = { 言葉たち, 束, 言語たち, まとめる };
