/**
 * ログアウトの確認に出す文言を決める。
 *
 * ログアウトは手元の記録を全部捨てるので、送れていないものがあるときは
 * まず送信を試し、送れなかったときだけ「捨てて抜ける」を選べるようにする。
 * 捨てる操作には、そうと分かる名前を付ける。
 *
 *   確認 ──(未送信あり・押す)──> 送信中 ──┬─> 送信済み ─> ログアウト
 *     │                                    └─> 失敗 ──> 捨ててログアウト
 *     └──(未送信なし・押す)────────────────────> ログアウト
 *
 * 画面（JP_SettingsScreen_1023.js）から使う。ここに切り出してあるのは、
 * 画面を動かさずに文言の出し分けを検査するため。
 */
'use strict';

const 確認 = '確認';
const 送信中 = '送信中';
const 送信済み = '送信済み';
const 失敗 = '失敗';

/** 確認に出す本文 */
function logoutMessage(段階, 残り) {
  if (段階 === 送信中) return '送信しています...';
  if (段階 === 送信済み) return '送信できました。ログアウトします。';
  if (段階 === 失敗)
    return `送信できませんでした。電波の届く場所でもう一度お試しください。このままログアウトすると、送信できていない${残り}件は失われます。`;
  return 残り > 0
    ? `送信できていない記録が${残り}件あります。このままログアウトすると失われます。`
    : 'ログアウトしますか？';
}

/** 右側（赤いほう）のボタンの名前 */
function logoutButtonLabel(段階, 残り) {
  if (段階 === 送信中) return '送信中...';
  if (段階 === 失敗) return '未送信の記録を削除してログアウト';
  if (段階 === 送信済み) return 'ログアウト';
  return 残り > 0 ? '送信してログアウト' : 'ログアウト';
}

/** 押している最中は両方のボタンを止める */
function logoutButtonsDisabled(段階) {
  return 段階 === 送信中 || 段階 === 送信済み;
}

/** 押したときに、まず送信を試すべきか */
function shouldTrySendFirst(段階, 残り) {
  return 段階 === 確認 && 残り > 0;
}

module.exports = {
  logoutMessage,
  logoutButtonLabel,
  logoutButtonsDisabled,
  shouldTrySendFirst,
  段階: { 確認, 送信中, 送信済み, 失敗 },
};
