/**
 * ログアウトの確認に出す文言を決める。
 *
 * 送れていないものがあるときは、まず送信を試す。送れなかったぶんは捨てずに、
 * 団体ごとの控えとして端末に残し（src/unsentStash.js）、次に同じ団体で入ったときに送る。
 * 2026-10-17 までは「未送信の記録を削除してログアウト」しか選べず、ログインが外れて
 * 送れない端末で部内戦 27 人分が消えた。
 *
 *   確認 ──(未送信あり・押す)──> 送信中 ──┬─> 送信済み ─> ログアウト
 *     │                                    └─> 失敗（端末に残した）─> ログアウト
 *     └──(未送信なし・押す)────────────────────> ログアウト
 *
 * 画面（SettingsScreen.js）から使う。ここに切り出してあるのは、
 * 画面を動かさずに文言の出し分けを検査するため。
 */
'use strict';

const 確認 = '確認';
const 送信中 = '送信中';
const 送信済み = '送信済み';
const 失敗 = '失敗';

/** 確認に出す本文 */
function logoutMessage(段階, 残り) {
  if (段階 === 送信中) return '送信しています...';
  if (段階 === 送信済み) return '送信できました。ログアウトします。';
  if (段階 === 失敗)
    return `送れなかった${残り}件は、この端末に残しました。次に同じ団体でログインすると送られます。ログアウトします。`;
  return 残り > 0
    ? `送れていない記録が${残り}件あります。この端末に残しておき、次に同じ団体でログインすると送られます。`
    : 'ログアウトしますか？';
}

/** 右側のボタンの名前 */
function logoutButtonLabel(段階) {
  if (段階 === 送信中) return '送信中...';
  return 'ログアウト';
}

/** 押している最中は両方のボタンを止める */
function logoutButtonsDisabled(段階) {
  return 段階 === 送信中 || 段階 === 送信済み || 段階 === 失敗;
}

/** 押したときに、まず送信を試すべきか */
function shouldTrySendFirst(段階, 残り) {
  return 段階 === 確認 && 残り > 0;
}

module.exports = {
  logoutMessage,
  logoutButtonLabel,
  logoutButtonsDisabled,
  shouldTrySendFirst,
  段階: { 確認, 送信中, 送信済み, 失敗 },
};
