/**
 * 指示文の 1 つの節（見出しから次の節の手前まで）を取り出す。
 * 共通の決まり（用語の読み方・言葉づかい・答え方）は、団体用の指示文から取って、二重に書かない。
 * @param {string} 基本 団体用の指示文
 * @param {string} 見出し 【…】で始まる節の見出し
 */
function 節を取る(基本, 見出し) {
  const i = 基本.indexOf(見出し);
  if (i < 0) return '';
  const j = 基本.indexOf('\n\n【', i + 見出し.length);
  return 基本.slice(i, j < 0 ? undefined : j).trim();
}

/**
 * 個人ログイン用の指示文。
 * @param {string} 基本 団体用の指示文（systemInstructionBase）
 * @param {{name?: string, grade?: number}|null} 本人
 */
function 個人用の指示文(基本, 本人) {
  const 名前 = (本人 && 本人.name) || '';
  // 学年 0 は「その他」（画面と同じ。0年とは書かない）
  const 学年 =
    本人 && typeof 本人.grade === 'number'
      ? 本人.grade >= 5
        ? '卒業生'
        : 本人.grade === 0
          ? 'その他'
          : `${本人.grade}年`
      : '';
  const 呼び名 = 名前 ? `「${名前}」${学年 ? `（${学年}）` : ''}` : '本人';
  const 名前の引数 = 名前 ? `「${名前}」` : '本人の名前';

  const できないこと = 節を取る(基本, '【できないこと（正直に断ること）】').replace(
    '手元にあるのは、この団体の記録とQ&Aだけです',
    '手元にあるのは、本人の記録とQ&Aだけです'
  );

  return [
    `あなたは「弓道部的中ノート」専用の、弓道の記録を読み解き、アプリの使い方を案内するアシスタントです。
話し相手は、個人ログインで入っている部員本人（${呼び名}）です。次の2つを行ってください。

1. [データを読む] ツールで取ってきた本人の記録に基づいて、調子や的中の傾向を伝える。
2. [使い方の案内] アプリの仕様の質問には、下の【アプリ操作・仕様Q&A】だけを根拠に答える。`,

    `【本人の分だけを扱います（必ず守ること）】
・手元にあるのは、本人の記録と成績だけです。ほかの部員・団体全体の成績、順位、ランキング、出欠、名前は、ありません。
・ほかの人の成績や順位、団体全体の的中率などを聞かれたら、「個人で入っているときは、自分の分だけお答えできます。ほかの人のことは団体の担当者に聞いてください」と断ってください。数字や名前を作らないでください。
・「私」「自分」「僕」「俺」と言われたら本人のことです。ツールに名前を渡すときは ${名前の引数} を使ってください。
・記録に「（他の人）」と出てくるのは、途中で交代した相手などです。誰かは分かりません。推測して名前を挙げないでください。
・部員の追加や削除、記録の編集・削除、出欠の管理、団体の設定はできません。頼まれたら、団体の担当者に頼むよう伝えてください。`,

    できないこと,

    `【数字の扱い（守ること）】
・的中数・射数・的中率は、必ずツールが返した値をそのまま使ってください。自分で足し算・割り算をしないでください。
・ツールを呼ばずに、会話の記憶から成績を答えないでください。分からなければツールを呼んでください。
・ツールが返していない期間については「その範囲は集計していない」と伝え、数字を作らないでください。
・ツールに渡していない条件を、答えに書かないでください。渡した条件だけを述べてください。
・射数の少ない期間や射位の的中率は数字が揺れます。率だけでなく射数も添えてください。`,

    `【どのツールを使うか】
・本人の詳しい成績（1射ごと、大前・落など） → getDetailedMemberStats（memberName は ${名前の引数}）
・本人の射位ごとの的中率 → getPositionStats
・日付が分かっている記録 → getSessionsByDate
・日付が分からない記録を言葉で探す → searchSessions
・「自主練の的中率」「試合だけの成績」など、タグで分けた自分の成績 → getDetailedMemberStats・getPositionStats の tags にタグを渡す（返ってきた数字は「そのタグで絞った数字」と添える）
・「自主練に何回参加したか」など、タグや言葉で絞った記録に自分が何回参加したか → countSessionParticipation（返ってきた回数をそのまま使う）
・画面を開く → navigateToScreen（開けるのは ${個人が行ける画面.join('・')}）`,

    `【射位や立ち順について】
・本人の射位ごとの的中率は getPositionStats の数字を根拠に伝え、射数が少ないときはその旨を添えてください。誰をどこに置くかは団体の担当者が決めることなので、本人には決められません。`,

    節を取る(基本, '【弓道用語の読み方（厳守）】'),
    節を取る(基本, '【アプリの言葉づかい（画面と揃えること）】'),
    節を取る(基本, '【答え方】'),
  ]
    .filter(Boolean)
    .join('\n\n');
}

/**
 * 個人に出す道具の宣言。使える道具だけに絞り、団体向けの言い回しを本人向けに直す。
 * 元の宣言は書き換えない。
 * @param {Array<{name: string, description?: string, parameters?: object}>} 宣言たち
 */
function 個人向けの道具(宣言たち) {
  const 直す = {
    getDetailedMemberStats: {
      description:
        '本人の詳細な成績データを取得します。初矢から4本目（留矢）まで何本目の矢が当たりやすいか、また大前や落など立順ごとの成績などを分析する際に呼び出してください。memberName には本人の名前を渡してください。「9月の」「今年度の」のように期間が付いていれば dateFrom / dateTo を渡してください（省くと全期間）。',
    },
    getPositionStats: {
      description:
        '本人の射位（大前・2番・落など）ごとの的中率を返します。「大前と落でどちらが得意」「射位ごとの成績」などに使います。射数が少ない射位は数字が揺れるので、射数も一緒に伝えてください。',
      // 本人だけなので、人を絞る引数は要らない
      除く引数: ['memberNames'],
    },
    searchSessions: {
      description:
        '本人が参加した記録を言葉で探します。題・覚え書き・目印（タグ）を見ます。「雨で中断した練習はいつ」「審査のタグが付いた記録」など、日付が分からないときに使います。日付が分かっているときは getSessionsByDate を使ってください。',
    },
    countSessionParticipation: {
      description:
        '本人が、タグや言葉で絞った記録に何回参加したかを数えます。「自主練に何回参加した？」「合宿に何回参加した？」などに使います。ゲストとして出た記録は数えません。',
    },
    getSessionsByDate: {
      description:
        '本人が参加した練習記録を、日付や期間を指定して取得します。「昨日の記録」「今週の練習」「5月の記録」「直近3回」などの質問に使います。dateとdateFrom/dateToとrecentCountはいずれか一つを指定してください。',
    },
    navigateToScreen: {
      description: '指定した画面タブへ遷移します。',
      画面: `遷移先の画面名（${個人が行ける画面.join(', ')} のいずれか）`,
    },
  };
  return (Array.isArray(宣言たち) ? 宣言たち : [])
    .filter((宣言) => 宣言 && 個人が使える道具.includes(宣言.name))
    .map((宣言) => {
      const 元 = JSON.parse(JSON.stringify(宣言));
      const 変更 = 直す[元.name] || {};
      if (変更.description) 元.description = 変更.description;
      if (元.parameters && 元.parameters.properties) {
        for (const 引数 of 変更.除く引数 || []) delete 元.parameters.properties[引数];
        if (変更.画面 && 元.parameters.properties.screenName)
          元.parameters.properties.screenName.description = 変更.画面;
      }
      return 元;
    });
}

