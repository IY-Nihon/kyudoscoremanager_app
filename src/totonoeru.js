/**
 * 人が打った・貼った ID とメールを、照合に使える形に整える。
 *
 * スマホの予測変換や、LINE・メモ帳からの貼り付けで、全角の英数字（１２３４５６）や
 * 見えない空白（幅の無い空白・全角の空白・改行）が混じる。そのまま照合すると、
 * 合っているのに「正しくありません」になり、見た目では気づけない。
 *
 * パスワードには使わないこと（全角も空白もパスワードの字のうち）。
 * 画面から切り離してあり、そのまま検査できる（test/totonoeru.test.js）。
 */
'use strict';

/** 全角の英数字と記号（！〜～）を半角にする。漢字・かなは触らない */
const 半角にする = (値) =>
  String(値 == null ? '' : 値).replace(/[\uFF01-\uFF5E]/g, (字) => String.fromCharCode(字.charCodeAt(0) - 0xfee0));

/** 見えない空白。\s（ふつうの空白・改行・全角の空白・BOM）に加えて、幅の無い空白・つなぎの字 */
const 見えない空白 = /[\s\u200B-\u200D\u2060]+/g;

/** 半角にして、見えない空白を除く（大文字・小文字はそのまま） */
const 字をそろえる = (値) => 半角にする(値).replace(見えない空白, '');

/** 人が打つ団体ID・個人ID。字をそろえて大文字にする */
const IDを整える = (値) => 字をそろえる(値).toUpperCase();

/**
 * 登録メールアドレス。字をそろえて小文字にする。
 * Firebase の認証はメールを小文字で持ち、決まり（firestore.rules の callerEmail）はそれと比べる。
 * 大文字が混じったまま帳面に書くと、団体を作るときも、アドレスを切り替えるときも断られる
 */
const メールを整える = (値) => 字をそろえる(値).toLowerCase();

module.exports = { 半角にする, 字をそろえる, IDを整える, メールを整える };
