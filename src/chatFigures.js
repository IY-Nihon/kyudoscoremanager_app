/**
 * AI チャットの図（showFigure）。道具が返した結果から、図の形（折れ線・棒・表・矢所）を作る。
 *
 * 2026-10-25 に本人と決めた：数字の推移や比べ・ランキング・表・矢所は、答えの文の下に図で出す。
 * 図は模型に数字を書き写させず、道具が数えた結果（端末に控えたもの）から直に作る。
 * 模型は「どの結果を・どの形で」だけを選ぶ（showFigure の source と kind）。
 *
 * 画面にも Firebase にも触れないので、node --test で確かめられる（test/chatFigures.test.js）。
 * 描くのは src/ChatFigure.js。
 */
'use strict';

/** 図の形 */
const 形たち = ['折れ線', '棒', '表', '矢所'];

/** 一つの図に入れる上限（多すぎると読めない・控えが膨らむ） */
const 上限 = { 棒: 30, 表: 50, 折れ線の点: 60, 折れ線の系列: 6, 矢所の点: 200 };

/** 時の流れのある切り口（折れ線にできる） */
const 時の切り口 = new Set(['月', '週', '日', '記録']);
/** 順のある短い切り口（縦の棒） */
const 短い切り口 = new Set(['射目', '立目', '曜日', '射位', '学年', '性別']);
/** 順に並べる切り口（棒は率の順ではなくこの順） */
const 順の切り口 = new Set(['射目', '立目', '曜日', '射位', '学年']);

/** 切り口の値の並びの順（曜日は月〜日、ほかは値に含まれる数） */
function 順の値(切り口, 値) {
  if (切り口 === '曜日') return '月火水木金土日'.indexOf(String(値).charAt(0));
  // 射位は大前が先、落が最後（大前が 7 番の後ろに並んでいた）
  if (切り口 === '射位' && 値 === '大前') return -1;
  if (切り口 === '射位' && 値 === '落') return 1000;
  const 数 = parseFloat(String(値).replace(/[^\d.]/g, ''));
  return Number.isFinite(数) ? 数 : 999;
}

const 率の字 = (率) => (率 == null || !Number.isFinite(Number(率)) ? '—' : `${Number(率).toFixed(1)}%`);
const 学年の字 = (学年) =>
  typeof 学年 === 'number' ? (学年 > 0 ? `${学年}年` : 'その他') : String(学年 ?? '');
const 文の率 = (文) => {
  const 数 = parseFloat(String(文 || '').replace('%', ''));
  return Number.isFinite(数) ? 数 : null;
};

/**
 * 月の切り口の名を短く。YYYY-MM がみな同じ年なら「8月」、年をまたぐなら「26/8」
 * @param {string[]} 名たち
 */
function 月を短く(名たち) {
  const 年たち = new Set(名たち.map((名) => String(名).slice(0, 4)));
  return (名) => {
    const m = /^(\d{4})-(\d{2})$/.exec(String(名));
    if (!m) return 名;
    return 年たち.size === 1 ? `${Number(m[2])}月` : `${m[1].slice(2)}/${Number(m[2])}`;
  };
}

/**
 * 折れ線の横の名を短く（2026-11-13）。記録「2026-10-03 通常練習」・日「2026-10-03」→「10/3」、
 * 週「2026-10-05の週」→「10/5〜」、記録の一覧の「2026/10/3」→「10/3」。
 * 前は名の後ろ 5 字を取っていて、記録ごとの図は「通常練習」ばかり、週は「-06の週」になっていた
 */
function 線の短い名(切り口, 名) {
  const m = /^(\d{4})[-/](\d{1,2})[-/](\d{1,2})/.exec(String(名));
  if (!m || !['日', '週', '記録', '日付'].includes(切り口)) return 名;
  return `${Number(m[2])}/${Number(m[3])}${切り口 === '週' ? '〜' : ''}`;
}

/** 棒の並び。長い名前や多いときは横の棒 */
function 棒にする(題, 並び, 注文 = {}) {
  const 使う = 並び.filter((項) => 項.値 != null && Number.isFinite(項.値)).slice(0, 上限.棒);
  const 横 = 注文.横 != null ? 注文.横 : 使う.length > 8 || 使う.some((項) => String(項.名).length > 4);
  return {
    形: '棒',
    題,
    向き: 横 ? '横' : '縦',
    単位: 注文.単位 || '%',
    並び: 使う,
    // 通算の的中率（縦の棒で、通算より上の棒を濃くし、点線を引く。2026-11-14）
    ...(Number.isFinite(注文.通算) ? { 通算: 注文.通算 } : {}),
    ...(並び.length > 使う.length ? { 注: `上から ${使う.length} 件` } : {}),
  };
}

/** 表。数の列は右に寄せ、いちばん大事な列（率）は青で出す */
function 表にする(題, 列, 行たち, 注文 = {}) {
  const 使う = 行たち.slice(0, 上限.表);
  return {
    形: '表',
    題,
    列,
    行: 使う.map((行) => 行.map((値) => (値 == null ? '—' : String(値)))),
    数の列: 注文.数の列 || [],
    強める列: 注文.強める列 ?? null,
    ...(行たち.length > 使う.length ? { 注: `上から ${使う.length} 件（全 ${行たち.length} 件）` } : {}),
  };
}

/** 折れ線。系列ごとに点（x の名と y の値） */
function 折れ線にする(題, 元の系列たち, 注文 = {}) {
  // 同じ日に記録が 2 つあると、短い名が「10/3」で重なる。2 つ目からは「10/3②」にする（重なると点が消える）
  const 丸数字 = '②③④⑤⑥⑦⑧⑨';
  const 系列たち = 元の系列たち.map((系列) => {
    const 数 = new Map();
    return {
      ...系列,
      点: 系列.点.map((点) => {
        const n = (数.get(点.x) || 0) + 1;
        数.set(点.x, n);
        return n === 1 ? 点 : { ...点, x: `${点.x}${丸数字[n - 2] || `(${n})`}` };
      }),
    };
  });
  const 使う = 系列たち.slice(0, 上限.折れ線の系列).map((系列) => ({
    名: 系列.名,
    点: 系列.点.filter((点) => 点.y != null && Number.isFinite(点.y)).slice(-上限.折れ線の点),
  }));
  // 横の名の並び。値の無い点を落とす前の並び（人×月なら月の順）から、どれかの系列に点がある名だけを取る。
  // 1 本目の系列の名だけで並べると、1 本目に値の無い月の点がほかの系列から消えていた
  const 元の並び = [];
  for (const 系列 of 系列たち.slice(0, 上限.折れ線の系列))
    for (const 点 of 系列.点) if (!元の並び.includes(点.x)) 元の並び.push(点.x);
  const 点のある名 = new Set(使う.flatMap((系列) => 系列.点.map((点) => 点.x)));
  return {
    形: '折れ線',
    題,
    単位: 注文.単位 || '%',
    名たち: 元の並び.filter((名) => 点のある名.has(名)),
    系列: 使う.filter((系列) => 系列.点.length),
    // 通算の的中率（線が 1 本のとき、灰色の点線で引く）
    ...(Number.isFinite(注文.通算) && 使う.length === 1 ? { 通算: 注文.通算 } : {}),
    ...(系列たち.length > 使う.length ? { 注: `上から ${使う.length} 人（全 ${系列たち.length} 人）` } : {}),
  };
}

/**
 * 道具の結果ごとの、作れる形と作り方。
 * 返すのは { 形たち: string[], 作る: (形, 題) => 図 }。作れなければ形たちは空
 * @param {string} 道具 道具の名前
 * @param {any} 結果 道具が返した中身（模型に渡したものと同じ。矢所は _点たち も入る）
 */
function 作り方(道具, 結果) {
  const r = 結果 || {};
  switch (道具) {
    case 'aggregateStats': {
      const 切り口 = Array.isArray(r.切り口) ? r.切り口 : [];
      const 一覧 = Array.isArray(r.一覧) ? r.一覧 : [];
      if (!切り口.length || !一覧.length) return { 形たち: [] };
      const [一, 二] = 切り口;
      // 月の名を短く（「2026-08」→「8月」）
      const 短く = (切り口の名, 値たち) => (切り口の名 === '月' ? 月を短く(値たち) : (名) => 名);
      const 一の名 = 短く(
        一,
        一覧.map((行) => 行[一])
      );
      if (二) {
        // 1 つ目ごとの行に、2 つ目の列（的中率）
        const 列の名 = [];
        for (const 行 of 一覧)
          for (const 内 of 行.内訳 || []) if (!列の名.includes(内[二])) 列の名.push(内[二]);
        // 行の順に初めて出た順のままだと、1 行目の人に無い月が後ろに付いて「10月・9月」と崩れた（表の列も折れ線の横も）。
        // 月は年月（YYYY-MM）の順、順のある切り口はその順に並べる。ほかの切り口は出てきた順のまま
        if (二 === '月') 列の名.sort((甲, 乙) => (String(甲) < String(乙) ? -1 : String(甲) > String(乙) ? 1 : 0));
        else if (順の切り口.has(二)) 列の名.sort((甲, 乙) => 順の値(二, 甲) - 順の値(二, 乙));
        const 二の名 = 短く(二, 列の名);
        const 値 = (行, 名) => {
          const 内 = (行.内訳 || []).find((x) => x[二] === 名);
          return 内 ? 内.的中率 : null;
        };
        return {
          形たち: ['表', '折れ線'],
          作る: (形, 題) =>
            形 === '表'
              ? 表にする(
                  題 || `${一}×${二}の的中率`,
                  [一, ...列の名.map(二の名), ...(一覧.some((行) => 行.振れ幅 != null) ? ['振れ幅'] : [])],
                  一覧.map((行) => [
                    一の名(行[一]),
                    ...列の名.map((名) => 率の字(値(行, 名))),
                    ...(一覧.some((x) => x.振れ幅 != null) ? [行.振れ幅 == null ? '—' : `${行.振れ幅}`] : []),
                  ]),
                  { 数の列: 列の名.map((_, i) => i + 1) }
                )
              : 折れ線にする(
                  題 || `${一}ごとの${二}の的中率`,
                  一覧.map((行) => ({
                    名: 一の名(行[一]),
                    点: 列の名.map((名) => {
                      const 内 = (行.内訳 || []).find((x) => x[二] === 名);
                      return { x: 線の短い名(二, 二の名(名)), y: 値(行, 名), 射数: 内 ? 内.射数 : null };
                    }),
                  }))
                ),
        };
      }
      // 順のある切り口の棒は、率の順ではなくその順に並べ、射目・立目・射位は番号だけを名にする
      //（率の順のまま 30 本並べると「26射目」が「2」に切れて読めなかった。10/26 本番）
      const 順に = 順の切り口.has(一);
      const 並び = (順に ? [...一覧].sort((甲, 乙) => 順の値(一, 甲[一]) - 順の値(一, 乙[一])) : 一覧).map(
        (行) => ({
          // 射位は名のまま（「大前」「落」が空になっていた）
          名: /^(射目|立目)$/.test(一) ? String(行[一]).replace(/\D+$/, '') : 一の名(行[一]),
          射数: 行.射数,
          ...(行.順位 != null && !順に ? { 順位: 行.順位 } : {}),
          値: 行.的中率,
          補足: `${行.射数}射${行.的中}中`,
        })
      );
      const 皆中あり = 一覧.some((行) => 行.皆中 != null);
      const 表 = (題) =>
        表にする(
          題 || `${一}ごとの的中率`,
          [
            ...(一覧[0].順位 != null ? ['順位'] : []),
            一,
            '射数',
            '的中',
            ...(皆中あり ? ['皆中'] : []),
            '的中率',
          ],
          一覧.map((行) => [
            ...(行.順位 != null ? [行.順位] : []),
            一の名(行[一]),
            行.射数,
            行.的中,
            ...(皆中あり ? [行.皆中] : []),
            率の字(行.的中率),
          ]),
          { 数の列: [], 強める列: -1 }
        );
      const 形たち = 時の切り口.has(一) || 順に ? ['折れ線', '棒', '表'] : ['棒', '表'];
      // 順のある切り口で 13 本以上の棒は、細い棒が並んで読めないので折れ線にする（本人 10/26）
      const 線にする = (形) => 形 === '折れ線' || (形 === '棒' && 順に && 並び.length > 12);
      return {
        形たち,
        作る: (形, 題) =>
          形 === '表'
            ? 表(題)
            : 線にする(形)
              ? 折れ線にする(
                  題 || `${一}ごとの的中率`,
                  [
                    {
                      名: '的中率',
                      点: 順に
                        ? 並び.map((項) => ({ x: 線の短い名(一, 項.名), y: 項.値, 補足: 項.補足, 射数: 項.射数 }))
                        : 一覧.map((行) => ({
                            x: 線の短い名(一, 一の名(行[一])),
                            y: 行.的中率,
                            補足: `${行.射数}射${行.的中}中`,
                            射数: 行.射数,
                          })),
                    },
                  ],
                  { 通算: r.全体 && Number(r.全体.的中率) }
                )
              : 棒にする(題 || `${一}ごとの的中率`, 並び, {
                  横: !短い切り口.has(一) && 一 !== '月',
                  通算: r.全体 && Number(r.全体.的中率),
                }),
      };
    }
    case 'getAllMembersStats': {
      const 一覧 = Array.isArray(r.順位) ? r.順位 : [];
      if (!一覧.length) return { 形たち: [] };
      return {
        形たち: ['棒', '表'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || '的中率の順位',
                ['順位', '名前', '学年', '射数', '的中', '的中率'],
                一覧.map((行) => [行.順位, 行.名前, 学年の字(行.学年), 行.射数, 行.的中, 率の字(行.的中率)]),
                { 強める列: -1 }
              )
            : 棒にする(
                題 || '的中率',
                一覧.map((行) => ({
                  名: 行.名前,
                  値: 行.的中率,
                  補足: `${行.射数}射${行.的中}中`,
                  射数: 行.射数,
                  順位: 行.順位,
                })),
                { 横: true }
              ),
      };
    }
    case 'compareMemberStats':
    case 'compareShotRanges': {
      const 一覧 = Array.isArray(r.一覧) ? r.一覧 : [];
      if (!一覧.length) return { 形たち: [] };
      const 前 = 道具 === 'compareMemberStats' ? '前の期間' : '前の射';
      const 後 = 道具 === 'compareMemberStats' ? '今の期間' : '後の射';
      const 前の名 = 道具 === 'compareMemberStats' ? '前' : r.前の射の範囲 || '前';
      const 後の名 = 道具 === 'compareMemberStats' ? '今' : r.後の射の範囲 || '後';
      return {
        形たち: ['表'],
        作る: (形, 題) =>
          表にする(
            題 || (道具 === 'compareMemberStats' ? '2 つの期間の的中率' : '前の射と後の射の的中率'),
            ['順位', '名前', 前の名, 後の名, '差'],
            一覧.map((行) => [
              行.順位,
              行.名前,
              率の字(行[前] && 行[前].的中率),
              率の字(行[後] && 行[後].的中率),
              行.差 == null ? '—' : `${行.差 > 0 ? '+' : ''}${行.差}`,
            ]),
            { 強める列: -1 }
          ),
      };
    }
    case 'getAttendanceStats': {
      if (Array.isArray(r.月たち)) {
        const 一覧 = Array.isArray(r.一覧) ? r.一覧 : [];
        if (!一覧.length) return { 形たち: [] };
        const 月たち = r.月たち;
        const 数あり = 一覧.some((行) => 行.当てはまった月の数 != null);
        return {
          形たち: ['表'],
          作る: (形, 題) =>
            表にする(
              題 || '月ごとの出席率',
              [
                '名前',
                ...月たち.map((月) => `${Number(月.slice(5))}月`),
                ...(数あり ? ['当てはまった月'] : []),
              ],
              一覧.map((行) => [
                行.名前,
                ...月たち.map((月) => {
                  const 月の行 = (行.月ごと || []).find((x) => x.月 === 月);
                  return 月の行 ? 率の字(月の行.出席率) : '—';
                }),
                ...(数あり ? [行.当てはまった月の数] : []),
              ])
            ),
        };
      }
      const 一覧 = Array.isArray(r.一覧) ? r.一覧 : [];
      if (!一覧.length) return { 形たち: [] };
      return {
        形たち: ['棒', '表'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || '出席率',
                ['順位', '名前', '来た回数', '練習日数', '出席率'],
                一覧.map((行) => [行.順位, 行.名前, 行.来た回数, 行.練習日数 ?? '—', 率の字(行.出席率)]),
                { 強める列: -1 }
              )
            : 棒にする(
                題 || '出席率',
                一覧.map((行) => ({ 名: 行.名前, 値: 行.出席率, 補足: `来た ${行.来た回数} 回`, 順位: 行.順位 })),
                { 横: true }
              ),
      };
    }
    case 'getPositionStats': {
      const 順位 = Array.isArray(r.その射位の順位) ? r.その射位の順位 : null;
      if (!順位 || !順位.length) return { 形たち: [] };
      return {
        形たち: ['棒', '表'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || `${順位[0].射位}の見込みの的中率`,
                ['順位', '名前', '射数', '的中率', '見込み'],
                順位.map((行) => [行.順位, 行.名前, 行.射数, 率の字(行.的中率), 率の字(行.見込みの的中率)]),
                { 強める列: -1 }
              )
            : 棒にする(
                題 || `${順位[0].射位}の見込みの的中率`,
                順位.map((行) => ({
                  名: 行.名前,
                  値: 行.見込みの的中率,
                  補足: `${行.射数}射`,
                  射数: 行.射数,
                  順位: 行.順位,
                })),
                { 横: true }
              ),
      };
    }
    case 'getSessionsByDate': {
      const 記録 = Array.isArray(r.sessions) ? r.sessions : [];
      if (!記録.length) return { 形たち: [] };
      return {
        形たち: ['表', '折れ線'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || '記録',
                ['日付', '題', '射数', '的中率'],
                記録.map((x) => [x.date, x.title, x.totalArrows, x.hitRate]),
                { 強める列: -1 }
              )
            : 折れ線にする(題 || '記録ごとの的中率', [
                {
                  名: '的中率',
                  // 新しい順で来るので、古い順に並べ直す
                  点: [...記録]
                    .reverse()
                    .map((x) => ({
                      x: 線の短い名('日付', x.date),
                      y: 文の率(x.hitRate),
                      補足: `${x.totalArrows}射`,
                      射数: x.totalArrows,
                    })),
                },
              ]),
      };
    }
    case 'getArrowLocationStats': {
      const 点 = Array.isArray(r._点たち) ? r._点たち : [];
      if (!点.length) return { 形たち: [] };
      return {
        形たち: ['矢所'],
        作る: (形, 題) => {
          const 使う = 点.slice(-上限.矢所の点);
          const 的 = 使う[使う.length - 1].targetType || 'kasumi36';
          // 描くのは同じ的の点だけ。凡例の 中り・外れ も同じ点で数える（違う的の点まで数えて、図の点の数とずれていた）
          const 的の点 = 使う.filter((p) => (p.targetType || 'kasumi36') === 的);
          return {
            形: '矢所',
            題: 題 || '矢所',
            的,
            点たち: 的の点.map((p) => ({ x: p.x, y: p.y, mark: p.印, targetType: p.targetType })),
            中り: 的の点.filter((p) => p.印 === '○').length,
            外れ: 的の点.filter((p) => p.印 !== '○').length,
          };
        },
      };
    }
    case 'getEquipmentTrend': {
      const 一覧 = Array.isArray(r.一覧) ? [...r.一覧].reverse() : [];
      if (!一覧.length) return { 形たち: [] };
      const 名 = (行) => `${行.変えた日.slice(5).replace('-', '/')}〜 ${行.弓力 || 行.種類}`;
      return {
        形たち: ['棒', '表'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || '弓具ごとの的中率',
                ['変えた日', '弓具', '射数', '的中率', '前との差'],
                一覧.map((行) => [
                  行.変えた日,
                  行.弓力 || 行.種類,
                  行.その弓具のあいだ && 行.その弓具のあいだ.射数,
                  率の字(行.その弓具のあいだ && 行.その弓具のあいだ.的中率),
                  行.差 == null ? '—' : `${行.差 > 0 ? '+' : ''}${行.差}`,
                ]),
                { 強める列: 3 }
              )
            : 棒にする(
                題 || '弓具ごとの的中率',
                一覧.map((行) => ({
                  名: 名(行),
                  値: 行.その弓具のあいだ && 行.その弓具のあいだ.的中率,
                  補足: `${行.その弓具のあいだ ? 行.その弓具のあいだ.射数 : 0}射`,
                })),
                { 横: true }
              ),
      };
    }
    case 'makeBalancedTeams': {
      const 組 = Array.isArray(r.組) ? r.組 : [];
      if (!組.length) return { 形たち: [] };
      return {
        形たち: ['表'],
        作る: (形, 題) =>
          表にする(
            題 || '組分け',
            ['組', '顔ぶれ', '見込み'],
            組.map((x) => [x.組, (x.部員 || []).map((人) => 人.名前).join('・'), 率の字(x.見込みの的中率)]),
            { 強める列: -1 }
          ),
      };
    }
    case 'listMembers': {
      const 一覧 = Array.isArray(r.一覧) ? r.一覧 : [];
      if (!一覧.length) return { 形たち: [] };
      const 期あり = 一覧.some((x) => x.期);
      return {
        形たち: ['表', '棒'],
        作る: (形, 題) =>
          形 === '表'
            ? 表にする(
                題 || '名簿',
                ['名前', '学年', '性別', ...(期あり ? ['期'] : [])],
                一覧.map((x) => [x.名前, x.学年, x.性別, ...(期あり ? [x.期 || '—'] : [])])
              )
            : 棒にする(
                題 || '学年ごとの人数',
                Object.entries(r.学年ごと || {}).map(([名, 数]) => ({ 名, 値: 数 })),
                { 単位: '人', 横: false }
              ),
      };
    }
    default:
      return { 形たち: [] };
  }
}

/** 図にできる結果か（模型に「図の番号と使える形」を添えるかどうか） */
function 使える形(道具, 結果) {
  return 作り方(道具, 結果).形たち;
}

/**
 * 図を作る。作れないときは error と 使える形 を返す（模型に選び直させる）
 * @param {string} 道具
 * @param {any} 結果
 * @param {string} 形
 * @param {string} [題]
 */
function 図を作る(道具, 結果, 形, 題, 注文 = {}) {
  const 方 = 作り方(道具, 結果);
  if (!方.形たち.length) return { error: 'この結果は図にできません' };
  const 選ぶ形 = 形たち.includes(形) && 方.形たち.includes(形) ? 形 : null;
  if (!選ぶ形) return { error: `この結果で作れる形は ${方.形たち.join('・')} です`, 使える形: 方.形たち };
  const 題の字 = 題 ? String(題).slice(0, 40) : '';
  const 図 = 方.作る(選ぶ形, 題の字);
  // 縦軸は値のある所に寄せるのが既定。「0% から」と頼まれたときだけ 0 から（2026-11-14 本人）
  return 注文.零から && 図 && 図.形 === '折れ線' ? { ...図, 縦軸: '零から' } : 図;
}

/** 模型に渡す前に、図のためだけの中身（_ で始まる項目）を外す */
function 図の分を外す(結果) {
  if (!結果 || typeof 結果 !== 'object' || Array.isArray(結果)) return 結果;
  const 外した = {};
  for (const [鍵, 値] of Object.entries(結果)) if (!鍵.startsWith('_')) 外した[鍵] = 値;
  return 外した;
}

module.exports = { 図を作る, 使える形, 図の分を外す, 形たち, 上限 };
