const 右回し = (値, ビット数) => (値 >>> ビット数) | (値 << (32 - ビット数));

/** 文字列を UTF-8 のバイト列にする。TextEncoder が無い環境でも動くように自前で持つ */
function バイト列にする(文字列) {
  const 文 = String(文字列);
  const 出 = [];
  for (let 位置 = 0; 位置 < 文.length; 位置++) {
    let 符号 = 文.charCodeAt(位置);
    // 上位・下位のサロゲート対を1つの符号位置へ戻す
    if (符号 >= 0xd800 && 符号 <= 0xdbff && 位置 + 1 < 文.length) {
      const 次 = 文.charCodeAt(位置 + 1);
      if (次 >= 0xdc00 && 次 <= 0xdfff) ((符号 = 0x10000 + ((符号 - 0xd800) << 10) + (次 - 0xdc00)), 位置++);
    }
    if (符号 < 0x80) 出.push(符号);
    else if (符号 < 0x800) 出.push(0xc0 | (符号 >> 6), 0x80 | (符号 & 63));
    else if (符号 < 0x10000) 出.push(0xe0 | (符号 >> 12), 0x80 | ((符号 >> 6) & 63), 0x80 | (符号 & 63));
    else
      出.push(0xf0 | (符号 >> 18), 0x80 | ((符号 >> 12) & 63), 0x80 | ((符号 >> 6) & 63), 0x80 | (符号 & 63));
  }
  return 出;
}

/** バイト列を SHA-256 にかけ、32バイトの配列を返す */
function バイト列を要約する(バイト) {
  const 長さ = バイト.length;
  // 末尾に 0x80 を足し、長さ（ビット数・64bit）が入るまで 0 で埋める
  const 全体 = バイト.slice();
  全体.push(0x80);
  while (全体.length % 64 !== 56) 全体.push(0);
  const ビット数 = 長さ * 8;
  // 上位32ビット。この用途では 2^32 ビット（512MB）を超える入力は来ない
  全体.push(0, 0, 0, 0);
  全体.push((ビット数 >>> 24) & 255, (ビット数 >>> 16) & 255, (ビット数 >>> 8) & 255, ビット数 & 255);

  const 要約の途中 = 初期値.slice();
  // FIPS の W。64語に広げた入力の塊
  const 語の表 = new Int32Array(64);
  for (let 位置 = 0; 位置 < 全体.length; 位置 += 64) {
    for (let 番 = 0; 番 < 16; 番++)
      語の表[番] =
        (全体[位置 + 番 * 4] << 24) |
        (全体[位置 + 番 * 4 + 1] << 16) |
        (全体[位置 + 番 * 4 + 2] << 8) |
        全体[位置 + 番 * 4 + 3];
    for (let 番 = 16; 番 < 64; 番++) {
      const σ0 = 右回し(語の表[番 - 15], 7) ^ 右回し(語の表[番 - 15], 18) ^ (語の表[番 - 15] >>> 3);
      const σ1 = 右回し(語の表[番 - 2], 17) ^ 右回し(語の表[番 - 2], 19) ^ (語の表[番 - 2] >>> 10);
      語の表[番] = (語の表[番 - 16] + σ0 + 語の表[番 - 7] + σ1) | 0;
    }
    // FIPS の a〜h。毎周ひとつずつ送って詰めていく8つの作業用の語
    let [作業a, 作業b, 作業c, 作業d, 作業e, 作業f, 作業g, 作業h] = 要約の途中;
    for (let 周 = 0; 周 < 64; 周++) {
      const Σ1 = 右回し(作業e, 6) ^ 右回し(作業e, 11) ^ 右回し(作業e, 25);
      const 選択 = (作業e & 作業f) ^ (~作業e & 作業g); // FIPS の Ch
      const 一時1 = (作業h + Σ1 + 選択 + 丸め定数[周] + 語の表[周]) | 0;
      const Σ0 = 右回し(作業a, 2) ^ 右回し(作業a, 13) ^ 右回し(作業a, 22);
      const 多数決 = (作業a & 作業b) ^ (作業a & 作業c) ^ (作業b & 作業c); // FIPS の Maj
      const 一時2 = (Σ0 + 多数決) | 0;
      ((作業h = 作業g), (作業g = 作業f), (作業f = 作業e), (作業e = (作業d + 一時1) | 0));
      ((作業d = 作業c), (作業c = 作業b), (作業b = 作業a), (作業a = (一時1 + 一時2) | 0));
    }
    const この塊の結果 = [作業a, 作業b, 作業c, 作業d, 作業e, 作業f, 作業g, 作業h];
    for (let 番 = 0; 番 < 8; 番++) 要約の途中[番] = (要約の途中[番] + この塊の結果[番]) | 0;
  }

  const 出 = [];
  for (const 語 of 要約の途中) 出.push((語 >>> 24) & 255, (語 >>> 16) & 255, (語 >>> 8) & 255, 語 & 255);
  return 出;
}

const 十六進 = (バイト) => バイト.map((一バイト) => 一バイト.toString(16).padStart(2, '0')).join('');

/** 文字列の SHA-256 を十六進64文字で返す */
function 要約(文字列) {
  return 十六進(バイト列を要約する(バイト列にする(文字列)));
}

/** 文字列の SHA-256 をバイト列で返す。繰り返し掛けるときに使う */
function 要約のバイト列(文字列) {
  return バイト列を要約する(バイト列にする(文字列));
}

/** バイト列の SHA-256 をバイト列で返す */
function バイト列から(バイト) {
  return バイト列を要約する(バイト);
}

