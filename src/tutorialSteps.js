/**
 * 使い方の案内の手順。役割で出し分ける。
 *
 * ここには画面の部品を一切持ち込まない。React Native を読み込まないので、
 * 手元の検査（node --test）からそのまま呼べる。団体でログインしないと
 * 見られない手順も、これで中身を確かめられる。
 *
 * 各手順の項目
 *   画面 … 見せる前に移動しておくタブ（省略なら移動しない）
 *   目印 … 指す要素の名前（省略なら中央に吹き出しだけ）
 *   題   … 見出し
 *   文   … 説明。1文ずつに分けて配列で持つ（長い塊にしない）
 *   操作 … 実際に触ってもらう手順のときだけ置く
 *          { 案内: 画面に出す一言, 種類: 達成の判定に使う種別 }
 *
 * 操作の種類
 *   射手を増やす … 射手の数が増えたら次へ
 *   ○×を入れる  … ○か×が1つ増えたら次へ
 *   タブへ移動   … その画面へ移ったら次へ
 *
 * 押すと困るもの（ライブの開始、終了・保存）は、触らせずに説明だけにしてある。
 */
'use strict';

/**
 * @param 役割   'group' なら団体アカウント
 * @param 手持ち { 部員数, 記録数 } … いまの中身。あるものを「まだ無い」と
 *               言わないための出し分けに使う。省略すると空とみなす
 */
function 手順を作る(役割, 手持ち) {
  const 団体 = 役割 === 'group';
  const { 部員数 = 0, 記録数 = 0 } = 手持ち || {};
  const 手順 = [
    {
      題: 'ようこそ',
      文: [
        '弓道の的中を記録・分析するアプリです。',
        団体
          ? '「部員を登録する → 記録を取る → 保存する → あとで振り返る」の順にご案内します。'
          : '部員として使える機能を、実際の画面で順にご案内します。',
        '途中でやめたいときは、右上の「スキップ」を押してください。',
      ],
    },
  ];
  // 団体は、まず部員の登録から。作ったばかりの団体には部員が1人もいないので、
  // 先に記録の取り方を教えても「選択」に誰も出てこず、そこで詰まる
  if (団体) {
    手順.push(
      {
        目印: 'タブ.メンバー',
        題: 部員数 > 0 ? '部員はここで管理します' : 'はじめに部員を登録します',
        文:
          部員数 > 0
            ? [`いま${部員数}人が登録されています。`, '部員の追加や氏名・学年の変更は、ここから行います。']
            : ['まだ部員が1人も登録されていません。', '記録を取る前に、ここで部員を登録します。'],
        操作: { 案内: '「メンバー」を押してみましょう', 種類: 'タブへ移動', 先: 'メンバー' },
      },
      {
        画面: 'メンバー',
        目印: 'メンバー.追加',
        題: '部員を1人ずつ足します',
        文: [
          'ここから氏名・学年を登録します。',
          '登録すると、一人ずつに「個人ID」が割り当てられます。',
          '団体IDと個人IDを部員に伝えると、部員のスマホからも入れます。',
          部員数 > 0
            ? 'ここでは押せないようにしてあります。'
            : 'ここでは押せないようにしてあります。あとで登録してください。',
        ],
      },
      {
        目印: 'タブ.記録',
        題: 'それでは記録を取ってみましょう',
        文: ['部員を登録したら、記録画面に戻って練習の的中を入れていきます。'],
        操作: { 案内: '「記録」を押してみましょう', 種類: 'タブへ移動', 先: '記録' },
      }
    );
  }
  手順.push({
      画面: '記録',
      目印: '記録.人',
      題: 'まず射手を並べます',
      文: ['「人」を押すと、記録表に射手の列が増えます。'],
      操作: { 案内: '「人」を押してみましょう', 種類: '射手を増やす' },
    },
    {
      画面: '記録',
      目印: '記録.射手選択',
      題: '誰の記録かを決めます',
      文: [
        '列の下の「選択」から、登録済みの人を割り当てます。',
        団体
          ? '割り当てないと、誰の記録か分からないまま残ります。'
          : '自分を選ばないと、自分の記録として残りません。',
        '○×を入れる前に決めておくのが確実です。',
      ],
      操作: { 案内: '「選択」を押して、誰か選んでみましょう', 種類: '名前を決める' },
    },
    {
      画面: '記録',
      目印: '記録.表',
      題: '○×はタップで入れます',
      文: ['ますを押すたびに ○ → × → 空欄 と変わります。', '一番上の数字が的中数です。'],
      操作: { 案内: 'どこかのますを押してみましょう', 種類: '○×を入れる' },
    },
    {
      画面: '記録',
      目印: '記録.保存',
      題: '終わったら保存します',
      文: [
        '「終了・保存」を押すと、出欠を確かめてから記録として残ります。',
        '保存すると記録表は空になり、次の練習を始められます。',
        'ここまでが、練習1回ぶんの流れです。',
        'ここでは押せないようにしてあります。',
      ],
    }
  );

  // ここまでが基本。以降は、続きを見ると答えた人にだけ出す
  const 続き = [
    {
      画面: '記録',
      目印: '記録.射数',
      題: '1人あたりの射数を変えられます',
      文: ['ここを押すと、1人あたりの射数を選べます。', '立ちの本数に合わせてください。'],
      操作: { 案内: '押して、射数を選んでみましょう', 種類: '射数を変える' },
    },
    {
      画面: '記録',
      目印: '記録.拡大',
      題: '表示の大きさを変えられます',
      文: [
        '⊖ ⊕ で記録表を小さく・大きくできます。',
        '人数が多いときは小さく、見づらいときは大きくしてください。',
      ],
      操作: { 案内: '⊖ か ⊕ を押してみましょう', 種類: '表示を変える' },
    },
    {
      画面: '記録',
      目印: '記録.間隔',
      題: '立ちの区切りを入れられます',
      文: [
        '「間隔」を押すと、記録表に細い区切りの列が入ります。',
        '1立ち目と2立ち目のように、まとまりを分けたいときに使います。',
      ],
      操作: { 案内: '「間隔」を押してみましょう', 種類: '間隔を足す' },
    },
    {
      画面: '記録',
      目印: '記録.人',
      題: '区切りの先に、次の立ちを並べます',
      文: ['区切りを入れたら、その先に次の立ちの射手を並べていきます。'],
      // 間隔のすぐ隣に計を置くと、鍵が自分の列しか掴まず効かない。
      // 案内どおりに進めても隣り合わないよう、間に射手を1人挟む
      操作: { 案内: 'もう一度「人」を押してみましょう', 種類: '射手を増やす' },
    },
    {
      画面: '記録',
      目印: '記録.計',
      題: 'その場で合計を出せます',
      文: [
        '「計」を押すと、合計だけの列が入ります。',
        'その右どなりから、間隔にぶつかるまでの人の的中を足します。',
      ],
      操作: { 案内: '「計」を押してみましょう', 種類: '計を足す' },
    },
    {
      画面: '記録',
      目印: '記録.表',
      題: '数え終わったところを固定できます',
      // 記録表そのものを指す手順は、脇に空きが少ない。文が長いと送りが出るので短く
      文: [
        '「間隔」と「計」の列に、4射ごとに鍵の印が出ます。',
        '押すと、そのまとまりの○×を変えられなくなります。もう一度押すと外れます。',
      ],
      操作: { 案内: '鍵の印を押してみましょう', 種類: '鍵をかける' },
    },
    {
      画面: '記録',
      目印: '記録.取り消し',
      題: '押し間違えは戻せます',
      文: [
        '左の矢印で1つ前に戻り、右の矢印でやり直せます。',
        '○×だけでなく、射手を足した・消したのも戻せます。',
        'ライブ記録中は、全員で1つの履歴を共有します。誰かが戻すと全員の画面が戻ります。',
      ],
    },
    {
      画面: '記録',
      目印: '記録.画像',
      題: '紙の記録や立ち順を写真から取り込めます',
      文: [
        '「画像」から、紙の記録用紙や、黒板の立ち順表を読み取れます。',
        '手書きの○×も、ある程度そのまま読み取れます。',
        '読み取ったあとの画面で、押して直せます。',
        'ここでは押せないようにしてあります。',
      ],
    },
    {
      画面: '記録',
      目印: '記録.ライブ',
      題: '複数の端末で同時に記録できます',
      文: [
        '「ライブ」で記録を始めると、同じ団体の人が同じ記録表に参加できます。',
        '誰かが入れた○×が、その場で全員の画面に反映されます。',
        'ここでは押せないようにしてあります。',
      ],
    },
    {
      画面: '記録',
      目印: '記録.リセット',
      題: '「リセット」は取り扱い注意です',
      文: [
        '押すと、いま入力中の○×と射手がすべて消えます。',
        '保存していない記録は戻せません。',
        '書き間違えを直すだけなら、左下の矢印で1つずつ戻すほうが安全です。',
        'ここでは押せないようにしてあります。',
      ],
    },
    {
      目印: 'タブ.履歴',
      題: '過去の記録を見返せます',
      文: [
        団体
          ? '保存すると、ここに日付順で並びます。'
          : '保存すると、自分が含まれる記録がここに並びます。',
        '押すと、そのときの記録表をそのまま開けます。',
        記録数 > 0 ? `いま${記録数}件たまっています。` : 'まだ保存していないので、いまは空です。',
      ],
      操作: { 案内: '「履歴」を押してみましょう', 種類: 'タブへ移動', 先: '履歴' },
    },
    {
      目印: 'タブ.分析',
      題: '的中の移り変わりが見られます',
      文: [
        団体 ? '的中率の推移や、部員どうしの比較ができます。' : '自分の的中率の推移が見られます。',
        '期間やタグで絞り込めます。',
        '記録がたまってから見ると役に立ちます。',
      ],
      操作: { 案内: '「分析」を押してみましょう', 種類: 'タブへ移動', 先: '分析' },
    },
  ];
  if (団体) {
    続き.push({
      目印: 'タブ.出欠',
      題: '出欠を管理できます',
      文: ['練習日ごとの出欠を記録できます。', '記録を保存するときにも、出欠の確認画面が出ます。'],
      操作: { 案内: '「出欠」を押してみましょう', 種類: 'タブへ移動', 先: '出欠' },
    });
  }
  続き.push(
    {
      目印: 'タブ.設定',
      題: '設定を見てみましょう',
      文: ['書き出し、画面の配色、矢所の記録などがここにあります。'],
      操作: { 案内: '「設定」を押してみましょう', 種類: 'タブへ移動', 先: '設定' },
    },
    {
      画面: '設定',
      目印: '設定.矢所の記録機能を有効化',
      題: '矢所（当たった場所）も残せます',
      文: [
        'ここを入れると、○×を入れたときに的のどこに当たったかを記録できます。',
        '長押しすると、あとから場所を直せます。',
        '使わないときは切っておけます。',
      ],
    },
    {
      画面: '設定',
      目印: '設定.運用ガイド・ヘルプ',
      題: '困ったときはここです',
      文: [
        '団体IDやパスワードの扱いなど、運用のきまりを書いてあります。',
        'お問い合わせもこの画面の下のほうにあります。',
      ],
    },
    {
      題: '以上です',
      文: [
        'この案内は、設定の「使い方を見る」からいつでも見返せます。',
        団体 ? '困ったときは運用ガイドやお問い合わせをご利用ください。' : '困ったときはお問い合わせをご利用ください。',
        'さっそく記録を始めてみてください。',
      ],
    }
  );
  return { 基本: 手順, 続き };
}

module.exports = { 手順を作る };
