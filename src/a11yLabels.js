/**
 * Module ID: a11yLabels
 *
 * 読み上げ（VoiceOver / TalkBack）が読む言葉を作る。
 *
 * ■ なぜ別に持つのか
 * 画面に出ている字は「○」「×」だけで、読み上げると「まる」「かける」に
 * なってしまう。押す前に何のますかも分からない。ここで
 * 「1立目 大前 山田太郎 1射目 的中」のような言葉に組み直す。
 *
 * ■ 射位の呼び方は1か所に置く
 * 大前・N番・落 の決まりは chatStats.js が持っていたものを、ここへ出した。
 * 2か所に書くと、AIの答えと読み上げで違う呼び方になる。
 *
 * ■ 言葉は src/messages.js から引く
 * 読み上げは、画面の字が読めない人にとって唯一の手がかりになる。
 * 英語の端末で日本語のまま読まれると、何も分からない。だからここは
 * 画面のどこよりも先に、差し替えられる形にしてある。
 * 既定は日本語のままなので、いまの読み上げは変わらない。
 *
 * 「大前」「落」は訳していない。相当する英語が無く、こしらえると
 * かえって通じなくなる（src/messages.js の説明を参照）。
 *
 * 画面にも Firebase にも触れない純粋な関数なので、そのまま検査できる
 * （test/a11yLabels.test.js）。
 */
'use strict';

const { 訳 } = require('./i18n');

/** 1立ちの射数。4本で1立ち */
const 一立ちの射数 = 4;

/**
 * 射位の名前。先頭が大前、最後が落、あいだは「N番」。
 *
 * 1人だけのときは「大前」。落は2人以上のときだけ使う
 * （1人で「落」と呼ぶことはない）。
 */
function 射位の名前(番, 人数) {
  const n = 'number' == typeof 番 ? 番 : 0;
  const 全 = 'number' == typeof 人数 ? 人数 : 0;
  if (n === 0) return 訳('射位.大前');
  if (n === 全 - 1 && 全 > 1) return 訳('射位.落');
  return 訳('射位.番', { n: n + 1 });
}

/** ○×の読み。「まる」「かける」と読まれないように言い換える */
function 印の読み(印) {
  if ('○' === 印) return 訳('印.的中');
  if ('×' === 印 || '☓' === 印) return 訳('印.はずれ');
  return 訳('印.未記入');
}

/** 射番（0から）から「N立目 M射目」を作る */
function 立ちと射の読み(射番) {
  const i = 'number' == typeof 射番 && 射番 >= 0 ? 射番 : 0;
  return {
    立ち: Math.floor(i / 一立ちの射数) + 1,
    射: (i % 一立ちの射数) + 1,
  };
}

/**
 * ますの読み。
 *
 * 例：「1立目 大前 山田太郎 1射目 的中」
 * 名前が無い射手（まだ選んでいない）は「名前未設定」と読む。
 * 黙って飛ばすと、どの列の話か分からなくなる
 *
 * どれも欠けていてよい。欠けたときは既定の言い方に落とす
 * @param {{射手名?: string, 番?: number, 人数?: number, 射番?: number, 印?: string}} [中身]
 * @returns {string}
 */
function ますの読み({ 射手名, 番, 人数, 射番, 印 } = {}) {
  const { 立ち, 射 } = 立ちと射の読み(射番);
  return 訳('ます.読み', {
    立ち,
    射,
    射位: 射位の名前(番, 人数),
    名前: 名を整える(射手名),
    印: 印の読み(印),
  });
}

/** 名前が空の射手は「名前未設定」と読む。黙って飛ばすと、どの列か分からなくなる */
function 名を整える(射手名) {
  return String(射手名 == null ? '' : 射手名).trim() || 訳('射手.名前未設定');
}

/**
 * 射手の列そのものの読み。名前の欄に付ける。
 *
 * 例：「大前 山田太郎 8射中5的中」
 *
 * @param {{射手名?: string, 番?: number, 人数?: number, marks?: (string|null)[]}} [中身]
 * @returns {string}
 */
function 射手の読み({ 射手名, 番, 人数, marks } = {}) {
  const 一覧 = Array.isArray(marks) ? marks : [];
  const 射数 = 一覧.filter((m) => '○' === m || '×' === m || '☓' === m).length;
  const 的中 = 一覧.filter((m) => '○' === m).length;
  return 訳('射手.読み', {
    射位: 射位の名前(番, 人数),
    名前: 名を整える(射手名),
    成績: 合計の読み(射数, 的中),
  });
}

/** 立ちの合計の読み。例：「この立ち 20射中13的中」 */
function 合計の読み(射数, 的中) {
  const s = 'number' == typeof 射数 ? 射数 : 0;
  const h = 'number' == typeof 的中 ? 的中 : 0;
  // n は単数・複数を選ぶのに使う（英語の 1 hit / 2 hits）
  return s > 0 ? 訳('成績.あり', { 射数: s, 的中: h, n: h }) : 訳('成績.なし');
}

module.exports = {
  射位の名前,
  印の読み,
  立ちと射の読み,
  ますの読み,
  射手の読み,
  合計の読み,
  一立ちの射数,
};
